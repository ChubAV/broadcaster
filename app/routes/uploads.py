logger = structlog.get_logger()

router = APIRouter(prefix="/api/uploads", tags=["uploads"])

# Клиентское имя файла из составного запроса полностью подконтрольно отправителю
# и участвует в построении ключа объекта: без нормализации сегменты пути в имени
# выводят ключ за префикс пользователя, то есть в чужую область того же хранилища.
_PATH_SEPARATORS = re.compile(r"[\\/]")
_UNSAFE_FILENAME_CHARS = re.compile(r"[^A-Za-z0-9._-]")
MAX_FILENAME_LENGTH = 100
FALLBACK_FILENAME = "upload"

# Размер порции чтения тела. Одна порция — то, на что предел размера может быть
# превышен, прежде чем чтение прервётся: превышение обнаруживает ровно тот блок,
# который его создал.
UPLOAD_CHUNK_SIZE = 64 * 1024


# Заголовок типа из составного запроса подконтролен отправителю ровно так же, как
# имя файла: он тип ОБЪЯВЛЯЕТ, но не доказывает. SVG, принятый под видом PNG,
# отдаётся браузеру с origin хранилища и исполняет свой скрипт в его контексте —
# это вектор CR-02. Поэтому тип определяется по первым байтам содержимого, а
# присланный заголовок не используется нигде, включая запись в хранилище.
#
# Проверка написана руками намеренно, без библиотеки: `python-magic` тянет
# системный `libmagic` в Docker-образ, а `imghdr` удалён из stdlib в Python 3.13.
#
# ⚠️ ЗАПРЕТ НА ДЕКОДИРОВАНИЕ НЕДОВЕРЕННОГО ФАЙЛА СНЯТ, И СНЯТ СОЗНАТЕЛЬНО
# (issue #40). Прежде здесь стояло, что `Image.open()` добавил бы вектор
# decompression bomb ровно тому эндпоинту, который чинится, — и пока файл
# сохранялся байт в байт, это было верно. С issue #40 сохраняется не присланное,
# а ПРОИЗВЕДЁННОЕ из него, то есть декодировать приходится по существу задачи, а
# не ради удобства. Взамен запрета введён явный предел числа точек
# (`MAX_DECODED_PIXELS` в `app/services/images.py`), и стоит он ДО распаковки
# пикселей: заголовок изображения размеры лишь ЗАЯВЛЯЕТ, поэтому проверка,
# сделанная после `load()`, защищала бы уже занятую память. Само распознавание
# по сигнатуре Pillow при этом не отдано: список форматов закрыт здесь и по
# первым байтам, а декодер вызывается уже ПОСЛЕ отказа неподходящему типу.
#
# Список закрыт на двух форматах, и закрыт он не разбором самих форматов, а тем,
# что принятый файл обязан пережить ОТПРАВКУ. Загрузка здесь не самоцель:
# картинка уходит в рассылку, и послать её ОБЫЧНЫМ изображением должны уметь все
# три мессенджера сразу. Таких форматов ровно два — JPEG и PNG. С остальными
# происходит следующее:
#
#  * WebP. `app/messengers/telegram_user.py:200-221` кладёт картинку в
#    `io.BytesIO`, берёт `buf.name` из имени файла в URL «чтобы сохранить
#    расширение», и зовёт `client.send_file(..., force_document=False)`. Тип медиа
#    Telethon выводит именно из этого расширения: на `.webp` он собирает
#    документ-СТИКЕР, а стикер Telegram не принимает ни в альбоме, ни с подписью.
#    Это и есть поломка из issue #39. В WhatsApp то же самое с другой стороны:
#    `wa_worker/index.js:453-477` зовёт Baileys как `{ image, mimetype }`, где
#    mimetype — Content-Type сохранённого объекта, а `image/webp` для WhatsApp —
#    mimetype СТИКЕРА, то есть полем `image` уходит не сообщение-картинка.
#  * GIF. Для WhatsApp это не годная статическая картинка — анимацию там ожидают
#    видеофайлом. Для Telegram это не фотография: файл становится анимацией либо
#    документом, что вдобавок ломает смешанный альбом.
#  * MAX (`max_worker/main.py:567-600`) оборачивает файл в `Photo(path=...)` из
#    pymax — растровый путь загрузки фотографии, рассчитанный на JPEG и PNG.
#
# Отказ на этом эндпоинте стоит пользователю одного клика; та же ошибка, дожившая
# до рассылки, стоит несостоявшейся рассылки, и узнаёт о ней пользователь тогда,
# когда чинить уже поздно. Поэтому формат, переживающий загрузку, но не отправку,
# отвергается здесь, а не там. Ни один уже сохранённый объект при этом не
# переписывается: сужение действует на входе и только вперёд.
_IMAGE_SIGNATURES: tuple[tuple[bytes, str], ...] = (
    (b"\xff\xd8\xff", "image/jpeg"),
    (b"\x89PNG\r\n\x1a\n", "image/png"),
)

# Та же строка дословно лежит в `app/templates/ads/form.html` как
# `UPLOAD_TYPE_ERROR`: обработчик загрузки в редакторе показывает свою копию на
# любом ответе 400 и `detail` из ответа не читает. Совпадение копий держит
# render-тест в `tests/test_pages/test_ads_editor.py`, а не дисциплина.
#
# Придаточное про мессенджеры не украшение: пользователь, чей WebP отвергнут,
# видит заведомо корректное изображение и без объяснения читает отказ как
# поломку сервиса.
UNSUPPORTED_IMAGE_MESSAGE = (
    "Не удалось загрузить: подойдут только изображения JPEG или PNG — "
    "другие форматы принимают не все мессенджеры. Выберите другой файл."
)

# Отказ по числу точек — СВОЙ текст, а не переиспользованный текст про форматы
# (P-9). Файл на входе корректен: это честный снимок, просто слишком подробный,
# и совет «выберите другой файл» был бы советом мимо причины — ровно тот класс
# неправды, из-за которого выше написан абзац про WebP. Формат здесь не
# упоминается ни словом: менять его бессмысленно, а действие, которое ДЕЙСТВИТЕЛЬНО
# помогает, названо прямо.
#
# Читать этот текст пользователю приходится через `uploadFile()` в
# `app/templates/ads/form.html`: обработчик берёт `detail` из тела ответа, и
# именно ради таких отказов он этому научен — своя копия у него осталась лишь
# запасной на случай нечитаемого тела.
OVERSIZED_IMAGE_MESSAGE = (
    "Не удалось загрузить: в изображении слишком много точек. "
    "Уменьшите разрешение и попробуйте снова."
)

# Расширения, которые приведение считает СВОИМИ и заменяет, а не приписывает
# поверх. Список закрыт парой принимаемых форматов и их вариантом написания:
# `.jpeg` — то же расширение, что `.jpg`, и оставить его значило бы завести
# вторую форму ключа на один формат.
_KNOWN_IMAGE_EXTENSIONS = (".jpeg", ".jpg", ".png")


def sniff_image(content: bytes) -> str | None:
    """Определить MIME-тип изображения по первым байтам содержимого.

    Возвращает тип для JPEG и PNG либо ``None`` для всего остального. Список
    закрыт: распознаются ровно те два формата, которые названы в тексте отказа,
    и ровно те, которые все три мессенджера отправляют обычной картинкой.

    SVG в список не входит осознанно — это XML-документ, способный нести скрипт,
    и именно он является вектором CR-02.
    """
    for signature, mime in _IMAGE_SIGNATURES:
        if content.startswith(signature):
            return mime

    return None


def safe_filename(filename: str | None) -> str:
    """Свести клиентское имя файла к безопасному звену ключа объекта.

    Сегменты пути отбрасываются целиком (остаётся только последнее звено), всё
    вне набора «латинские буквы, цифры, точка, дефис, подчёркивание» заменяется
    на подчёркивание, результат обрезается до ``MAX_FILENAME_LENGTH``.

    Обрезка идёт ПОСЛЕ замены намеренно: усечение до неё могло бы оставить
    половину заменяемой последовательности. Если после нормализации не осталось
    ничего, возвращается непустое значение по умолчанию — пустое звено сделало бы
    ключ оканчивающимся на подчёркивание и неотличимым от соседних.
    """
    if not filename:
        return FALLBACK_FILENAME

    last_segment = _PATH_SEPARATORS.split(filename)[-1]
    cleaned = _UNSAFE_FILENAME_CHARS.sub("_", last_segment)[:MAX_FILENAME_LENGTH]
    return cleaned or FALLBACK_FILENAME


def retarget_extension(filename: str, extension: str) -> str:
    """Привести расширение нормализованного имени к СОХРАНЁННОМУ формату.

    Принимает результат ``safe_filename`` и целевое расширение (с точкой),
    срезает завершающее расширение из числа известных — без учёта регистра, ибо
    регистр в клиентском имени подконтролен отправителю, — и приписывает целевое.

    Приведение БЕЗУСЛОВНО (P-5): `.jpeg` становится `.jpg`, `.PNG` — `.png`, даже
    когда формат не менялся. Инвариант «расширение ключа описывает байты, лежащие
    под ключом» без этого имел бы исключение, а опирается на него не интерфейс, а
    отправка: `app/messengers/telegram_user.py` берёт имя файла из URL, и Telethon
    выводит тип медиа именно из расширения. Расширение, разошедшееся с
    содержимым, воспроизводит поломку issue #39 — только теперь по вине самого
    приложения, а не пользователя.

    ОБЯЗАТЕЛЬНОЕ СВОЙСТВО РЕЗУЛЬТАТА: он остаётся в наборе ``[A-Za-z0-9._-]`` и в
    пределе ``MAX_FILENAME_LENGTH``. Усечение поэтому делается по ОСНОВЕ имени, а
    не по готовой строке: обрезка после приписывания срезала бы само расширение и
    ключ перестал бы проходить собственный образец владения — объявление с таким
    вложением просто не сохранилось бы (T-Q40-03). Пустая основа заменяется
    значением по умолчанию по той же причине, по какой это делает
    ``safe_filename``.
    """
    lowered = filename.lower()
    base = filename
    for known in _KNOWN_IMAGE_EXTENSIONS:
        if lowered.endswith(known):
            base = filename[: -len(known)]
            break

    base = base[: MAX_FILENAME_LENGTH - len(extension)] or FALLBACK_FILENAME
    return f"{base}{extension}"


@router.post("/image")
async def upload_image(
    file: UploadFile,
    user_id: int = Depends(get_current_user_id),
    settings: Settings = Depends(get_settings),
):
    # Чтение ПОРЦИЯМИ с накоплением, а не `await file.read()` без аргумента.
    # Единовременное чтение материализовало бы всё тело до того, как предел
    # вообще проверен: `max_image_size_mb` тогда ограничивает то, что
    # СОХРАНЯЕТСЯ, а не то, что ПРИНИМАЕТСЯ, и любой аутентифицированный клиент
    # заставляет ASGI-воркер удерживать в памяти тело произвольного размера
    # (WR-02). Путь отказа платил ту же цену: распознавание типа стояло выше
    # проверки размера и уже успевало получить всё тело.
    max_bytes = settings.max_image_size_mb * 1024 * 1024
    chunks: list[bytes] = []
    received = 0
    while True:
        chunk = await file.read(UPLOAD_CHUNK_SIZE)
        if not chunk:
            break
        received += len(chunk)
        if received > max_bytes:
            # Прерывание на первом же превышении: остаток тела не читается, и
            # собранные порции не склеиваются вовсе.
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"File size exceeds {settings.max_image_size_mb}MB limit",
            )
        chunks.append(chunk)

    content = b"".join(chunks)

    # Тип берётся из содержимого, а не из присланного клиентом заголовка
    # (CR-02). Проверка стоит теперь НИЖЕ предела размера, и это неизбежно: при
    # потоковом чтении предел срабатывает раньше, чем содержимое целиком
    # доступно для распознавания. Следствие наблюдаемо и намеренно — тело,
    # которое одновременно превышает предел и не является изображением, получает
    # отказ по размеру, а не по типу. Оба отказа — код 400, ни один вход не
    # становится мягче.
    if sniff_image(content) is None:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=UNSUPPORTED_IMAGE_MESSAGE,
        )

    # Сжатие и миниатюра — счётная работа, и вынесена она В ПОТОК намеренно
    # (issue #40). Боевой артефакт держит ОДИН uvicorn-воркер: выполненные прямо
    # здесь декодирование и два кодирования останавливали бы событийный цикл на
    # всё своё время, то есть каждый загруженный снимок подвешивал бы вместе с
    # собой и чужие запросы, и `/health` — а по нему принимается решение о
    # живости контейнера. Кодеки Pillow отпускают GIL, поэтому вынос
    # действительно освобождает цикл, а не изображает освобождение.
    try:
        prepared = await asyncio.to_thread(prepare_upload, content)
    except ImageTooLarge:
        # Файл корректен, и текст отказа обязан говорить о числе точек, а не о
        # форматах: см. разбор над OVERSIZED_IMAGE_MESSAGE.
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=OVERSIZED_IMAGE_MESSAGE,
        )
    except ImageUnreadable:
        # Сигнатуру файл прошёл, а картинкой не оказался — то есть повреждён.
        # Берётся ИМЕННО текст про форматы, и это не экономия на сообщении:
        # совет «выберите другой файл» для повреждённого файла верен дословно, а
        # заводить третью формулировку значило бы завести третью копию, которую
        # нечем удерживать в step с шаблоном редактора.
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=UNSUPPORTED_IMAGE_MESSAGE,
        )

    # Generate unique key. Формат ключа прежний — идентификатор пользователя,
    # слеш, шестнадцатеричный токен, подчёркивание, имя; меняется только то, что
    # имя нормализуется, а расширение приводится к сохранённому формату. Уже
    # сохранённые ключи не переименовываются.
    filename = retarget_extension(safe_filename(file.filename), prepared.extension)
    key = f"{user_id}/{uuid4().hex}_{filename}"

    # Upload to S3
    try:
        await upload_file_to_s3(
            content=prepared.delivery,
            key=key,
            # Тип ФАКТИЧЕСКИ сохранённых байтов, а не присланный клиентом: иначе
            # объект лёг бы в хранилище с подконтрольным отправителю
            # Content-Type и отдавался бы браузеру с ним же — вектор CR-02
            # пережил бы проверку на входе. С issue #40 это утверждение стало
            # строго сильнее: значение больше не выводится даже из содержимого
            # присланного файла, а описывает байты, произведённые приложением.
            content_type=prepared.content_type,
            endpoint_url=settings.s3_endpoint_url,
            access_key=settings.s3_access_key,
            secret_key=settings.s3_secret_key,
            bucket=settings.s3_bucket_name,
            region=settings.s3_region,
        )
    except Exception:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Failed to upload image to storage",
        )

    # Миниатюра сохраняется ВТОРОЙ и своим провалом запрос не проваливает (P-7).
    # Она нужна для СКОРОСТИ показа, а не для отправки: в рассылку уходит объект
    # выше, и он уже в хранилище. Механизм отката на полноразмерный адрес всё
    # равно обязан существовать — у вложений, загруженных до issue #40,
    # миниатюры нет и не появится (D-6), — поэтому отсутствующая миниатюра для
    # интерфейса не новость, а известный случай, который он умеет пережить.
    # Обратное решение стоило бы пользователю потерянной загрузки из-за объекта,
    # без которого всё работает.
    try:
        await upload_file_to_s3(
            content=prepared.thumbnail,
            key=thumb_key(key),
            content_type=prepared.content_type,
            endpoint_url=settings.s3_endpoint_url,
            access_key=settings.s3_access_key,
            secret_key=settings.s3_secret_key,
            bucket=settings.s3_bucket_name,
            region=settings.s3_region,
        )
    except Exception:
        logger.warning("thumbnail_upload_failed", key=key, exc_info=True)

    # Форма ответа не меняется: адрес миниатюры интерфейс выводит из ключа сам,
    # и хранить его негде — `Ad.images` держит ключи вложений, а миниатюра
    # вложением не является и стать им не должна (T-Q40-04).
    return {"path": key}
