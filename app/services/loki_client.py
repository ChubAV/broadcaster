# ПРЕДЕЛ ОЖИДАНИЯ ВНЕШНЕЙ СЛУЖБЫ НА ПУТИ СИНХРОННОГО РЕНДЕРА (T-06-LOG1).
#
# Подраздел рисуется в том же запросе, поэтому ожидание источника есть ожидание
# администратора. Без явного предела молчащая служба держала бы страницу
# столько, сколько молчит, — а молчит она как раз в аварии, когда подраздел и
# открывают. Три секунды — заведомо больше, чем нужно живому источнику в общей
# сети, и заведомо меньше, чем терпит человек перед пустым экраном.
LOKI_TIMEOUT_SEC = 3.0

# ПОТОЛОК ЧИСЛА СТРОК ОДНОГО ОКНА (D-29).
#
# ПОЧЕМУ ПОТОЛОК. Окно в сутки на боевом стенде — это десятки тысяч строк, и
# запрос без предела вернул бы их все: и по сети, и в разметку. Потолок
# существует затем, чтобы выдача не была НЕОГРАНИЧЕННОЙ.
#
# ⚠️ СРАБОТАВШИЙ ПОТОЛОК ОБЯЗАН НАЗЫВАТЬ СЕБЯ. Молча укороченный журнал читается
# как «больше ничего не было» — то есть как ответ на вопрос, ради которого
# журнал открыли, и администратор примет решение по неполной картине, не зная,
# что она неполная. Признак срабатывания живёт ОТДЕЛЬНЫМ полем `LogWindow.capped`
# и получается из лишней прочитанной строки, а не из длины перечня.
#
# Значение живёт ЗДЕСЬ, потому что его обязаны называть одинаково клиент, тест и
