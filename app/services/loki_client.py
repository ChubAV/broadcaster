LOKI_QUERY_RANGE_PATH = "/loki/api/v1/query_range"


# =============================================================================
# Словари осей отбора. ОБЪЯВЛЕНЫ ЗДЕСЬ ОДИН РАЗ И ЦЕЛИКОМ
# =============================================================================
#
# Форма повторяет наборы чипсов раздела истории (`app/pages/history.py`):
# перечень значений живёт на сервере — там же, где отсекается мусор, — поэтому
# нарисованное и принимаемое разойтись не могут. Второй перечень уровней в
# разметке запрещён по той же причине.

# ⚠️ ЧИПС УРОВНЯ → НАБОР ЗНАЧЕНИЙ МЕТКИ, А НЕ ОДНО ЗНАЧЕНИЕ. Это несущее место
# всего подраздела.
#
# Уровень приезжает в источник ДВУМЯ разными словарями, и оба читаемы в
# конфигурации сборщика логов (`monitoring/promtail.yml`):
#   * Python-контейнеры (веб, планировщик, оба celery-воркера, воркер канала
#     MAX) логируются через `structlog.stdlib.add_log_level`, который кладёт имя
#     метода логгера в НИЖНЕМ регистре: `info`, `warning`, `error`, `critical`.
#     Сборщик поднимает это значение в метку как есть;
#   * воркер канала WhatsApp логируется числовыми уровнями, и сборщик ПЕРЕВОДИТ
#     их шаблоном: 40 → `warn`, 50 → `error`, 60 → `fatal`.
#
# То есть `warning` и `warn` — ДВА РАЗНЫХ СЛОВА ОДНОГО УРОВНЯ. Чипс, собранный
# из одного слова, скрыл бы ровно половину предупреждений: молча, при статусе
# 200, с пустым перечнем, который читается как «предупреждений нет».
#
# Альтернатива — выровнять конфигурацию сборщика — отвергнута дважды: она
# трогает эксплуатационный конфиг и НЕ ПЕРЕПИШЕТ уже уехавшие в источник метки,
# то есть починит будущее и оставит сломанным прошлое, за которым сюда и
# приходят.
#
# Ключ пустой строки — вариант «все». Он же — значение, которое компонент чипсов
# УБИРАЕТ из адреса, а не пишет пустым: `?level=` и отсутствие ключа обязаны
# означать одно и то же.
LEVEL_CHIPS: dict[str, tuple[str, ...]] = {
    "": (),
    "error": ("error", "critical", "fatal"),
    "warn": ("warn", "warning"),
    "info": ("info",),
}

# Подписи чипсов уровня в порядке отрисовки. Форма — как у наборов чипсов
# истории: пара «значение, подпись», пустое значение первым.
LEVEL_CHIP_OPTIONS: tuple[tuple[str, str], ...] = (
    ("", "Все"),
    ("error", "Ошибки"),
    ("warn", "Предупреждения"),
    ("info", "Инфо"),
)


# ТОН УРОВНЯ — ПО ЧИПСУ, А НЕ ПО СЛОВУ МЕТКИ, И ЭТО НЕСУЩЕЕ РАЗЛИЧИЕ.
#
# Ключи здесь — те же три чипса, что объявлены выше, поэтому ВТОРОГО перечня
# слов уровня не возникает ни здесь, ни тем более в разметке. Выпиши тона по
# словам метки — и словарь пришлось бы держать синхронным с `LEVEL_CHIPS`
# вручную: `warn` покрасился бы, а `warning` — нет, то есть половина
# предупреждений приехала бы на экран нейтральным серым.
LEVEL_TONES: dict[str, str] = {
    "error": "danger",
    "warn": "warn",
    "info": "muted",
}


def level_tone(level: str) -> str:
    """Тон строки по её уровню, выведенный ИЗ СЛОВАРЯ ЧИПСОВ.

    Незнакомое слово уровня — нейтральный тон: покрасить его тревожно значило бы
    выдать незнание за измерение.
    """
    for chip, values in LEVEL_CHIPS.items():
        if level and level in values:
            return LEVEL_TONES[chip]
    return "muted"


@dataclass(frozen=True, slots=True)
class LogWindowChoice:
    """Окно отбора: подпись для чипса и длительность для запроса."""

    label: str
    delta: timedelta


# ОКОН РОВНО ТРИ, И ПРОИЗВОЛЬНОГО ДИАПАЗОНА НЕТ (D-29).
#
# Прецедент прямой (Фаза 4, D-30), но здесь есть и собственный довод: срок
# хранения источника — семь суток, и произвольный диапазон уткнулся бы в него
# МОЛЧА, вернув неполную выдачу без единого признака неполноты. Все три
# объявленных окна в срок хранения укладываются с запасом.
LOG_WINDOWS: dict[str, LogWindowChoice] = {
    "15m": LogWindowChoice("15 мин", timedelta(minutes=15)),
    "1h": LogWindowChoice("1 час", timedelta(hours=1)),
    "24h": LogWindowChoice("24 часа", timedelta(hours=24)),
}
LOG_WINDOW_DEFAULT = "1h"

# Подписи чипсов окна выводятся ИЗ ТОГО ЖЕ словаря: второй перечень окон
# разъехался бы с первым молча — нарисованное окно перестало бы совпадать с
# запрашиваемым.
LOG_WINDOW_CHIPS: tuple[tuple[str, str], ...] = tuple(
    (key, choice.label) for key, choice in LOG_WINDOWS.items()
)

# ⚠️ ИМЯ КОНТЕЙНЕРА СЛУЖБЫ, РАЗБИРАЮЩЕЙ ОЧЕРЕДЬ КАНАЛА TELEGRAM, — ЕДИНСТВЕННОЕ
# ГЕНЕРИРУЕМОЕ. Это единственная служба боевой сборки без явного имени
# контейнера, поэтому её метка складывается сборкой из имени проекта, имени
# службы и порядкового номера. Значение живёт ОДНОЙ строкой и здесь: его
# уточнение на живом стенде обязано быть правкой одной строки, а не переделкой
# фильтра. Проверка имени входит в человеческую приёмку фазы.
LOG_SOURCE_TELEGRAM_WORKER = "broadcaster-celery-worker-telegram-1"

# ПЕРЕЧЕНЬ ИСТОЧНИКОВ ОБЪЯВЛЕН СЛОВАРЁМ НА СЕРВЕРЕ, И ЭТО НЕ УДОБСТВО.
#
# ⚠️ ОДНО ИЗ ЭТИХ ИМЁН ГЕНЕРИРУЕТСЯ СБОРКОЙ. Служба, разбирающая очередь канала
# Telegram, — единственная в боевой сборке БЕЗ явного имени контейнера, поэтому
# её метка складывается из имени проекта, имени службы и порядкового номера.
# Имя записано здесь предположением, снимаемым на живом стенде; при расхождении
# правка — ОДНА СТРОКА этого словаря, а не переделка фильтра. Ради этого перечень
# и объявлен здесь, а не собран в разметке.
#
# Воркеров аккаунтов в перечне НЕТ намеренно: их число растёт вместе с
# пользователями, и полоса чипсов переполнилась бы ровно тем перечнем, который
# не имеет предела. В подраздел они приходят идентификатором — ссылкой из строки
# воркера (D-10).
LOG_SOURCES: tuple[tuple[str, str], ...] = (
    ("", "Все"),
    ("web-broadcaster", "Веб"),
    ("celery-beat-broadcaster", "Планировщик"),
    ("celery-worker-default-broadcaster", "Воркер задач"),
    (LOG_SOURCE_TELEGRAM_WORKER, "Воркер Telegram"),
)

LOG_SOURCE_VALUES: frozenset[str] = frozenset(
    value for value, _ in LOG_SOURCES if value
)

# СЕЛЕКТОР ОБЯЗАН НЕСТИ ХОТЯ БЫ ОДИН МАТЧЕР: пустой источник запрос отвергает.
#
# ⚠️ ВЗЯТА МЕТКА ИМЕНИ КОНТЕЙНЕРА, А НЕ МЕТКА ЗАДАНИЯ СБОРЩИКА. Имя контейнера
# сборщик проставляет КАЖДОЙ цели явным правилом, которое читается в его
# конфигурации; метка задания приходит из имени раздела настроек сборщика, и её
# расхождение с ожидаемым дало бы пустую выдачу при статусе 200 — то есть
# «логов нет» вместо «спросили не то». Ровно этот класс молчаливой ошибки
# подраздел и обязан исключать.
LOG_ANY_SOURCE_MATCHER = 'container_name=~".+"'


def _is_account_id(value: str) -> bool:
    """Значение источника имеет форму идентификатора аккаунта.

    ⚠️ ЯВНО ТОЛЬКО ASCII-ЦИФРЫ. Проверка на «цифру» без этого условия принимает
    цифры других письменностей и надстрочные знаки — то есть значения, которые
    идентификатором аккаунта не являются и в метке источника не встречаются.
    """
    return bool(value) and value.isascii() and value.isdigit()


def clean_level(value: str | None) -> str:
    """Уровень из адреса → ключ объявленного словаря либо вариант «все».

    Значение приезжает строкой запроса, то есть из ссылки, закладки или чужого
    сообщения. Подставленное сырым, оно ушло бы в чужой язык запросов; принятое
    за отбор — нарисовало бы администратору фильтр, которого он не задавал.
    Форма отсечки — та же, что у осей раздела истории (`clean_choice`).
    """
    if not value:
        return ""
    value = value.strip()
    return value if value in LEVEL_CHIPS else ""


def clean_source(value: str | None) -> str | None:
    """Источник из адреса → имя объявленной службы ЛИБО идентификатор аккаунта.

    Множество закрыто с ДВУХ сторон, и обе стороны обязательны: службы
    перечислимы и перечислены, воркеры аккаунтов не перечислимы — но их
    идентификатор состоит только из цифр и ничем иным быть не может. Значение,
    не подходящее ни под то, ни под другое, фильтром не становится вовсе.
    """
    if not value:
        return None
    value = value.strip()
    if value in LOG_SOURCE_VALUES or _is_account_id(value):
        return value
    return None


def clean_window(value: str | None) -> str:
    """Окно из адреса → ключ объявленного словаря либо умолчание в один час."""
    if value and value.strip() in LOG_WINDOWS:
        return value.strip()
    return LOG_WINDOW_DEFAULT


def _escape_line_filter(text: str) -> str:
    """Экранирование текста поиска для фильтра строки.

    ⚠️ ОБРАТНАЯ КОСАЯ ЭКРАНИРУЕТСЯ ПЕРВОЙ. Переставь порядок — и косая,
    добавленная при экранировании кавычки, сама попала бы под замену, съев
    собственную кавычку и сломав запрос ровно тем способом, который здесь
    закрывается.
    """
    return text.replace("\\", "\\\\").replace('"', '\\"')


def build_logql(level: str | None, source: str | None, text: str | None) -> str:
    """Запрос к источнику из трёх осей отбора и текста поиска.

    ⚠️ ТЕКСТ УХОДИТ В ФИЛЬТР СТРОКИ, А НЕ В СЕЛЕКТОР МЕТОК (T-06-LQL). Селектор
    индексируется источником и произвольного текста не принимает: уехав туда,
    поиск не нашёл бы ничего при исправном на вид запросе. И это же —
    единственный вход фазы, уходящий в чужой язык запросов, поэтому кавычка и
    обратная косая экранируются ДО сборки: неэкранированная кавычка ломает
    запрос синтаксически, и подраздел ответил бы отказом источника на нормальный
    пользовательский ввод.

    ⚠️ УСЛОВИЕ УРОВНЯ СТРОИТСЯ СОПОСТАВЛЕНИЕМ С НАБОРОМ, А НЕ РАВЕНСТВОМ ОДНОМУ.
    Причина — два словаря уровня у источника; разбор выписан у `LEVEL_CHIPS`.
    """
    source = clean_source(source)
    if source is None:
        matchers = [LOG_ANY_SOURCE_MATCHER]
    elif _is_account_id(source):
        matchers = [f'account_id="{source}"']
    else:
        matchers = [f'container_name="{source}"']

    values = LEVEL_CHIPS.get(clean_level(level), ())
    if values:
        matchers.append(f'level=~"{"|".join(values)}"')

    selector = "{" + ", ".join(matchers) + "}"

    text = (text or "").strip()
    if not text:
        return selector
    return f'{selector} |= "{_escape_line_filter(text)}"'


@dataclass(frozen=True, slots=True)
class LogLine:
    """Одна строка журнала: момент, уровень, источник, текст.

    Именованные поля, а не кортеж: строку читает разметка, и `line[3]` в шаблоне
    ничего не сообщает о том, что печатается. Текст здесь СЫРОЙ — экранирует его
    разметка, и собственной сборки разметки строками модуль не заводит.
    """

    at: datetime
    level: str
    source: str
    text: str

    @property
    def tone(self) -> str:
        """Тон уровня для разметки: выводится из объявленного словаря чипсов."""
        return level_tone(self.level)


@dataclass(frozen=True, slots=True)
class LogWindow:
    """Результат чтения окна: строки, признак потолка и признак недоступности.

    ⚠️ ТРИ ПОЛЯ, ПОТОМУ ЧТО СОСТОЯНИЙ ТРИ, И РАЗМЕТКА РАЗЛИЧАЕТ ВСЕ ТРИ. Пустая
    выдача при живом источнике — обычное пустое состояние («за окно тихо»).
    Недоступный источник — ИМЕНОВАННАЯ плашка («мы не знаем, что было»).
    Сработавший потолок — подпись над списком. Сведи их к одному полю — и первые
    два станут неразличимы ровно в той аварии, ради которой сюда приходят.
    """

    lines: list[LogLine] = field(default_factory=list)
    capped: bool = False
    unavailable: bool = False


_http_client = None


def _client():
    """Ленивый HTTP-клиент чтения логов.

    ЕДИНСТВЕННАЯ точка подмены модуля — на ней держится проверяемость всего
    подраздела «Логи» без поднятого источника. Клиент асинхронный: синхронный в
    страничном обработчике заблокировал бы цикл событий на время обращения по
    сети, то есть весь веб-процесс.
    """
    global _http_client
    if _http_client is None:
        try:
            _http_client = httpx.AsyncClient(timeout=LOKI_TIMEOUT_SEC)
        except Exception:
            logger.warning("loki_client_unavailable")
            return None
    return _http_client


def _parse_stream(stream: dict) -> list[LogLine]:
    """Один поток ответа → строки журнала.

    ⚠️ ИСТОЧНИК СТРОКИ ЧИТАЕТСЯ ПО ДВУМ МЕТКАМ В ОБЪЯВЛЕННОМ ПОРЯДКЕ. У воркера
    аккаунта есть метка идентификатора — она точнее имени контейнера, потому что
    имя динамического контейнера собирается сборщиком и меняется при
    пересоздании. У служб сборки идентификатора нет вовсе, и остаётся имя
    контейнера.
    """
    labels = stream.get("stream") or {}
    # Пустая строка, а не прочерк: печатать нечего — решает РАЗМЕТКА, и там же
    # живёт объяснение причины, по которой величины нет. Прочерк, пришедший из
    # сервиса, был бы оформлением, приехавшим из слоя данных.
    source = labels.get("account_id") or labels.get("container_name") or ""
    level = labels.get("level") or ""
    lines = []
    for value in stream.get("values") or []:
        ts_ns, text = value[0], value[1]
        lines.append(
            LogLine(
                at=datetime.fromtimestamp(int(ts_ns) / 1e9, tz=timezone.utc),
                level=level,
                source=source,
                text=text,
            )
        )
    return lines


async def query_range(logql: str, window: timedelta) -> LogWindow:
    """Строки источника за окно. Недоступность НАЗЫВАЕТСЯ, а не молчит.

    ⚠️ ИСКЛЮЧЕНИЕ НАРУЖУ НЕ ВЫХОДИТ НИ ПО ОДНОЙ ПРИЧИНЕ. Отказ соединения,
    истёкший предел ожидания и код ошибки источника ведут в ОДНУ ветку: с точки
    зрения администратора это одно и то же событие — «сейчас негде прочитать», —
    и три разных исхода на экране только разделили бы внимание. Текст стороннего
    исключения на экран не выходит: он уходит в журнал именованным ключом, а на
    экране стоит фиксированная строка с командой подъёма мониторинга.
    """
    end = datetime.now(timezone.utc)
    start = end - window

    client = _client()
    if client is None:
        return LogWindow(lines=[], capped=False, unavailable=True)

    try:
        # ⚠️ АДРЕС ЧИТАЕТСЯ ВНУТРИ ГАРДА, А НЕ ДО НЕГО, И ЭТО НЕ ПЕДАНТИЗМ.
        # Сборка настроек — обращение к внешнему по отношению к подразделу
        # факту: она читает окружение и падает, если обязательного поля в нём
        # нет. Прочитанный ДО гарда адрес превращал бы это падение в ПЯТИСОТКУ
        # на подразделе — то есть отнимал бы и логи, и сам подраздел разом,
        # ради службы, которая объявлена опциональной. «Адреса источника нет»
        # означает ровно то же, что «источник не отвечает»: прочитать негде.
        url = f"{get_settings().loki_url.rstrip('/')}{LOKI_QUERY_RANGE_PATH}"
        response = await client.get(
            url,
            params={
                "query": logql,
                # ⚠️ НАНОСЕКУНДЫ СТРОКОЙ — КОНТРАКТ ЗАПРОСА, А НЕ ОФОРМЛЕНИЕ.
                # Секунды источник разберёт как момент в далёком прошлом и
                # вернёт пустоту: ошибка этого класса неотличима от тишины.
                "start": str(int(start.timestamp() * 1e9)),
                "end": str(int(end.timestamp() * 1e9)),
                "limit": LOG_READ_LIMIT,
                "direction": "backward",
            },
        )
        response.raise_for_status()
        payload = response.json()
    except Exception as e:
        logger.warning("loki_unavailable", error=str(e), query=logql)
        return LogWindow(lines=[], capped=False, unavailable=True)

    try:
        streams = payload["data"]["result"]
    except (KeyError, TypeError):
        # Ответ пришёл, но формы, о которой договаривались, в нём нет. Это тоже
        # «прочитать негде», а не «строк не было»: выдать пустой перечень
        # значило бы утверждать про журнал то, чего мы не читали.
        logger.warning("loki_unreadable_answer", query=logql)
        return LogWindow(lines=[], capped=False, unavailable=True)

    lines: list[LogLine] = []
    for stream in streams:
        lines.extend(_parse_stream(stream))
    lines.sort(key=lambda line: line.at, reverse=True)

    return LogWindow(
        lines=lines[:LOG_LINE_CAP],
        capped=len(lines) > LOG_LINE_CAP,
        unavailable=False,
    )
