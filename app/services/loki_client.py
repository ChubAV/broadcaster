"""Единственная точка чтения логов из внешнего источника для веб-процесса.

Форма модуля скопирована с `app/services/ops_state.py` и `billing_cache.py`
дословно: модульная переменная-клиент, ленивая ИМЕНОВАННАЯ функция-получатель
`_client`, возвращающая пустоту при несобравшемся клиенте, и обёртка вокруг
каждого обращения. Именованная точка здесь не стиль: суита проекта идёт без
единой внешней службы, и подменить чтение логов в тестах нечем, кроме
именованной точки модуля (`unittest.mock.patch`). Обработчик, собирающий
HTTP-запрос у себя внутри, был бы непроверяем — а проверять здесь надо ровно то,
что случается, когда источника НЕТ.

⚠️ ИСТОЧНИК ЛОГОВ ОПЦИОНАЛЕН И ОСТАЁТСЯ ТАКИМ (D-28). Мониторинг не поднимается
боевыми командами запуска и выката — это решение проекта, а не недоделка, — и
его сеть подключена как внешняя: адрес виден только при поднятом мониторинге.
Значит НЕДОСТУПНОСТЬ ЕСТЬ ШТАТНАЯ ВЕТКА, а не исключительная, и она обязана
возвращаться ОТДЕЛЬНЫМ ПОЛЕМ результата.

⚠️ ПУСТОЙ ПЕРЕЧЕНЬ И ОТСУТСТВУЮЩИЙ ИСТОЧНИК — РАЗНЫЕ СОСТОЯНИЯ МИРА. Оба дают
ноль строк, и вывести одно из другого нельзя: пустой список читается как «ошибок
нет» — то есть как ответ на вопрос, ради которого администратор в подраздел и
пришёл, — и в аварии он ушёл бы искать причину не туда. Различие живёт в
`LogWindow.unavailable`, а не в длине `LogWindow.lines`.

⚠️ ПОТОЛОК УЗНАЁТСЯ, А НЕ УГАДЫВАЕТСЯ. Предел выдачи запрашивается на ЕДИНИЦУ
больше потолка показа: лишняя прочитанная строка — единственная улика усечения.
Приём в проекте уже применён дважды (`PAYMENT_LIST_CAP`, `QUEUE_ROW_CAP`).

⚠️ АУТЕНТИФИКАЦИИ У ИСТОЧНИКА НЕТ (`monitoring/loki.yml`: `auth_enabled: false`),
и заголовок разграничения арендаторов сюда НЕ добавляется. Он был бы обещанием
разграничения, которого не существует: источник его просто игнорирует, а
читающий код принял бы его за меру защиты.
"""
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone

import httpx
import structlog

from app.config import get_settings

logger = structlog.get_logger(__name__)


# ПРЕДЕЛ ОЖИДАНИЯ ВНЕШНЕЙ СЛУЖБЫ НА ПУТИ СИНХРОННОГО РЕНДЕРА (T-06-LOG1).
#
# Подраздел рисуется в том же запросе, поэтому ожидание источника есть ожидание
# администратора. Без явного предела молчащая служба держала бы страницу
# столько, сколько молчит, — а молчит она как раз в аварии, когда подраздел и
# открывают. Три секунды — заведомо больше, чем нужно живому источнику в общей
# сети, и заведомо меньше, чем терпит человек перед пустым экраном.
LOKI_TIMEOUT_SEC = 3.0

# ПОТОЛОК ЧИСЛА СТРОК ОДНОГО ОКНА (D-29).
#
# ПОЧЕМУ ПОТОЛОК. Окно в сутки на боевом стенде — это десятки тысяч строк, и
# запрос без предела вернул бы их все: и по сети, и в разметку. Потолок
# существует затем, чтобы выдача не была НЕОГРАНИЧЕННОЙ.
#
# ⚠️ СРАБОТАВШИЙ ПОТОЛОК ОБЯЗАН НАЗЫВАТЬ СЕБЯ. Молча укороченный журнал читается
# как «больше ничего не было» — то есть как ответ на вопрос, ради которого
# журнал открыли, и администратор примет решение по неполной картине, не зная,
# что она неполная. Признак срабатывания живёт ОТДЕЛЬНЫМ полем `LogWindow.capped`
# и получается из лишней прочитанной строки, а не из длины перечня.
#
# Значение живёт ЗДЕСЬ, потому что его обязаны называть одинаково клиент, тест и
# подпись подраздела: выписанное в разметке второй раз, оно разъехалось бы с
# первым молча.
LOG_LINE_CAP = 200

# ПРЕДЕЛ ЧТЕНИЯ — ПОТОЛОК ПЛЮС ОДИН. Лишний элемент не печатается: он и есть
# улика усечения. Запросив ровно потолок, отличить «прочитано двести» от «за
# окно ровно двести» было бы нечем, и признак пришлось бы выводить из длины —
# то есть объявлять полный перечень усечённым.
LOG_READ_LIMIT = LOG_LINE_CAP + 1

# ПУТЬ ЧТЕНИЯ ОКНА У ИСТОЧНИКА. Собирается с адресом из настройки, а не
# выписывается в вызове: место обращения одно, но имя пути читают ещё и тесты.
LOKI_QUERY_RANGE_PATH = "/loki/api/v1/query_range"


@dataclass(frozen=True, slots=True)
class LogLine:
    """Одна строка журнала: момент, уровень, источник, текст.

    Именованные поля, а не кортеж: строку читает разметка, и `line[3]` в шаблоне
    ничего не сообщает о том, что печатается. Текст здесь СЫРОЙ — экранирует его
    разметка, и собственной сборки разметки строками модуль не заводит.
    """

    at: datetime
    level: str
    source: str
    text: str


@dataclass(frozen=True, slots=True)
class LogWindow:
    """Результат чтения окна: строки, признак потолка и признак недоступности.

    ⚠️ ТРИ ПОЛЯ, ПОТОМУ ЧТО СОСТОЯНИЙ ТРИ, И РАЗМЕТКА РАЗЛИЧАЕТ ВСЕ ТРИ. Пустая
    выдача при живом источнике — обычное пустое состояние («за окно тихо»).
    Недоступный источник — ИМЕНОВАННАЯ плашка («мы не знаем, что было»).
    Сработавший потолок — подпись над списком. Сведи их к одному полю — и первые
    два станут неразличимы ровно в той аварии, ради которой сюда приходят.
    """

    lines: list[LogLine] = field(default_factory=list)
    capped: bool = False
    unavailable: bool = False


_http_client = None


def _client():
    """Ленивый HTTP-клиент чтения логов.

    ЕДИНСТВЕННАЯ точка подмены модуля — на ней держится проверяемость всего
    подраздела «Логи» без поднятого источника. Клиент асинхронный: синхронный в
    страничном обработчике заблокировал бы цикл событий на время обращения по
    сети, то есть весь веб-процесс.
    """
    global _http_client
    if _http_client is None:
        try:
            _http_client = httpx.AsyncClient(timeout=LOKI_TIMEOUT_SEC)
        except Exception:
            logger.warning("loki_client_unavailable")
            return None
    return _http_client


def _parse_stream(stream: dict) -> list[LogLine]:
    """Один поток ответа → строки журнала.

    ⚠️ ИСТОЧНИК СТРОКИ ЧИТАЕТСЯ ПО ДВУМ МЕТКАМ В ОБЪЯВЛЕННОМ ПОРЯДКЕ. У воркера
    аккаунта есть метка идентификатора — она точнее имени контейнера, потому что
    имя динамического контейнера собирается сборщиком и меняется при
    пересоздании. У служб сборки идентификатора нет вовсе, и остаётся имя
    контейнера.
    """
    labels = stream.get("stream") or {}
    source = labels.get("account_id") or labels.get("container_name") or "—"
    level = labels.get("level") or ""
    lines = []
    for value in stream.get("values") or []:
        ts_ns, text = value[0], value[1]
        lines.append(
            LogLine(
                at=datetime.fromtimestamp(int(ts_ns) / 1e9, tz=timezone.utc),
                level=level,
                source=source,
                text=text,
            )
        )
    return lines


async def query_range(logql: str, window: timedelta) -> LogWindow:
    """Строки источника за окно. Недоступность НАЗЫВАЕТСЯ, а не молчит.

    ⚠️ ИСКЛЮЧЕНИЕ НАРУЖУ НЕ ВЫХОДИТ НИ ПО ОДНОЙ ПРИЧИНЕ. Отказ соединения,
    истёкший предел ожидания и код ошибки источника ведут в ОДНУ ветку: с точки
    зрения администратора это одно и то же событие — «сейчас негде прочитать», —
    и три разных исхода на экране только разделили бы внимание. Текст стороннего
    исключения на экран не выходит: он уходит в журнал именованным ключом, а на
    экране стоит фиксированная строка с командой подъёма мониторинга.
    """
    end = datetime.now(timezone.utc)
    start = end - window

    client = _client()
    if client is None:
        return LogWindow(lines=[], capped=False, unavailable=True)

    url = f"{get_settings().loki_url.rstrip('/')}{LOKI_QUERY_RANGE_PATH}"
    try:
        response = await client.get(
            url,
            params={
                "query": logql,
                # ⚠️ НАНОСЕКУНДЫ СТРОКОЙ — КОНТРАКТ ЗАПРОСА, А НЕ ОФОРМЛЕНИЕ.
                # Секунды источник разберёт как момент в далёком прошлом и
                # вернёт пустоту: ошибка этого класса неотличима от тишины.
                "start": str(int(start.timestamp() * 1e9)),
                "end": str(int(end.timestamp() * 1e9)),
                "limit": LOG_READ_LIMIT,
                "direction": "backward",
            },
        )
        response.raise_for_status()
        payload = response.json()
    except Exception as e:
        logger.warning("loki_unavailable", error=str(e), query=logql)
        return LogWindow(lines=[], capped=False, unavailable=True)

    try:
        streams = payload["data"]["result"]
    except (KeyError, TypeError):
        # Ответ пришёл, но формы, о которой договаривались, в нём нет. Это тоже
        # «прочитать негде», а не «строк не было»: выдать пустой перечень
        # значило бы утверждать про журнал то, чего мы не читали.
        logger.warning("loki_unreadable_answer", query=logql)
        return LogWindow(lines=[], capped=False, unavailable=True)

    lines: list[LogLine] = []
    for stream in streams:
        lines.extend(_parse_stream(stream))
    lines.sort(key=lambda line: line.at, reverse=True)

    return LogWindow(
        lines=lines[:LOG_LINE_CAP],
        capped=len(lines) > LOG_LINE_CAP,
        unavailable=False,
    )
