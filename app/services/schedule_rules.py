"""Правила расписания, общие для страничного и JSON-входа.

Модуль НЕЙТРАЛЕН: от него зависят оба слоя, а сам он не зависит ни от одного из
них. Направление зависимости здесь не украшение архитектуры, а прямое следствие
причины, по которой модуль появился: правило, живущее на одном входе и
отсутствующее на другом, расходится молча. Так разъехались определение полноты
расписания (страничный тумблер требовал аккаунт И группы И дни И времена,
API-тумблер — только аккаунт, WR-05 при том что D-08 требует ОДНОГО определения)
и правило владения группами (страничный слой сводил `group_ids` к своим,
JSON-API писал их дословно, CR-02 / T-02G-06).

⚠️ ПРАВИЛО ЗДЕСЬ ОДНО, А ПОЛИТИКА У КАЖДОГО ВХОДА СВОЯ — И ЭТО НЕ ТО ЖЕ САМОЕ,
ЧТО РАСХОЖДЕНИЕ WR-05. Модуль отвечает на вопрос «годится ли значение», и ответ
обязан быть один. Что делать с негодным — вопрос ВХОДА, и у каждого он решён
давно: страница ОТБРАСЫВАЕТ негодное и сохраняет остальное, потому что форма
шлёт повторяющиеся поля и одно испорченное значение не повод потерять все
(`_clean_times`, `_clean_ints`); JSON-API ОТКАЗЫВАЕТ формой 422, как он с самого
начала отказывает на незнакомом `timezone` и на явном null (CR-03).
Расхождением WR-05 было другое: там у ОДНОГО правила было ДВА РАЗНЫХ
ОПРЕДЕЛЕНИЯ.
"""

import re

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.group import Group

# Границы дня недели. Те же, что у `datetime.date.weekday()` — 0 понедельник,
# 6 воскресенье, — и та же пара чисел, которую страничный слой передавал в
# `_clean_ints` литералами. Литералов было два (создание и обновление), и это
# ровно то количество, с которого начинается расхождение.
DAY_OF_WEEK_MIN = 0
DAY_OF_WEEK_MAX = 6

# Формат значения времени: два числа через двоеточие в допустимых диапазонах.
# ПОЧЕМУ ПРОВЕРКА ВООБЩЕ СУЩЕСТВУЕТ: `compute_next_run_at` разбирает строку
# `int(parts[0])` / `parts[1]` без всякой защиты, поэтому любое значение не
# этого формата давало 500 — сперва на прямом POST мимо браузера (T-02-24,
# Pitfall 9), а после переноса сюда выяснилось, что JSON-вход не был закрыт и
# этой проверкой тоже.
#
# ЧАС ЗАПИСЫВАЕТСЯ ДВУМЯ ЦИФРАМИ. Не косметика: значение уезжает в разметку
# карточки и в `<input type="time">` редактора как есть, а два написания одного
# времени («9:00» и «09:00») означали бы два значения, равных по смыслу и
# разных по строке, — то есть второе определение формата.
TIME_OF_DAY_RE = re.compile(r"^([01]\d|2[0-3]):([0-5]\d)$")


def is_valid_day_of_week(value: object) -> bool:
    """Годится ли значение как номер дня недели.

    `bool` исключается ЯВНО, хотя в Python он и есть подкласс `int`: `True`
    прошёл бы как единица и молча означал бы вторник.
    """
    return (
        isinstance(value, int)
        and not isinstance(value, bool)
        and DAY_OF_WEEK_MIN <= value <= DAY_OF_WEEK_MAX
    )


def is_valid_time_of_day(value: object) -> bool:
    """Годится ли значение как время запуска — СТРОГО, без обрезки пробелов.

    Обрезку делает вызывающий, если ему это нужно: страничный слой сверяет
    `v.strip()`, потому что форма приносит значения из разметки, а JSON-клиент
    присылает документ и обрезать его значения за него — значит принять не то,
    что прислано. Правило при этом одно, а обрезка — свойство входа.

    Тип проверяется ДО строковых операций. Многочастный запрос вправе прислать
    часть `times_of_day` файлом, и тогда `getlist` отдаёт `UploadFile`, у
    которого нет `.strip()`: получался 500 вместо валидации (WR-03, T-02G-10).
    """
    return isinstance(value, str) and TIME_OF_DAY_RE.match(value) is not None


def is_schedule_complete(
    account_id: int | None,
    group_ids: list[int],
    days_of_week: list[int],
    times_of_day: list[str],
) -> bool:
    """D-08: заполнено ли расписание настолько, чтобы его можно было включить.

    Одно определение на все обработчики обоих входов и на разметку карточки
    (app/templates/ads/includes/sched_card.html): второе разъехалось бы с
    первым, и пользователь видел бы бейдж «Не заполнено» на расписании, которое
    сервер считает полным.
    """
    return bool(account_id and group_ids and days_of_week and times_of_day)


async def owned_group_ids(
    db: AsyncSession,
    user_id: int,
    account_id: int | None,
    group_ids: list[int],
) -> set[int]:
    """Подмножество `group_ids`, принадлежащее пользователю И этому аккаунту.

    Ровно то правило, которое страничный слой уже применяет через
    `_groups_of_account`, поднятое на уровень, доступный обоим входам. Оно
    двойное намеренно: связки по владельцу мало, потому что расписание не может
    нести группы другого аккаунта — иначе своя группа чужого канала уехала бы в
    рассылку, для которой она не подключена.

    Пустой аккаунт (законное состояние отвязанного расписания, issue #35) не
    даёт групп вовсе: групп «без аккаунта» не существует.
    """
    if account_id is None or not group_ids:
        return set()
    rows = await db.execute(
        select(Group.id).where(
            Group.id.in_(group_ids),
            Group.user_id == user_id,
            Group.account_id == account_id,
        )
    )
    return set(rows.scalars().all())
