async def _stale_subscription_intents(
    db: AsyncSession, user_id: int, now: datetime
) -> list[Payment]:
    """Подписочные намерения пользователя, ПРОСРОЧЕННЫЕ сроком давности.

    ЭТО СЕЛЕКТОР УБОРКИ, А НЕ ПОДСЧЁТА, И ИМЯ НАЗЫВАЕТ ИМЕННО РАБОТУ. Прежде эта
    функция отбирала НЕЗАКРЫТЫЕ и СВЕЖИЕ намерения — её читала прикладная
    проверка потолка. Проверки больше нет: потолок стал свойством схемы
    (`uq_payments_open_subscription_intent`), и у отбора осталась ровно одна
    работа — назвать строки, которые уборка обязана погасить.
    Закреплено `test_the_sweep_takes_exactly_what_the_index_counts`.

    ⚠️ УСЛОВИЕ ПО СТАТУСУ СУЖЕНО ДО РАВЕНСТВА `STATUS_PENDING`, И ЭТО ПРАВКА, А
    НЕ ПЕРЕНОС. Прежний отбор брал «всё, что вне `TERMINAL_STATUSES`», и довод
    под ним стоял такой: третий нетерминальный статус, добавленный когда-нибудь,
    обязан попасть в отбор сам. Для ПОДСЧЁТА это было верно; для УБОРКИ — ровно
    наоборот, и по двум причинам (закреплено
    `test_the_sweep_takes_exactly_what_the_index_counts`):

    * `STATUS_EXPIRED` в терминальные статусы не входит НАМЕРЕННО — на этом
      держится оплачиваемость погашенной строки. Отбор «вне терминальных»
      возвращал бы уже погашенные строки СНОВА при каждом создании платежа:
      уборка переписывала бы `expired` в `expired` и отдавала бы ненулевое число
      тронутых строк. Само по себе это идемпотентно, но счётчик уборки —
      величина, по которой разбирают ДЕНЕЖНЫЕ жалобы, и врать он не вправе ни
      разу. Закреплено `test_a_second_sweep_touches_nothing_and_says_so`;
    * уборка не считает, а ПИШЕТ по денежной таблице. Статус, о котором этот код
      ничего не знает, обязан остаться нетронутым: молча гасить неизвестное
      состояние — не то умолчание, которое ставят на денежном пути.

    ИТОГ: ОТБОР ЗЕРКАЛИТ ПРЕДИКАТ ИНДЕКСА (`kind = 'subscription' AND
    status = 'pending'`) и берёт РОВНО те строки, которые считает потолок, — ни
    одной сверх. Совпадение это несущее: разойдись они, уборка либо запирала бы
    человека (взяв уже, чем предикат), либо врала бы счётчиком (взяв шире).
    Закреплено `test_the_sweep_takes_exactly_what_the_index_counts`.

    ⚠️ СРОК ДАВНОСТИ ПРИМЕНЯЕТСЯ В PYTHON, А НЕ УСЛОВИЕМ SQL, И ЭТО НЕ ВКУС.
    Колонка объявлена `DateTime(timezone=True)`, но SQLite отдаёт её NAIVE, а
    PostgreSQL — aware. Сравнение, ушедшее в SQL, разошлось бы ровно на одном из
    двух диалектов: суита (SQLite) зеленела бы, а на бою (PostgreSQL) уборка
    вела бы себя иначе — то есть дефект ловился бы пользователем, а не тестом.
    Значение проходит через `normalize_utc` — тот же приём и та же причина, что
    у `next_expiry` и `subscription_is_live`.
    Закреплено `test_the_deadline_is_applied_in_python`.
    """
    rows = (
        (
            await db.execute(
                select(Payment).where(
                    Payment.user_id == user_id,
                    Payment.kind == KIND_SUBSCRIPTION,
                    Payment.status == STATUS_PENDING,
                )
            )
        )
        .scalars()
        .all()
    )

    cutoff = now - timedelta(hours=PENDING_INTENT_TTL_HOURS)
    stale = []
    for row in rows:
        born = normalize_utc(row.created_at)
        # Строка без времени рождения (её ещё не видела СУБД) считается СВЕЖЕЙ и
        # уборкой НЕ ТРОГАЕТСЯ: «неизвестно когда» на денежной строке означало
        # бы гашение по отсутствию данных, а это не то умолчание.
        # Закреплено `test_a_row_without_a_birth_time_is_left_alone`.
        if born is not None and born < cutoff:
            stale.append(row)
    return stale


async def _expire_stale_intents(
    db: AsyncSession, user_id: int, now: datetime
) -> int:
    """Гасит просроченные намерения пользователя. Возвращает число тронутых строк.

    ЛЕНИВАЯ УБОРКА НА СВОЁМ ЖЕ ПУТИ (D-02) — ТОЧНАЯ ИДИОМА `_claim_retry_slot`
    (`app/pages/history.py`), который снимает просроченные удержания чужих
    записей на пути того, кто пришёл ставить своё: обхода реестра нет нигде,
    периодической задачи под него не заведено, и уборка идёт там, где по ней всё
    равно проходят.
    Закреплено `test_a_stale_intent_is_swept_at_the_start_of_a_payment`.

    ДВА ОТВЕРГНУТЫХ ВАРИАНТА НАЗВАНЫ, ЧТОБЫ СЛЕДУЮЩИЙ ЧИТАТЕЛЬ НЕ ЗАВЁЛ ИХ
    ЗАНОВО. Что уборка идёт СИНХРОННО, на пути самого человека, закреплено
    `test_a_stale_intent_is_swept_at_the_start_of_a_payment`:

    * периодическая задача Celery beat — асинхронна (человек, прождавший сутки,
      остался бы заперт до ближайшего тика) и вводит ВТОРОГО ПИСАТЕЛЯ на
      денежный путь;
    * отмена намерения у ЮKassa — ВТОРОЙ сетевой вызов на денежном пути, и её
      отказ снова запирает человека. Что уборка обходится БЕЗ сети, видно по
      `test_a_stale_intent_is_swept_at_the_start_of_a_payment`: подменённый SDK
      в нём вызывается ровно за новым платежом, а не за отменой старого.

    ЦЕНА РАЗМЕНА НАЗВАНА, А НЕ ЗАМОЛЧАНА (D-02): строка, просроченная и не
    тронутая уборкой — потому что её владелец за оплатой больше не приходил, —
    остаётся `pending` и читается на экранах биллинга и админки как «в
    обработке». Это ЗАФИКСИРОВАННОЕ СЛЕДСТВИЕ, а не дефект: увидев такую строку,
    не заводите под неё ни обхода реестра, ни периодической задачи. Что уборка не
    дотягивается до чужих строк — то есть что цена именно такова, — закреплено
    `test_the_sweep_takes_exactly_what_the_index_counts`.

    ⚠️ КОММИТ ЗДЕСЬ СВОЙ, И ЭТО НЕСУЩЕЕ. Путь отказа потолка откатывает точку
    сохранения резерва; уборка, не зафиксированная отдельно, уехала бы в тот же
    откат — человек, чьё просроченное намерение только что убрали, получил бы
    отказ И потерю уборки одновременно.
    Закреплено `test_the_sweep_survives_a_refused_reserve`.

    Пустой отбор — ранний выход с нулём, БЕЗ оператора и без коммита.
    """
    stale = await _stale_subscription_intents(db, user_id, now)
    if not stale:
        return 0

    result = await db.execute(
        update(Payment)
        .where(Payment.id.in_([row.id for row in stale]))
        .values(status=STATUS_EXPIRED)
        .execution_options(synchronize_session=False)
    )
    await db.commit()
    # Число ТРОНУТЫХ строк, а не число проходов: по этому счётчику разбирают
    # денежные жалобы («почему моё намерение погасло»), и отбор сужен до
    # `STATUS_PENDING` ровно ради его честности.
    logger.info(
        "stale_subscription_intents_expired",
        user_id=user_id,
        expired=result.rowcount,
    )
    return result.rowcount


