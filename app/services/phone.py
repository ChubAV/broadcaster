"""Форма номера телефона аккаунта: E.164 на хранение, разбивка на показ.

Модуль РЕШАЕТ ФОРМУ НОМЕРА И НИЧЕГО НЕ ПИШЕТ. Базы и сети здесь нет (D-12):
только `phonenumbers` и стандартная библиотека. Писать номер в колонку —
забота единственного писателя (`app/application/accounts/phone.py`, план
16-05); здесь лишь ответ на вопрос «какая строка E.164 стоит за этим вводом».

⚠️ ПРАВИЛО ОДНО, А ПОЛИТИКА У КАЖДОГО ВХОДА СВОЯ — так же, как в
`schedule_rules.py`. Входов два, и отказ у них выглядит по-разному:

- РУЧНОЙ ввод человека (`normalize_manual`, форма Фазы 18) ОБЪЯСНЯЕТ отказ:
  поднимает `PhoneError` с русским текстом и примером, потому что человек
  может исправить написание.
- АВТОМАТИЧЕСКИЙ источник (`normalize_reported`, ответ мессенджера или
  воркера) МОЛЧА ОТДАЁТ `None`: объяснять некому, а исключение уронило бы
  вход аккаунта из-за сбоя источника. Старый воркер без номера или мусор в
  ответе оставляют номер неизвестным (PHONE-15), а не превращаются в «номер».

ПОЧЕМУ В АВТОПУТИ НЕТ ПРОВЕРКИ «ВОЗМОЖНОСТИ» НОМЕРА. Анонимные номера
Fragment (`+888…`) библиотека считает слишком короткими (`TOO_SHORT`), хотя
Telegram выдаёт их настоящим аккаунтам. Проверка «возможности» в автопути
молча теряла бы такой номер навсегда. Вместо неё автопуть требует одних цифр
ASCII в пределах 5…15 и успешного разбора с кодом страны.

ПОЧЕМУ ВАЛИДАТОР «ДЕЙСТВИТЕЛЬНОСТИ» НОМЕРА НЕ ПРИМЕНЯЕТСЯ ВОВСЕ (D-05).
Он сверяет номер с метаданными нумерации, а метаданные отстают от операторов:
вчера выданный диапазон он назвал бы недействительным, Fragment — тоже. Ложный
отказ здесь хуже пропуска: номер, сообщённый мессенджером, заведомо настоящий.

Fragment попадает в базу ТОЛЬКО автопутём (решение владельца О-1, 2026-10-08).

⚠️ ПРИВАТНОСТЬ (D-18, PHONE-21). Модуль не пишет журналов и не печатает; ни
номер, ни его цифры не попадают в текст исключения — тексты отказа закрыты
набором констант, а исключение библиотеки не сцепляется с нашим.
"""

import phonenumbers
from phonenumbers import NumberParseException, PhoneNumberFormat

# Границы числа цифр автоисточника. Верхняя — предел E.164 (не больше 15
# цифр вместе с кодом страны); нижняя — самый короткий номер, который ещё
# имеет смысл хранить (код страны плюс абонентская часть). Всё, что вне
# границ, — сбой источника, а не номер.
REPORTED_MIN_DIGITS = 5
E164_MAX_DIGITS = 15

# Регион ручного ввода: номер без кода страны человек из России пишет как
# `8 999 …` или `999 …`, и разбор обязан понять его как российский.
MANUAL_REGION = "RU"

# Предел сырого ручного ввода (D-14), меряется по строке КАК ПРИШЛА — до
# разбора. Самое длинное честное написание (`+7 (999) 123-45-67` с пробелами
# по краям) укладывается с запасом; всё длиннее отвергается, не доходя до
# библиотеки и до колонки `String(16)`.
MANUAL_INPUT_MAX_CHARS = 32

# Пример в каждом тексте отказа: человек видит, как написать правильно.
EXAMPLE_PHONE = "+7 999 123-45-67"

# Тексты отказа ручного ввода — ЗАКРЫТЫЙ НАБОР констант (D-18, PHONE-21).
# Ввод в них не подставляется никогда: исключение может уйти в журнал, а номер
# в журнал не попадает. Показывает тексты форма ручной правки Фазы 18.
PHONE_ERROR_BLANK = f"Введите номер телефона. Пример: {EXAMPLE_PHONE}"
PHONE_ERROR_TOO_LONG = (
    f"Слишком длинный ввод: не больше {MANUAL_INPUT_MAX_CHARS} символов "
    f"и {E164_MAX_DIGITS} цифр. Пример: {EXAMPLE_PHONE}"
)
PHONE_ERROR_EXTENSION = (
    f"Добавочный номер не поддерживается — укажите номер без него. Пример: {EXAMPLE_PHONE}"
)
PHONE_ERROR_NOT_A_NUMBER = f"Не похоже на номер телефона. Пример: {EXAMPLE_PHONE}"
PHONE_ERROR_MESSAGES = (
    PHONE_ERROR_BLANK,
    PHONE_ERROR_TOO_LONG,
    PHONE_ERROR_EXTENSION,
    PHONE_ERROR_NOT_A_NUMBER,
)


class PhoneError(ValueError):
    """Ручной ввод не сводится к номеру; текст — один из `PHONE_ERROR_MESSAGES`."""


def normalize_manual(text: str) -> str:
    """Ручной ввод → E.164 или `PhoneError` (заготовка RED)."""
    return text


def normalize_reported(raw: object) -> str | None:
    """Номер от мессенджера (строка или целое) → E.164 или `None` (D-05, D-15).

    Источник отдаёт номер то строкой без `+` (`"79991234567"`), то с `+`, то
    целым числом — все три сводятся к одной строке. Регион не подставляется:
    у автоисточника номер всегда полный, с кодом страны, и дописанный `+`
    говорит об этом разбору прямо.

    `None` — номер неизвестен: на `None`, `bool`, пустой строке, на чём-либо
    кроме одних цифр ASCII (скобки, сырой JID `79991234567:12`), на длине вне
    `REPORTED_MIN_DIGITS…E164_MAX_DIGITS` и на несуществующем коде страны.
    `bool` отсекается явно: `True` — подкласс `int`, и полагаться на то, что
    `str(True)` не пройдёт проверку цифр, значило бы держать правило на
    случайности.
    """
    if raw is None or isinstance(raw, bool):
        return None
    digits = str(raw).strip()
    if digits.startswith("+"):
        digits = digits[1:]
    if not (digits.isascii() and digits.isdigit()):
        return None
    if not REPORTED_MIN_DIGITS <= len(digits) <= E164_MAX_DIGITS:
        return None
    try:
        number = phonenumbers.parse("+" + digits, None)
    except NumberParseException:
        return None
    return phonenumbers.format_number(number, PhoneNumberFormat.E164)


def format_phone(stored: str) -> str:
    """Сохранённый номер → международная разбивка своей страны для показа.

    Разбивка у каждой страны своя (`+7 999 123-45-67` у России,
    `+7 701 123 4567` у Казахстана, `+888 01234567` у Fragment), поэтому её
    решает библиотека, а не шаблон. Значение, которое не разбирается, но лежит
    в колонке, показывается КАК ЕСТЬ (D-06): спрятать его под «неизвестен»
    значило бы солгать о состоянии аккаунта. Пустой номер (`None`) — забота
    подписи Фазы 17, а не этой функции.
    """
    try:
        number = phonenumbers.parse(stored, None)
    except NumberParseException:
        return stored
    return phonenumbers.format_number(number, PhoneNumberFormat.INTERNATIONAL)


def mask_phone(stored: str) -> str:
    """Сохранённый номер → маска для человека (заготовка RED)."""
    return stored
