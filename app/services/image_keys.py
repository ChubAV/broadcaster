"""Форма ключа вложения и правило владения им, общие для обоих слоёв.

Модуль НЕЙТРАЛЕН: от него зависят и страничный слой, и JSON-API, а сам он не
зависит ни от одного из них. Прежде правило жило в `app/pages/ads.py`, и
`app/routes/ads.py` импортировал его оттуда — то есть JSON-API затягивал в свой
граф импорта окружение Jinja, глобалы изображений и шесть модулей моделей и
стоял в одном импорте от цикла (WR-04). Правило при этом обязано быть ОДНИМ:
разъехавшись, входы оставили бы дыру ровно там, где её не проверяли.
"""

import re

from fastapi import HTTPException, status

# Список ключей вложений приходит скрытыми полями формы (и телом JSON на
# API-входе) и полностью управляем клиентом: он ключ ОБЪЯВЛЯЕТ, но не доказывает
# ни его формы, ни принадлежности отправителю. Без проверки объявление
# сохраняется с ключом из чужого префикса того же хранилища, и чужое изображение
# начинает отдаваться в карточке, истории и админке (WR-01 / T-10-04).
#
# Форма ключа — источник правды `app/services/image_upload.py`:
# `{user_id}/{32 hex}_{имя}`, где `uuid4().hex` даёт ровно 32 шестнадцатеричных
# символа, а `safe_filename` сводит имя к `[A-Za-z0-9._-]` длиной до 100.
# ⚠️ ССЫЛКА ОБНОВЛЕНА ПЕРЕЕЗДОМ (Фаза 12, план 12-05), А ТЕКСТ ПРАВИЛА — НЕТ:
# прежде источником правды назывался модуль маршрута слоя JSON-API, снятый тем же
# планом целиком (D-03). Форма ключа не менялась ни на символ.
#
# Якорей `^` и `$` в образце НЕТ, и сопоставление идёт методом `fullmatch`:
# якорь `$` в Python совпадает и непосредственно перед завершающим переводом
# строки, поэтому с ним и с `match` значение `"7/<32 hex>_a.png\n"` проходило
# проверку и ложилось в `Ad.images` дословно — оттуда оно попадает в адрес
# изображения и в адаптеры мессенджеров.
#
# Первый разряд префикса ненулевой: маршрут загрузки подставляет туда
# `user_id` десятичной записью, и `007/…` — ключ, которого он выдать не мог.
_IMAGE_KEY_PATTERN = re.compile(r"([1-9][0-9]*)/[0-9a-f]{32}_[A-Za-z0-9._-]{1,100}")

INACCESSIBLE_IMAGE_MESSAGE = (
    "Одно из вложений недоступно. Обновите страницу и добавьте изображение заново."
)

# Приставка ключа МИНИАТЮРЫ (issue #40). Выбрана она не за красоту адреса: до
# первого слэша образец выше требует ТОЛЬКО цифры, а `thumbs` — не цифры,
# поэтому производный ключ образец не проходит и в `Ad.images` попасть не может
# ни через скрытое поле формы, ни через тело JSON. Приставка — и есть механизм
# запрета; проверяется он регрессией
# `test_a_thumbnail_key_is_not_a_storable_attachment`, а не рассуждением о
# выбранном слове.
#
# Зачем запрет вообще нужен. Миниатюра — объект, СОЗДАННЫЙ приложением из уже
# проверенного ключа, и владения им никто не подтверждал: разреши образец такой
# ключ, и отправитель прикрепил бы к объявлению чужую миниатюру, у которой
# префикс пользователя стоит не первым звеном, а вторым (T-Q40-04).
#
# Вторая сторона выбора — эксплуатационная: приставка отделяет производные
# объекты от хранимых на уровне бакета, поэтому правило жизненного цикла
# (например, «пересоздаваемое хранить меньше») задаётся для них позже одной
# записью по префиксу, а не перебором ключей.
THUMB_KEY_PREFIX = "thumbs/"


def thumb_key(key: str) -> str:
    """Вывести ключ миниатюры из ключа вложения.

    Функция ЧИСТАЯ и владения не проверяет: она применяется к значению, уже
    прошедшему ``own_image_keys`` (или только что выданному маршрутом загрузки),
    и своего решения о доступе не принимает.

    Идемпотентна намеренно. Адрес миниатюры строится на двух сторонах — в
    маршруте загрузки и в шаблонном глобале, — и двойное применение по
    недосмотру дало бы `thumbs/thumbs/…`, то есть ссылку на объект, которого
    нет: пользователь увидел бы пустую плитку вместо картинки, а причина жила бы
    в адресе, а не в хранилище.

    Пустое значение остаётся пустым: приставка сама по себе адресом объекта не
    является, и превращать «картинки нет» в «есть картинка по адресу приставки»
    нельзя.
    """
    if not key:
        return ""
    if key.startswith(THUMB_KEY_PREFIX):
        return key
    return f"{THUMB_KEY_PREFIX}{key}"


def partition_own_image_keys(
    values: list[str], user_id: int
) -> tuple[list[str], list[str]]:
    """Разделить присланные значения на СВОИ и виновные, сохранив порядок.

    ⚠️ ЕДИНСТВЕННОЕ МЕСТО В ДЕРЕВЕ, ГДЕ РЕШАЕТСЯ ВОПРОС «МОЙ ЛИ ЭТО КЛЮЧ».
    Через эту функцию выражена и ``own_image_keys``: второго написания сравнения
    в проекте нет намеренно (D-07). Два авторитета по принадлежности разошлись
    бы молча и оставили бы дыру ровно там, где её не проверяли (Hyrum).

    ЗАЧЕМ НУЖНА РАЗДЕЛЯЮЩАЯ ФОРМА, а не только отказ. У двух вызывающих разные
    вопросы. Сохранение объявления решает, что записать в базу, и обязано
    ОТКАЗАТЬ целиком: частичная запись превратила бы попытку подмены в
    «успешное сохранение без картинки». Маршрут загрузки решает, что показать на
    экране, — и «всё или ничего» там значит СТИРАНИЕ: полоса вложений есть
    единственный источник списка ключей в документе, и пустой ответ выносит из
    него скрытые поля вместе с законными. Ему нужно «что подтверждено, то
    остаётся на экране», а отвергается только виновное.

    Порядок каждой половины — исходный: порядок ключей есть порядок отправки.
    """
    own: list[str] = []
    offending: list[str] = []
    for value in values:
        match = _IMAGE_KEY_PATTERN.fullmatch(value)
        # Префикс сравнивается как СТРОКА: приведение группы к целому принимало
        # бы `007/…` за `7/…`, то есть допускало бы ключ, которого маршрут
        # загрузки для этого вызывающего никогда не порождал.
        if match is None or match.group(1) != str(user_id):
            offending.append(value)
        else:
            own.append(value)
    return own, offending


def own_image_keys(values: list[str], user_id: int, max_images: int) -> list[str]:
    """Проверить, что каждый ключ вложения принадлежит вызывающему.

    Возвращает список в исходном порядке загрузки. Поднимает ``HTTPException``
    с кодом 400, если значение не соответствует форме ключа, лежит вне префикса
    вызывающего или если вложений больше ``max_images``.

    Отказ, а не молчаливое отбрасывание значения: отбрасывание превратило бы
    попытку подмены в «успешное сохранение без картинки» и скрыло бы её от
    пользователя, оставив в БД тихо расходящееся с формой состояние.

    Отказ оформлен ``HTTPException`` на обоих слоях сознательно. Страничный слой
    в этом проекте отвечает редиректами, но редирект здесь означал бы потерю
    данных без объяснения: пользователь увидел бы список объявлений и не узнал,
    что сохранение не состоялось. Ошибка по данным — не навигация.
    """
    if len(values) > max_images:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=(
                f"Объявление не сохранено: вложений больше {max_images}. "
                "Удалите лишние и нажмите «Сохранить»."
            ),
        )

    # Предикат принадлежности берётся у ``partition_own_image_keys`` и вторым
    # разом здесь не пишется (D-07). Поведение этой функции при этом не
    # сдвинуто ни на символ: первое же виновное значение даёт тот же отказ 400 с
    # тем же текстом, а при пустом ``offending`` подтверждённое подмножество
    # совпадает с входом целиком и в исходном порядке.
    own, offending = partition_own_image_keys(values, user_id)
    if offending:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=INACCESSIBLE_IMAGE_MESSAGE,
        )

    return own
