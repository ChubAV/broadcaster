# ШИРИНА ОКНА ВЕЛИЧИНЫ УШЕДШИХ, В СУТКАХ (D-41 буквально).
#
# ⚠️ ЭТО ЕДИНСТВЕННОЕ ЧИСЛО ПОДРАЗДЕЛА БЕЗ ГОТОВОГО ОБЪЯВЛЕНИЯ В ПРОЕКТЕ, и
# поэтому оно объявлено ЗДЕСЬ ОДНОЙ СТРОКОЙ. В подпись величины оно приезжает
# подстановкой, а не выписывается в текст экрана: копия числа в копирайте
# разошлась бы с окном молча — экран называл бы один срок, а считалось бы по
# другому, и заметить это можно было бы только пересчитав руками.
#
# ПОЧЕМУ МЕСЯЦ. Подписка продлевается помесячно, поэтому окно короче месяца
# считало бы ушедшими тех, кто просто ещё не дошёл до оплаты, а окно длиннее
# смешивало бы два разных месяца в одно число. Смена значения — правка ЭТОЙ
# строки, и подпись на экране поедет за ней сама.
EXPIRED_LOOKBACK_DAYS = 30


# --- Оси фильтра журнала ------------------------------------------------------
#
# ⚠️ ОСЬ ОБЪЯВЛЕНА ОДНИМ СЛОВАРЁМ, А ЧИПСЫ И ДОПУСТИМЫЕ ЗНАЧЕНИЯ ВЫВЕДЕНЫ ИЗ
# НЕГО. Выписанный второй раз перечень — ровно тот способ, которым чипс
# переживает снятие своего условия: подпись рисуется, значение принимается,
# выражения за ним нет, и экран при этом исправен на вид. Тот же приём уже стоит
# у окон журнала логов (`LOG_WINDOW_CHIPS`) и у осей списка пользователей.
#
# ⚠️ САНАЦИЯ ВСТРОЕНА В ПОИСК УСЛОВИЯ, А НЕ ПРИСТАВЛЕНА К НЕМУ СБОКУ. Значение
# приезжает строкой адреса — из ссылки, закладки или чужого сообщения
# (T-06-PAY3) — и служит КЛЮЧОМ в замкнутом словаре. Неизвестный ключ не находит
# условия, то есть означает «все», и в выражение не попадает ВОВСЕ: ни сырым, ни
# экранированным. Отдельный отсекатель рядом можно было бы забыть позвать;
# словарь забыть нельзя — без него нет условия.


@dataclass(frozen=True, slots=True)
class _StatusAxis:
    """Подпись чипса и условие за ним — ОДНОЙ записью.

    Разложенные по двум словарям, они разъезжаются: значение остаётся в
    подписях, теряется в условиях, и чипс продолжает рисоваться, ничего не
    отбирая.
    """

    label: str
    clause: object


# ⚠️ «В ОБРАБОТКЕ» ОТБИРАЕТСЯ ПО ОБЪЯВЛЕННОМУ МНОЖЕСТВУ НАБЛЮДАЕМЫХ СТАТУСОВ, А
# НЕ ПО ДОПОЛНЕНИЮ ТЕРМИНАЛЬНЫХ (§Pitfall 12, D-01, план 08-11). Правило
# по-прежнему ОДНО и берётся у признака инцидента ОБЪЕКТОМ
# (`unclosed_payment_clause`), а не копируется: копия разошлась бы с оригиналом
# молча. Изменилась ФОРМА правила — оно стало положительным, и вместе с ней
# изменился состав чипса: снятое по сроку давности намерение (`expired`) под
# него больше не приходит. Подпись чипса впервые совпадает со словом, которым
# те же строки печатает `PAY_LABELS`: слово подписи взято у пользовательского
# раздела дословно (05.1-UI-SPEC), и одно состояние называется одним словом и у
# человека, и у администратора.
#
# ⚠️ ЧЕТВЁРТЫЙ ЧИПС ДЛЯ `expired` НЕ ЗАВЕДЁН, И ЭТО НАЗВАННАЯ ЦЕНА. Просроченная
# строка читается в журнале под «Все» и своего чипса не имеет; заводить его
# внутри правки-закрытия значило бы расширять продуктовую поверхность. Условие
# возврата записано прямо: понадобится администратору искать просроченные
# намерения списком — чипс добавляется ОДНОЙ записью этого словаря, потому что
# и подписи (`PAYMENT_STATUS_CHIPS`), и допустимые значения
# (`PAYMENT_STATUS_VALUES`) выводятся из него самого.
PAYMENT_STATUS_FILTERS: dict[str, _StatusAxis] = {
    "succeeded": _StatusAxis("Проведённые", lambda: Payment.status == STATUS_SUCCEEDED),
    "canceled": _StatusAxis("Отклонённые", lambda: Payment.status == STATUS_CANCELED),
    "unclosed": _StatusAxis("В обработке", unclosed_payment_clause),
}

# ⚠️ ОКНА НАЗВАНЫ ДЛИТЕЛЬНОСТЬЮ, А НЕ СЛОВОМ «СЕГОДНЯ». Слово «сегодня» уже
# занято разделом истории, и означает оно там ЛОКАЛЬНУЮ полночь пользователя
# (D-30) — величину, которой у административного журнала нет: он смотрит на
# платежи всех людей сразу, и чья именно полночь считалась бы «сегодня»,
# ответить нечем. Скользящее окно с честным именем не врёт ни одному читателю,
# а второе значение одного слова на соседних экранах — врёт обоим. Форма
# объявления взята у окон журнала логов, где стоит тот же довод.
PAYMENT_PERIOD_WINDOWS: dict[str, tuple[str, timedelta]] = {
    "24h": ("24 часа", timedelta(hours=24)),
    "7d": ("7 дней", timedelta(days=7)),
    "30d": ("30 дней", timedelta(days=30)),
}

# Вариант «все» стоит ПЕРВЫМ у обеих осей — как у обеих осей списка
# пользователей. Он не несёт значения и существует затем, чтобы снять фильтр
# можно было нажатием, а не правкой адреса руками.
PAYMENT_STATUS_CHIPS: tuple[tuple[str, str], ...] = (("", "Все"),) + tuple(
    (value, axis.label) for value, axis in PAYMENT_STATUS_FILTERS.items()
)
PAYMENT_PERIOD_CHIPS: tuple[tuple[str, str], ...] = (("", "Всё время"),) + tuple(
    (value, label) for value, (label, _) in PAYMENT_PERIOD_WINDOWS.items()
)

PAYMENT_STATUS_VALUES = frozenset(PAYMENT_STATUS_FILTERS)
PAYMENT_PERIOD_VALUES = frozenset(PAYMENT_PERIOD_WINDOWS)


def apply_payment_filters(
    query: Select,
    *,
    status: str | None = None,
    period: str | None = None,
    now: datetime,
) -> Select:
    """Навешивает обе оси на готовую выборку платежей.

    ⚠️ ЭТА ФУНКЦИЯ — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ УСЛОВИЯ ЖУРНАЛА СТРОЯТСЯ. И строки,
    и счёт над ними проходят через неё; второго набора `where` рядом нет и быть
    не должно (D-34). Раздельные выражения для выдачи и счёта уже давали в
    проекте расхождение «показано не то, что посчитано», и администратор,
    прочитавший «платежей 12» под одиннадцатью строками, перестаёт верить обоим
    числам сразу.
    """
    axis = PAYMENT_STATUS_FILTERS.get(status or "")
    if axis is not None:
        query = query.where(axis.clause())

    window = PAYMENT_PERIOD_WINDOWS.get(period or "")
    if window is not None:
        # Момент приводится к единой зоне ДО арифметики: наивный `now` из
        # вызывающего дал бы отсечку, несравнимую с колонкой на одном из двух
        # диалектов.
        query = query.where(Payment.created_at > normalize_utc(now) - window[1])

    return query


# --- Величина ушедших (D-41) --------------------------------------------------


async def expired_not_renewed(session: AsyncSession, *, now: datetime) -> int:
    """Сколько людей истекло и не продлило за окно.

    ОПРЕДЕЛЕНИЕ ЦЕЛИКОМ: дата окончания подписки в прошлом, но не старше окна, и
    после этой даты нет НИ ОДНОГО успешного платежа. Оно помещается в подпись
    экрана — ровно затем и выбрано вместо доли, которую подписка без истории
    продлений честно не даёт.

    ⚠️ ПРОДЛЕНИЕ ИЩЕТСЯ В ЖУРНАЛЕ ПЛАТЕЖЕЙ, А НЕ В СТРОКЕ ПОДПИСКИ. Строка
    сдвигает свою дату при продлении и прошлых значений не хранит, поэтому
    «продлил ли он» — вопрос к `Payment` и только к нему. Успешным считается
    ТОЛЬКО терминально успешный платёж: незакрытый и отклонённый деньгами не
    стали, и человек, отказавшийся от оплаты у платёжного провайдера, из
    величины не выпадает.

    ⚠️ СЧИТАЮТСЯ ЛЮДИ, А НЕ СТРОКИ. История подписок пользователя лежит в тех же
    строках, и счёт строк дал бы человека столько раз, сколько у него
    деактивированных периодов. Условие активности отсекает их и без этого, но
    различный счёт — свойство величины, а не следствие соседнего условия.

    ⚠️ ТРИ УСЛОВИЯ ПОДПИСКИ ПРИХОДЯТ ИЗ СЛОЯ ДОСТУПА К ДАННЫМ, А НЕ ВЫПИСАНЫ
    ЗДЕСЬ. Одно из них читает признак бесплатного доступа, а в `app/application/`
    его читает РОВНО ОДИН файл — предикат доступа; правило машинное
    (`test_the_free_access_flag_is_read_in_exactly_one_place_of_the_decision`), и
    вторая копия здесь развела бы одно правило по двум выражениям. Тот же довод
    уже записан над счётом платящих (`overview_stats.paying_total`).
    """
    moment = normalize_utc(now)
    since = moment - timedelta(days=EXPIRED_LOOKBACK_DAYS)

    renewed = (
        select(Payment.id)
        .where(
            Payment.user_id == Subscription.user_id,
            Payment.status == STATUS_SUCCEEDED,
            Payment.created_at > Subscription.expires_at,
        )
        .exists()
    )

    query = select(func.count(func.distinct(Subscription.user_id))).where(
        *expired_not_renewed_clauses(moment, since), ~renewed
    )
    return (await session.execute(query)).scalar() or 0


