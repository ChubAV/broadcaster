"""Величина ушедших и журнал платежей админского подраздела «Платежи» (ADMIN-10).

ГРАНИЦЫ МОДУЛЯ (по образцу `queue_rows.py`, `users_query.py` и `overview_stats.py`).
Модуль знает про запрос к базе и НЕ знает ни про Jinja, ни про `Request`, ни про
подписи чипсов в разметке: он принимает значения фильтров и отдаёт числа и
строки. Права администратора проверяет обработчик — здесь их нет и быть не
должно.

⚠️ ВЫРУЧКИ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК. Она уже посчитана в
`overview_stats.py` — там же, где живут «люди и деньги» «Обзора», — двумя
функциями: счётом платящих по трём условиям (D-38) и умножением его на цену
доступа. Подраздел «Платежи» зовёт ТЕ ЖЕ ДВЕ, а не заводит третью: одна и та же
величина, посчитанная в двух местах, рано или поздно даёт два разных числа на
двух экранах одной админки, и узнаётся это по жалобе на то, что «MRR на обзоре
не сходится с MRR в платежах». Ровно этот довод уже записан в `overview_stats`
про счёт отправок (D-35, D-39); здесь он применён к деньгам.

⚠️ СРЕДНЕЙ ВЕЛИЧИНЫ ПЛАТЕЖА НЕТ И БЫТЬ НЕ МОЖЕТ (D-41). Цена в продукте одна,
поэтому такая величина тождественно равна ей: она заняла бы место показателя,
ничего не измеряя, а первый же взгляд на неё создал бы впечатление измерения там,
где его нет. Отсутствие закреплено гейтом по тексту этого файла
(`tests/test_application/test_admin_payments.py`).

⚠️ ДОЛИ УШЕДШИХ НЕТ ТОЖЕ, И ВМЕСТО НЕЁ СТОИТ ЧИСЛО, НАЗЫВАЮЩЕЕ РОВНО ТО, ЧТО
СЧИТАЕТ. Подписка одна на пользователя, дата окончания сдвигается при продлении,
и истории продлений строка подписки НЕ ХРАНИТ — она живёт только в журнале
платежей. Доля, посчитанная из имеющегося, была бы числом, чьё определение никто
не сможет назвать через месяц; «истекло и не продлено за окно» помещается в
подпись целиком.
"""
