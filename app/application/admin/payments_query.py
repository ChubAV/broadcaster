# ПРЕДМЕТ ПОКУПКИ — ЗАМКНУТОЕ МНОЖЕСТВО ИЗ ТРЁХ СТРОК, И СОБИРАЕТСЯ ОНО ЗДЕСЬ, А
# НЕ В РАЗМЕТКЕ.
#
# ⚠️ ТАРИФНОГО ПЛАНА ПЛАТЕЖА В ЭТОМ МНОЖЕСТВЕ НЕТ НИ В ОДНОЙ ВЕТКЕ (D-42).
# Колонка осталась в хранилище и заполнена у исторических платежей, но тарифов в
# продукте больше нет: напечатанное имя старого тарифа сообщило бы
# администратору, что они живы, — и он стал бы отвечать так же клиентам.
# Основание ПО СУЩЕСТВУ, а не подчинение проверке: исследование фазы проверило
# прямо, что голое имя колонки не подпадает ни под один существующий запрет
# (Ф-10), и обходить или расширять его не нужно.
#
# ⚠️ ЗАПРЕТ ЗАКРЫТ ФОРМОЙ СТРОКИ, А НЕ ДИСЦИПЛИНОЙ ШАБЛОНА. Из модуля уезжает
# готовая подпись, а не строка модели, поэтому дотянуться из разметки до
# тарифного плана НЕЛЬЗЯ — его там просто нет. Правило, исполняемое человеком,
# держится до первого, кто решит, что «в одной колонке можно»; правило,
# исполняемое формой данных, не держать невозможно. Тем же движением из разметки
# исчезает идентификатор платежа во внешней платёжной системе — ключ подделки
# уведомления об оплате, чей запрет старше этого подраздела (T-06-PAY1).
PURPOSE_SUBSCRIPTION = "Доступ к системе"
PURPOSE_PACKAGE = "Пакет сообщений"


def _purpose(kind: str | None, package_name: str | None) -> str:
    """Предмет платежа словами.

    Подписочный платёж называется доступом — тем же словом, каким его называет
    раздел пользователя. Не подписочный несёт имя пакета; пустое имя даёт
    родовую подпись, а не пустую ячейку: пустое место в денежном журнале
    читается как «строка неполная».
    """
    if kind == KIND_SUBSCRIPTION:
        return PURPOSE_SUBSCRIPTION
    return package_name or PURPOSE_PACKAGE


@dataclass(frozen=True, slots=True)
class PaymentLedgerRow:
    """Строка журнала — ЗНАЧЕНИЯМИ, а не строкой модели.

    Состав закрыт пятью величинами колонок плюс идентификаторами, по которым
    строится переход к пользователю. Перевёрстка не является основанием показать
    больше: строка модели несёт и тарифный план (D-42), и ключ платежа во
    внешней системе (T-06-PAY1), и оба обязаны быть недостижимы из разметки по
    построению, а не по договорённости.

    Имени пользователя может не быть: строка платежа переживает удаление
    человека только в обход внешнего ключа, но денежный журнал обязан показать
    её и тогда — исчезнувший платёж хуже платежа без имени.
    """

    payment_id: int
    created_at: datetime | None
    user_id: int
    user_name: str | None
    amount_value: str | None
    purpose: str
    status: str


@dataclass(frozen=True, slots=True)
class PaymentLedger:
    """Строки журнала вместе с числами, которые печатаются рядом с ним.

    Числа едут ВМЕСТЕ со строками одним значением намеренно: подпись потолка и
    сам список обязаны приходить из одного источника, иначе они разойдутся —
    сперва ровно на потолке, потом везде.
    """

    rows: list[PaymentLedgerRow]
    total: int
    truncated: bool
    cap: int


async def payment_ledger(
    session: AsyncSession,
    *,
    status: str | None = None,
    period: str | None = None,
    now: datetime,
) -> PaymentLedger:
    """Журнал платежей под обеими осями, от свежих к старым, с честным потолком.

    ⚠️ ПОТОЛОК СВЕРЯЕТСЯ ДО КОНСТРУИРОВАНИЯ СПИСКА, а признак его срабатывания
    едет ОТДЕЛЬНЫМ полем. Вывести срабатывание из длины уже выбранного списка
    нельзя: ровно на потолке список полон, и «показано не всё» стало бы
    неотличимо от «столько и есть». Приём тот же, что у журнала платежей раздела
    пользователя и у потолка выгрузки истории.

    ⚠️ ПОТОЛОК ВЗЯТ У ПРОЕКТА, А НЕ НАЗНАЧЕН ЗДЕСЬ. Комментарий объявления
    (`app/constants.py`) прямо называет этот подраздел потребителем значения, и
    второе число разошлось бы с первым молча: раздел человека и подраздел
    администратора обещали бы разные «последние N».

    ⚠️ ЧИСЛО ОБРАЩЕНИЙ К БАЗЕ ПОСТОЯННО И РАВНО ДВУМ — счёт и строки, — сколько
    бы платежей ни лежало под фильтром, и имя пользователя приезжает ТЕМ ЖЕ
    запросом. Запрос на строку ради имени стоил бы числа обращений, растущего
    вместе с числом платежей сервиса, — а этот подраздел видит их все сразу.

    ⚠️ ПРИСОЕДИНЕНИЕ ИМЕНИ ВНЕШНЕЕ. Внешний ключ платежа объявлен с каскадным
    удалением, поэтому платежа без человека в норме не бывает; внутреннее
    присоединение тем не менее УРОНИЛО БЫ такую строку из денежного журнала
    молча, а молча пропавший платёж — худший из возможных исходов для экрана,
    ради которого в подраздел и приходят.

    ⚠️ ПОРЯДОК ДОБИРАЕТСЯ ИДЕНТИФИКАТОРОМ. Платежи, созданные в одну секунду,
    без второго ключа сортировки раскладываются как придётся, и потолок отрезал
    бы у них разные строки при двух одинаковых запросах.
    """
    cap = PAYMENT_LIST_CAP

    total = (
        await session.execute(
            apply_payment_filters(
                select(func.count(Payment.id)), status=status, period=period, now=now
            )
        )
    ).scalar() or 0

    query = apply_payment_filters(
        select(
            Payment.id,
            Payment.created_at,
            Payment.user_id,
            Payment.kind,
            Payment.package_name,
            Payment.amount_value,
            Payment.status,
            User.name,
        ).outerjoin(User, User.id == Payment.user_id),
        status=status,
        period=period,
        now=now,
    )
    query = query.order_by(Payment.created_at.desc(), Payment.id.desc()).limit(cap)

    rows = [
        PaymentLedgerRow(
            payment_id=row.id,
            # Момент приводится к единой зоне ЗДЕСЬ, на выходе из базы: SQLite
            # отдаёт колонку наивной, PostgreSQL — с зоной, и дефект, оставленный
            # тут, существовал бы ровно на одном из двух диалектов.
            created_at=normalize_utc(row.created_at),
            user_id=row.user_id,
            user_name=row.name,
            amount_value=row.amount_value,
            purpose=_purpose(row.kind, row.package_name),
            status=row.status,
        )
        for row in (await session.execute(query)).all()
    ]

    return PaymentLedger(rows=rows, total=total, truncated=total > cap, cap=cap)
