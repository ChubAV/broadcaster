"""Выборка пользователей админского подраздела: поиск, две оси, страница, счёт.

ГРАНИЦЫ МОДУЛЯ (по образцу `app/application/admin/queue_rows.py`). Модуль знает
про запрос к базе и НЕ знает ни про Jinja, ни про Request, ни про подписи чипсов
в разметке: он принимает значения фильтров и отдаёт строки со счётом. Права
администратора проверяет обработчик — здесь их нет и быть не должно.

⚠️ ГЛАВНОЕ СВОЙСТВО МОДУЛЯ ОДНО: ПОИСК, ОБЕ ОСИ, СТРАНИЦА И СЧЁТ СЧИТАЮТСЯ
ОДНИМ ВЫРАЖЕНИЕМ (D-34). Условия навешивает РОВНО ОДНА функция —
`apply_user_filters`, — и `count_users` зовёт её же, а не переписанный рядом
набор `where`. Это не стилистика: раздельные выражения для выдачи и счёта уже
давали в проекте расхождение «показано не то, что посчитано» (раздел истории,
Фаза 4), и закрыто оно было ровно общим выражением фильтров. Повтор дефекта
здесь означает администратора, который видит «найдено 12», листает и не находит
человека, за которым пришёл.

⚠️ ВЫБОРКИ БЕЗ ПРЕДЕЛА НА ПУТИ ПОДРАЗДЕЛА НЕТ (D-33, T-06-USR2). Прежний список
тянул всю таблицу пользователей и растворял её в разметке; страница — 50 строк с
ТОЧНЫМ общим счётом отдельным запросом по тому же выражению (та же форма, что в
разделе истории и на экране групп). Бесконечная прокрутка отвергнута по
существу, а не по вкусу: администратор ищет КОНКРЕТНОГО человека и возвращается
по адресу, а не листает ленту.
"""
from dataclasses import dataclass
from datetime import datetime

from sqlalchemy import Select, func, or_, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.user import User
from app.repositories.user import access_axis_clause

# Размер страницы объявлен ЗДЕСЬ и только здесь: число, выписанное вторым местом
# в разметке или в обработчике, разъехалось бы с запрашиваемым пределом молча —
# подпись обещала бы одно, а страница отдавала бы другое.
USERS_PAGE_SIZE = 50

# ДВЕ ОСИ ФИЛЬТРА, И РОВНО ДВЕ (D-32). Столько же групп, сколько в макете,
# поэтому раскладка полосы чипсов не ломается. Пятое значение любой оси
# потребовало бы пересмотра вёрстки, а не добавления строки в этот кортеж.
#
# ⚠️ ПОРЯДОК ЗНАЧЕНИЙ ОСИ ДОСТУПА ПОВТОРЯЕТ ПОРЯДОК ВЕТОК ВЕРДИКТА: льгота
# отдельным значением и РАНЬШЕ платного. У человека с выданным бесплатным
# доступом дата может быть мёртвой, и «открыт», оказавшись выше, забрал бы его
# себе — то есть спрятал бы от администратора его собственное действие.
ACCESS_CHIPS: tuple[tuple[str, str], ...] = (
    ("", "Все"),
    ("open", "Открыт"),
    ("comped", "Открыт бесплатно"),
    ("expired", "Истёк"),
)

STATE_CHIPS: tuple[tuple[str, str], ...] = (
    ("", "Все"),
    ("active", "Активные"),
    ("blocked", "Заблокированные"),
)


def _values(chips: tuple[tuple[str, str], ...]) -> frozenset[str]:
    """Допустимые значения оси без варианта «все» — ВЫВЕДЕННЫЕ из объявления.

    Выписанный второй раз перечень — это ровно тот способ, которым чипс
    переживает снятие своего условия: подпись рисуется, значение принимается,
    выражения за ним нет, и экран при этом исправен на вид.
    """
    return frozenset(value for value, _ in chips if value)


ACCESS_VALUES = _values(ACCESS_CHIPS)
STATE_VALUES = _values(STATE_CHIPS)


# ⚠️ УСЛОВИЕ ОСИ ДОСТУПА ПРИХОДИТ ИЗ СЛОЯ ДОСТУПА К ДАННЫМ, А НЕ СТРОИТСЯ ЗДЕСЬ
# (`app/repositories/user.py::access_axis_clause`). Причина не в раскладке
# файлов: признак бесплатного доступа читается в `app/application/` РОВНО ОДНИМ
# файлом — предикатом доступа, — и это машинный гейт, а не соглашение. Второе
# чтение признака в прикладной логике развело бы одно правило по двум
# выражениям. SQL-выражения по нашим таблицам — работа слоя доступа к данным, и
# перевод вердикта живёт там вместе с объяснением своей цены.
_STATE_CLAUSES = {
    "active": lambda: User.is_blocked.is_(False),
    "blocked": lambda: User.is_blocked.is_(True),
}


def apply_user_filters(
    query: Select,
    *,
    search: str | None = None,
    access: str | None = None,
    state: str | None = None,
    now: datetime,
) -> Select:
    """Навешивает поиск и обе оси на готовую выборку пользователей.

    ⚠️ ЭТА ФУНКЦИЯ — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ УСЛОВИЯ ПОДРАЗДЕЛА СТРОЯТСЯ. И
    страница, и счёт проходят через неё; второго набора `where` рядом нет и быть
    не должно (D-34).

    ⚠️ САНАЦИЯ ВСТРОЕНА В ПОИСК УСЛОВИЯ, А НЕ ПРИСТАВЛЕНА К НЕМУ СБОКУ.
    Значение оси приезжает строкой запроса — из ссылки, закладки или чужого
    сообщения (T-06-USR3) — и служит КЛЮЧОМ в замкнутом словаре условий.
    Неизвестный ключ не находит условия, то есть означает «все», и в выражение
    не попадает вовсе: ни сырым, ни экранированным. Отдельный отсекатель рядом
    можно было бы забыть позвать; словарь забыть нельзя — без него нет условия.

    ⚠️ ОБЕ СТОРОНЫ СРАВНЕНИЯ ПРИВОДЯТСЯ К РЕГИСТРУ ЯВНО, И ЭТО НЕ ПЕДАНТИЗМ.
    `ilike` в SQLite складывает регистр только для латиницы, в PostgreSQL — для
    юникода, и поиск по русскому имени вёл бы себя в суите иначе, чем в бою.
    Явный `lower()` с ОБЕИХ сторон делает выражение одинаковым; тем, что сам
    `lower()` в SQLite тоже знает только латиницу, занимается
    `app/database.py` — там встроенная функция заменена юникодной ровно ради
    этого выражения.
    """
    text = (search or "").strip()
    if text:
        # ⚠️ ПОДСТАНОВОЧНЫЕ ЗНАКИ `LIKE` ЭКРАНИРУЮТСЯ, И ЭТО НЕ ВОПРОС
        # БЕЗОПАСНОСТИ (WR-10 ревизии фазы 6). Инъекции здесь не было и нет:
        # текст едет параметром. Но `%` и `_` ВНУТРИ него сохраняли своё
        # значение для `LIKE`, и подраздел, обещающий «администратор ищет
        # КОНКРЕТНОГО человека», тихо обещал неправду: поиск `a_b` находил
        # `axb`, а поиск одного знака подчёркивания — ВСЕХ. Подчёркивание —
        # частый знак в локальной части почтового адреса, то есть случай
        # рабочий, а не выдуманный.
        #
        # Экранирующий знак назван ЯВНО (`escape=`): умолчания у него нет ни в
        # одном из двух диалектов, и без него обратная косая осталась бы
        # обычным знаком — то есть экранирование не состоялось бы вовсе, молча.
        # Сама обратная косая экранируется ПЕРВОЙ: сделай это позже, и
        # экранирующие знаки, дописанные строками ниже, были бы экранированы
        # повторно.
        escaped = (
            text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        )
        pattern = func.lower(f"%{escaped}%")
        query = query.where(
            or_(
                func.lower(User.name).like(pattern, escape="\\"),
                func.lower(User.email).like(pattern, escape="\\"),
            )
        )

    access_clause = access_axis_clause(access, now)
    if access_clause is not None:
        query = query.where(access_clause)

    state_clause = _STATE_CLAUSES.get(state or "")
    if state_clause is not None:
        query = query.where(state_clause())

    return query


async def count_users(
    session: AsyncSession,
    *,
    search: str | None = None,
    access: str | None = None,
    state: str | None = None,
    now: datetime,
) -> int:
    """Число пользователей под ТЕМ ЖЕ набором условий, что и страница (D-34).

    Счёт и список отвечают на один вопрос одним числом, поэтому условия
    навешивает ТА ЖЕ `apply_user_filters`, а не переписанный рядом набор `where`.
    Точный `COUNT` отдельным запросом — та же форма, что в разделе истории и на
    экране групп: приблизительное число над списком, который можно пролистать до
    конца, администратор проверит руками за минуту и перестанет верить ему
    навсегда.
    """
    query = apply_user_filters(
        select(func.count(User.id)), search=search, access=access, state=state, now=now
    )
    return (await session.execute(query)).scalar() or 0


@dataclass(frozen=True)
class UsersPage:
    """Страница списка вместе с числами, которые печатаются рядом с ней.

    Числа едут ВМЕСТЕ со строками одним значением намеренно: счётчик над списком
    и подпись пагинации обязаны приходить из одного источника, иначе два числа
    об одном и том же разойдутся — сперва на границе страницы, потом везде.
    """

    users: list[User]
    total: int
    page: int
    pages: int
    page_size: int = USERS_PAGE_SIZE


async def users_page(
    session: AsyncSession,
    *,
    search: str | None = None,
    access: str | None = None,
    state: str | None = None,
    now: datetime,
    page: int = 1,
) -> UsersPage:
    """Страница пользователей и точное общее число под теми же условиями.

    НОМЕР СТРАНИЦЫ ЗАЖИМАЕТСЯ, А НЕ ПРОВЕРЯЕТСЯ НА ДОПУСТИМОСТЬ. Он приезжает
    строкой запроса, и отказ страницы был бы здесь отказом в обслуживании по
    подконтрольному отправителю значению (T-06-USR3); молча пустая страница за
    последней — экраном, по которому не прочитать, что произошло. Зажим даёт
    третий исход: администратор видит крайнюю страницу и понимает, где он.

    ПУСТАЯ ВЫДАЧА — ЭТО ОДНА ПУСТАЯ СТРАНИЦА, А НЕ НОЛЬ СТРАНИЦ. «Страница 1 из
    0» не соответствует ни одному состоянию продукта.

    ЧИСЛО ОБРАЩЕНИЙ К БАЗЕ ПОСТОЯННО И РАВНО ДВУМ — счёт и строки, — сколько бы
    строк ни лежало на странице. Прежний список ходил в базу за каждым
    пользователем, и цена росла вместе с числом зарегистрированных, то есть
    ровно там, где страница администратора видит их всех сразу.
    """
    total = await count_users(session, search=search, access=access, state=state, now=now)
    pages = max(1, -(-total // USERS_PAGE_SIZE))
    page = min(max(page, 1), pages)

    query = apply_user_filters(
        select(User), search=search, access=access, state=state, now=now
    )
    query = query.order_by(User.id).offset((page - 1) * USERS_PAGE_SIZE).limit(USERS_PAGE_SIZE)
    users = list((await session.execute(query)).scalars().all())

    return UsersPage(users=users, total=total, page=page, pages=pages)
