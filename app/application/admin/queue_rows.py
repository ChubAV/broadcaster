"""Тело задачи из очереди → строка подраздела «Очередь» (D-16).

ЧИСТЫЕ функции над УЖЕ ПРОЧИТАННЫМ телом задачи — отдельным модулем рядом с
признаками инцидента (`incidents.py`) и по той же причине: разбор, написанный
внутри страничного обработчика, проверялся бы только через поднятый Redis и
отрисованную страницу, то есть самое тонкое место фазы осталось бы без прямой
улики. Здесь оно проверяется словарём и вызовом.

⚠️ ЕДИНИЦЫ ВРЕМЕНИ ОТЛОЖЕННОСТИ ЗАВИСЯТ ОТ КАНАЛА, И ЭТО ГЛАВНОЕ В МОДУЛЕ.
WA дописывает `_delay_until` в МИЛЛИСЕКУНДАХ (`Date.now() + delaySec * 1000`,
`wa_worker/index.js:583`), MAX — в СЕКУНДАХ (`time.time() + delay_sec`,
`max_worker/main.py:719`). Каждый воркер читает своё значение своей меркой и
потому работает; подраздел читает ОБА списка одним кодом.

Единая формула здесь НЕ ПАДАЕТ — и потому опаснее исключения. `fromtimestamp(v)`
покажет WA-задачу отложенной до 55-го тысячелетия, `fromtimestamp(v / 1000)` —
MAX-задачу отложенной до 1970 года. Обе даты правдоподобны на вид, обе
напечатаются молча, и администратор прочитает выдумку как измеренную величину.
Поэтому канал приходит ЯВНЫМ аргументом без умолчания: умолчание сделало бы
единую формулу достижимой по недосмотру.

⚠️ ОБА ПОЛЯ ЧИТАЮТСЯ ЧЕРЕЗ ДОСТУП С УМОЛЧАНИЕМ. В свежепоставленной задаче их
НЕТ вовсе: постановщик (`dispatch_send_tasks`, `app/worker/tasks.py:113-140`)
кладёт двенадцать полей, а `_retry_count`/`_delay_until` дописывает только воркер
при повторе. Обращение по индексу уронило бы подраздел на первой же нормальной
задаче — то есть в самом частом случае, а не в краевом.

⚠️ НОВЫХ СУЩНОСТЕЙ МОДУЛЬ НЕ ЗАВОДИТ. Обе величины воркеры кладут в тело задачи
сами и возвращают её в тот же список при повторе; подраздел их только читает.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, Mapping, Sequence

from app.application.analytics.send_analytics import normalize_utc

# Каналы, у которых очередь — собственный JSON проекта, а не конверт брокера.
# Telegram сюда не входит НАМЕРЕННО (D-14): его тело задачи распаковывать
# запрещено, и строки у него нет вовсе — есть число задач.
CHANNEL_WA = "wa"
CHANNEL_MAX = "max"

# Состояния строки очереди (D-16). Строки, а не булевы признаки: «ждёт»,
# «отложена до T» и «ретрай N» отвечают на разные вопросы, и сведение их к
# паре флагов потеряло бы ровно ту разницу, ради которой в подраздел заходят.
QUEUE_STATE_WAITING = "waiting"
QUEUE_STATE_DELAYED = "delayed"
QUEUE_STATE_RETRYING = "retrying"

# ПОТОЛОК ЧИСЛА СТРОК ОДНОЙ ОЧЕРЕДИ.
#
# ⚠️ ОН ЗДЕСЬ НЕ РАДИ ПАМЯТИ, А РАДИ ЧЕСТНОСТИ ЭКРАНА. Список Redis неограничен,
# и очередь встающего канала растёт неограниченно же; отрисовка всей очереди
# уложила бы подраздел ровно в той аварии, ради которой его открывают
# (T-06-Q2). Но у усечения есть своя цена: молча укороченный перечень читается
# как «остальных задач нет» — то есть как ОТВЕТ на вопрос, ради которого сюда и
# пришли. Поэтому срабатывание потолка возвращается ОТДЕЛЬНЫМ полем `capped`, а
# не выводится из длины: ровно `QUEUE_ROW_CAP` задач — это неусечённый список, и
# вывод по длине объявил бы его усечённым.
#
# Число выбрано того же порядка, что потолок инцидентов (`INCIDENT_LIST_CAP =
# 20`) и потолок журнала (200): достаточно, чтобы увидеть характер затора, и
# мало, чтобы страница осталась читаемой на 375px.
QUEUE_ROW_CAP = 50


@dataclass(frozen=True, slots=True)
class QueueRow:
    """Строка подраздела: состояние задачи плюс поля, которые печатает разметка.

    Идентификатор задачи несётся отдельным полем, потому что именно он, а не
    тело, уезжает в форму снятия: тело содержит текст объявления и может быть
    большим, а доверять клиенту точные байты удаляемого не нужно вовсе
    (T-06-DROP2).
    """

    task_id: str | None
    state: str
    delay_until: datetime | None
    retries: int
    ad_title: str | None
    group_name: str | None


@dataclass(frozen=True, slots=True)
class QueueRows:
    """Перечень строк одной очереди и признак срабатывания потолка."""

    rows: tuple[QueueRow, ...]
    capped: bool


def parse_delay_until(raw: Any, channel: str) -> datetime | None:
    """`_delay_until` из тела задачи → момент. ЕДИНИЦЫ ЗАВИСЯТ ОТ КАНАЛА (Ф-7).

    ⚠️ КАНАЛ — ОБЯЗАТЕЛЬНЫЙ АРГУМЕНТ БЕЗ УМОЛЧАНИЯ. Умолчание молча выбрало бы
    одну из двух мерок, и на второй половине задач подраздел рисовал бы
    правдоподобную дату, которой никогда не было: «отложена до 55-го
    тысячелетия» либо «отложена до 1970 года». Ни то, ни другое не поднимает
    исключения и ничем не выдаёт себя на экране.

    Нечисловое и отсутствующее значение возвращают пустоту, а не поднимают
    исключение: подраздел обязан рисоваться и при мусоре в очереди — иначе
    одна битая задача прятала бы от администратора все остальные.

    Момент возвращается aware-UTC через тот же хелпер, которым проект приводит
    всякое время перед арифметикой: сравнение naive и aware поднимает
    TypeError, и дефект существовал бы ровно на одном из двух диалектов.
    """
    if raw is None:
        return None
    try:
        value = float(raw)
    except (TypeError, ValueError):
        return None

    seconds = value / 1000.0 if channel == CHANNEL_WA else value
    try:
        moment = datetime.fromtimestamp(seconds, tz=timezone.utc)
    except (OverflowError, OSError, ValueError):
        # Значение вне представимого диапазона — тоже «неизвестно», а не 500.
        return None
    return normalize_utc(moment)


def queue_row_state(
    task: Mapping[str, Any],
    channel: str,
    now: datetime | None = None,
) -> QueueRow:
    """Тело задачи → строка подраздела: «ждёт» / «отложена до T» / «ретрай N».

    ⚠️ ОБА НЕОБЯЗАТЕЛЬНЫХ ПОЛЯ ЧИТАЮТСЯ С УМОЛЧАНИЕМ. В свежепоставленной
    задаче их нет вовсе — это НОРМАЛЬНОЕ тело, а не повреждённое.

    ⚠️ ОТЛОЖЕННОСТЬ В ПРОШЛОМ — НЕ «ОТЛОЖЕНА ДО». Наступивший момент означает,
    что задача снова ждёт своей очереди; напечатанный как «отложена до вчера»,
    он сообщал бы, что подраздел ждёт события, которое уже произошло.

    Поданное тело НЕ мутируется: оно прочитано из очереди и остаётся тем же
    значением, которым очередь его хранит.
    """
    moment = normalize_utc(now) or datetime.now(timezone.utc)

    raw_retries = task.get("_retry_count", 0)
    try:
        retries = int(raw_retries)
    except (TypeError, ValueError):
        retries = 0

    until = parse_delay_until(task.get("_delay_until"), channel)
    if until is not None and until > moment:
        state = QUEUE_STATE_DELAYED
    else:
        state = QUEUE_STATE_RETRYING if retries else QUEUE_STATE_WAITING
        until = None

    return QueueRow(
        task_id=task.get("task_id"),
        state=state,
        delay_until=until,
        retries=retries,
        ad_title=task.get("ad_title"),
        group_name=task.get("group_name"),
    )


def queue_rows(
    tasks: Sequence[Mapping[str, Any]],
    channel: str,
    now: datetime | None = None,
) -> QueueRows:
    """Перечень тел задач → строки подраздела, усечённые потолком.

    Признак срабатывания потолка возвращается отдельным полем, а разметка
    обязана назвать его словами: усечение, о котором не сказано, отвечает на
    вопрос «что ещё ждёт отправки» словом «ничего».
    """
    rows = tuple(
        queue_row_state(task, channel, now) for task in tasks[:QUEUE_ROW_CAP]
    )
    return QueueRows(rows=rows, capped=len(tasks) > QUEUE_ROW_CAP)
