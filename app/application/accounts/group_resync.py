"""Полная переинвентаризация состава групп аккаунта — одна на все три пути.

ПОЧЕМУ ХЕЛПЕР ОДИН. До этой фазы блок синхронизации был скопирован в трёх
местах — страничный TG-обработчик (`app/pages/accounts.py`) и две Celery-таски
WA и MAX (`app/worker/tasks.py`) — и копии уже разошлись посимвольно. Пока
логика сводилась к «добавить недостающие», расхождение было терпимым. Начиная
с D-10/D-11/D-12 она втрое сложнее: обновление имён, пометка пропавших, снятие
пометки у вернувшихся, запись результата на аккаунт. Реализация этого в трёх
копиях означает, что однажды поправят две из трёх, и WA-путь начнёт вести себя
иначе, чем MAX-путь, — молча, без падения тестов. Поэтому логика живёт здесь, а
три места её ВЫЗЫВАЮТ (вызовы — план 03-04).

Смысл «полной переинвентаризации» (D-10): ответ мессенджера — это состав групп
целиком, а не список изменений. Группа, ранее удалённая пользователем вручную,
приходит в ответе и создаётся ЗАНОВО как новая: включённая, без старых связей с
расписаниями. Томбстоунов нет — если группа не нужна, её выключают, а не
удаляют.

ЧЕГО ХЕЛПЕР НЕ ДЕЛАЕТ (D-11, прохибиция плана):
- не удаляет строк: группа, не вернувшаяся из мессенджера, помечается
  `missing_since` и остаётся в списке. Мессенджер может не отдать группу из-за
  собственного сбоя, и удаление по такому сигналу стирало бы данные
  пользователя без его решения;
- не читает и не пишет флаг включённости группы: включённость — выбор
  пользователя, а не свойство ответа мессенджера. Отсутствие этого имени во
  всём модуле — проверяемая форма прохибиции;
- не коммитит: транзакцией управляет вызывающий — страничный обработчик и
  Celery-таска ведут её по-разному.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Mapping, Sequence

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.application.accounts.dto import GroupResyncResult
from app.models.group import Group
from app.models.messenger_account import MessengerAccount


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _encode_result(result: GroupResyncResult) -> str:
    """Сериализует счётчики в форму, которую читает сводка синка.

    Ключ `new` соответствует полю `created` DTO — см. комментарий к
    `GroupResyncResult`. `ensure_ascii=False`: в `error` попадает текст ошибки
    мессенджера, и экранирование кириллицы раздувало бы значение вчетверо.
    """
    return json.dumps(
        {
            "found": result.found,
            "new": result.created,
            "renamed": result.renamed,
            "missing": result.missing,
            "error": result.error,
        },
        ensure_ascii=False,
    )


# Текст плашки, которую видит пользователь, когда предохранитель ниже не дал
# применить вырожденный ответ. Вынесен константой, потому что его проверяют
# тесты и на него ссылаются вызывающие.
EMPTY_RESPONSE_MESSAGE = (
    "мессенджер вернул пустой состав групп — пометки не ставились"
)

MALFORMED_RESPONSE_MESSAGE = (
    "мессенджер вернул состав групп не списком — синхронизация не выполнена"
)

# Границы колонок `groups.group_external_id` и `groups.name` (обе String(255)).
# Числа продублированы здесь намеренно: обрезка обязана происходить ДО того,
# как значение попадёт в сессию, а модель на этом уровне не читается — хелпер
# знает про недоверенность входа, а не про DDL.
#
# Почему обрезка, а не отказ: на SQLite (вся тестовая суита) длина не
# проверяется вовсе, а на PostgreSQL (прод) строка длиннее 255 роняет commit
# с DataError — то есть класс дефекта, который ни один зелёный тест поймать не
# может. Обрезанное имя чата читается хуже полного, но синхронизация целого
# аккаунта из-за одного длинного названия падать не должна.
_EXTERNAL_ID_MAX = 255
_NAME_MAX = 255


async def apply_group_resync(
    session: AsyncSession,
    account: MessengerAccount,
    fetched: Sequence[Mapping[str, Any]],
    *,
    messenger_type: str,
    allow_full_wipe: bool = False,
) -> GroupResyncResult:
    """Приводит состав групп аккаунта к ответу мессенджера.

    `fetched` — последовательность словарей `{"id": ..., "name": ...}` ровно
    того формата, что уже отдают `messenger.get_groups()` и поле `groups`
    ответа `get_sync_status()`. Содержимое НЕДОВЕРЕННОЕ: и идентификатор, и имя
    приходят из внешней системы — и с этой недоверенностью здесь ЧТО-ТО
    ДЕЛАЕТСЯ, а не только объявляется. Форма всего ответа проверяется, мусорные
    элементы пропускаются, идентификатор и имя обрезаются по границе колонки.

    Аннотация — `Sequence`, а не `Iterable`, намеренно: проверка формы отвергает
    всё, что не список и не кортеж, и это ровно то, что передают все три
    вызывающих. Генератор сюда передать нельзя — состав групп приходит
    материализованным из `response.json()`.

    `allow_full_wipe` снимает предохранитель вырожденного ответа (см. ниже).
    По умолчанию он взведён, и ни один существующий вызывающий его не снимает:
    достоверного источника «у аккаунта действительно не осталось ни одной
    группы» в проекте пока нет. Параметр существует, чтобы такой путь, если он
    появится, объявлял себя явно, а не получал разрушительное поведение молча.

    Не коммитит. Возвращает счётчики и записывает их на аккаунт.
    """
    # ФОРМА ВСЕГО ОТВЕТА. Недоверенность входа объявлена докстрингом, но до
    # этой проверки ни разу не проверялась: `response.json()` моста мог отдать
    # JSON-объект (`{"error": "..."}`), и цикл ниже пошёл бы по СТРОКОВЫМ
    # ключам, а `str.get` дал бы AttributeError — то есть пятисотку через
    # generic_error_handler вместо внятной плашки. Отказ здесь называет
    # причину той же формой, что и любой другой отказ синка.
    if not isinstance(fetched, (list, tuple)):
        result = GroupResyncResult(
            found=0, created=0, renamed=0, missing=0, error=MALFORMED_RESPONSE_MESSAGE
        )
        # `last_synced_at` не трогается: синхронизация не состоялась.
        account.last_sync_result = _encode_result(result)
        return result

    # Двойной скоуп (T-03-06): внешний идентификатор уникален внутри
    # мессенджера, но не внутри нашей базы — у другого пользователя может
    # лежать группа с тем же group_external_id. Условие по владельцу здесь
    # избыточно ровно до тех пор, пока account передан после проверки владения;
    # оно и стоит на случай, когда это перестанет быть правдой.
    existing_rows = await session.execute(
        select(Group).where(
            Group.account_id == account.id,
            Group.user_id == account.user_id,
        )
    )
    existing: dict[str, Group] = {
        group.group_external_id: group for group in existing_rows.scalars().all()
    }

    created = 0
    renamed = 0
    seen: set[str] = set()

    for item in fetched:
        # Мусорный ЭЛЕМЕНТ не роняет весь синк: массив скаляров (`[1, 2, 3]`)
        # или подмешанный null стоят пропуска одной группы, а не потери всей
        # переинвентаризации аккаунта. Отказ целиком оставлен только форме
        # ответа выше — там ошибся мост, а не отдельный чат.
        if not isinstance(item, Mapping):
            continue
        external_id = item.get("id")
        if external_id is None:
            continue
        external_id = str(external_id)[:_EXTERNAL_ID_MAX]
        if external_id in seen:
            # Дубли внутри одного ответа мессенджера схлопываются: вторая
            # запись про ту же группу не должна порождать вторую строку.
            continue
        seen.add(external_id)

        raw_name = item.get("name")
        name = (str(raw_name) if raw_name else external_id)[:_NAME_MAX]
        group = existing.get(external_id)

        if group is None:
            session.add(
                Group(
                    user_id=account.user_id,
                    account_id=account.id,
                    messenger_type=messenger_type,
                    group_external_id=external_id,
                    name=name,
                )
            )
            created += 1
            continue

        if group.name != name:
            group.name = name
            renamed += 1
        # Группа вернулась — пометка снимается независимо от того,
        # переименовалась она или нет.
        group.missing_since = None

    # ПРЕДОХРАНИТЕЛЬ ВЫРОЖДЕННОГО ОТВЕТА. Ответ, не содержащий НИ ОДНОЙ ранее
    # известной группы при непустом существующем составе, — с большей
    # вероятностью сбой мессенджера, чем одномоментный выход пользователя из
    # всех чатов сразу.
    #
    # Прохибиция D-11 распознала опасность верно («мессенджер может не отдать
    # группу из-за собственного сбоя»), но защитила не тот уровень: строки
    # уцелели, а `missing_since` — это состояние, которое экран выводит как
    # утверждение о факте («не найдена при синке»). После одного сбоя моста
    # помеченным оказывался ВЕСЬ список аккаунта, и настоящая пропажа одной
    # группы становилась в нём неразличима — признак обесценивался целиком.
    #
    # Отказ адаптера теперь отличим от пустоты (`MessengerFetchError`), но этот
    # предохранитель нужен независимо от него: WA/MAX-путь берёт состав не из
    # `get_groups()`, а из поля `groups` ответа `get_sync_status()`, где мост
    # при `state == "ready"` вправе положить `null`, `[]` или не положить поле
    # вовсе — и это не исключение, а валидный по его же документации ответ.
    #
    # Пометка НЕ ставится, а результат называет причину: ветка `error` уже
    # умеет рисовать красную плашку, и пользователь видит «повторите», а не
    # зелёное «не найдено 42».
    if existing and not seen and not allow_full_wipe:
        # Сюда невозможно попасть с непустыми `created`/`renamed`: оба
        # счётчика растут только после `seen.add`, поэтому пустой `seen`
        # означает, что база ещё не тронута и откатывать нечего.
        result = GroupResyncResult(
            found=0, created=0, renamed=0, missing=0, error=EMPTY_RESPONSE_MESSAGE
        )
        # `last_synced_at` не трогается: синхронизация не состоялась.
        account.last_sync_result = _encode_result(result)
        return result

    missing = 0
    marked_at = _utcnow()
    for external_id, group in existing.items():
        if external_id in seen:
            continue
        missing += 1
        # Время ПЕРВОЙ пропажи не перетирается: подпись «не найдена с …»
        # обязана говорить, когда группа исчезла, а не когда о ней вспомнили в
        # последний раз.
        if group.missing_since is None:
            group.missing_since = marked_at

    result = GroupResyncResult(
        found=len(seen),
        created=created,
        renamed=renamed,
        missing=missing,
        error=None,
    )
    account.last_synced_at = marked_at
    account.last_sync_result = _encode_result(result)
    return result


async def record_sync_failure(
    session: AsyncSession, account: MessengerAccount, message: str
) -> None:
    """Записывает неудавшийся синк той же формой, что и удавшийся.

    Счётчики нулевые, `error` — текст сообщения. Эта форма позволяет планам
    03-04 и 03-06 показать ошибку синка вместо сводки, не заводя второй
    колонки и не гадая по отсутствию значения. Не коммитит.

    `last_synced_at` НЕ ТРОГАЕТСЯ. Колонка означает «синхронизация
    состоялась», и оба её потребителя читают её именно так:

    - шапка экрана групп печатает «последняя синхронизация N назад» — она
      обязана называть последний УДАВШИЙСЯ синк, иначе экран одновременно
      сообщает «синхронизация только что» и «синхронизация не удалась»;
    - ветка пустого состояния различает «все группы удалены» и «групп пока
      нет» ровно по этой колонке — аккаунт, у которого синк не удавался ни
      разу, а групп никогда не было, получал утверждение «Все группы удалены».

    Время неудачной попытки несёт сама сводка: она перезаписывается при каждой
    попытке, и отдельной колонки под него не нужно.
    """
    account.last_sync_result = _encode_result(
        GroupResyncResult(found=0, created=0, renamed=0, missing=0, error=message)
    )


def parse_sync_result(raw: str | None) -> dict | None:
    """Читает `last_sync_result` с защитой от мусора.

    Возвращает `None` на пустом значении, невалидном JSON и несловарном
    верхнем уровне — и НИКОГДА не поднимает исключения (T-03-08). Значение
    пишется только кодом, но плашка результата обязана деградировать в
    отсутствие плашки, а не в стек-трейс на экране групп: строка в колонке
    может оказаться оборванной на полуслове или написанной прежней версией
    формата.
    """
    if not raw:
        return None
    try:
        payload = json.loads(raw)
    except (ValueError, TypeError):
        return None
    if not isinstance(payload, dict):
        return None
    return payload
