"""Четыре оси тарифа числами: сколько израсходовано и сколько положено.

Экран тарифов обязан ответить на один вопрос — «сколько у меня из скольких» —
по четырём осям макета (D-09). До этого модуля тарифных лимитов в коде проекта
не существовало ВООБЩЕ: единственный лимит (`app/services/billing_cache.py`)
разрешает всё, кроме `send`, а неподключённый шаблон тарифов (снесённый планом
05-05 — маршрута у него не было, а переменных, на которые он ссылался, не было
ни в одном контексте) знал три оси. Здесь «лимит тарифа» впервые становится
наблюдаемой величиной.

ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ:

- НЕ БЛОКИРУЕТ НИЧЕГО (D-08). Это ключевая граница фазы: строится ВИТРИНА, а не
  механизм принуждения. Ни один путь создания объявления, группы, аккаунта или
  отправки не получает здесь гейта, и превышение лимита не является ошибкой —
  пользователь, уже находящийся за лимитом, не наказывается задним числом.
  Применение лимитов остаётся долгом BILL-02 и в эту фазу не входит;
- не читает объект HTTP-запроса, не знает про cookie и про то, кто вошёл (имя
  типа не упомянуто здесь НАМЕРЕННО: границу держит греп приёмки по сырому
  тексту модуля, и слово в обосновании выглядело бы для него импортом): владелец
  приезжает обязательным именованным `user`, а в запрос уходит предикатом
  `user_id ==`; ветки «по всем пользователям» здесь нет вовсе;
- ничего не пишет в БД и не коммитит: обе функции только читают;
- не знает про Jinja, шаблоны и разметку: наружу выходят ЧИСЛА, а не строки
  для показа. Ширину метра, цвет и склонения решает разметка;
- не читает настройки: лимиты приезжают готовым отображением, а не
  вычитываются из `Settings` вторым источником.

ПЕРЕНОСИМОСТЬ АГРЕГАЦИИ. Тесты проекта идут на SQLite, бой работает на
PostgreSQL. Календарная группировка средствами БД пишется на этих диалектах
по-разному, и ветка, написанная под боевой диалект, не исполнилась бы тестами
НИ РАЗУ — то есть проверялась бы впервые на деплое. Поэтому окно оси месяца
режется сравнением `sent_at` с посчитанными в Python границами, а сами границы
считает модуль аналитики отправок, который этой таблицей и владеет (D-35).
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Mapping

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.application.analytics.send_analytics import sends_in_current_month_query
from app.models.group import Group
from app.models.user import User

# --- Оси тарифа ----------------------------------------------------------------
#
# Идентификаторы осей ДОСЛОВНО совпадают с ключами записи тарифа в
# `Settings.plan_limits` (`{"ads":3,"groups":5,"sends":300,"accounts":1}`): один
# и тот же смысл обязан называться одним словом в конфиге, в модуле и в
# разметке, иначе переименование в одном месте молча оставит ось без лимита.
AXIS_ADS = "ads"
AXIS_GROUPS = "groups"
AXIS_SENDS = "sends"
AXIS_ACCOUNTS = "accounts"

# Порядок рисования — порядок МАКЕТА, а не порядок словаря: словарь Python
# сохраняет порядок вставки, и опереться на него значило бы поставить порядок
# осей на экране в зависимость от того, в какой строке их однажды присвоили.
AXIS_ORDER = (AXIS_ADS, AXIS_GROUPS, AXIS_SENDS, AXIS_ACCOUNTS)

# Подписи из макета (design/new_broadcaster_design.unpacked.html:1861-1867).
# Живут ЗДЕСЬ, а не в шаблоне, по той же причине, что подписи рядов heatmap:
# это НАЗВАНИЯ осей, а не форматирование данных пользователя, и вторая их копия
# в разметке разъехалась бы с первой молча.
AXIS_LABELS = {
    AXIS_ADS: "Объявлений",
    AXIS_GROUPS: "Групп",
    AXIS_SENDS: "Отправок в месяц",
    AXIS_ACCOUNTS: "Аккаунтов",
}

# Безлимит кодируется None, а не нулём и не большим числом. Ноль неотличим от
# «лимит ноль» — валидного состояния гипотетического заблокированного тарифа, —
# а большое число рано или поздно будет достигнуто и покажет метр на доли
# процента там, где ограничения нет вовсе. То же значение приезжает из конфига
# JSON-литералом `null`.
UNLIMITED = None


@dataclass(slots=True)
class PlanAxis:
    """Одна ось тарифа ЦЕЛИКОМ: что меряем, сколько израсходовано, сколько дано.

    `percent` — поле, а не свойство: у безлимитной оси делителя нет вовсе, и
    правило «при отсутствии лимита процент равен нулю» обязано жить в ОДНОМ
    месте, а не повторяться у каждого читателя. Разметка получает готовое
    число и ничего не делит.
    """

    key: str
    label: str
    used: int
    limit: int | None
    percent: int


def axis_percent(used: int, limit: int | None) -> int:
    """Доля израсходованного в процентах; 0, если делить не на что.

    ДЕЛЕНИЕ ИДЁТ ТОЛЬКО ПРИ ЦЕЛОМ ЛИМИТЕ СТРОГО БОЛЬШЕ НУЛЯ. Безлимит (`None`)
    и нулевой лимит дают ноль — оба случая иначе роняли бы страницу тарифов
    делением на ноль, а не показывали бы «неограниченно».

    ПОТОЛОК В СТО ПРОЦЕНТОВ. Превышение лимита возможно и исключением не
    является (D-08): `used` отдаётся как есть, а вот наружу число вроде 133%
    модуль не выпускает — макрос `progress` клампит и сам, но отдавать
    вызывающему величину, которой не бывает, значит рассчитывать на то, что её
    поправит кто-то другой. Приём и формула те же, что у квоты шелла
    (`app/pages/common.py`): один и тот же процент считается одинаково.
    """
    if limit is None or limit <= 0:
        return 0
    return min(100, round(used * 100 / limit))


async def plan_axes(
    db: AsyncSession,
    *,
    user: User,
    limits: Mapping[str, int | None],
    nav_counts: Mapping[str, int],
    now: datetime | None = None,
) -> list[PlanAxis]:
    """Четыре оси тарифа владельца в порядке макета.

    `limits` — запись тарифа из `Settings.parsed_plan_limits`: ключи осей,
    значения — целое либо `None` для безлимита. Отсутствующий ключ читается как
    безлимит, а не как падение: перечень тарифов правится через окружение, и
    опечатка в нём обязана стоить одной ненарисованной шкалы, а не пятисотки на
    странице тарифов.

    ДВА ЧИСЛИТЕЛЯ ПРИХОДЯТ БЕСПЛАТНО. `nav_counts['ads']` и
    `nav_counts['accounts']` уже посчитаны шеллом на ЭТОМ ЖЕ запросе
    (`get_shell_context`). Считать их вторым запросом не «медленнее», а хуже:
    два источника одного числа расходятся молча, и пользователь получил бы на
    одном экране два ответа на вопрос «сколько у меня объявлений».
    ЧЕРНОВИКИ ВХОДЯТ в ось «Объявления» (D-23) — `nav_counts['ads']` считает все
    объявления без фильтра по статусу, и это единственный вариант, при котором
    число на экране тарифов совпадает с навигационным счётчиком, стоящим рядом.
    Ось «Аккаунты» берёт `nav_counts['accounts']` — количество ЗАВЕДЁННЫХ
    аккаунтов, а не число онлайн: у шелла есть отдельный счёт онлайн-сессий, и
    взять его значило бы, что у пользователя с упавшей сессией внезапно
    «освободился» слот тарифа.

    ДВА ОСТАЛЬНЫХ ЧИСЛИТЕЛЯ СЧИТАЮТСЯ ОДНИМ round-trip скалярными подзапросами —
    приёмом счётчиков шелла. Ось отправок берёт запрос у модуля аналитики
    (`sends_in_current_month_query`), а не пишет свой: календарное окно в зоне
    пользователя (D-11) и решение «квоту расходует любая попытка» (D-25)
    определены ТАМ и здесь не повторяются.

    ВЛАДЕНИЕ — ПРЕДИКАТ ЗАПРОСА (`user_id ==`), а не фильтр на стороне
    вызывающего: чужие группы и отправки в оси не попадают по построению
    (T-05-16).
    """
    row = (
        await db.execute(
            select(
                select(func.count())
                .select_from(Group)
                .where(Group.user_id == user.id)
                .scalar_subquery()
                .label("groups"),
                sends_in_current_month_query(user, user_id=user.id, now=now)
                .scalar_subquery()
                .label("sends"),
            )
        )
    ).one()

    used_by_axis = {
        AXIS_ADS: int(nav_counts.get(AXIS_ADS, 0) or 0),
        AXIS_GROUPS: int(row.groups or 0),
        AXIS_SENDS: int(row.sends or 0),
        AXIS_ACCOUNTS: int(nav_counts.get(AXIS_ACCOUNTS, 0) or 0),
    }

    axes: list[PlanAxis] = []
    for key in AXIS_ORDER:
        used = used_by_axis[key]
        limit = limits.get(key, UNLIMITED)
        axes.append(
            PlanAxis(
                key=key,
                label=AXIS_LABELS[key],
                used=used,
                limit=limit,
                percent=axis_percent(used, limit),
            )
        )
    return axes
