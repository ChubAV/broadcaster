"""Правило перехода между тарифами — ЕДИНСТВЕННОЕ объявление на проект.

ГРАНИЦЫ МОДУЛЯ (по образцу app/application/billing/subscription_period.py).
Модуль НИЧЕГО НЕ ПИШЕТ и ничего не читает из БД: он принимает два значения и
возвращает ответ. Он не знает ни про Jinja, ни про `Request`, ни про сессию
SQLAlchemy, и его единственный импорт — `app.constants`.

ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В ОДНОМ ИЗ ДВУХ ПОТРЕБИТЕЛЕЙ. Читателей у него
ровно два, и они лежат в разных слоях: `app/pages/billing.py` (стадия НАМЕРЕНИЯ)
и `app/services/payment_service.py` (стадия ПРИМЕНЕНИЯ). Первый уже импортирует
второй, поэтому обратный импорт замкнул бы цикл; слой `app/application/` —
единственное место, которое видно ОБОИМ и не видит ни одного из них.

Причина, впрочем, не в топологии импортов, а в цене расхождения. До этого модуля
правило существовало ровно на входе: гард формы отвергал понижение, а
`_apply_extension` перезаписывал план подтверждённого платежа безусловно.
Пользователь без подписки заводил два платежа — Pro, затем Basic, — гард не
участвовал ни в одном нажатии (сжигать было нечего), и оплаченный месяц старшего
тарифа становился днями младшего. Вторая копия сравнения рангов воспроизвела бы
ровно этот класс дефекта снова, поэтому копии здесь нет и завестись ей негде.
"""
from app.constants import PLAN_ORDER


def switch_is_refused(
    current_plan: str, target_plan: str, *, period_is_live: bool
) -> bool:
    """Отвергается ли переход подписчика `current_plan` на `target_plan`.

    РЕШЕНИЕ ВЛАДЕЛЬЦА (C2/WR-02, чекпойнт плана 05-10, вариант `upgrade-only`):
    повышение разрешено и оплаченный остаток не сжигает; понижение не
    предлагается карточкой и не ПРОДАЁТСЯ. Закрыта денежно опасная половина —
    уничтожение уплаченного за старший тариф, — и оставлена открытой безопасная.

    УСЛОВИЕ СРОКА ОТНОСИТСЯ К ПРАВИЛУ ЦЕЛИКОМ, А НЕ К ОДНОЙ ИЗ СТАДИЙ. Правило
    защищает УПЛАЧЕННОЕ; когда оплаченный срок истёк, защищать нечего, и отказ
    снимается — при `period_is_live is False` ответ `False` при любых планах, и
    сравнение рангов не выполняется вовсе (чекпойнт плана 05-13, вариант
    `apply-after-expiry`).

    ПРИЗНАК ПРИЕЗЖАЕТ АРГУМЕНТОМ `period_is_live`, А НЕ ВЫЧИСЛЯЕТСЯ ВЫЗЫВАЮЩИМ ПО
    СВОЕМУ УСМОТРЕНИЮ. Считает его `subscription_is_live` из
    `app/application/billing/subscription_period.py` — тоже единственным
    объявлением. Параметр keyword-only и БЕЗ значения по умолчанию: спросить
    правило, не сказав, есть ли что защищать, физически нельзя. Умолчание вернуло
    бы дисциплину вызывающего, из-за которой стадии и разошлись.

    ⚠️ У ПРАВИЛА ДВЕ СТАДИИ, И ОНИ СПРАШИВАЮТ ЕГО В РАЗНЫЕ МОМЕНТЫ. Между
    моментом ПРОДАЖИ и моментом ПРИМЕНЕНИЯ лежит вся сессия оплаты у ЮKassa, и
    состояние подписки за это время меняется — самим пользователем, соседним
    подтверждённым платежом или просто временем. Совпадает у двух стадий ФОРМА
    аргументов, а не их ЗНАЧЕНИЯ, и утверждать обратное здесь было ошибкой:
    предыдущая редакция этого абзаца объявляла совпадение значений правилом,
    которого код не исполнял, и следующий читатель верил комментарию, а не коду.

    ПОЭТОМУ ОТВЕТ СТАДИИ НАМЕРЕНИЯ ЗАПИСЫВАЕТСЯ НА ПЛАТЁЖ (D-28): колонка
    `payments.switch_authorized`, ревизия `0019`. Стадия применения читает
    записанный ФАКТ — что было ПРОДАНО этому платежу, — и правило спрашивает
    ТОЛЬКО у строк, записанного ответа не имеющих (`NULL`: пакетный платёж либо
    строка старше ревизии). Окно между стадиями этим закрывается не тем, что оно
    исчезает, а тем, что ответ переживает его.

    Различие между стадиями настоящее ровно одно — ЦЕНА ОТКАЗА:

    * НАМЕРЕНИЕ — `POST /billing/subscribe` решает, ПРОДАВАТЬ ЛИ. Отказ здесь
      стоит одного экрана: платежа ещё нет, деньги не тронуты.
    * ПРИМЕНЕНИЕ — `_apply_extension` решает, что делать с УЖЕ УПЛАЧЕННЫМ.
      Отказать платежу здесь нельзя вовсе: деньги списаны, и «не выдать ничего»
      было бы худшим из исходов. Поэтому отказ означает не отклонение платежа, а
      СОХРАНЕНИЕ действующего тарифа: срок двигается всегда.

    ⚠️ ПРЕЖНЯЯ РЕДАКЦИЯ ДОБАВЛЯЛА К ПОСЛЕДНЕЙ СТРОКЕ ОБЪЯВЛЕНИЕ ИНВАРИАНТА,
    КОТОРОГО КОД НЕ ИСПОЛНЯЕТ, — что план на стадии применения ТОЛЬКО РАСТЁТ.
    Прогон верификации раунда 6 опроверг его (`WR-03`): стадия применения
    спрашивает это правило ТОЛЬКО у строк без записанного ответа, а строка с
    записанным разрешением `True` исполняется как ПРОДАНА — и план по ней может
    пойти ВНИЗ, если подписка за время оплаты стала старшей. Решение владельца
    (чекпойнт задачи 1 плана `05-24`, вариант `record-wins`) оставило этот исход
    в силе — D-28 не сужается — и СНЯЛО объявление из обоих мест, где оно
    стояло. То есть `upgrade-only` есть правило стадии НАМЕРЕНИЯ: оно определяет,
    что ПРОДАЁТСЯ, а не то, чем кончается любой подтверждённый платёж.
    Достижимо понижение через окно СРОКА ДАВНОСТИ незакрытого намерения
    (`PENDING_INTENT_TTL_HOURS`) — записанный долг фазы, планом `05-24` не
    закрытый, — и с этого плана оно пишет на стороне применения собственный ключ
    журнала уровня `warning`, потому что до него происходило вовсе без следа
    (прохибиция BILL-05).

    Расхождение между этими двумя стадиями и есть тот дефект, ради которого
    модуль заведён (гэп 1, `05-VERIFICATION.md`). План 05-11 объединил
    ОБЪЯВЛЕНИЕ правила и не объединил его ВХОДНЫЕ ДАННЫЕ — отсюда обязательный
    третий вход. План 05-13 объединил ФОРМУ входных данных и не объединил МОМЕНТ
    их снятия — отсюда записанное разрешение на платеже.

    ОТКАЗ ПО УМОЛЧАНИЮ У НЕЗНАКОМОГО ПЛАНА. Ранг берётся из `PLAN_ORDER`
    (app/constants.py), и плану, которого там нет, ранг НЕ УГАДЫВАЕТСЯ: перечень
    тарифов правится окружением, а порядок — кодом, и догадка в любую сторону
    стоит денег. Продление СВОЕГО тарифа правилом не задевается вовсе — у него
    план не меняется, и сравнивать нечего.
    """
    if not period_is_live:
        return False

    if target_plan == current_plan:
        return False

    ranks = {plan: index for index, plan in enumerate(PLAN_ORDER)}
    current = ranks.get(current_plan)
    target = ranks.get(target_plan)
    if current is None or target is None:
        return True
    return target < current
