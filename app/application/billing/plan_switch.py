"""Правило перехода между тарифами — ЕДИНСТВЕННОЕ объявление на проект.

ГРАНИЦЫ МОДУЛЯ (по образцу app/application/billing/subscription_period.py).
Модуль НИЧЕГО НЕ ПИШЕТ и ничего не читает из БД: он принимает два значения и
возвращает ответ. Он не знает ни про Jinja, ни про `Request`, ни про сессию
SQLAlchemy, и его единственный импорт — `app.constants`.

ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В ОДНОМ ИЗ ДВУХ ПОТРЕБИТЕЛЕЙ. Читателей у него
ровно два, и они лежат в разных слоях: `app/pages/billing.py` (стадия НАМЕРЕНИЯ)
и `app/services/payment_service.py` (стадия ПРИМЕНЕНИЯ). Первый уже импортирует
второй, поэтому обратный импорт замкнул бы цикл; слой `app/application/` —
единственное место, которое видно ОБОИМ и не видит ни одного из них.

Причина, впрочем, не в топологии импортов, а в цене расхождения. До этого модуля
правило существовало ровно на входе: гард формы отвергал понижение, а
`_apply_extension` перезаписывал план подтверждённого платежа безусловно.
Пользователь без подписки заводил два платежа — Pro, затем Basic, — гард не
участвовал ни в одном нажатии (сжигать было нечего), и оплаченный месяц старшего
тарифа становился днями младшего. Вторая копия сравнения рангов воспроизвела бы
ровно этот класс дефекта снова, поэтому копии здесь нет и завестись ей негде.
"""
from app.constants import PLAN_ORDER


def switch_is_refused(current_plan: str, target_plan: str) -> bool:
    """Отвергается ли переход подписчика `current_plan` на `target_plan`.

    РЕШЕНИЕ ВЛАДЕЛЬЦА (C2/WR-02, чекпойнт плана 05-10, вариант `upgrade-only`):
    повышение разрешено и оплаченный остаток не сжигает; понижение не
    предлагается и не принимается. Закрыта денежно опасная половина —
    уничтожение уплаченного за старший тариф, — и оставлена открытой безопасная.

    У ПРАВИЛА ДВЕ СТАДИИ, И ОБЕ ЧИТАЮТ ЭТУ ФУНКЦИЮ.

    * НАМЕРЕНИЕ — `POST /billing/subscribe` решает, ПРОДАВАТЬ ЛИ. Отказ здесь
      стоит одного экрана: платежа ещё нет, деньги не тронуты. Вызов идёт только
      при действующей подписке — истёкший срок гард снимает, потому что защищать
      уже нечего.
    * ПРИМЕНЕНИЕ — `_apply_extension` решает, что делать с УЖЕ УПЛАЧЕННЫМ.
      Отказать платежу здесь нельзя вовсе: деньги списаны, и «не выдать ничего»
      было бы худшим из исходов. Поэтому отказ означает не отклонение платежа, а
      СОХРАНЕНИЕ действующего тарифа: срок двигается всегда, план только растёт.

    Расхождение между этими двумя стадиями и есть тот дефект, ради которого
    модуль заведён (гэп 1, `05-VERIFICATION.md`).

    ОТКАЗ ПО УМОЛЧАНИЮ У НЕЗНАКОМОГО ПЛАНА. Ранг берётся из `PLAN_ORDER`
    (app/constants.py), и плану, которого там нет, ранг НЕ УГАДЫВАЕТСЯ: перечень
    тарифов правится окружением, а порядок — кодом, и догадка в любую сторону
    стоит денег. Продление СВОЕГО тарифа правилом не задевается вовсе — у него
    план не меняется, и сравнивать нечего.
    """
    if target_plan == current_plan:
        return False

    ranks = {plan: index for index, plan in enumerate(PLAN_ORDER)}
    current = ranks.get(current_plan)
    target = ranks.get(target_plan)
    if current is None or target is None:
        return True
    return target < current
