"""Арифметика срока подписки: сдвиг на календарный месяц и точка отсчёта.

ГРАНИЦЫ МОДУЛЯ (по образцу app/application/analytics/send_analytics.py).
Модуль НИЧЕГО НЕ ПИШЕТ и ничего не читает из БД: он принимает значения и
возвращает значения. Он не знает ни про Jinja, ни про Request, ни про сессию
SQLAlchemy. Причина не в чистоте ради чистоты — срок подписки это ровно то
место, где ошибка стоит денег в обе стороны (сгоревший оплаченный остаток или
подаренный месяц), и такую арифметику надо уметь проверять без поднятия БД,
на каждом краевом дне календаря.

ПОЧЕМУ СТАНДАРТНАЯ БИБЛИОТЕКА, А НЕ СТОРОННИЙ `relativedelta`. Пакет, дающий
`relativedelta(months=1)`, решил бы ту же задачу, но он НЕ объявлен в
`pyproject.toml` — в окружении он присутствует только транзитивно, и опора на
него означала бы зависимость, которая исчезает при следующем `uv lock` без
единой правки нашего кода. `calendar.monthrange` совпадает с ним на всех
краевых датах, включая 31-е числа и 29 февраля, и это проверено тестами
модуля проходом по каждому дню обычного и високосного года.

ПРИЗНАК ЖИВОСТИ ОПЛАЧЕННОГО СРОКА ЛЕЖИТ ЗДЕСЬ, А НЕ РЯДОМ С `switch_is_refused`.
Он про СРОК, а не про порядок тарифов, и его ловушка — порядок относительно
`next_expiry`, то есть функции ЭТОГО модуля. Вторая причина техническая:
`app/application/billing/plan_switch.py` держит инвариант «единственная внешняя
зависимость — `app.constants`» (тест `test_the_only_import_of_the_rule_is_the_declared_plan_order`
разбирает его по синтаксическому дереву), а признаку живости нужен
`normalize_utc` — перенос туда ослабил бы инвариант, который держит топологию
импортов.
"""
import calendar
from datetime import datetime, timedelta
from decimal import Decimal

from app.application.analytics.send_analytics import normalize_utc


def add_one_month(value: datetime) -> datetime:
    """Сдвигает момент на один календарный месяц вперёд.

    ДЕНЬ ЗАЖИМАЕТСЯ до последнего дня целевого месяца: 31 января + месяц = 28
    февраля (29-е в високосный год), а не 3 марта. Перенос «лишних» дней вперёд
    удлинял бы оплаченный месяц на пару дней двенадцать раз в год.

    Наивная реализация `value.replace(month=value.month + 1)` НЕ годится по двум
    независимым причинам, и обе — ValueError у пользователя, а не в суите:
    31 января она поднимает «day is out of range for month», а в декабре —
    «month must be in 1..12». Перенос года считается явно, день — через
    `calendar.monthrange`.
    """
    year = value.year + (1 if value.month == 12 else 0)
    month = value.month % 12 + 1
    day = min(value.day, calendar.monthrange(year, month)[1])
    return value.replace(year=year, month=month, day=day)


def subscription_is_live(expires_at: datetime | None, now: datetime) -> bool:
    """Есть ли у пользователя НЕИСТЁКШИЙ оплаченный срок.

    Гард смены тарифа защищает УПЛАЧЕННОЕ, а не запирает пользователя в тарифе
    навсегда: когда срок истёк, сжигать нечего, и переход в любую сторону снова
    открыт.

    ⚠️ ПОРЯДОК ОТНОСИТЕЛЬНО `next_expiry` — ПРАВИЛО, А НЕ ОФОРМЛЕНИЕ. Признак
    обязан сниматься ДО того, как срок сдвинут: `next_expiry` перезаписывает ту
    самую величину, по которой признак считается, и ПОСЛЕ неё любая подписка
    выглядит живой — отказ не снялся бы никогда, а блокер восстановился бы молча,
    правкой, выглядящей безобидной перестановкой двух строк. Абзац стоит здесь, а
    не только в вызывающем: следующий человек, переставляющий два оператора,
    читает эту функцию, а не отчёт верификации. Порядок закреплён тестом по
    синтаксическому дереву `test_the_liveness_is_sampled_before_the_date_moves`.

    Сравнение идёт через `normalize_utc` по той же причине, что и у `next_expiry`:
    колонка объявлена с таймзоной, но SQLite отдаёт её naive, а PostgreSQL aware —
    сравнение без приведения падало бы TypeError ровно на одном из двух диалектов.

    Сравнение СТРОГОЕ: момент, равный `now`, живым не считается — оплаченный
    момент уже прошёл.
    """
    normalized = normalize_utc(expires_at)
    return normalized is not None and normalized > normalize_utc(now)


def next_expiry(current: datetime | None, now: datetime) -> datetime:
    """Новый срок подписки после подтверждённой оплаты.

    ПРАВИЛО (D-04). Отсчёт идёт от ПОЗДНЕЙШЕЙ из двух точек — действующего срока
    и сегодняшнего дня:

    * подписки не было (`current is None`) → месяц от сегодня;
    * срок ещё не истёк → месяц от СРОКА, а не от сегодня. Пользователь уже
      заплатил за неистраченный остаток, и продление за неделю до конца периода
      не имеет права его сжигать;
    * срок истёк → месяц от сегодня, а не от прошедшей даты. Иначе оплата после
      двухмесячного перерыва купила бы месяц, который закончился в прошлом.

    ОБА ЗНАЧЕНИЯ ПРОХОДЯТ ЧЕРЕЗ `normalize_utc`. Колонка `subscriptions.expires_at`
    объявлена `DateTime(timezone=True)`, но SQLite отдаёт её NAIVE, а PostgreSQL —
    aware. Сравнение naive с aware поднимает TypeError ровно на одном из двух
    диалектов, то есть дефект такого рода не ловится суитой, которая идёт на
    SQLite, — его ловит пользователь на PostgreSQL.
    """
    return add_one_month(countdown_base(current, now))


def countdown_base(current: datetime | None, now: datetime) -> datetime:
    """Точка отсчёта нового срока — позднейшая из действующего срока и сегодня.

    Объявлена ОДИН раз и читается обеими функциями сдвига — `next_expiry` и
    `prorated_expiry`, — а также денежным путём, которому нужно НАЗВАТЬ в журнале
    число выданных дней. Вторая копия правила D-04 была бы ровно тем классом
    расхождения, ради которого заведён этот модуль: две функции двигали бы срок
    от РАЗНЫХ точек, и разница проявилась бы только у пользователя с
    неистраченным остатком.

    Публичная, а не приватная, именно поэтому: журналу нужна ТА ЖЕ база, от
    которой посчитан сдвиг, и вычислить её у себя означало бы завести третью
    копию правила отсчёта.
    """
    now_utc = normalize_utc(now)
    base = normalize_utc(current)
    if base is None or base <= now_utc:
        return now_utc
    return base


def prorated_days(paid: Decimal, price: Decimal, month_days: int) -> int:
    """Сколько дней покупает `paid` при цене полного месяца `price`.

    Целая часть доли, но НЕ МЕНЬШЕ ОДНОГО ДНЯ. Нижняя граница — не округление, а
    решение D-29 дословно: деньги ВСЕГДА превращаются в дни, и исход «взяли
    деньги и не дали ничего» назван худшим из возможных. Целая часть доли от
    рубля при цене 4900 ₽ равна нулю, поэтому без явной границы этот исход
    возник бы сам собой, на самом незаметном краю.

    ВЕРХНЕГО ПОТОЛКА НЕТ, И ЭТО ТОЖЕ РЕШЕНИЕ, А НЕ УПУЩЕНИЕ. Сумма больше цены
    действующего плана даёт больше месяца — дни выдаются по тому, что УПЛАЧЕНО,
    и обрезание было бы взятием денег без выдачи, то есть тем же худшим исходом
    с другой стороны.

    АРИФМЕТИКА В `Decimal`, НИКАКОГО float. Деньги в этом проекте через float не
    проходят нигде: `payments.amount_value` объявлена строкой намеренно, и цена
    плана приезжает строкой из конфига. Двоичная дробь дала бы разные ответы на
    одинаковых суммах в зависимости от того, как они записаны.
    """
    return max(int(Decimal(month_days) * paid / price), 1)


def prorated_expiry(
    current: datetime | None, now: datetime, *, paid: Decimal, price: Decimal
) -> datetime:
    """Новый срок подписки, когда УПЛАЧЕННЫЙ план применён НЕ БУДЕТ (D-29).

    РЕШЕНИЕ ВЛАДЕЛЬЦА D-29. Платёж, чей план отвергнут правилом смены тарифа,
    продолжает давать дни — но по УПЛАЧЕННОМУ тарифу, а не по действующему: долю
    календарного месяца по отношению уплаченной суммы к цене действующего плана.
    До этого решения такой платёж покупал ПОЛНЫЙ календарный месяц действующего
    тарифа, то есть 1490 ₽ давали месяц Pro стоимостью 4900 ₽, и повторов не
    ограничивало ничто.

    ОТВЕРГНУТЫ ОДНОЙ ФРАЗОЙ, чтобы следующий читатель не восстановил ни один из
    них как «упрощение»: сохранение безусловного полного месяца с записью цены
    как принятого размена — и полный отказ в сдвиге срока при отказе перехода.
    Второй вводил бы исход «взяли деньги и не дали ничего», названный худшим.

    ТОЧКА ОТСЧЁТА — ТА ЖЕ, ЧТО У `next_expiry` (D-04): позднейшая из действующего
    срока и сегодняшнего дня, через общий `_countdown_base`. Доля ДОБАВЛЯЕТСЯ к
    оплаченному остатку, а не заменяет его отсчётом от сегодня — иначе отвергнутый
    платёж сжигал бы уже оплаченное, то есть наказывал бы за попытку заплатить.

    ДЛИНА МЕСЯЦА БЕРЁТСЯ У `add_one_month` ОТ ТОЙ ЖЕ БАЗЫ, А НЕ КОНСТАНТОЙ 30.
    Константа разошлась бы с `next_expiry` в феврале и в декабре, и «полный
    месяц» получил бы два разных определения — ровно тот класс расхождения, из-за
    которого эта фаза переписывается четвёртый раунд подряд. При `paid == price`
    ответ поэтому СОВПАДАЕТ с `next_expiry` точно, а не приблизительно.

    ⚠️ ПРЕДУСЛОВИЕ: `price` СТРОГО БОЛЬШЕ НУЛЯ, И ПРОВЕРЯЕТ ЕГО ВЫЗЫВАЮЩИЙ.
    У бесплатного плана цены нет вовсе, а у плана, выпавшего из конфига, её
    нельзя прочитать. Решать, что делать в этих случаях, — дело денежного пути,
    а не арифметики: там есть и журнал, и откат к полному месяцу, и обязанность
    не уронить обработчик уведомления. Здесь такого решения принять нельзя, не
    выдумав его.
    """
    base = countdown_base(current, now)
    month_days = (add_one_month(base) - base).days
    return base + timedelta(days=prorated_days(paid, price, month_days))


def converted_remainder(
    current: datetime | None,
    now: datetime,
    *,
    old_price: Decimal,
    new_price: Decimal,
) -> datetime:
    """Точка отсчёта при переходе на ДРУГОЙ тариф: остаток переносится ПО ДЕНЬГАМ.

    РЕШЕНИЕ ВЛАДЕЛЬЦА, ФОРМА `convert-remainder` (чекпойнт задачи 1 плана 05-18).
    Повышение тарифа СЧИТАЕТ ДОПЛАТУ: неистраченный остаток, купленный по цене
    старого плана, пересчитывается в дни по цене нового, и уже к этой точке
    вызывающий добавляет оплаченный месяц. После перехода срок снова однороден —
    он весь куплен по одной цене.

    ЧТО ЭТО ЗАКРЫВАЕТ И ПОЧЕМУ ГРАНИЦА ВООБЩЕ ПОНАДОБИЛАСЬ. Величина
    `expires_at` не имела верхней границы ни в коде, ни в схеме, а управляет ею
    ПОКУПАТЕЛЬ: он предоплачивает младший тариф сколько угодно раз (повтор своего
    тарифа не задевают ни гард формы, ни потолок одновременных намерений — и не
    должны), после чего один платёж старшего тарифа переводил на него ВЕСЬ
    накопленный горизонт, потому что `subscription.plan` — скаляр без истории.
    Двенадцать месяцев `basic` (17 880 ₽) плюс один `pro` (4 900 ₽) давали
    тринадцать месяцев Pro при прейскуранте 63 700 ₽, и утечка росла ЛИНЕЙНО с
    горизонтом предоплаты (гэп 1 раунда 5, воспроизведён верификацией).

    ЭТО ТОТ ЖЕ АППАРАТ D-29, ЗАПУЩЕННЫЙ В ДРУГУЮ СТОРОНУ, А НЕ ВТОРАЯ АРИФМЕТИКА
    ДЕНЕГ. `prorated_days` отвечает на вопрос «сколько дней покупает сумма X при
    цене месяца P»; здесь сначала считается, СКОЛЬКО СТОИТ остаток по старой
    цене, и ровно этот же вопрос задаётся с новой ценой. Вторая копия деления
    денег на цену была бы ровно тем расхождением, из-за которого фаза
    переписывается пятый раунд: две формулы разошлись бы на краевом дне, и
    разницу увидел бы пользователь, а не суита.

    НИЖНЯЯ ГРАНИЦА В ОДИН ДЕНЬ ДОСТАЁТСЯ ОТ `prorated_days`, И ЭТО ЕЁ ГЛАВНОЕ
    СВОЙСТВО ЗДЕСЬ. Живой оплаченный остаток НИКОГДА не конвертируется в ноль
    дней: обещание «оплаченный остаток не сгорает» остаётся верным и после смены
    формы — меняется единица измерения переноса (деньги вместо дней), а не сам
    факт переноса. Без границы самый дешёвый остаток обнулялся бы молча, то есть
    исход «взяли деньги и не дали ничего» (D-29 называет его худшим) возник бы
    сам собой на самом незаметном краю.

    ИСТЁКШИЙ ЛИБО ОТСУТСТВУЮЩИЙ СРОК ВОЗВРАЩАЕТ СЕГОДНЯ, А НЕ ПОДНИМАЕТ ОШИБКУ.
    Конвертировать нечего, и решение `apply-after-expiry` (чекпойнт плана 05-13)
    этим не задевается: план платежа применяется, срок считается от сегодня.

    ДЛИНА МЕСЯЦА БЕРЁТСЯ У `add_one_month` ОТ ТОЙ ЖЕ БАЗЫ, А НЕ КОНСТАНТОЙ 30 —
    по той же причине, что у `prorated_expiry`: константа разошлась бы с
    `next_expiry` в феврале и в декабре, и «полный месяц» получил бы два разных
    определения. Секунды остатка и секунды месяца берутся ЦЕЛОЧИСЛЕННЫМ делением
    `timedelta` на `timedelta`: `total_seconds()` вернула бы двоичную дробь и
    завела бы `float` на денежный путь.

    ⚠️ ПРЕДУСЛОВИЕ: ОБЕ ЦЕНЫ СТРОГО БОЛЬШЕ НУЛЯ, И ПРОВЕРЯЕТ ИХ ВЫЗЫВАЮЩИЙ —
    ровно как у `prorated_expiry`. У плана Free цены нет вовсе, а у плана,
    выпавшего из конфига, её нельзя прочитать; решать, что делать в этих случаях,
    — дело денежного пути, где есть и журнал, и откат к прежнему поведению, и
    обязанность не уронить обработчик уведомления пятисоткой.
    """
    now_utc = normalize_utc(now)
    base = countdown_base(current, now_utc)
    if base <= now_utc:
        return now_utc

    month_days = (add_one_month(now_utc) - now_utc).days
    second = timedelta(seconds=1)
    paid = (
        old_price
        * Decimal((base - now_utc) // second)
        / Decimal(timedelta(days=month_days) // second)
    )
    return now_utc + timedelta(days=prorated_days(paid, new_price, month_days))
