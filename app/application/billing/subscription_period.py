"""Арифметика срока подписки: сдвиг на календарный месяц и точка отсчёта.

ГРАНИЦЫ МОДУЛЯ (по образцу app/application/analytics/send_analytics.py).
Модуль НИЧЕГО НЕ ПИШЕТ и ничего не читает из БД: он принимает значения и
возвращает значения. Он не знает ни про Jinja, ни про Request, ни про сессию
SQLAlchemy. Причина не в чистоте ради чистоты — срок подписки это ровно то
место, где ошибка стоит денег в обе стороны (сгоревший оплаченный остаток или
подаренный месяц), и такую арифметику надо уметь проверять без поднятия БД,
на каждом краевом дне календаря.

ПОЧЕМУ СТАНДАРТНАЯ БИБЛИОТЕКА, А НЕ СТОРОННИЙ `relativedelta`. Пакет, дающий
`relativedelta(months=1)`, решил бы ту же задачу, но он НЕ объявлен в
`pyproject.toml` — в окружении он присутствует только транзитивно, и опора на
него означала бы зависимость, которая исчезает при следующем `uv lock` без
единой правки нашего кода. `calendar.monthrange` совпадает с ним на всех
краевых датах, включая 31-е числа и 29 февраля, и это проверено тестами
модуля проходом по каждому дню обычного и високосного года.

⚠️ ПЯТЬ ФУНКЦИЙ ДОЛИ МЕСЯЦА СНЯТЫ ПЛАНОМ 05.1-07 ВМЕСТЕ С ИХ ПРЕДМЕТОМ, А НЕ
«ПОЧИЩЕНЫ». Доля месяца, конвертация остатка по отношению цен и верхняя граница
предоплаченного горизонта существовали ровно для перехода МЕЖДУ ТАРИФАМИ: они
делили уплаченную сумму на цену плана. Тариф в системе один (D-A), цен две не
бывает, и делить стало не на что — отсюда же ушёл и десятичный тип, у которого
в этом модуле не осталось ни одного потребителя. Что снятые имена не вернулись
в приложение, закреплено машинным грепом
`test_no_metering_remains_in_the_application_sources`; что живой остаток модуля
не потерял покрытия — `test_next_expiry_keeps_the_unused_remainder`.
"""
import calendar
from datetime import datetime

from app.application.analytics.send_analytics import normalize_utc


def add_one_month(value: datetime) -> datetime:
    """Сдвигает момент на один календарный месяц вперёд.

    ДЕНЬ ЗАЖИМАЕТСЯ до последнего дня целевого месяца: 31 января + месяц = 28
    февраля (29-е в високосный год), а не 3 марта. Перенос «лишних» дней вперёд
    удлинял бы оплаченный месяц на пару дней двенадцать раз в год. Закреплено
    `test_add_one_month_clamps_to_a_shorter_month`,
    `test_add_one_month_hits_the_leap_day` и
    `test_add_one_month_rolls_over_the_year`; отсутствие исключения на любом дне
    года — `test_add_one_month_never_raises_on_any_day_of_the_year`.

    Наивная реализация `value.replace(month=value.month + 1)` НЕ годится по двум
    независимым причинам, и обе — ValueError у пользователя, а не в суите:
    31 января она поднимает «day is out of range for month», а в декабре —
    «month must be in 1..12». Перенос года считается явно, день — через
    `calendar.monthrange`.
    """
    year = value.year + (1 if value.month == 12 else 0)
    month = value.month % 12 + 1
    day = min(value.day, calendar.monthrange(year, month)[1])
    return value.replace(year=year, month=month, day=day)


def subscription_is_live(expires_at: datetime | None, now: datetime) -> bool:
    """Есть ли у пользователя НЕИСТЁКШИЙ оплаченный срок.

    Гард смены тарифа защищает УПЛАЧЕННОЕ, а не запирает пользователя в тарифе
    навсегда: когда срок истёк, сжигать нечего, и переход в любую сторону снова
    открыт.

    ⚠️ ПОРЯДОК ОТНОСИТЕЛЬНО `next_expiry` — ПРАВИЛО, А НЕ ОФОРМЛЕНИЕ. Признак
    обязан сниматься ДО того, как срок сдвинут: `next_expiry` перезаписывает ту
    самую величину, по которой признак считается, и ПОСЛЕ неё любая подписка
    выглядит живой — отказ не снялся бы никогда, а блокер восстановился бы молча,
    правкой, выглядящей безобидной перестановкой двух строк. Абзац стоит здесь, а
    не только в вызывающем: следующий человек, переставляющий два оператора,
    читает эту функцию, а не отчёт верификации. Порядок закреплён тестом по
    синтаксическому дереву `test_the_liveness_is_sampled_before_the_date_moves`.

    Сравнение идёт через `normalize_utc` по той же причине, что и у `next_expiry`:
    колонка объявлена с таймзоной, но SQLite отдаёт её naive, а PostgreSQL aware —
    сравнение без приведения падало бы TypeError ровно на одном из двух диалектов.

    Сравнение СТРОГОЕ: момент, равный `now`, живым не считается — оплаченный
    момент уже прошёл.
    """
    normalized = normalize_utc(expires_at)
    return normalized is not None and normalized > normalize_utc(now)


def access_is_open(subscription, now: datetime) -> bool:
    """Открыт ли пользователю доступ к продукту ПРЯМО СЕЙЧАС.
    Закреплено `test_the_trial_expires_and_payment_reopens_access`
    (`tests/test_pages/test_access_lifecycle.py`) — весь путь от пробного срока
    до восстановления доступа оплатой.

    ⚠️ ПОЛЬЗОВАТЕЛЬ БЕЗ СТРОКИ ПОДПИСКИ ИМЕЕТ ОПРЕДЕЛЁННОЕ СОСТОЯНИЕ, А НЕ `None`.
    Функция возвращает БУЛЕВО при любом входе: `None` вместо строки — это
    «доступа нет», а не «ответа нет». До плоской модели строка подписки была у
    МЕНЬШИНСТВА пользователей (её заводил только подтверждённый платёж), и
    читатель подставлял на её месте литерал `"free"`; в новой модели такой
    пользователь обязан получить закрытый доступ, а не исключение на середине
    рендера страницы. Ветка `subscription is None` поэтому НЕСУЩАЯ, а не
    защитная — она отвечает на состояние, которое переживёт выкат (D-G, П-о-1).
    Закреплено `test_a_user_without_a_subscription_row_has_a_definite_verdict`.

    ПРИЗНАК СНИМАЕТСЯ С ДВУХ ВЕЛИЧИН, И ОБЕ ОБЯЗАТЕЛЬНЫ. Деактивированная строка
    (`is_active` ложно) доступа не даёт, каким бы поздним ни был её срок: история
    подписок пользователя лежит в тех же строках, и читать срок, не спросив про
    активность, значило бы выдать доступ по отменённому периоду. Живость самого
    срока считает `subscription_is_live` — ЕДИНСТВЕННОЕ его объявление на
    проект, и второго сравнения дат здесь нет: разойдясь на строгости сравнения,
    две копии выдали бы разный ответ ровно в последнюю секунду оплаченного дня.
    Закреплено `test_a_deactivated_row_gives_no_access_however_late_its_date` и
    `test_the_verdict_follows_the_liveness_of_the_period` (граница строгости).

    ⚠️ ВЕТКИ БЕСПЛАТНОГО ДОСТУПА АДМИНИСТРАТОРА ЗДЕСЬ ПОКА НЕТ, И ЭТО РЕШЕНИЕ, А
    НЕ ЗАБЫТОЕ УСЛОВИЕ. Колонку `has_free_access` заводит план `05.1-08` вместе с
    её ревизией; объявить её чтение сейчас значило бы читать атрибут, которого
    нет ни в модели, ни в схеме, — то есть завести второй источник правды на один
    план вперёд и получить `AttributeError` на каждом рендере до выката ревизии.
    План `05.1-08` добавляет ветку СЮДА, в это объявление, а не рядом. Что ветки
    сегодня нет, закреплено
    `test_the_verdict_does_not_read_a_free_access_column_yet` — он разбирает тело
    функции по синтаксическому дереву и обязан покраснеть, когда ветка появится.
    """
    if subscription is None or not subscription.is_active:
        return False
    return subscription_is_live(subscription.expires_at, now)


def days_left(expires_at: datetime | None, now: datetime) -> int | None:
    """Сколько ПОЛНЫХ суток осталось до конца доступа; `None` — срока нет вовсе.

    `None` ОЗНАЧАЕТ РОВНО ОДНО — срока не существует (строки подписки нет), — и
    отличается от нуля намеренно. Ноль есть ЖИВОЙ последний день доступа, а не
    край и не отсутствие ответа: правило P-6 UI-контракта опирается на его
    достижимость, и разметка обязана уметь сказать «последний день», а не
    промолчать. Слить их в одно значение значило бы показать человеку в его
    последний оплаченный день то же самое, что человеку без подписки.
    Закреплено `test_a_period_that_does_not_exist_has_no_number_of_days` и
    `test_the_last_day_of_access_is_zero_and_not_absent`.

    СЧИТАЕТСЯ АТРИБУТ `days` РАЗНОСТИ, А НЕ ОКРУГЛЕНИЕ ЧАСОВ: «полные сутки» —
    это и есть целая часть разности, и деление секунд на 86400 дало бы ту же
    величину другой формулой, то есть вторую копию правила. Закреплено
    `test_whole_days_are_counted_and_not_hours_rounded`, который требует нуля на
    двадцати трёх часах и единицы на двадцати пяти.

    ОБА МОМЕНТА ПРОХОДЯТ ЧЕРЕЗ `normalize_utc` (Pattern 3) по той же причине,
    что у `subscription_is_live` и `next_expiry`: колонка объявлена
    `DateTime(timezone=True)`, но SQLite отдаёт её NAIVE, а PostgreSQL — aware,
    и вычитание без приведения падало бы TypeError ровно на одном из двух
    диалектов — то есть у пользователя, а не в суите. Закреплено
    `test_the_remaining_days_accept_a_naive_moment`.
    """
    normalized = normalize_utc(expires_at)
    if normalized is None:
        return None
    return (normalized - normalize_utc(now)).days


def next_expiry(current: datetime | None, now: datetime) -> datetime:
    """Новый срок подписки после подтверждённой оплаты.

    ПРАВИЛО (D-04). Отсчёт идёт от ПОЗДНЕЙШЕЙ из двух точек — действующего срока
    и сегодняшнего дня:

    * подписки не было (`current is None`) → месяц от сегодня;
    * срок ещё не истёк → месяц от СРОКА, а не от сегодня. Пользователь уже
      заплатил за неистраченный остаток, и продление за неделю до конца периода
      не имеет права его сжигать;
    * срок истёк → месяц от сегодня, а не от прошедшей даты. Иначе оплата после
      двухмесячного перерыва купила бы месяц, который закончился в прошлом.

    ОБА ЗНАЧЕНИЯ ПРОХОДЯТ ЧЕРЕЗ `normalize_utc`. Колонка `subscriptions.expires_at`
    объявлена `DateTime(timezone=True)`, но SQLite отдаёт её NAIVE, а PostgreSQL —
    aware. Сравнение naive с aware поднимает TypeError ровно на одном из двух
    диалектов, то есть дефект такого рода не ловится суитой, которая идёт на
    SQLite, — его ловит пользователь на PostgreSQL. Закреплено
    `test_next_expiry_accepts_a_naive_current_value`,
    `test_next_expiry_accepts_an_aware_current_value` и
    `test_next_expiry_accepts_a_naive_now`.
    """
    return add_one_month(countdown_base(current, now))


def countdown_base(current: datetime | None, now: datetime) -> datetime:
    """Точка отсчёта нового срока — позднейшая из действующего срока и сегодня.

    Объявлена ОДИН раз и читается функцией сдвига `next_expiry`, а также
    денежным путём, которому нужно НАЗВАТЬ в журнале число выданных дней. Вторая
    копия правила D-04 была бы ровно тем классом расхождения, ради которого
    заведён этот модуль: две функции двигали бы срок от РАЗНЫХ точек, и разница
    проявилась бы только у пользователя с неистраченным остатком. Закреплено
    `test_next_expiry_keeps_the_unused_remainder` и
    `test_next_expiry_of_an_expired_subscription_counts_from_today`.

    Публичная, а не приватная, именно поэтому: журналу нужна ТА ЖЕ база, от
    которой посчитан сдвиг, и вычислить её у себя означало бы завести третью
    копию правила отсчёта.
    """
    now_utc = normalize_utc(now)
    base = normalize_utc(current)
    if base is None or base <= now_utc:
        return now_utc
    return base
