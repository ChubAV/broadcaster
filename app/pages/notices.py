# «переехало» от «переписано». Посимвольное равенство закреплено гейтом
# переноса.
#
# ТЕКСТЫ ПОСТОЯННЫ И ИЗ ОТВЕТОВ СТОРОННИХ ВЫЗОВОВ НЕ СОБИРАЮТСЯ. Ни одна
# запись не подставляет в себя ни путь, ни адрес, ни текст чужого исключения:
