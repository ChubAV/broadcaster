"""ЗАКРЫТЫЙ РЕЕСТР УВЕДОМЛЕНИЙ: код исхода → готовый текст и вариант плашки.

Единственный владелец слов, которыми продукт сообщает пользователю ИСХОД ЕГО
ДЕЙСТВИЯ. До этого модуля таких владельцев было пять: три частных отображения
«код → текст (+вариант)» в разделах истории, оплаты и админки, и два места, где
исход вообще не имел реестра — признак сохранённого профиля был БУЛЕВЫМ, а не
кодом, и один признак жил прямо в разметке экрана входа. Сведение их в один
модуль и есть предмет FOUND-05.

⚠️ ПОЧЕМУ МНОЖЕСТВО ЗАКРЫТОЕ, А НЕ «ЛЮБОЕ НЕПУСТОЕ ЗНАЧЕНИЕ».
Код приезжает на страницу параметром адресной строки, то есть от владельца
ссылки — в том числе с чужого сайта. Плашка, отрисованная по любому непустому
значению, означала бы, что произвольный текст печатается пользователю ОТ ИМЕНИ
ПРИЛОЖЕНИЯ на его собственной странице: достаточно прислать ссылку. Поэтому в
разметку уходит строка ИЗ ЭТОГО модуля, а значение параметра сравнивается
ЦЕЛИКОМ и в документ не попадает ни одним путём. Это НЕДОСТИЖИМОСТЬ, а не
экранирование: подставлять нечего, потому что вход в разметку не связан со
входом из адреса. Обоснование не новое — им уже закрыты все три сегодняшних
частных реестра, и сюда оно переезжает вместе с текстами.

Неизвестный код возвращает ``None``, а не пустую запись: «плашки нет вовсе» и
«плашка без текста» — разные вещи, и вторая рисует пользователю пустую рамку,
сообщающую о событии, которого не было.

⚠️ ПРИЗНАК ЗАКРЫТОГО ДОСТУПА В РЕЕСТР НЕ ВХОДИТ И НЕ ВОЙДЁТ (D-11).
Гейт доступа уводит человека на раздел оплаты, добавляя к адресу свой признак.
Кодом уведомления этот признак НЕ является: состояние доступа сервер знает из
строки подписки, и решать вопрос «закрыт ли доступ» по параметру адресной
строки значило бы отдать его владельцу ссылки. Признак остаётся артефактом
редиректа — он нужен, чтобы в журналах было видно, что человек попал сюда
отказом гейта, а не пришёл сам, — и раздел оплаты его не читает (UI-контракт
E2). Отсутствие признака в реестре закреплено машинно
(``tests/test_pages/test_notices_registry.py``).

⚠️ ПОЧЕМУ РЕЕСТР СОБИРАЕТСЯ ИЗ ПАР, А НЕ ЛИТЕРАЛОМ СЛОВАРЯ (D-10).
Литерал словаря Python при повторе ключа МОЛЧА перезаписывает первую запись.
Для реестра исходов это худший вид ошибки: исход, о котором пользователю
сообщали, исчезает вместе со своим текстом, экран продолжает работать, и не
краснеет ничего. Поэтому записи объявлены кортежем, а отображение собирает
``_index`` — он поднимает ``ValueError`` на втором вхождении того же кода, то
есть роняет ИМПОРТ МОДУЛЯ, а не отдельный запрос. Зубы этого правила доказаны
контролем, а не заявлены.

⚠️ КОД ЕДЕТ КОНСТАНТОЙ, А НЕ ЛИТЕРАЛОМ.
На каждую запись заведена модульная константа, и обработчики обязаны писать в
адрес именно её. Канон взят у раздела истории: опечатка в литерале даёт
молчаливое «плашки нет» — то есть кнопку, вернувшую ту же страницу без единого
слова, — а опечатка в имени константы падает ошибкой на импорте.

⚠️ ИМЕНА ПЯТИ СНИМАЕМЫХ НАПИСАНИЙ ЗДЕСЬ НЕ НАЗВАНЫ НАМЕРЕННО.
Регрессия, утверждающая ноль их вхождений, читает исходники ТЕКСТОМ, и
объяснение, набранное снятым литералом, уронило бы собственный запрет. Приём не
новый — им же закрыт разбор снятых записей в разделе оплаты. Снятое поэтому
называется описательно: два признака раздела оплаты и админки, признак
сохранённого профиля, признак смены пароля, признак исхода повтора и признак
отказа расписания. Все пять — артефакты редиректа: порождаются сервером и
потребляются один раз.
⚠️ СНЯТЫХ НАПИСАНИЙ С ПЛАНА 11-14 ШЕСТЬ (D-10): шестое — признак исхода снятия
задачи из очереди админки, с его частным словарём и местом отрисовки. Названо
описательно по тому же доводу.
"""

from typing import NamedTuple


class Notice(NamedTuple):
    """Одна запись реестра: код исхода, его текст и вариант плашки.

    ``variant`` — не украшение: макрос ``components/alert.html`` выводит из
    него И класс, И ``role`` (``alert`` для отказа, ``status`` для остального).
    То есть вариант решает, объявит ли вспомогательная технология сообщение
    настойчиво. Множество вариантов закрыто и проверяется гейтом.
    """

    code: str
    text: str
    variant: str


# --- коды исходов ------------------------------------------------------------
#
# Пространство имён плоское ``snake_case`` (D-10) — той же формы, что коды
# сегодняшних частных реестров. Префикс по разделу отвергнут: адрес шумнее,
# стиль для проекта новый, а столкновения закрывает сборщик.

# Исход повтора отправки. Раздел истории — единственное место продукта, где
# ДЕЙСТВИЕ уходит прямо в боевую очередь, поэтому исходов у него четыре, а не
# два: успех, невосстановимая пропажа предмета, закрытый доступ и отказ окна
# удержания.
RETRY_QUEUED = "retry_queued"
RETRY_GONE = "retry_gone"
RETRY_ACCESS_CLOSED = "retry_access_closed"
RETRY_BUSY = "retry_busy"

# Отказ начать оплату. Три причины различимы человеком и требуют разных
# действий: подождать и повторить, обратиться к администратору, дождаться
# результата предыдущей попытки.
PAYMENT_FAILED = "payment_failed"
PAYMENT_DISABLED = "payment_disabled"
PAYMENT_PENDING = "payment_pending"

# Отказ перезапустить воркер в админке. Кнопку жмут в аварии, и по её
# результату решают, идти ли на сервер руками, — молчащий отказ здесь дороже,
# чем где-либо ещё.
WORKER_NO_CONTAINER = "worker_no_container"
WORKER_RESTART_FAILED = "worker_restart_failed"

# Исход снятия ОДНОЙ задачи из очереди отправки в админке (D-17 Фазы 6).
#
# ⚠️ ОТСУТСТВИЕ ЗАДАЧИ — ТОЖЕ ИСХОД, И ОН НАЗЫВАЕТСЯ СЛОВАМИ. Задача могла уйти
# из очереди сама, пока администратор читал экран; молчаливый возврат на ту же
# страницу он прочитал бы как «кнопка сломана» — и пошёл бы жать её снова.
# Довод перенесён из комментария частного словаря подраздела вместе с текстами.
#
# ⚠️ ЧЕТЫРЕ КОДА ЗАМЕЩАЮТ СУЩЕСТВУЮЩИЙ ЧАСТНЫЙ РЕЕСТР, А НЕ ДОБАВЛЯЮТ СООБЩЕНИЙ
# (Фаза 11, план 11-14, D-10). До плана у подраздела очереди был свой закрытый
# словарь исходов, свой ключ адресной строки и своё место отрисовки — шестой
# частный микро-контракт, уцелевший после свода Фазы 8. Тексты и варианты
# переехали посимвольно; нового слова продукт человеку не говорит, поэтому
# запрет D-03 Фазы 10 на новые сообщения этот свод не связывает.
QUEUE_DROP_REMOVED = "queue_drop_removed"
QUEUE_DROP_MISSING = "queue_drop_missing"
QUEUE_DROP_UNAVAILABLE = "queue_drop_unavailable"
QUEUE_DROP_NO_QUEUE = "queue_drop_no_queue"

# Отказ обработчика расписания в редакторе объявлений.
SCHEDULE_ACCOUNT_GONE = "schedule_account_gone"
SCHEDULE_AD_MISSING = "schedule_ad_missing"

# Отказ ВКЛЮЧИТЬ расписание, полное по составу и неисполнимое по значениям
# (CR-01). Отдельный код, а не один из двух предыдущих: те сообщают о
# НЕДОСТУПНОСТИ чужой или исчезнувшей записи, здесь же запись своя, найдена и
# цела, — неверен её СОСТАВ, и действие человеку нужно совсем другое.
SCHEDULE_VALUES_OUT_OF_DOMAIN = "schedule_values_out_of_domain"

# Исходы, у которых сегодня реестра нет вовсе.
PASSWORD_RESET_DONE = "password_reset_done"
PROFILE_SAVED = "profile_saved"
IMPERSONATION_FORBIDDEN = "impersonation_forbidden"


# --- записи ------------------------------------------------------------------
#
# ТЕКСТЫ ПЕРЕНЕСЕНЫ ДОСЛОВНО, А НЕ ПЕРЕПИСАНЫ. Они уже прошли ревью на своих
