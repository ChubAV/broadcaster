"""Заглушка снесённого глобального раздела «Группы» (D-01, план 03-08).

До Фазы 3 здесь жил раздел целиком: список, порция бесконечной прокрутки,
фильтры по аккаунту/мессенджеру/активности, тумблер, удаление и массовые
операции. Всё это переехало на экран групп аккаунта
(`app/pages/account_groups.py`): список ограничен ОДНИМ аккаунтом, владение
проверяется на каждом входе, а массовых операций и лишних фильтров у экрана нет
по решению фазы (D-03). Двух конкурирующих экранов групп в продукте быть не
должно, поэтому раздел снят, а не оставлен «на всякий случай».

ПОЧЕМУ ОСТАЛСЯ ВХОД, А НЕ ПУСТОЕ МЕСТО. У пользователей остались закладки и
ссылки на прежний адрес — вместе с разделом исчезла страница, но не адрес в
чужих закладках. Ответ об отсутствии страницы на них был бы потерей без нужды,
поэтому старый адрес и любая старая глубокая ссылка отвечают перенаправлением
на экран аккаунтов, откуда группы теперь и открываются (T-03-33, UI-SPEC E8).

Перенаправление БЕЗУСЛОВНО: заглушка не читает ни параметров запроса, ни
состояния, ни сессии — отвечать ей нечем, кроме одного и того же адреса
(T-03-35). Обработчиков POST в модуле нет ни одного: тумблер и удаление живут
на маршрутах экрана аккаунта, а массовые операции сняты вместе с разделом.
"""

from fastapi import APIRouter
from fastapi.responses import RedirectResponse

router = APIRouter(tags=["pages"])


# Два адреса — ОДИН обработчик: базовый адрес раздела и любая его глубокая
# ссылка (`/groups/partial`, `/groups/{id}/toggle` в закладке, адрес с
# параметрами фильтров). Отдельный маршрут на каждый снятый вход означал бы
# перечень, который придётся поддерживать ради страницы, которой нет.
@router.get("/groups")
@router.get("/groups/{deep_link:path}")
async def groups_retired(
    # ПАРАМЕТР НЕ ЧИТАЕТСЯ И НЕ ДОЛЖЕН — перенаправление безусловно (T-03-35).
    # Он объявлен ТОЛЬКО чтобы FastAPI принял путевой параметр `{deep_link:path}`
    # второго декоратора: без него регистрация маршрута падает. Значение по
    # умолчанию нужно первому декоратору, у которого этого сегмента нет вовсе.
    # Снять аргумент по подсказке линтера «неиспользуемый» — сломать маршрут.
    deep_link: str = "",  # noqa: ARG001
) -> RedirectResponse:
    """Старый адрес раздела ведёт на экран аккаунтов."""
    return RedirectResponse(url="/accounts", status_code=302)
