# Одна константа покрывает и время работы обработчика, и окно после ответа:
# заводить две сущности там, где хватает одной, значит объяснять читателю
# разницу, которой на экране нет.
RETRY_COOLDOWN_SECONDS: float = 60.0


# Реестр удержания повтора. Хранит НЕ факт «повтор обрабатывается прямо сейчас»,
# а СРОК, до которого повтор записи отклоняется: ключ — идентификатор записи
# журнала, значение — момент по монотонным часам. Реестр — в памяти, а не в БД,
# по образцу реестра синхронизации аккаунтов (`app/pages/accounts.py`).
#
# ЧТО ЭТО ДАЁТ. Окно ПЕРЕЖИВАЕТ ответ 302, поэтому два ПОСЛЕДОВАТЕЛЬНЫХ нажатия
# «Повторить» по одной записи в пределах окна дают ОДНУ постановку и один платёж
# баланса. Это единственная линия, которая держит при ВЫКЛЮЧЕННОМ JavaScript:
# панель подтверждения тогда не открывается вовсе и форма уходит напрямую.
# Прежняя редакция снимала удержание сразу по выходе из обработчика и потому
# останавливала только ПЕРЕСЕКАЮЩИЕСЯ во времени запросы.
#
# ⚠️ ДВЕ ГРАНИЦЫ, НАЗВАННЫЕ ЯВНО.
#
# 1. ЭТО ОКНО, А НЕ ЗАМОК. Удержание истекает; на путях, где задача в очередь не
#    ушла, оно не остаётся вовсе; исключение его снимает; ключуется оно по
#    КОНКРЕТНОЙ записи, поэтому повтор соседней неуспешной записи не блокируется.
#    Дальше окна защита не идёт: третье нажатие через час поставит вторую задачу,
#    и это намеренно — к тому времени пользователь повторяет уже по новой записи.
#
# 2. ЭТО ОДИН ПРОЦЕСС. Реестр живёт в памяти ОДНОГО рабочего процесса и
#    нескольких процессов не переживает: два нажатия, попавшие в разные
#    процессы, откроют по своему окну каждое и обе задачи поставят. Ограничение
#    уже принято проектом для синхронизации, но здесь цена ошибки выше — вторая
#    необратимая отправка в чужую группу. Поэтому оно записано и здесь, и в
#    отчёте безопасности фазы, а не умолчано.
#
# РАЗМЕР РЕЕСТРА ОГРАНИЧЕН ЧИСЛОМ ДЕЙСТВУЮЩИХ ОКОН, а не числом повторов за всё
# время работы процесса. Значения здесь — СРОКИ, то есть структура выглядит
# истекающей; без явной уборки она бы ею не была, и словарь рос бы до
# перезапуска — молча и только на долгоживущем боевом процессе, где этого никто
# не увидит. Уборку делает `_claim_retry_slot`.
#
# Остальные линии защиты от двойной отправки (перенаправление после формы,
# отсутствие автоперезапуска у самого таска) от числа процессов не зависят. Гард
# панели подтверждения не зависит тоже, но он требует РАБОТАЮЩЕГО JavaScript —
# именно поэтому серверное окно здесь и заведено.
_RETRY_IN_FLIGHT: dict[int, float] = {}


# Причины, по которым повтор заведомо не пройдёт (D-21). Названы ПОИМЁННО, а не
# одним «повторить нельзя»: общая формулировка на четыре случая не сказала бы
# пользователю ничего о том, что чинить.
RETRY_REASON_AD_GONE = "Объявление удалено"
# Черновик и удаление — РАЗНЫЕ причины, и своя строка у каждой не оформление:
# «Объявление удалено» под снятым с публикации послало бы пользователя искать
# его в корзине, хотя объявление на месте и вернуть кнопку он может сам.
RETRY_REASON_AD_DRAFT = "Объявление в черновике"
RETRY_REASON_GROUP_GONE = "Группа удалена"
# То же и с группой: «Группа удалена» под выключенной отправила бы
# пересинхронизировать живую группу вместо того, чтобы включить её обратно.
RETRY_REASON_GROUP_OFF = "Группа выключена"
RETRY_REASON_ACCOUNT_GONE = "Аккаунт удалён"
RETRY_REASON_ACCOUNT_OFF = "Аккаунт отключён"


async def retry_availability(
    db: AsyncSession, rows, user_id: int
) -> dict[int, str | None]:
    """Причина недоступности повтора для каждой НЕуспешной записи страницы.

    Ключ — идентификатор записи, значение — причина или `None`, если повтор
    возможен. Успешные записи в результат не попадают вовсе: повтор им не
    предлагается по статусу, и тратить на них запросы незачем. Именно поэтому
    отсутствие ключа и `None` под ключом — РАЗНЫЕ ответы, и разметка обязана
    различать их: «повторить нельзя, потому что успешно» и «повторить можно».

    ФИКСИРОВАННОЕ ЧИСЛО ЗАПРОСОВ, а не по три на запись. Проверка тройки по
    каждой строке стоила бы девяносто обращений к базе на страницу в тридцать
    записей — и так на каждый рендер списка (тот же класс дефекта, что T-04-19
    у блока ближайших отправок). Оба запроса идут ПО ОБЪЕДИНЕНИЮ
    идентификаторов показываемых строк.

    ГРУППА ПРИЕЗЖАЕТ АРГУМЕНТОМ, а не берётся с записи: списочный запрос
    выбирает пару внешним соединением, и у записи с удалённой группой второй
    элемент пары пуст. Аккаунт выводится ЧЕРЕЗ группу — колонки аккаунта в
    журнале нет вовсе.

    ПРЕДИКАТ НЕУСПЕШНОСТИ — «статус не успешный», а не «статус из перечня
    известных неудач»: перечень конечен ровно до появления следующего статуса,
    и запись с неизвестным значением оказалась бы ни успешной, ни повторяемой.
    Тот же предикат держат счётчик неудач дашборда, кнопка копирования
    диагностики и сам обработчик повтора.

    ВЛАДЕЛЕЦ ПРИЕЗЖАЕТ АРГУМЕНТОМ, И ОБА ВСПОМОГАТЕЛЬНЫХ ЗАПРОСА ЕГО НЕСУТ.
    `send_logs.ad_id` и `send_logs.group_id` — простые Integer БЕЗ внешнего
    ключа (`app/models/send_log.py`), поэтому идентификатор переживает удаление
    своей цели. На PostgreSQL последовательности номера не переиспользуют, и
    протухший идентификатор просто ничего не находит; на SQLite — на котором
    идёт вся суита — INTEGER PRIMARY KEY без AUTOINCREMENT выдаёт max(rowid)+1
    и номер переиспользует. То есть инвариант, на котором держалась
    безопасность этих запросов, ЛОМАЕТСЯ ИМЕННО В ТЕСТОВОЙ СРЕДЕ и не ломается
    в боевой: тест такую регрессию поймать не мог бы в принципе. Предикат
    владения делает инвариант локальным и стоит ровно ничего.
    """
    candidates = [(log, group) for log, group in rows if log.status != STATUS_OK]
    if not candidates:
        return {}

    # Статус выбирается ВМЕСТЕ с идентификатором, а не вторым запросом: пара
    # приезжает из той же строки, и число запросов на страницу не растёт.
    # Присутствия строки НЕДОСТАТОЧНО — снятое с публикации объявление живо, но
    # повтору не подлежит (CR-01), и кнопка обязана это назвать, а не
    # предлагать отправку, которую обработчик всё равно отвергнет.
    ad_ids = {log.ad_id for log, _group in candidates if log.ad_id}
    live_ads: dict[int, str] = {}
    if ad_ids:
        live_ads = {
            row_id: status
            for row_id, status in (
                await db.execute(
                    select(Ad.id, Ad.status).where(
                        Ad.id.in_(ad_ids), Ad.user_id == user_id
                    )
                )
            ).all()
        }

    account_ids = {
        group.account_id for _log, group in candidates if group and group.account_id
    }
    account_status: dict[int, str] = {}
    if account_ids:
        account_status = {
            row_id: status
            for row_id, status in (
                await db.execute(
                    select(MessengerAccount.id, MessengerAccount.status).where(
                        MessengerAccount.id.in_(account_ids),
                        MessengerAccount.user_id == user_id,
                    )
                )
            ).all()
        }

    verdict: dict[int, str | None] = {}
    for log, group in candidates:
        if not log.ad_id or log.ad_id not in live_ads:
            verdict[log.id] = RETRY_REASON_AD_GONE
        elif effective_status_value(live_ads[log.ad_id]) == AD_STATUS_DRAFT:
            verdict[log.id] = RETRY_REASON_AD_DRAFT
        elif group is None:
            verdict[log.id] = RETRY_REASON_GROUP_GONE
        elif not group.is_active:
            verdict[log.id] = RETRY_REASON_GROUP_OFF
        # ⚠️ ВЕТКА НЕДОСТИЖИМА ПРИ ВКЛЮЧЁННЫХ ВНЕШНИХ КЛЮЧАХ, и это записано
        # здесь, чтобы следующий читатель не потратил время на её проверку.
        # `groups.account_id` объявлен NOT NULL с `ondelete="CASCADE"`
        # (`app/models/group.py`), поэтому удаление аккаунта уносит и группу:
        # состояние «группа жива, аккаунта нет» на PostgreSQL не существует, и
        # такая запись доходит сюда уже отвергнутой веткой `group is None` со
        # словом «Группа удалена». Ветка ОСТАВЛЕНА защитой в глубину: SQLite не
        # проверяет внешние ключи без `PRAGMA foreign_keys`, а сюда же попадает
        # и случай чужого аккаунта — предикат владения выше исключает его из
        # выборки, и «Аккаунт удалён» тогда правда.
        elif not group.account_id or group.account_id not in account_status:
            verdict[log.id] = RETRY_REASON_ACCOUNT_GONE
        elif account_status[group.account_id] != "active":
            verdict[log.id] = RETRY_REASON_ACCOUNT_OFF
        else:
            verdict[log.id] = None
    return verdict


def _claim_retry_slot(log_id: int) -> bool:
    """Открывает окно удержания повтора записи. `False` — окно ещё не истекло.

    Функция не «занимает заявку на время обработчика»: срок проставляется на
    `RETRY_COOLDOWN_SECONDS` вперёд, и окно ПЕРЕЖИВАЕТ ответ. Именно поэтому
    второе ПОСЛЕДОВАТЕЛЬНОЕ нажатие по той же записи второй задачи не ставит —
    в том числе при выключенном JavaScript, когда панель подтверждения не
    открывается. Удержание, снимаемое по выходе из обработчика, остановило бы
    только ПЕРЕСЕКАЮЩИЕСЯ во времени запросы.

    Функция СИНХРОННАЯ и не содержит ни одного `await` намеренно: между чтением
    срока и его записью не должно быть точки переключения задач, иначе гонка
    вернётся ровно туда, откуда её убирают.

    ЗДЕСЬ ЖЕ СНИМАЮТСЯ ПРОСРОЧЕННЫЕ УДЕРЖАНИЯ ЧУЖИХ ЗАПИСЕЙ. Успешная постановка
    удержание СОХРАНЯЕТ (в этом вся защита от второго нажатия), и снимать его
    больше некому: обхода реестра нет нигде, периодической задачи под него не
    заведено. Без уборки словарь рос бы на одну запись за каждый успешный повтор
    и не уменьшался до перезапуска процесса. Проход по всему реестру стоит
    столько же, сколько число ДЕЙСТВУЮЩИХ окон, и идёт только на этом пути —
    один раз на нажатие «Повторить», а не на рендер списка.
    """
    now = monotonic()
    for stale in [key for key, until in _RETRY_IN_FLIGHT.items() if until <= now]:
        del _RETRY_IN_FLIGHT[stale]
    deadline = _RETRY_IN_FLIGHT.get(log_id)
    if deadline is not None and now < deadline:
        return False
    _RETRY_IN_FLIGHT[log_id] = now + RETRY_COOLDOWN_SECONDS
    return True


def _release_retry_slot(log_id: int) -> None:
    """Снимает удержание повтора. К БД не обращается и отказать не может.

    ВЫЗЫВАЕТСЯ ТОЛЬКО НА ПУТЯХ, ГДЕ ЗАДАЧА В ОЧЕРЕДЬ НЕ УШЛА: отказ
    предпроверки целости тройки, отказ гейта баланса, исключение внутри
    обработчика. Успешная постановка удержание СОХРАНЯЕТ — в переживающем ответ
    окне вся защита от второго нажатия. Пользователь, у которого повтор до
    очереди не дошёл, исправляет причину и повторяет сразу, а не ждёт окно за
    несостоявшуюся отправку.

    Снятие идёт со значением по умолчанию, поэтому повторный вызов безобиден и
    не бросает: блок завершения обязан отрабатывать в том числе после
    исключения, когда сессия непригодна ни для чего, кроме отката.
    """
    _RETRY_IN_FLIGHT.pop(log_id, None)


@router.get("/history/partial", response_class=HTMLResponse)
async def history_partial(
    request: Request,
    status: str | None = Query(default=None),
    messenger: str | None = Query(default=None),
    account_id: str | None = Query(default=None),
    period: str | None = Query(default=None),
    offset: int = Query(0, ge=0),
    limit: int = Query(PAGE_SIZE, ge=1, le=100),
    # D-15: параметр компоновки принимается и игнорируется — см. app/pages/ads.py
    layout: str | None = Query(None),
    db: AsyncSession = Depends(get_db),
    settings: Settings = Depends(get_settings),
):
    user = await get_user_from_cookie(request, db, settings)
    if not user:
        return RedirectResponse(url="/login", status_code=302)
    status = clean_choice(status, STATUS_VALUES)
    messenger = clean_choice(messenger, MESSENGER_VALUES)
    period = clean_choice(period, PERIOD_VALUES)
    account_id_int = parse_account_id(account_id)
    query = (
        select(SendLog, Group)
        .outerjoin(Group, SendLog.group_id == Group.id)
        .where(SendLog.user_id == user.id)
    )
    query = apply_history_filters(
        query,
        status=status,
        messenger_type=messenger,
        account_id=account_id_int,
        period=period,
        user=user,
    )
    query = query.order_by(SendLog.sent_at.desc()).offset(offset).limit(limit + 1)
    result = await db.execute(query)
    rows = list(result.all())
    has_next = len(rows) > limit
    # Признак доступности повтора считает СЕРВЕР и здесь тоже: признак,
    # вычисленный только в списочном обработчике, потерялся бы на тридцать
    # первой записи — молча, с исправным на вид экраном.
    retry_blockers = await retry_availability(db, rows[:limit], user.id)
    logs = [
        {
            "id": r.id,
            "ad_title": r.ad_title or "—",
            # СНАПШОТА ТЕЛА ОБЪЯВЛЕНИЯ В СТРОКЕ СПИСКА НЕТ. Ни `ad_text`, ни
            # `ad_images` карточка списка не рисует — их читает только экран
            # записи, и он получает ORM-сущность, а не этот словарь. Пока они
            # тут лежали, каждый рендер списка и каждый тик бесконечной
            # прокрутки поднимал в память до тридцати полных снимков тела
            # объявления (`ad_text` — Text, длина не ограничена) ради контекста,
            # который их выбрасывает.
            "group_name": r.group_name or "—",
            "group_external_id": group.group_external_id if group else None,
            "account_id": group.account_id if group else None,
            "task_id": r.task_id,
            "status": r.status,
            "messenger_type": r.messenger_type,
            "error_message": r.error_message,
            "sent_at": r.sent_at,
            # Отсутствие ключа в вердикте и `None` под ключом — РАЗНЫЕ ответы:
            # первое означает успешную запись, второе — что повтор возможен.
            "can_retry": r.id in retry_blockers and retry_blockers[r.id] is None,
            "retry_reason": retry_blockers.get(r.id),
        }
        for r, group in rows[:limit]
    ]
    filter_params = history_filter_params(status, messenger, account_id_int, period)
    return templates.TemplateResponse(
        "history/partial_cards.html",
        {
            "request": request,
            "user": user,
            "logs": logs,
            "has_next": has_next,
            "next_offset": offset + limit,
            # Размер страницы уезжает в сентинель ИЗ КОНТЕКСТА, а не литералом
            # в разметке: литерал разъехался бы с `next_offset` молча — вторая
            # страница выдачи начала бы перекрываться с первой или пропускать
            # записи, а экран остался бы исправным на вид. Значение — тот самый
            # `limit`, которым выбрана ЭТА порция.
            "page_size": limit,
            "status_filter": status,
            "filter_messenger": messenger,
            "filter_account_id": account_id_int,
            "filter_period": period,
            "filter_params": filter_params,
        },
    )


@router.get("/history/export")
async def history_export(
    request: Request,
    status: str | None = Query(default=None),
    messenger: str | None = Query(default=None),
    account_id: str | None = Query(default=None),
    period: str | None = Query(default=None),
    db: AsyncSession = Depends(get_db),
    settings: Settings = Depends(get_settings),
):
    """Потоковая выгрузка ОТФИЛЬТРОВАННОЙ истории файлом (HIST-03).

    ОБЪЯВЛЕН ВЫШЕ МАРШРУТА ЗАПИСИ. Сопоставление идёт в порядке объявления, и
    объявленный ниже адрес уехал бы в `log_id` маршрута записи, отдав ошибку
    разбора вместо файла. Ровно по этой причине выше маршрута записи уже стоит
    паршал бесконечной прокрутки.

    ФИЛЬТРЫ — ТЕ ЖЕ, ЧТО У СПИСКА, И НАВЕШИВАЕТ ИХ ТА ЖЕ ФУНКЦИЯ. Иначе
    обещание «выгружено именно то, что показано» перестало бы быть проверяемым
    утверждением: две копии условий расходятся молча, и пользователь уносит
    файл, не совпадающий с экраном. Отсечка `clean_choice` стоит и здесь —
    выгрузка ТРЕТИЙ вход на те же оси, и без неё подобранное вручную значение
    отдавало бы пустой файл, неотличимый от «записей действительно нет».

    ВНЕШНЕЕ СОЕДИНЕНИЕ С ГРУППОЙ ОБЯЗАТЕЛЬНО даже без фильтра по аккаунту:
    условие по `Group.account_id` иначе не с чем связать, и фильтр развалился
    бы молча. Записей соединение не теряет — отправка с удалённой группой
    остаётся в файле.

    ⚠️ НЕСУЩЕЕ ОГРАНИЧЕНИЕ. Корректность держится на том, что генераторные
    зависимости (сессия БД из `get_db`) закрываются ПОСЛЕ отправки тела ответа;
    требование `fastapi>=0.129.0` записано в `pyproject.toml` и ослаблению не
    подлежит. Суита эту границу не проверяет вовсе: подмена `get_db` в тестах
    генератором не является, и времени закрытия сессии в тестах не наблюдается.
    Пункт вынесен в ручные проверки плана 04-10.
    """
    user = await get_user_from_cookie(request, db, settings)
    if not user:
        return RedirectResponse(url="/login", status_code=302)

    status = clean_choice(status, STATUS_VALUES)
    messenger = clean_choice(messenger, MESSENGER_VALUES)
    period = clean_choice(period, PERIOD_VALUES)
    account_id_int = parse_account_id(account_id)

    # ПОТОЛОК ПРОВЕРЯЕТСЯ ДО КОНСТРУИРОВАНИЯ ПОТОКА (D-27, T-04-33). У потокового
    # ответа код и заголовки уходят до первого фрагмента тела и после уже
    # неизменяемы: проверка внутри генератора дала бы либо файл со статусом
    # успеха и текстом ошибки внутри, либо обрезанный файл без единого признака
    # обрезки. Число считает тот же счётчик, что показывает линейка над
    # списком, — вызов один, потребителя два, и разойтись им не на чем.
    total = await history_count(
        db,
        user_id=user.id,
        status=status,
        messenger_type=messenger,
        account_id=account_id_int,
        period=period,
        user=user,
    )
    if total > EXPORT_ROW_CAP:
        # Перенаправление на ТОТ ЖЕ отфильтрованный список: потерянные здесь
        # фильтры показали бы другой экран и предложили бы сузить период у
        # выборки, которую пользователь не выгружал.
        params = history_filter_params(status, messenger, account_id_int, period)
        params["export"] = EXPORT_TOO_MANY
        return RedirectResponse(url=f"/history?{urlencode(params)}", status_code=302)

    query = (
        select(SendLog, Group)
        .outerjoin(Group, SendLog.group_id == Group.id)
        .where(SendLog.user_id == user.id)
    )
    query = apply_history_filters(
        query,
        status=status,
        messenger_type=messenger,
        account_id=account_id_int,
        period=period,
        user=user,
    )
    query = query.order_by(SendLog.sent_at.desc()).execution_options(
        yield_per=EXPORT_YIELD_PER
    )

    async def body():
        """Метка порядка байтов, шапка, затем строки — партиями.

        Запись идёт стандартным модулем CSV в буфер на одну строку: он ставит
        кавычки там, где значение содержит разделитель, кавычку или перевод
        строки, — руками этот набор случаев не выписывается без ошибок.
        """
        buffer = io.StringIO()
        writer = csv.writer(
            buffer,
            delimiter=EXPORT_DELIMITER,
            quoting=csv.QUOTE_MINIMAL,
            lineterminator="\r\n",
        )

        def flush() -> str:
            chunk = buffer.getvalue()
            buffer.seek(0)
            buffer.truncate(0)
            return chunk

        writer.writerow(EXPORT_HEADER)
        # Метка порядка байтов — ПЕРВЫЕ байты тела (D-25). Без неё табличный
        # редактор в русской локали читает файл однобайтовой кодировкой, и
        # кириллица приезжает мусором: файл открывается, выглядит заполненным и
        # не содержит ни одного читаемого слова.
        yield EXPORT_BOM + flush()

        # Чтение ПОТОКОМ, а не одной выборкой: память держится порядка размера
        # партии, а не размера выборки (T-04-32). На боевом драйвере это
        # серверный курсор, на тестовом — буферизация партиями; интерфейс один.
        #
        # ОБРЫВ ПОСРЕДИ ПОТОКА НАЗЫВАЕТ СЕБЯ (D-27). Код 200 и заголовок с
        # именем файла уходят ДО первого фрагмента тела и после уже
        # неизменяемы: ошибка базы, оборванный курсор или сбой сериализации
        # после первого `yield` оставили бы пользователя с файлом, который
        # открывается, выглядит полным и короче правды. Потолок строк проверен
        # ДО начала ответа ровно затем, чтобы такого исхода не было, — здесь
        # закрыт второй вход в него. Строка-маркёр не чинит выгрузку: она
        # делает неполноту ВИДИМОЙ, а исключение уходит дальше, чтобы попасть в
        # журнал приложения.
        try:
            result = await db.stream(query)
            async for log, group in result:
                writer.writerow(export_row(log, group, user))
                yield flush()
        except Exception:
            logger.error(
                "history_export_stream_failed", user_id=user.id, exc_info=True
            )
            writer.writerow([EXPORT_TRUNCATED_MARKER])
            yield flush()
            raise

    return StreamingResponse(
        body(),
        media_type="text/csv; charset=utf-8",
        # Имя файла — константа модуля и из значений пользователя не собирается
        # (T-04-34): подстановка в заголовок ответа невозможна по построению.
        headers={
            "Content-Disposition": f'attachment; filename="{EXPORT_FILENAME}"',
        },
    )


