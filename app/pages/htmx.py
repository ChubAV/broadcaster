"""Слой ответа: единственное место, где приложение решает, ЧЕМ отвечать.

ПОЧЕМУ МОДУЛЬ ОДИН. Ветвление «пришёл ли запрос от слоя письма» до этой фазы
жило в двух местах редактора объявлений двумя литеральными копиями чтения
заголовка. Копия — не оформление: обработчик, скопировавший строку и забывший
ветку деградации, отвечает человеку без JavaScript пустотой, и обнаруживается
это жалобой, а не тестом. Здесь признак объявлен РОВНО ОДИН раз, и второе
объявление ловится машинным гейтом (план 08-07, `HX_HEADER_READS = 1`), а не
бдительностью читателя.

ДВА ВЫХОДА, А НЕ ОДИН (D-15). `respond()` обслуживает ОБРАБОТЧИКИ — они
возвращают ответ. `refuse()` обслуживает ЗАВИСИМОСТИ — они ответа не
возвращают вовсе и прервать цепочку могут единственным способом, исключением
(довод выписан у `require_access` и повторён у `forbid_when_impersonating`).
Один общий выход покрыть оба случая не может: `return` из зависимости FastAPI
ОТБРАСЫВАЕТ, и запрет выглядел бы поставленным, не срабатывая ни разу.

Третий выход — переход на ВНЕШНИЙ адрес — здесь сознательно отсутствует и
вводится Фазой 11 вместе с формой оплаты, когда у него появится предмет.
Ловушка записана заранее: внешний адрес НИКОГДА не едет в `redirect=`, он
уходит заголовком `HX-Redirect`, потому что `selfRequestsOnly: true` из блока
конфигурации заблокировал бы межсайтовый переход по `HX-Location`.
"""
from typing import Awaitable, Callable, NoReturn

from fastapi import HTTPException, Request
from fastapi.responses import RedirectResponse, Response

# ЕДИНСТВЕННОЕ НА ПРОЕКТ ИМЯ ЗАГОЛОВКА ПРИЗНАКА (критерий 1 фазы, FOUND-04).
# Второе его вхождение в `app/**/*.py` роняет гейт единственности — именно
# поэтому в докстрингах этого файла имя не повторяется ни разу и упоминается
# словами «признак запроса htmx».
HX_REQUEST_HEADER = "HX-Request"

# Заголовок ответа, ПРИКАЗЫВАЮЩИЙ браузеру уйти по адресу без перезагрузки.
# Константой, а не строкой по месту: значение уезжает клиенту, и любое его
# вхождение обязано быть видно одним грепом при разборе инцидента.
HX_LOCATION_HEADER = "HX-Location"

# Ключ параметра, которым код исхода действия едет на приземляющуюся страницу.
# ЕДЕТ КОД, А НЕ ТЕКСТ, и это несущее свойство канала: текст в адресной строке
# означал бы, что владелец ссылки пишет пользователю сообщение от имени
# приложения, а кириллица в значении заголовка вдобавок роняет кодирование
# заголовков в latin-1.
NOTICE_QUERY_KEY = "notice"


def is_htmx(request: Request) -> bool:
    """Пришёл ли запрос от слоя письма — ЕДИНСТВЕННОЕ на проект чтение признака.

    Единственность здесь есть предмет фазы, а не стиль (критерий 1). Пока
    чтений было два, «улучшенный» и «базовый» пути расходились молча: правка,
    внесённая в одну ветку, оставляла вторую прежней, и человек без JavaScript
    получал другой продукт. Одно объявление превращает это расхождение из
    возможного в невыразимое, а полноту стережёт машинный гейт (план 08-07):
    второе вхождение имени заголовка в исходники приложения роняет тест.

    ⚠️ ПУСТОЕ ЗНАЧЕНИЕ СЧИТАЕТСЯ ОТСУТСТВИЕМ ПРИЗНАКА. Слой письма присылает
    `true` и не присылает пустоты никогда; «пустая строка есть признак»
    означало бы, что ветку htmx включает запрос, ничего о ней не сказавший.

    ⚠️ ПРИЗНАК ПРИХОДИТ ОТ КЛИЕНТА И ЦЕЛИКОМ ИМ УПРАВЛЯЕМ, и это принято
    (T-08-09, disposition `accept`). Разница исходов — только транспорт одного
    и того же решения: привилегий подделанный заголовок не выдаёт, потому что
    вердикт вычисляется ДО развилки транспорта и от заголовка не зависит.
    """
    return bool(request.headers.get(HX_REQUEST_HEADER))


class HtmxRefusal(Exception):
    """Отказ зависимости, обязанный доехать заголовком, а не телом.

    ⚠️ ТИП СВОЙ, А НЕ `HTTPException`, И ВЫБОР ВЫНУЖДЕННЫЙ. Обработчик FastAPI
    для `HTTPException` отдаёт `JSONResponse` при ЛЮБОМ статусе, включая 2xx, —
    то есть тело `{"detail": …}`. FOUND-07 запрещает человеку со слоем письма и
    редирект, и JSON, поэтому отказ обязан миновать этот обработчик. Наследовать
    от `HTTPException` нельзя по той же причине: поиск обработчика идёт по
    порядку наследования, и потомок ушёл бы в тот же `JSONResponse`.

    В ответ исключение превращает обработчик, зарегистрированный в
    `app/main.py` — по форме четырёх доменных исключений, живущих там же.
    """

    def __init__(self, location: str) -> None:
        super().__init__(location)
        self.location = location


def _local_path(value: str) -> str:
    """Пропустить значение в заголовок ответа — или отказать до отправки.

    Проверка закрывает ТРИ угрозы одной строкой требований:

    1. ОТКРЫТЫЙ РЕДИРЕКТ (T-08-05). Заголовок перехода есть готовый примитив
       увода с сайта: браузер уходит по нему молча. Адрес со схемой и адрес
       протокол-относительный (`//чужой.сайт`) отвергаются, поэтому увести
       человека можно только правкой исходника, а не подбором ссылки.
    2. ИНЪЕКЦИЯ ЗАГОЛОВКА (T-08-01). Перевод строки внутри значения дописывает
       в ответ ЛЮБОЙ заголовок — в том числе `Set-Cookie`. Управляющие символы
       отвергаются целым классом, а не перечнем известных.
    3. ПАДЕНИЕ НА КОДИРОВАНИИ (T-08-02). Значения заголовков кодируются в
       latin-1, и кириллица в них роняет ответ пятисоткой. Именно поэтому по
       этому каналу едет КОД уведомления, а не его текст.

    ⚠️ ТЕКСТ ОШИБКИ НЕ ПОДСТАВЛЯЕТ САМО ЗНАЧЕНИЕ. Отвергнутое значение попало
    бы в журнал и в трассировку, то есть враждебная строка получила бы второй
    маршрут наружу — ровно то, от чего проверка и стоит.
    """
    if not value.startswith("/") or value.startswith("//"):
        raise ValueError(
            "адрес перехода обязан быть локальным путём: он начинается с "
            "одного «/», без схемы и без имени узла"
        )
    if "\\" in value:
        raise ValueError(
            "адрес перехода содержит обратную косую черту — браузеры "
            "разбирают её как разделитель пути, и адрес перестаёт быть тем, "
            "чем выглядит"
        )
    if any(ord(char) < 0x20 or ord(char) == 0x7F for char in value):
        raise ValueError(
            "адрес перехода содержит управляющий символ — значение заголовка, "
            "несущее перевод строки, дописывает в ответ чужие заголовки"
        )
    if not value.isascii():
        raise ValueError(
            "адрес перехода содержит символ вне ASCII — значения заголовков "
            "кодируются в latin-1, и такой ответ не отправится вовсе"
        )
    return value


def location_response(location: str) -> Response:
    """ЕДИНСТВЕННАЯ сборка ответа, приказывающего браузеру уйти по адресу.

    ⚠️ СТАТУС 204, А НЕ 200, И ЭТО НЕ ПЕДАНТИЗМ. У ответа 204 тела нет ПО
    ОПРЕДЕЛЕНИЮ — требование «не JSON» становится свойством статуса, а не
    обещанием кода, и нарушить его нельзя даже случайно. Вдобавок правило
    `{"code":"204","swap":false}` из блока конфигурации означает, что браузер,
    по какой-то причине не отработавший заголовок перехода, НЕ опустошит
    область свопа: худшим исходом остаётся «ничего не произошло», а не «экран
    стёрся».

    Статус разбору заголовка не мешает: слой письма читает заголовок перехода
    ДО применения правил обработки ответа (проверено по вендоренному 2.0.10).
    """
    return Response(
        status_code=204, headers={HX_LOCATION_HEADER: _local_path(location)}
    )


def refuse(
    request: Request, *, location: str, without_htmx: HTTPException
) -> NoReturn:
    """Узкий выход ОТКАЗА ЗАВИСИМОСТИ: тот же вердикт, два транспорта.

    ⚠️ ФОРМА ОТКАЗА БЕЗ htmx ПРИХОДИТ ПАРАМЕТРОМ, А НЕ СОБИРАЕТСЯ ЗДЕСЬ.
    Сегодняшних форм две и они РАЗНЫЕ: 302 с заголовком `location` у гейта
    доступа (человеку нужен экран, где чинят) и 403 с `detail` у запрета
    действий под чужой личностью (текст называет причину и выход). Помощник,
    скроенный под одну, вторую переписал бы — то есть починка видимости отказа
    оплачивалась бы потерей его смысла. Вызывающий остаётся владельцем своей
    формы, а общим становится только ВЫБОР транспорта.

    ⚠️ РАЗВИЛКА СТОИТ СТРОГО ПОСЛЕ ВЫЧИСЛЕНИЯ ВЕРДИКТА (T-08-04). Сюда
    приходят уже отвергнутым: предикат отказа читается вызывающим и этой
    функцией не трогается ни на одном из двух путей. Слой меняет ТРАНСПОРТ
    отказа и не имеет права изменить решение об авторизации.

    ⚠️ ОБА ПУТИ — `raise`, А НЕ `return`. Зависимость, объявленная через
    `include_router(dependencies=[...])`, своего возвращаемого значения никуда
    не отдаёт: FastAPI его отбрасывает, и «вернуть отказ» значило бы поставить
    запрет, не срабатывающий НИ НА ОДНОМ маршруте.
    """
    if is_htmx(request):
        raise HtmxRefusal(location)
    raise without_htmx


def _require_registered_notice(code: str) -> None:
    """Сверить код исхода с ЗАКРЫТЫМ реестром — на стороне ЗАПИСИ, а не рисования.

    Отрисовка по незнакомому коду не рисует НИЧЕГО (реестр закрыт сознательно:
    иначе владелец ссылки писал бы пользователю сообщения от имени приложения).
    Само по себе это правильно и небезопасно одновременно: опечатка в коде,
    записанном обработчиком, привела бы к тому, что исход действия ПРОПАЛ БЫ
    молча, и обнаружилось бы это жалобой. Сверка здесь ловит ту же опечатку
    там, где её ещё можно исправить, — в исходнике обработчика.

    ⚠️ ИМПОРТ РЕЕСТРА ОТЛОЖЕН ВНУТРЬ ФУНКЦИИ. Слой ответа обязан оставаться
    независимым от порядка сборки страниц: реестр — модуль того же пакета, и
    импорт на уровне модуля привязал бы слой к очерёдности импортов, которая
    сегодня складывается случайно.

    ⚠️ ОТСУТСТВИЕ РЕЕСТРА НЕ ГЛУШИТСЯ. Модуль реестра заводится соседним планом
    той же волны; «тихо пропустить проверку, пока его нет» означало бы дыру,
    которая переживёт причину своего появления и никем не будет замечена.
    Пусть лучше вызов упадёт вслух.
    """
    from app.pages.notices import notice_for

    if notice_for(code) is None:
        raise ValueError(
            "код исхода действия отсутствует в реестре уведомлений: "
            "рисовать по нему нечего, и человек не узнал бы об исходе вовсе"
        )


NOTICE_OOB_TEMPLATE = "includes/notice_oob.html"

# Тип содержимого, в тело которого приклейка блока уведомления допустима.
# Сравнение по вхождению, а не по равенству: заголовок несёт ещё и кодировку
# (`text/html; charset=utf-8`), и равенство отвергло бы каждый настоящий ответ.
_HTML_MEDIA_TYPE = "text/html"


def _notice_oob(code: str) -> str:
    """Внеполосный блок уведомления, собранный ОКРУЖЕНИЕМ ШАБЛОНОВ.

    Форма взята у `accounts.py::_connect_status` — единственного сегодняшнего
    места, где разметка ответа собирается вне обработчика: шаблон берётся из
    окружения и рендерится, а не склеивается строкой. Довод тот же: разметка
    плашки объявлена ОДИН раз, макросом, и вторая её копия, набранная здесь
    конкатенацией, разошлась бы с первой молча.

    ⚠️ ИМПОРТЫ ОТЛОЖЕНЫ ВНУТРЬ ФУНКЦИИ. Слой ответа обязан оставаться
    независимым от порядка сборки страниц: окружение шаблонов живёт в
    `app.pages.common`, который сам импортирует реестр уведомлений, — и импорт
    на уровне модуля привязал бы слой к очерёдности, которая сегодня
    складывается случайно. Та же причина, по которой отложен импорт реестра в
    `_require_registered_notice`.

    Код сюда приходит УЖЕ СВЕРЕННЫМ с закрытым реестром (`respond` зовёт
    сверку первой строкой), поэтому запись здесь не может не найтись; проверка
    всё же стоит, потому что «не может» относится к сегодняшнему вызывающему, а
    функция переживёт его.
    """
    from app.pages.common import templates
    from app.pages.notices import notice_for

    record = notice_for(code)
    if record is None:
        raise ValueError(
            "внеполосный блок уведомления собирается по коду, которого нет в "
            "реестре: рисовать нечего, и человек не узнал бы об исходе вовсе"
        )

    return templates.env.get_template(NOTICE_OOB_TEMPLATE).render(notice=record)


def _glue_notice(response: Response, notice: str) -> Response:
    """Дописать внеполосный блок к телу фрагмента — или отказать до отправки.

    ⚠️ ПРИКЛЕЙКА ДОПУСТИМА ТОЛЬКО К ТЕЛУ HTML. Дописать разметку в тело иного
    типа означало бы отдать клиенту документ, который тот разбирает по
    объявленным правилам, — то есть сломать его без единого признака: разбор
    JSON упадёт на первом же угловом скобке, и виноватым будет выглядеть
    клиент. Молча портить чужое тело нельзя, поэтому отказ громкий и достаётся
    он разработчику, а не пользователю.

    ⚠️ ДЛИНА ТЕЛА ПЕРЕСЧИТЫВАЕТСЯ. Заголовок длины уже собран вызывающим по
    ИСХОДНОМУ телу; оставленный как есть, он обрезал бы дописанный блок ровно
    по прежней границе — ответ ушёл бы усечённым, и увидеть это можно было бы
    только по проводу.
    """
    content_type = response.headers.get("content-type", "")
    if _HTML_MEDIA_TYPE not in content_type.lower():
        raise ValueError(
            "внеполосный блок уведомления приклеивается только к телу HTML, а "
            f"фрагмент объявил тип содержимого {content_type!r}: дописанная "
            "разметка сломала бы разбор на стороне клиента"
        )

    body = getattr(response, "body", None)
    if body is None:
        raise ValueError(
            "у ответа фрагмента нет собранного тела (потоковый ответ): "
            "дописать к нему внеполосный блок нечем"
        )

    response.body = body + _notice_oob(notice).encode("utf-8")
    response.headers["content-length"] = str(len(response.body))
    return response


def _with_notice(redirect: str, notice: str | None) -> str:
    """Адрес приземления с кодом исхода — и это ЕДИНСТВЕННАЯ его сборка.

    Разделитель выбирается по наличию строки запроса: второй «?» в адресе
    превратил бы код в часть значения соседнего параметра, и приземлившаяся
    страница не нарисовала бы плашку, ничего об этом не сказав.

    Экранирования значения здесь нет и оно не нужно: код приходит из ЗАКРЫТОГО
    реестра, сверенного строкой выше, — то есть из исходника, а не из запроса.
    Итог всё равно проходит `_local_path`: адрес, собранный кодом, обязан
    выдерживать ту же проверку, что и адрес, объявленный константой.
    """
    if notice is None:
        return _local_path(redirect)

    separator = "&" if "?" in redirect else "?"
    return _local_path(f"{redirect}{separator}{NOTICE_QUERY_KEY}={notice}")


async def respond(
    request: Request,
    *,
    redirect: str,
    notice: str | None = None,
    fragment: Callable[[], Awaitable[Response]] | None = None,
) -> Response:
    """ГЛАВНЫЙ выход обработчика: один путь для обоих способов прийти.

    ⚠️ `redirect` ОБЪЯВЛЕН КЛЮЧЕВЫМ И БЕЗ УМОЛЧАНИЯ, И ЭТО НЕСУЩЕЕ СВОЙСТВО, А
    НЕ ПРИДИРКА К СИГНАТУРЕ (FOUND-04). Обработчик, забывший путь деградации,
    отвечает человеку без JavaScript пустотой — и до этой сигнатуры такую
    забывчивость ловила только внимательность читателя. Обязательный аргумент
    делает её невыразимой: обработчик без пути деградации НЕ СОБИРАЕТСЯ КАК
    ВЫЗОВ. Ключевым, а не позиционным, — чтобы адрес деградации нельзя было
    подать «случайно, третьим по счёту» и перепутать с чем-то соседним.

    ⚠️ КОД ИСХОДА ЕДЕТ АДРЕСОМ НА ОБОИХ ТРАНСПОРТАХ (D-12). Именно поэтому
    приземлившаяся страница рисует плашку ОДНИМ путём — тем же, что и после
    полной перезагрузки. Второй механизм отрисовки не заводится и разойтись с
    первым не может. По каналу едет КОД, а не текст: текст в адресной строке
    означал бы, что владелец ссылки пишет пользователю от имени приложения, а
    кириллица в значении заголовка вдобавок уронила бы ответ пятисоткой.

    ⚠️ ВНЕШНИЙ АДРЕС НИКОГДА НЕ ЕДЕТ В `redirect=` (ловушка, записанная заранее
    для Фазы 11). Переход на чужой сайт — предмет ОТДЕЛЬНОГО заголовка
    (`HX-Redirect`), потому что `selfRequestsOnly: true` из блока конфигурации
    блокирует межсайтовый переход по `HX-Location`; ветку эту вводит Фаза 11
    вместе с формой оплаты. До тех пор внешний адрес, поданный сюда по
    невнимательности, не уезжает никуда: `_local_path` отвергает его ValueError
    на обоих транспортах.

    ⚠️ КОД ИСХОДА ДОЕЗЖАЕТ И НА ВЕТКЕ ФРАГМЕНТА — ВНЕПОЛОСНЫМ БЛОКОМ. Прежняя
    редакция этого абзаца объявляла приклейку границей, которую функция не
    пересекает, и отдавала фрагмент ровно таким, каким его собрал вызывающий.
    Граница закрыта: когда задан и код, и фрагмент, тело ответа дополняется
    блоком, подменяющим СОДЕРЖИМОЕ области уведомления шелла. Без этого исход
    действия был бы виден только тому, кто получил редирект, — то есть каналом
    пользовался бы лишь один из двух транспортов.

    ⚠️ ПРИКЛЕЙКА НЕ МОЛЧИТ НА ЧУЖОМ ТЕЛЕ. Фрагмент, объявивший тип содержимого
    не-HTML, приклейку не получает: вызов падает `ValueError`. Дописать
    разметку в такое тело значило бы сломать разбор на стороне клиента без
    единого признака на стороне сервера.
    """
    if notice is not None:
        _require_registered_notice(notice)

    if not is_htmx(request):
        return RedirectResponse(url=_with_notice(redirect, notice), status_code=302)

    if fragment is None:
        return location_response(_with_notice(redirect, notice))

    # Адрес деградации проверяется ДАЖЕ НА ВЕТКЕ ФРАГМЕНТА, где он никуда не
    # уезжает: иначе негодный адрес доживал бы в исходнике до дня, когда у
    # обработчика выключат фрагмент, и падал бы уже на человеке.
    _with_notice(redirect, notice)

    response = await fragment()
    if notice is None:
        return response
    return _glue_notice(response, notice)
