# ПРАВИЛО ДОСТУПА ОБЪЯВЛЕНО В `app/application/billing/`, А МОДУЛЬ ЕГО ТОЛЬКО
# ЧИТАЕТ. С плана 05.1-04 вердикт приезжает ГОТОВЫМ из контекста шелла
# (`access["open"]`), и собственного сравнения дат здесь нет ни одного: правило
# доступа одно на проект (`access_is_open`), и второе его выражение на странице
# разъехалось бы с зависимостью `require_access` молча (T-05.1-19).
#
# ⚠️ ПОРЯДОК ТАРИФОВ И ОСИ ПОТРЕБЛЕНИЯ УШЛИ ВМЕСТЕ С ПРЕДМЕТОМ. Ни правила
# перехода между тарифами, ни модуля осей этот файл больше не зовёт: тарифов
# нет, сравнивать нечего, а считать человеку нечего по построению — критерий
# фазы требует экрана, на котором не осталось арифметики. Имена снятых вызовов
# здесь не названы: гейт отсутствия читает файл по тексту.


def _access_state(access: dict, ever_paid: bool) -> str:
    """Одно из четырёх состояний экрана. ПОРЯДОК ПРОВЕРОК ОБЯЗАТЕЛЕН.

    Бесплатный доступ выигрывает у всех: человеку, которому доступ выдан
    администратором, дата окончания не читается вовсе, и показать ему «доступ
    закрыт» из-за просроченной колонки значило бы соврать про его собственную
    льготу.

    ⚠️ КЛЮЧ `is_comped` ПРИЕХАЛ ИЗ ШЕЛЛА ПЛАНОМ 05.1-09 — вместе с читателями
    колонки `subscriptions.has_free_access`, а не вместе с ней самой: колонку
    завела ревизия `0020` (план 05.1-08), и до появления читателей чтение через
    умолчание давало `False` на каждом рендере. Каскад ниже был объявлен ЗАРАНЕЕ
    и намеренно: приписать первую проверку к готовому каскаду позже — значит
    поставить её в конец и получить экран, на котором льгота проигрывает
    истёкшей дате. Порядок здесь тот же, что в предикате доступа и в виджете
    сайдбара; чтение остаётся через `.get(...)` с умолчанием, потому что
    пользователь без строки подписки обязан получить экран, а не пятисотку.

    Дальше — закрытый срок, затем «срок жив, а успешных подписочных платежей
    нет» (пробный период), иначе — оплачено.
    """
    if access.get("is_comped", False):
        return STATE_COMPED
    if not access.get("open", False):
        return STATE_EXPIRED
    return STATE_PAID if ever_paid else STATE_TRIAL


@router.get("/billing", response_class=HTMLResponse)
async def billing_page(
    request: Request,
    db: AsyncSession = Depends(get_db),
    settings: Settings = Depends(get_settings),
):
    """Раздел «Подписка»: доступ к системе и история платежей одним маршрутом.

    НА ЭКРАНЕ ОСТАЁТСЯ РОВНО ЧЕТЫРЕ ВЕЩИ и плашка причины: цена, дата окончания
    доступа, кнопка оплаты, журнал платежей. Пять блоков прежнего раздела
    (текущий тариф, оси потребления, витрина тарифов, баланс сообщений и пакеты,
    история операций) сняты вместе с предметом: четыре из них были СЧЁТОМ, а
    критерий фазы требует, чтобы человек видел дату и историю и больше ничего не
    считал.

    СТРАНИЦА НИЧЕГО НЕ АГРЕГИРУЕТ. Деньги приходят из журнала платежей,
    вердикт и дата — из уже посчитанного контекста шелла. Собственного запроса
    обработчик пишет ровно один — счёт успешных подписочных платежей, и тот
    живёт в сервисе, а не здесь.

    ⚠️ ОБРАБОТЧИК НЕ ПИШЕТ В БД НИ ПРИ КАКИХ УСЛОВИЯХ (D-05, T-05-24). Сюда
    приводит `return_url` ЮKassa, и редирект браузера происходит ТАКЖЕ ПРИ
    ОТКАЗЕ ОТ ОПЛАТЫ. Ленивое создание подписки на рендере — самое лёгкое
    место, где раздел начал бы раздавать платный ресурс бесплатно, поэтому
    обработчика возврата в проекте нет вовсе, а срок двигает только вебхук.
    Пользователь, вернувшийся до прихода уведомления, видит свой платёж СТРОКОЙ
    истории в статусе «в обработке» — то есть узнаёт, что деньги в обработке, а
    не что оплата не прошла.

    ⚠️ ИСХОД НАЖАТОЙ КНОПКИ ЭТОТ ОБРАБОТЧИК БОЛЬШЕ НЕ ЧИТАЕТ ВОВСЕ. Код исхода
    приезжает перенаправлением от форм оплаты и разрешается в слова ОДИН раз на
    продукт — областью уведомления шелла по закрытому реестру
    (`app/pages/notices.py`). Требование T-05-46 от этого не ослабло, а
    усилилось: значение параметра не попадает в разметку ни здесь, ни там, и
    мест, где эту недостижимость надо удерживать, стало одно вместо трёх.

    ⚠️ ПАРАМЕТР `expired`, КОТОРЫМ ГЕЙТ ПОМЕЧАЕТ СВОЙ РЕДИРЕКТ, НЕ ЧИТАЕТСЯ
    ЗДЕСЬ НИ ОДНОЙ СТРОКОЙ (T-05.1-21). Плашка о закрытом доступе рисуется по
    СОСТОЯНИЮ с сервера, и у этого два следствия, оба ценные: человек, открывший
    раздел из меню, читает те же слова — ему СКАЗАНО, а не повезло с маршрутом;
    и из адресной строки в разметку не уходит вообще ничего — это
    недостижимость, а не экранирование, подставлять нечего.
    """
    user = await get_user_from_cookie(request, db, settings)
    if not user:
        return RedirectResponse(url="/login", status_code=302)

    # Вердикт доступа и срок берутся из УЖЕ ПОСЧИТАННОГО контекста шелла, вторым
    # запросом не считаются: показатель один — источник обязан быть один
    # (D-09/D-19). Ключ `quota` заменён ключом `access` планом 05.1-04 вместе со
    # сменой ФОРМЫ значения: имени тарифа в нём больше нет, потому что тарифов
    # нет (D-F), а есть вердикт, дата и остаток дней.
    # ⚠️ ЧТЕНИЕ — ЧЕРЕЗ `.get(...)` С УМОЛЧАНИЕМ НА КАЖДОМ ШАГЕ. Пользователи,
    # заведённые до ревизии 05.1-08, строки подписки не имеют, и встретить их
    # пятисоткой значило бы закрыть единственный экран, с которого они могут
    # заплатить. Отсутствие строки — ОПРЕДЕЛЁННОЕ состояние (доступа нет), а не
    # исключение.
    shell = getattr(request.state, "shell", None) or {}
    # Копия словаря, а не он сам: в неё дописывается вычисленное состояние, а
    # словарь шелла рисует виджет на этом же документе — дописывать в чужой
    # объект значило бы менять то, что уже прочитано другой поверхностью.
    access = dict(shell.get("access", {}))

    # ПОТОЛОК СВЕРЯЕТСЯ ДО КОНСТРУИРОВАНИЯ СПИСКА (D-17), приёмом потолка
    # выгрузки истории. Вывести срабатывание из длины уже выбранного списка
    # нельзя: ровно на потолке список полон, и «показано не всё» стало бы
    # неотличимо от «столько и есть». Тихая обрезка запрещена — молча короткий
    # журнал денег читается как «других платежей не было».
    payments_total = await count_payments(db, user.id)
    payments = await get_payment_history(db, user.id, limit=PAYMENT_LIST_CAP)

    # ПРИЗНАК «ПЛАТИЛ КОГДА-НИБУДЬ» — ОДИН `count()` И ТОЛЬКО НА ЭТОЙ СТРАНИЦЕ.
    # В шелл он не уезжает намеренно: шелл исполняется на 26 маршрутах, и запрос
    # ради подписи виджета оплачивался бы на каждом рендере продукта. Следствие
    # принято сознательно и названо прямо — виджет сайдбара пробный период от
    # оплаченного НЕ ОТЛИЧАЕТ, и слова «пробный» в нём нет.
    #
    # Считаются только УСПЕШНЫЕ подписочные платежи: незавершённый и отклонённый
    # сделкой не являются, и человек, отказавшийся от оплаты на стороне ЮKassa,
    # не имеет права прочитать «подписка оплачена».
    ever_paid = await count_succeeded_subscription_payments(db, user.id) > 0

    # СОСТОЯНИЕ СЧИТАЕТСЯ ЗДЕСЬ И РОВНО ОДИН РАЗ. Разметке уходит готовый ответ:
    # вторая копия правила в Jinja разъехалась бы с гардом доступа молча.
    access["state"] = _access_state(access, ever_paid)

    # ⚠️ ПРИОРИТЕТА ДВУХ ПЛАШЕК ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО НЕ ЗАБЫТОЕ УСЛОВИЕ.
    # Он объявлялся затем, что исход только что нажатой кнопки и фоновое
    # состояние доступа рисовались В ОДНОМ месте карточки и читались подряд как
    # две разные беды. Конкурировать им теперь не за что: исход действия ушёл в
    # общую область шелла, а состояние доступа осталось в карточке раздела.
    # Условие снято ВМЕСТЕ со своим предметом — оставленное, оно гасило бы
    # объяснение закрытого доступа по причине, которой на экране больше нет.
    access_notice = (
        "" if access["state"] != STATE_EXPIRED else ACCESS_CLOSED_NOTICES[ever_paid]
    )

    return templates.TemplateResponse(
        "billing/balance.html",
        {
            "request": request,
            "user": user,
            "is_admin": check_is_admin(user, settings),
            # ВЕРДИКТ, ДАТА, ОСТАТОК СУТОК И ГОТОВОЕ СОСТОЯНИЕ — ОДНИМ КЛЮЧОМ.
            # Ключ `subscription` снят вместе со своим содержимым: имени тарифа
            # нет (D-F), а признак истечения выражается состоянием.
            "access": access,
            "ever_paid": ever_paid,
            # ЦЕНА — МАШИННАЯ СТРОКА НАСТРОЙКИ, подпись из неё делает глобал
            # форматирования. Литерала суммы нет ни здесь, ни в разметке: копия
            # числа разошлась бы с настройкой молча (T-05.1-06 — цену читает
            # сервер и на входе оплаты тоже).
            "subscription_price": settings.subscription_price,
            "payments": payments,
            "payments_total": payments_total,
            "payments_cap": PAYMENT_LIST_CAP,
            "payments_truncated": payments_total > PAYMENT_LIST_CAP,
            "payments_enabled": settings.yookassa_enabled,
            # ГОТОВАЯ СТРОКА, и её источник — СОСТОЯНИЕ, известное серверу из
            # строки подписки, а не адрес. Ключ исхода действия отсюда снят:
            # исход рисует общая область шелла, а состояние — эта карточка, и
            # смешивать их в одном ключе значило бы вернуть тот самый приоритет,
            # который стал беспредметным.
            "access_notice": access_notice,
            "active_page": "billing",
        },
    )


@money_router.post("/billing/subscribe")
async def subscribe_to_plan(
    request: Request,
    db: AsyncSession = Depends(get_db),
    settings: Settings = Depends(get_settings),
):
    """Заводит платёж за доступ и уводит пользователя на страницу оплаты ЮKassa.

    ⚠️ ФОРМА НЕ НЕСЁТ НИ ОДНОГО ПОЛЯ, И ЭТО ГЛАВНОЕ СВОЙСТВО ОБРАБОТЧИКА
    (T-05.1-06, ASVS V5). Доступ стоит ОДНО число, оно живёт в
    `settings.subscription_price`, и читает его СЕРВЕР. Покупателю нечего
    подменить: поверхность подмены суммы схлопнута до нуля, а не отфильтрована.
    До плоской модели из формы приезжал идентификатор тарифа, и цена искалась в
    прейскуранте ПО НЕМУ — защита работала, но существовала.

    ПОРЯДОК ПРОВЕРОК СОХРАНЁН ДОСЛОВНО: сначала кто пришёл, потом откуда
    пришёл, потом можно ли платить вообще. Сверка источника стоит ДО любого
    обращения к БД и до создания платежа.

    ⚠️ ГАРДА СМЕНЫ ТАРИФА ЗДЕСЬ БОЛЬШЕ НЕТ, ПОТОМУ ЧТО НЕТ ПРЕДМЕТА: тарифов
    Free/Basic/Pro не существует (D-A, D-D, D-F), сравнивать нечего, и правила
    смены тарифа никто не спрашивал. Ветка `error=downgrade` снята вместе с
    правилом — оставить её значило бы держать на экране слова о переходе,
    которого не бывает.

    СРОК ДОСТУПА ЭТОТ ОБРАБОТЧИК НЕ ТРОГАЕТ. Он создаёт намерение оплатить;
    оплату подтверждает только вебхук (D-05). Обработчика возврата с ЮKassa в
    проекте нет намеренно: редирект браузера происходит и при отказе от оплаты.
    """
    user = await get_user_from_cookie(request, db, settings)
    if not user:
        return RedirectResponse(url="/login", status_code=302)

    # СВЕРКА ИСТОЧНИКА ОСТАЁТСЯ 403 БЕЗ ПРИЧИНЫ. Чужому источнику причина
    # отказа не сообщается: межсайтовый запрос не имеет права узнать даже,
    # включены ли платежи. Порядок проверок не меняется — сначала кто пришёл,
    # потом откуда, потом что просит.
    if not is_same_origin(request):
        return Response(status_code=403)

    if not settings.yookassa_enabled:
        return RedirectResponse(url=f"/billing?notice={notices.PAYMENT_DISABLED}", status_code=302)

    try:
        result = await create_payment(
            db,
            user_id=user.id,
            # Предмет покупки — КОНСТАНТОЙ, никогда голым литералом (WR-04):
            # опечатка в литерале не падает громко, а уводит подписочный платёж
            # в пакетную ветку вебхука с пустым `messages_count`.
            kind=KIND_SUBSCRIPTION,
            # ТАРИФА У ПЛАТЕЖА НЕТ ВОВСЕ. `None` здесь — не умолчание, а запись
            # факта: предмет покупки один, и записать в колонку имя тарифа
            # значило бы завести второй источник правды о том, что продано.
            plan=None,
            # ЦЕНА ЧИТАЕТСЯ СЕРВЕРОМ ИЗ ОДНОГО ЛИТЕРАЛА НАСТРОЙКИ и не
            # собирается арифметикой: складывать и умножать нечего, поэтому
            # округлений в сумме не возникает по построению (D-A).
            price=settings.subscription_price,
            # `None` — НЕ УМОЛЧАНИЕ, А ЗАПИСЬ ФАКТА: гарда смены тарифа больше
            # не существует, ответа никто не давал, и `NULL` в этой колонке
            # означает ровно «правило не спрашивали» (`app/models/payment.py`).
            # Литерал `True` записал бы РАЗРЕШЕНИЕ, которого никто не выдавал, —
            # то есть подпись под сделкой от имени правила, которого нет
            # (T-05.1-11).
            switch_authorized=None,
            package_name=None,
            messages_count=None,
        )
    except PendingIntentCapError:
        # ОТДЕЛЬНАЯ ВЕТКА, А НЕ ОБЩАЯ С СОСЕДНЕЙ, И ЭТО НЕ ОФОРМЛЕНИЕ. Соседняя
        # говорит человеку «попробуйте ещё раз через минуту» — то есть ровно то
        # действие, которое этот отказ и вызвало. Различаются они ТИПОМ
        # исключения, потому что тип — единственное, что не разъедется.
        #
        # Потолок живёт ВНУТРИ создания платежа и своим шагом обработчика не
        # становится: второе место, где решается один вопрос, — ровно та
        # конструкция, за которую раздел получил два раунда правок.
        return RedirectResponse(url=f"/billing?notice={notices.PAYMENT_PENDING}", status_code=302)
    except PaymentCreationError:
        # Текст исключения СЮДА НЕ ПРИХОДИТ И НЕ НУЖЕН: он уже записан журналом
        # сервиса ключом `payment_create_failed`. На экран уезжает КОД причины,
        # а слова к нему принадлежат закрытому реестру (T-05-47).
        return RedirectResponse(url=f"/billing?notice={notices.PAYMENT_FAILED}", status_code=302)
    return RedirectResponse(url=result["confirmation_url"], status_code=302)
