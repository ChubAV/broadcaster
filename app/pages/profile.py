from fastapi import APIRouter, Depends, Form, Request
from fastapi.responses import HTMLResponse, RedirectResponse
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import Settings
from app.constants import TIMEZONE_CHOICES, VALID_TIMEZONES
from app.dependencies import forbid_when_impersonating, get_db, get_settings
from app.pages import notices
from app.pages.common import check_is_admin, get_user_from_cookie, templates
from app.pages.htmx import respond, respond_field_error


router = APIRouter(tags=["pages"])

# Включаемый шаблон настроек профиля (план 11-08) — ЕДИНСТВЕННЫЙ источник этой
# формы: им рисуется и карточка страницы, и ОБА фрагмента этого плана (успех и
# ошибка поля). Имя выписано константой, а не строкой по месту: два написания
# одного пути разошлись бы молча, и человек, сохранивший пояс без перезагрузки,
# получил бы форму, отличающуюся от страничной.
PROFILE_SETTINGS_TEMPLATE = "includes/profile_settings.html"

# Текст ошибки поля — ДОСЛОВНО тот же, что страница рисовала до перевода. Фаза
# меняет ТРАНСПОРТ ответа и его код, а не слова, которыми продукт говорит с
# человеком; переформулировка смешала бы два изменения в одном.
INVALID_TIMEZONE_MESSAGE = "Неверный часовой пояс"


def _settings_markup(*, selected: str, error: str | None = None) -> str:
    """Разметка настроек профиля, собранная ОКРУЖЕНИЕМ ШАБЛОНОВ.

    ⚠️ ФОРМА ВЗЯТА У `account_groups.py` И ОСНОВАНИЕ ТО ЖЕ: шаблон берётся из
    окружения и рендерится, а не склеивается строкой. Разметка формы объявлена
    ОДИН раз, включаемым шаблоном, и вторая её копия, набранная здесь
    конкатенацией, разошлась бы с первой МОЛЧА — обнаружилось бы это не тестом,
    а при первом обновлении страницы.

    ⚠️ ОБА ФРАГМЕНТА ПЛАНА СОБИРАЮТСЯ ЗДЕСЬ, И РАЗЛИЧАЮТСЯ ОНИ ТОЛЬКО
    КОНТЕКСТОМ. Успех подаёт СОХРАНЁННЫЙ пояс без ошибки, ошибка поля — пояс
    ПРИСЛАННЫЙ и текст ошибки. Две отдельные сборки различались бы ещё и
    разметкой, а разметке различаться здесь нечем.

    ⚠️ ЭКРАНИРОВАНИЕ ОБЕСПЕЧИВАЕТ ОКРУЖЕНИЕ, А НЕ ЭТОТ ПОМОЩНИК (T-11-13).
    Присланный пояс уезжает в шаблон ПАРАМЕТРОМ и ни на одном шаге не
    объявляется готовой разметкой. Вдобавок поле выбора рисует ЗАКРЫТЫЙ список
    поясов, а присланное значение лишь СРАВНИВАЕТСЯ с его элементами: значение,
    ни с одним не совпавшее, в документ не попадает ВОВСЕ. Это недостижимость,
    а не только экранирование, — и она сильнее.
    """
    return templates.env.get_template(PROFILE_SETTINGS_TEMPLATE).render(
        timezone_choices=TIMEZONE_CHOICES, selected=selected, error=error
    )


@router.get("/profile", response_class=HTMLResponse)
async def profile_get(
    request: Request,
    db: AsyncSession = Depends(get_db),
    settings: Settings = Depends(get_settings),
):
    user = await get_user_from_cookie(request, db, settings)
    if not user:
        return RedirectResponse(url="/login", status_code=302)

    return templates.TemplateResponse(
        "profile.html",
        {
            "request": request,
            "user": user,
            "is_admin": check_is_admin(user, settings),
            "active_page": "profile",
            "timezone_choices": TIMEZONE_CHOICES,
        },
    )


@router.post("/profile")
async def profile_post(
    request: Request,
    timezone: str = Form(""),
    db: AsyncSession = Depends(get_db),
    settings: Settings = Depends(get_settings),
    _under_another_identity: None = Depends(forbid_when_impersonating),
):
    """Правка учётных данных пользователя — ЗАПРЕЩЕНА ПОД ЧУЖОЙ ЛИЧНОСТЬЮ (D-22).

    ⚠️ ФОРМА ЗАКРЫТА ЦЕЛИКОМ, А НЕ ПОПОЛЬНО, И ЭТО РЕШЕНИЕ НА ВЫРОСТ. D-22
    называет смену адреса запрещённой, но ОТДЕЛЬНОГО маршрута смены адреса в
    продукте сегодня нет — когда его заведут, естественное место для него
    именно эта форма. Поле, добавленное в уже РАЗРЕШЁННЫЙ маршрут, машинный
    гейт запретов не заметил бы: маршрут-то объявлен, и полнота перечня по нему
    сходится. Запрет, поставленный заранее, снимает этот класс обхода целиком.

    ⚠️ ЧТЕНИЕ ПРОФИЛЯ ПРИ ЭТОМ ОТКРЫТО. Администратор под чужой личностью
    обязан ВИДЕТЬ настройки пользователя — часовой пояс объясняет, почему
    рассылка ушла не тогда, когда её ждали. Закрыт ровно изменяющий вход.

    Сегодняшнее содержимое формы — часовой пояс, и безобидным оно не является:
    им определяется, В КАКОЕ ВРЕМЯ уходят рассылки. Тихая правка часового пояса
    администратором сдвинула бы расписания пользователя, не оставив следа на
    экране, который тот открывает.

    ⚠️ ПЕРВЫЙ В ПРИЛОЖЕНИИ ОТВЕТ 422 С АВТОРСКИМ ФРАГМЕНТОМ (план 11-09,
    FORM-08). Правило 422 блока конфигурации получает подмену содержимого ТЕМ ЖЕ
    КОММИТОМ, что и этот маршрут, и порядок здесь несущий: подмена, включённая
    раньше авторского тела, сделала бы целью подмены DOM тело, состав которого
    приложение НЕ ВЫБИРАЕТ (умолчание фреймворка дословно повторяет присланное
    значение), — сток исполнения скрипта T-07-13. Сток закрыт ещё раньше,
    ОТДЕЛЬНЫМ планом 11-07 (`malformed_request_response`), поэтому ни на одном
    коммите фазы подмена не включена без обработчика.

    ⚠️ ПОЛЕ ПОЯСА ПОЛУЧИЛО УМОЛЧАНИЕ, И ЭТО РЕШЕНИЕ, А НЕ ОСЛАБЛЕНИЕ ПРОВЕРКИ.
    Обязательное поле срывало бы разбор СИГНАТУРЫ — то есть ответ собирал бы не
    продукт, а фреймворк, и на пути письма страничного слоя человек получил бы
    пустой 400 смягчения выше: ни формы, ни причины. С умолчанием отсутствующее
    поле идёт ТОЙ ЖЕ веткой, что и негодное значение, и человек получает форму с
    текстом ошибки. Новых проверок ввода при этом не заводится: годность пояса
    по-прежнему решает ОДНА сверка с закрытым перечнем (D-06).

    ⚠️ ОШИБКА ПОЛЯ — НЕ ИСХОД ДЕЙСТВИЯ, ПОЭТОМУ ВЫХОД У НЕЁ СВОЙ. Действие не
    состоялось, уводить человека некуда, и оба транспорта остаются на форме:
    путь без htmx получает СТРАНИЦУ со статусом ошибки, путь письма — фрагмент
    той же формы. Отсюда и отсутствие адреса деградации у этого вызова — у
    `respond()` он несущий, здесь был бы обязательным аргументом без предмета.

    ⚠️ ЭТОТ ИСХОД ВПЕРВЫЕ ПОДАЁТ КОД ИСХОДА ВМЕСТЕ С ФРАГМЕНТОМ. Приклейка
    внеполосного блока к телу фрагмента существует с Фазы 8 и до этого маршрута
    не использовалась НИ ОДНИМ обработчиком приложения — механизм был заведён и
    покрыт суитой заранее. Сохранение профиля и есть его первый потребитель:
    человек, оставшийся на странице благодаря слою письма, узнаёт исход ТЕМ ЖЕ
    каналом, что и человек, получивший перенаправление.
    """
    user = await get_user_from_cookie(request, db, settings)
    if not user:
        return await respond(request, redirect="/login")

    if timezone in VALID_TIMEZONES:
        user.timezone = timezone
        db.add(user)
        await db.commit()

        async def _saved() -> HTMLResponse:
            """Настройки с СОХРАНЁННЫМ поясом и без ошибки.

            ⚠️ ФУНКЦИЯ НУЛЬАРНАЯ И АСИНХРОННАЯ: слой ответа делает `await
            fragment()`. Отложенность несущая — на пути без htmx разметка не
            собирается вовсе.
            """
            return HTMLResponse(_settings_markup(selected=timezone))

        # ⚠️ ЭТОТ ИСХОД ВПЕРВЫЕ СТАНОВИТСЯ ВИДИМЫМ. Прежнее написание было
        # БУЛЕВЫМ признаком и не рисовалось НИ В ОДНОМ шаблоне продукта:
        # человек сохранял часовой пояс — то есть менял время, В КОТОРОЕ УХОДЯТ
        # ЕГО РАССЫЛКИ, — и получал ту же страницу молча, неотличимо от
        # «ничего не произошло». Код реестра рисуется общей областью шелла,
        # поэтому сохранение наконец отвечает.
        #
        # ⚠️ АДРЕС ПРИЗЕМЛЕНИЯ НЕ СДВИНУЛСЯ НИ НА СИМВОЛ: путь без htmx
        # по-прежнему уезжает на тот же адрес с тем же кодом реестра. Фаза
        # меняет ФОРМУ ответа, а не то, что действие делает.
        return await respond(
            request,
            redirect="/profile",
            notice=notices.PROFILE_SAVED,
            fragment=_saved,
        )

    async def _page() -> HTMLResponse:
        """Страница профиля с ошибкой поля — путь деградации ошибки заполнения.

        ⚠️ `selected` ПОДАЁТСЯ ПРИСЛАННЫМ, А НЕ СОХРАНЁННЫМ. Выбор источника
        значения — решение ВЫЗЫВАЮЩЕГО (включаемый шаблон умолчания не ставит),
        и на ветке ошибки форма обязана вернуть то, что человек ПРИСЛАЛ.
        """
        return templates.TemplateResponse(
            "profile.html",
            {
                "request": request,
                "user": user,
                "is_admin": check_is_admin(user, settings),
                "active_page": "profile",
                "timezone_choices": TIMEZONE_CHOICES,
                "selected": timezone,
                "error": INVALID_TIMEZONE_MESSAGE,
            },
        )

    async def _fragment() -> HTMLResponse:
        """Тот же включаемый шаблон с тем же контекстом — без шелла."""
        return HTMLResponse(
            _settings_markup(selected=timezone, error=INVALID_TIMEZONE_MESSAGE)
        )

    return await respond_field_error(request, page=_page, fragment=_fragment)

