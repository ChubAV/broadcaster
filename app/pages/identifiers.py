"""ГРАНИЦА ВЕЛИЧИНЫ ИДЕНТИФИКАТОРА — ОДНА НА ВЕСЬ ПРОЕКТ.

Модуль НЕЙТРАЛЬНЫЙ: он не импортирует ни одного страничного модуля и ни одной
модели. Зависимость идёт только в одну сторону — страничные модули зависят от
него, он не зависит ни от кого из них. Иначе первый же потребитель замкнул бы
цикл импорта, и граница, заведённая ради единственности, стала бы причиной, по
которой её нельзя ввезти.

⚠️ ЛЕТОПИСЬ МЕСТА. Прежним местом объявления был `app/pages/schedules.py`, и оно
НЕ БЫЛО ОШИБКОЙ: величина ограничивала ровно тот состав входов, который тогда
ограничивался, — пять входов файла расписаний, сведённых к одному владельцу
планом 10-12 ради закрытия блокеров `CR-01` и `CR-02` третьего круга ревизии.
Место пережило появление входов ТОГО ЖЕ КЛАССА в шести соседних модулях, и
расхождение стало наблюдаемым: ПЯТЫЙ круг ревизии
(`.planning/phases/10-rychag-components-modal-html/10-REVIEW.md`, находка
`CR-01`) предъявил ВОСПРОИЗВЕДЁННЫЕ исходы — `500` на шести маршрутах при `422`
на седьмом, ограниченном планом 10-12. Величина, объявленная в страничном
модуле, ограничивала там, куда смотрели, и молчала там, куда не смотрели.
Объявление переехало сюда планом 10-24; ПОТРЕБИТЕЛИ НЕ ПЕРЕИМЕНОВЫВАЛИСЬ —
переезд сделан переносом объявления, а не переименованием читателей, и имя
`ID_MAX` осталось доступным по прежнему пути импорта.

⚠️ ЧЕГО ПЕРЕЕЗД НЕ ДАЁТ, НАЗВАНО ЗДЕСЬ, А НЕ ОСТАВЛЕНО ЧИТАТЕЛЮ. Он не
проверяет поведения БОЕВОГО драйвера на неограниченном входе: у суиты драйвер
один (`sqlite+aiosqlite:///:memory:`), величина `2147483648` проходит в него
молча, тогда как asyncpg на ней даёт `DataError`. Переезд делает этот вопрос
МЕНЕЕ важным (отказ ставится ДО драйвера), но не отвечает на него — предмет
остаётся окном 39 реестра `.planning/WINDOWS.md`, и оно открыто.
"""

from typing import Annotated

from fastapi import Form, Path

# ВЕРХНЯЯ ГРАНИЦА ВЕЛИЧИНЫ ИДЕНТИФИКАТОРА — ОДНА НА ВЕСЬ ПРОЕКТ. Число здесь
# ВТОРИЧНО, основание первично: это верхняя граница КОЛОНКИ идентификатора
# (знаковое тридцатидвухбитное целое), то есть величина, вне которой значение
# не может принадлежать НИ ОДНОЙ строке ни на одном из двух драйверов проекта —
# ни на SQLite суиты, ни на PostgreSQL боевого стенда. Поэтому значение вне
# диапазона отбрасывается ДО запроса, а не роняет запрос драйвером: на SQLite
# это `OverflowError` («Python int too large to convert to SQLite INTEGER»), на
# PostgreSQL — `DataError` вне диапазона int32, и оба заканчиваются HTTP 500 на
# форменный POST — ровно тем, что модуль правил редактора себе и запретил
# (T-02-24, T-02-25).
#
# ОСНОВАНИЕ СНЯТО С МОДЕЛЕЙ, А НЕ ПЕРЕНЕСЕНО ЧИСЛОМ. Идентификаторы, участвующие
# в маршрутах страничного слоя, объявлены ОДНИМ И ТЕМ ЖЕ отображаемым целым без
# указания расширенной разрядности:
# `app/models/ad.py` — `id: Mapped[int] = mapped_column(primary_key=True)`;
# `app/models/schedule.py` — то же объявление;
# `app/models/messenger_account.py` — то же объявление.
# Колонки одной разрядности, поэтому граница у них ОДНА, и держать её надо в
# одном месте, а не в трёх — и тем более не в семи.
#
# ⚠️ ЛЕТОПИСЬ ИМЕНИ. Константа звалась `_AD_ID_MAX` и ограничивала РОВНО ОДИН
# вход — необязательное поле контекста `ad_id` помощника `_ad_id_from_form`
# (план 10-08, блокер `CR-01`). ПРЕЖНЕЕ ИМЯ НЕ БЫЛО ОШИБКОЙ: оно точно называло
# единственный вход, который тогда ограничивался. Оно пережило появление ещё
# ЧЕТЫРЁХ входов того же класса — трёх идентификаторов пути и обязательного
# поля объявления, — и расхождение имени с уже записанным основанием (основание
# называет предметом КОЛОНКУ, имя называло ОБЪЯВЛЕНИЕ) стало половиной причины,
# по которой граница осталась стоять там, куда смотрели, и молчать там, куда не
# смотрели (`CR-02`, отчёт верификации третьего круга). Имя приведено к
# основанию планом 10-12.
ID_MAX = 2_147_483_647

# ТРИ ПСЕВДОНИМА ОГРАНИЧЕННОГО ИДЕНТИФИКАТОРА, А НЕ ОДИН, И ЭТО РЕШЕНИЕ.
# Общей у них остаётся ВЕЛИЧИНА — ровно то единственное место, которого требует
# отчёт. Различается СПОСОБ ПЕРЕДАЧИ, а он есть свойство МАРШРУТА: один
# псевдоним на все входы либо потребовал бы от каждой сигнатуры выбирать способ
# на месте (то есть вернул бы решение туда, откуда его забирают), либо молча
# принял бы поле формы там, где ожидается адрес запроса.
#
# Нижняя граница у всех трёх — ЕДИНИЦА, а не ноль: идентификаторы
# автоинкремента начинаются с единицы, и ни ноль, ни отрицательные в домене не
# лежат (основание записано у `_ad_id_from_form` и перенесено дословно).
#
# Граница стоит НА ГРАНИЦЕ ПРИЛОЖЕНИЯ: значение вне диапазона отвергается ДО
# того, как тело обработчика получило управление, и потому ДО любого обращения
# к базе — включая вычисление вердикта о владении (`_ownership_verdict`), внутри
# которого падали два из пяти воспроизведённых отказов, и включая сверку
# источника (`is_same_origin`), которая на негодной величине была НЕДОСТИЖИМА:
# приведение к `int` удавалось, и отказ случался позже, уже в SQLAlchemy.
IdPath = Annotated[int, Path(ge=1, le=ID_MAX)]
IdForm = Annotated[int, Form(ge=1, le=ID_MAX)]
# У необязательного псевдонима ПУСТОЕ значение остаётся законным состоянием:
# схема допускает отвязанное расписание (`account_id` nullable с
# `ON DELETE SET NULL`, issue #35), и граница величины к ОТСУТСТВИЮ значения не
# применяется.
OptionalIdForm = Annotated[int | None, Form(ge=1, le=ID_MAX)]
