@dataclass(frozen=True)
class ModuleLogNames:
    """Имена журнала, связанные в одном модуле (IN-06, IN-09).

    `binders` — псевдонимы ввоза привязок `CONTEXT_BINDERS`
    (`from structlog.contextvars import bind_contextvars as bind_ctx` → `bind_ctx`).
    `receiver_names` — имена-получатели журнала вне `LOG_RECEIVERS` и шаблона
    `_LOGGER_NAME`: псевдоним ввоза модуля `logging` или журнала (`import logging as L`,
    `from … import logger as lg`), `from logging import root` и имя, связанное с
    получателем (`lg = logging.getLogger()`, `lg = structlog.get_logger().bind(...)`,
    `a = lg`, `if (lg := logging.getLogger()):`, `lg = …` в теле класса).
    `receiver_attributes` — атрибуты, связанные так же (`self.lg = structlog.get_logger()`),
    и имена, связанные с получателем в теле класса: их зовут через `self.lg` / `cls.lg`.
    `log_functions` — имена, голый вызов которых есть вызов журнала: функция модуля
    `logging` из `LOG_METHODS`, ввезённая в модуль (`from logging import info`,
    `from logging import warning as warn_`; ревью IN-09), и имя, связанное со ссылкой на
    вызываемое журнала (`info = logger.info`, `out = print`,
    `p = functools.partial(logger.info, …)`).
    `factories` — псевдонимы ввоза фабрик журнала (`from logging import getLogger as gl`) и
    имена и атрибуты, связанные со ссылкой на фабрику без вызова (`gl = logging.getLogger`);
    сверяются по последнему имени вызова, как и `LOGGER_FACTORIES`.
    `log_function_attributes` — атрибуты, связанные со ссылкой на вызываемое журнала
    (`self.out = logger.info`, `out = print` в теле класса), — вызов `self.out(…)`, `a.out(…)`
    у любого объекта (плоская область по владельцу, как у имени `methodcaller` и обёртки; цена
    «в сторону лишней находки» названа в шапке — решение владельца О-22 (а)). Имя, связанное с
    вызываемым журнала на уровне модуля или в функции (`out = logger.info`), сюда НЕ идёт: оно
    лежит в `log_functions` и читается членом только у объекта модуля —
    `getattr(sys.modules[__name__], "out")(…)`, `me.out(…)` (ревью WR-29: до плана 16-47 цикл
    самопроверки 1 плана 16-43, коммит `a77263ad`, клал его и сюда, и `fh.write(account.phone)`
    при `write = print` стал вызовом журнала; решение владельца О-20 (а), свойство 3).
    `module_objects` — имена, связанные в модуле с объектом модуля `sys.modules[__name__]` любой
    формой общей грамматики, цепочкой тоже (`me = sys.modules[__name__]`, `me2 = me`): член такого
    имени — член модуля (ревью WR-29, WR-30; помощник `_is_module_object`, план 16-47).
    `methodcaller_names` — имена, под которыми модуль зовёт `operator.methodcaller`
    (`from operator import methodcaller as mc`, `mc = operator.methodcaller`,
    `self.mc = operator.methodcaller`); `methodcallers` — пары «имя → вызов
    `methodcaller(…)`», связанные любой формой общей грамматики (`emit =
    operator.methodcaller("info", …)`, `self.emit = …`, цепочка `g = emit`) — по имени их
    зовут `emit(logger)` / `self.emit(logger)` (ревью WR-17).
    `partial_names` — имена, под которыми модуль зовёт `functools.partial`
    (`from functools import partial as bind_`, `bind_ = functools.partial`; самопроверка
    исполнителя 16-29 — гейт писателя разрешает псевдонимы `partial` с плана 16-22).
    `carrier_wrappers` — пары «имя → обёртка носителя»: имя, связанное общей грамматикой с
    `partial(<носитель>, <ссылка на вызываемое журнала или methodcaller>, …)`
    (`w = functools.partial(asyncio.to_thread, logger.info)`); вызов `w(…)`, `self.w(…)`,
    `getattr(self, "w")(…)` судится, как применённая обёртка `partial(…)(…)` (самопроверка
    исполнителя 16-32, цикл 2). Отображение строит функция общего модуля
    `carrier_wrapper_bindings` с общим предикатом `is_carrier_wrapper` (ревью WR-24, план
    16-37; О-16 (а), свойство 5).
    Область видимости — весь модуль. Новые поля — с умолчаниями, чтобы позиционное
    создание по трём прежним полям не ломалось.
    """

    binders: frozenset[str]
    receiver_names: frozenset[str]
    receiver_attributes: frozenset[str]
    log_functions: frozenset[str] = frozenset()
    factories: frozenset[str] = frozenset()
    log_function_attributes: frozenset[str] = frozenset()
    methodcaller_names: frozenset[str] = METHODCALLER_NAMES
    methodcallers: tuple[tuple[str, ast.Call], ...] = ()
    partial_names: frozenset[str] = PARTIAL_NAMES
    carrier_wrappers: tuple[tuple[str, ast.Call], ...] = ()
    module_objects: frozenset[str] = frozenset()


NO_MODULE_LOG_NAMES = ModuleLogNames(frozenset(), frozenset(), frozenset())

MODULE_OBJECT_EXPRESSION = "sys.modules[__name__]"


def _is_module_object(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Объект самого модуля: `sys.modules[__name__]` или имя, связанное в модуле с ним.

    Член объекта модуля — имя, связанное в этом модуле: `getattr(sys.modules[__name__], "lg")`,
    `sys.modules[__name__].lg`, `me.lg` при `me = sys.modules[__name__]` (цепочкой тоже —
    `names.module_objects`). Им читается и имя вызываемого журнала, связанное в модуле (ревью
    WR-29), и получатель журнала (ревью WR-30); член любого другого объекта с тем же именем —
    не член модуля. Решение владельца О-20 (а), свойства 3 и 4; план 16-47.
    """
    if isinstance(node, ast.Name):
        return node.id in names.module_objects
    return ast.unparse(node) == MODULE_OBJECT_EXPRESSION


def _module_object_names(bindings: list[Binding]) -> frozenset[str]:
    """Имена-цели общей грамматики, связанные с объектом модуля, — до неподвижной точки.

    `me = sys.modules[__name__]` и цепочка `me2 = me`: значение — `sys.modules[__name__]` или
    имя, уже признанное объектом модуля (`_is_module_object`).
    """
    found: set[str] = set()
    changed = True
    while changed:
        changed = False
        known = replace(NO_MODULE_LOG_NAMES, module_objects=frozenset(found))
        for target, value, _in_class_body in bindings:
            if isinstance(target, ast.Name) and target.id not in found and _is_module_object(value, known):
                found.add(target.id)
                changed = True
    return frozenset(found)


def _is_logger_name(name: str) -> bool:
    """Имя журнала по D-17: `LOG_RECEIVERS` или шаблон `_LOGGER_NAME`."""
    return name in LOG_RECEIVERS or bool(_LOGGER_NAME.search(name))


def _member(node: ast.expr) -> tuple[ast.expr, str] | None:
    """Доступ к члену объекта: `X.name` или `getattr(X, "name")` → (X, name).

    Строку в `getattr` читает `getattr_literal` общего модуля — один читатель обоих гейтов
    (план 16-32, ревью IN-15, О-15); имя, вычисленное во время исполнения
    (`getattr(logger, name)`), — не литерал (граница, названная в шапке).
    """
    if isinstance(node, ast.Attribute):
        return node.value, node.attr
    return getattr_literal(node)


def _last_name(node: ast.expr) -> str | None:
    """Последнее имя выражения: голое имя или имя члена (`X.name`, `getattr(X, "name")`).

    Читает общий `reading_name` (план 16-43, ревью WR-28; О-18 (а), свойство 2): до плана здесь
    жила своя копия того же чтения (имя, `_member` — атрибут и getattr-строка).
    """
    return reading_name(node)


def _is_factory_reference(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Фабрика журнала без вызова: `logging.getLogger`, `getattr(logging, "getLogger")`,
    псевдоним ввоза (`gl`) или имя, связанное с фабрикой, — по последнему имени."""
    name = _last_name(node)
    return name is not None and (name in LOGGER_FACTORIES or name in names.factories)


def _is_factory_call(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Вызов фабрики журнала по последнему имени или по псевдониму из `names.factories`."""
    return isinstance(node, ast.Call) and _is_factory_reference(node.func, names)


def _log_method_reference(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Ссылка на ЛЮБОЙ метод опознанного журнала (охват по получателю D-17, ревью WR-13):
    `logger.info`, `logger._log`, `getattr(logger, "makeRecord")` — член опознанного
    получателя, кроме журнала-атрибута (`root`, `parent`, атрибут, связанный в модуле с
    журналом) и
    фабрики (`logging.getLogger` — фабрика: её вызов — связывание, а не вызов журнала)."""
    member = _member(node)
    return (
        member is not None
        and member[1] not in LOGGER_ATTRIBUTE_LOGGERS
        and member[1] not in names.receiver_attributes
        and not _is_factory_reference(node, names)
        and _is_log_receiver(member[0], names)
    )


def _binder_reference(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Ссылка на привязку к контексту: имя из `CONTEXT_BINDERS` при любом получателе
    (и строкой в `getattr`) или псевдоним, под которым привязка ввезена в модуль."""
    if isinstance(node, ast.Name) and node.id in names.binders:
        return True
    return _last_name(node) in CONTEXT_BINDERS


def _is_print_reference(node: ast.expr) -> bool:
    """`print` или `builtins.print`."""
    if isinstance(node, ast.Name):
        return node.id == "print"
    member = _member(node)
    return (
        member is not None
        and member[1] == "print"
        and isinstance(member[0], ast.Name)
        and member[0].id in PRINT_MODULES
    )


def _log_function_reference(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Имя или член, связанные в модуле с вызываемым журнала (`log_functions`,
    `log_function_attributes`).

    Голое имя — из `log_functions`. Член (`X.f`, `getattr(X, "f")`, с умолчанием; имя читают
    `_member` и общий `reading_name`, план 16-43) — вызов журнала в двух случаях: (а) имя из
    `log_functions` и владелец — объект модуля (`getattr(sys.modules[__name__], "f")(…)`,
    `sys.modules[__name__].f(…)`, `me.f(…)` — `_is_module_object`); член другого объекта с тем же
    именем — не журнал: `fh.write(account.phone)` при `write = print` пишет номер в файл (ревью
    WR-29; решение владельца О-20 (а), свойство 3; план 16-47); (б) имя из
    `log_function_attributes` — у любого владельца, плоская область: `a.out(…)` при
    `self.out = logger.info` в чужом `__init__` (решение владельца О-22 (а), цена названа в шапке).
    """
    if isinstance(node, ast.Name):
        return node.id in names.log_functions
    member = _member(node)
    if member is not None and member[1] in names.log_functions and _is_module_object(member[0], names):
        return True
    return reading_name(node) in names.log_function_attributes


def _is_log_partial(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """`functools.partial(<вызываемое журнала>, …)` (и под псевдонимом модуля,
    `names.partial_names`): его аргументы уйдут в журнал."""
    return (
        isinstance(node, ast.Call)
        and _last_name(node.func) in (PARTIAL_NAMES | names.partial_names)
        and bool(node.args)
        and _is_log_callable(node.args[0], names)
    )


def _is_log_callable(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Вызываемое, вызов которого — вызов журнала: `print`, ссылка на метод опознанного
    журнала (`logger.info`, `getattr(logger, "info")`), ссылка на привязку к контексту,
    имя или атрибут, связанные в модуле с вызываемым журнала, и
    `functools.partial(<то же>, …)`."""
    return (
        _is_print_reference(node)
        or _log_method_reference(node, names)
        or _binder_reference(node, names)
        or _log_function_reference(node, names)
        or _is_log_partial(node, names)
    )


def _bind(target: ast.expr, in_class_body: bool, names: set[str], attributes: set[str]) -> bool:
    """Записать цель связывания; `True`, если множество выросло.

    Имя в теле класса идёт и в атрибуты: его зовут через `self.` / `cls.` / имя класса.
    """
    grew = False
    if isinstance(target, ast.Name):
        if target.id not in names:
            names.add(target.id)
            grew = True
        if in_class_body and target.id not in attributes:
            attributes.add(target.id)
            grew = True
    elif isinstance(target, ast.Attribute) and target.attr not in attributes:
        attributes.add(target.attr)
        grew = True
    return grew


def module_log_names(tree: ast.AST) -> ModuleLogNames:
    """Имена журнала, которые модуль `tree` связывает ввозом или связыванием.

    Связывания — по общей грамматике обоих гейтов номера (`module_bindings` модуля
    `tests/phone_gate_grammar.py`, решение владельца О-12 (а)): присваивание,
    аннотированное присваивание, оператор `:=` и присваивание в теле класса; кортеж на
    кортеж разбирается попарно (и со звёздной целью), `getattr(<obj>, "<const>")` приходит
    атрибутом. Они разбираются до
    неподвижной точки: `lg = logging.getLogger()` делает журналом `lg`, и тогда
    `bound = lg.bind(...)` и `a = lg` — тоже журнал. Значение связывания решает, кем
    становится цель: ссылка на фабрику без вызова — фабрикой (проверяется первой:
    `structlog.get_logger` подходит под шаблон имени журнала); получатель журнала (вызов
    фабрики, вызов уровня, `bind` / `new` или метода из `LOGGER_RETURNING_METHODS`, имя или
    атрибут, которые гейт уже признаёт журналом) — получателем; вызываемое журнала (любой
    метод опознанного журнала, `print`, `partial(…)`) — функцией журнала. Две последние
    проверки независимы (ревью WR-13): `emit = logger._log` — функция журнала, хотя `_log`
    подходит и под шаблон имени журнала.
    """
    binders: set[str] = set()
    receiver_names: set[str] = set()
    receiver_attributes: set[str] = set()
    log_functions: set[str] = set()
    log_function_attributes: set[str] = set()
    factories: set[str] = set()
    bindings = module_bindings(tree)
    # Имена объекта модуля — до неподвижной точки журнала (ревью WR-29, WR-30, план 16-47).
    module_objects = _module_object_names(bindings)
    # Обёртки ссылки под другим именем — до опознания журнала: `bind_(logger.info, …)`
    # судится, как `functools.partial(logger.info, …)`.
    partial_names = _wrapper_aliases(tree, bindings, PARTIAL_NAMES)
    methodcaller_names = _wrapper_aliases(tree, bindings, METHODCALLER_NAMES)
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            from_logging = node.level == 0 and node.module in LOGGING_MODULES
            for alias in node.names:
                local = alias.asname or alias.name
                if from_logging and alias.name in LOG_METHODS:
                    # `from logging import info` / `warning as warn_` — функция журнала (IN-09).
                    log_functions.add(local)
                elif from_logging and alias.name in LOGGING_MODULE_LOGGERS:
                    receiver_names.add(local)
                elif not alias.asname:
                    continue
                elif alias.name in CONTEXT_BINDERS:
                    binders.add(alias.asname)
                elif alias.name in LOGGER_FACTORIES:
                    # ДО шаблона имени журнала: `get_logger` подходит под `_LOGGER_NAME`.
                    factories.add(alias.asname)
                elif _is_logger_name(alias.name):
                    receiver_names.add(alias.asname)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name in LOGGING_MODULES and alias.asname:
                    receiver_names.add(alias.asname)

    changed = True
    while changed:
        changed = False
        known = ModuleLogNames(
            frozenset(binders),
            frozenset(receiver_names),
            frozenset(receiver_attributes),
            log_functions=frozenset(log_functions),
            factories=frozenset(factories),
            log_function_attributes=frozenset(log_function_attributes),
            partial_names=partial_names,
            module_objects=module_objects,
        )
        for target, value, in_class_body in bindings:
            if _is_factory_reference(value, known):
                changed |= _bind(target, in_class_body, factories, factories)
                continue
            # Получатель и вызываемое журнала — независимо (ревью WR-13): `emit = logger._log`
            # — ссылка на метод журнала, и `emit(…)` — вызов журнала, хотя имя `_log` подходит
            # и под шаблон журнала; `x = logger._logger` (обёрнутый журнал structlog) —
            # получатель, и `x.info(…)` — вызов журнала.
            if _is_log_receiver(value, known):
                changed |= _bind(target, in_class_body, receiver_names, receiver_attributes)
            # Цель-имя, связанное со ссылкой на вызываемое журнала, идёт в атрибуты только в теле
            # класса (как до `a77263ad`): имя уровня модуля и функции читается членом только у
            # объекта модуля (`getattr(sys.modules[__name__], "f")(…)` — ветка члена
            # `_log_function_reference`), а метод чужого объекта с тем же именем — не журнал:
            # `fh.write(account.phone)` при `write = print` (ревью WR-29; решение владельца О-20 (а),
            # свойство 3; план 16-47). Цикл самопроверки 1 плана 16-43 клал сюда `True`.
            if _is_log_callable(value, known):
                changed |= _bind(target, in_class_body, log_functions, log_function_attributes)
    # Имена, связанные с вызовом `methodcaller(…)` (и под псевдонимом), — той же общей
    # грамматикой, до неподвижной точки (`emit = mc("info", …)`, `g = emit`). Имя —
    # последнее звено цели (`binding_name`): `self.emit = …` зовут `self.emit(…)`.
    methodcallers: dict[str, list[ast.Call]] = {}
    changed = True
    while changed:
        changed = False
        for target, value, _in_class_body in bindings:
            name = binding_name(target)
            if name is None:
                continue
            found = _methodcaller_calls(value, methodcaller_names, methodcallers)
            if not found:
                continue
            known_calls = methodcallers.setdefault(name, [])
            for call in found:
                if all(call is not known for known in known_calls):
                    known_calls.append(call)
                    changed = True
    names = ModuleLogNames(
        frozenset(binders),
        frozenset(receiver_names),
        frozenset(receiver_attributes),
        log_functions=frozenset(log_functions),
        factories=frozenset(factories),
        log_function_attributes=frozenset(log_function_attributes),
        methodcaller_names=methodcaller_names,
        methodcallers=tuple(
            (name, call) for name, calls in sorted(methodcallers.items()) for call in calls
        ),
        partial_names=partial_names,
        module_objects=module_objects,
    )
    return replace(names, carrier_wrappers=_carrier_wrappers(bindings, names))


def _log_wrapper_reference(names: ModuleLogNames) -> Callable[[ast.expr], bool]:
    """Предикат ссылки гейта для обёртки носителя: вызываемое журнала или `methodcaller`.

    Вызываемое журнала (`_is_log_callable`: `logger.info`, `print`, `partial(logger.info, …)`
    — `partial` над самим вызываемым журнала остаётся функцией журнала, а не обёрткой) и
    `operator.methodcaller(…)` или имя, связанное с ним (`_methodcaller_calls`).
    """
    grouped = _grouped(names.methodcallers)

    def is_reference(node: ast.expr) -> bool:
        return _is_log_callable(node, names) or bool(
            _methodcaller_calls(node, names.methodcaller_names, grouped)
        )

    return is_reference


def _carrier_wrappers(bindings: list[Binding], names: ModuleLogNames) -> tuple[tuple[str, ast.Call], ...]:
    """Имена, связанные с обёрткой носителя `partial(<носитель>, <ссылка>, …)`: пары «имя → обёртка».

    `w = functools.partial(asyncio.to_thread, logger.info); w("x %s", account.phone)` —
    то же применение `partial(…)(…)`, что и на месте, разделённое связыванием. Отображение
    строит функция общего модуля `carrier_wrapper_bindings` (неподвижная точка «имя →
    обёртки», цепочка `g = w`, каждое связывание имени судится), что такое обёртка — общий
    рекурсивный предикат `is_carrier_wrapper`; гейт даёт им только имена `partial` модуля
    (`names.partial_names`) и свой предикат ссылки (`_log_wrapper_reference`). Решение
    владельца О-16 (а), свойство 5, и О-15; ревью WR-24: до плана 16-37 здесь жила своя копия
    неподвижной точки и проверки аргументов (самопроверка 16-32, цикл 2, коммит `5e57325d`),
    и она уже расходилась с гейтом писателя.
    """
    is_reference = _log_wrapper_reference(names)
    not_carriers = _not_carriers(names)

    def is_wrapper(value: ast.Call, known: dict[str, list[ast.Call]]) -> bool:
        return is_carrier_wrapper(value, names.partial_names, is_reference, not_carriers, known)

    found = carrier_wrapper_bindings(bindings, is_wrapper, nested=True)
    return tuple((name, wrapper) for name, wrappers in sorted(found.items()) for wrapper in wrappers)


def _log_wrappers_of(names: ModuleLogNames) -> Callable[[ast.AST], list[ast.Call]]:
    """Обёртки носителя, которые называет узел, — функцией общего модуля `named_wrappers`.

    Литерал обёртки (общий предикат `is_carrier_wrapper`), имя, атрибут и getattr-строка,
    связанные с обёрткой (`names.carrier_wrappers`): `w`, `self.w`, `getattr(self, "w")`.
    """
    bound = _grouped(names.carrier_wrappers)
    is_reference = _log_wrapper_reference(names)
    not_carriers = _not_carriers(names)

    def is_wrapper(value: ast.Call) -> bool:
        return is_carrier_wrapper(value, names.partial_names, is_reference, not_carriers, bound)

    return lambda node: named_wrappers(node, is_wrapper, bound)


def _wrapper_aliases(tree: ast.AST, bindings: list[Binding], originals: frozenset[str]) -> frozenset[str]:
    """Имена, под которыми модуль зовёт обёртку ссылки (`functools.partial`, `operator.methodcaller`).

    Исходные имена `originals`; псевдоним ввоза (`from functools import partial as bind_`,
    `from operator import methodcaller as mc`) и имя или атрибут, связанные с ссылкой на
    обёртку любой формой общей грамматики (`bind_ = functools.partial`,
    `self.mc = operator.methodcaller`, цепочка `g = mc`), — до неподвижной точки. Сверяется
    по последнему имени, как и исходное имя (ревью WR-17, самопроверка исполнителя 16-29).
    """
    names = set(originals)
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            names.update(alias.asname for alias in node.names if alias.name in originals and alias.asname)
    changed = True
    while changed:
        changed = False
        for target, value, _in_class_body in bindings:
            name = binding_name(target)
            # Имя значения читает общий `reading_name` (план 16-43): имя, атрибут, getattr-строка.
            if name is not None and name not in names and reading_name(value) in names:
                names.add(name)
                changed = True
    return frozenset(names)


def _methodcaller_calls(
    node: ast.expr, methodcaller_names: frozenset[str], methodcallers: Mapping[str, list[ast.Call]]
) -> list[ast.Call]:
    """Вызовы `methodcaller(…)`, которые называет выражение: сам вызов или имя, связанное с ним.

    Литеральный вызов `methodcaller(…)` (по последнему имени вызываемого, и под псевдонимом) —
    он сам. Иначе имя, которым выражение ЧИТАЕТ связанное, даёт общий читатель `reading_name`
    обоих гейтов: `emit`, `self.emit` и `getattr(self, "emit")` (и с умолчанием) читают одно
    имя `emit` (ревью WR-28, верификация раунда 8; решение владельца О-18 (а), свойство 2; план
    16-43). До плана здесь были свои ветки `Name` / `Attribute`, и `getattr(self, "f")(logger)`
    при `self.f = operator.methodcaller("info", "x %s", account.phone)` уходил мимо гейта.
    """
    if isinstance(node, ast.Call) and _last_name(node.func) in methodcaller_names:
        return [node]
    name = reading_name(node)
    return list(methodcallers.get(name, ())) if name is not None else []


def _is_log_receiver(node: ast.expr, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Получатель журнала: имя, член или результат вызова, которые гейт признаёт журналом.

    Член (`X.lg`, `getattr(X, "lg")`, с умолчанием) — получатель, если имя подходит под шаблон
    журнала, связано атрибутом с получателем (`receiver_attributes`), это журнал-атрибут
    опознанного получателя (`logging.root`, `logger.parent`) — или имя связано В МОДУЛЕ с
    получателем (`receiver_names`), а владелец — объект модуля (`_is_module_object`):
    `getattr(sys.modules[__name__], "lg").info(…)`, `sys.modules[__name__].lg`, `me.lg` при
    `me = sys.modules[__name__]`, поданный носителю или `methodcaller`. До плана 16-47 имя модуля
    сверялось с `receiver_names` только голым, и номер уходил в журнал мимо гейта на всех деревьях
    (ревью WR-30; решение владельца О-20 (а), свойство 4). Довод 16-43 «ломает
    `_log_method_reference` у `logger.log`» относится к плоскому варианту (имя модуля в
    `receiver_attributes`), а не к сверке по владельцу-модулю.
    """
    if isinstance(node, ast.Name):
        return _is_logger_name(node.id) or node.id in names.receiver_names
    member = _member(node)
    if member is not None:
        owner, attribute = member
        return (
            bool(_LOGGER_NAME.search(attribute))
            or attribute in names.receiver_attributes
            or (attribute in names.receiver_names and _is_module_object(owner, names))
            or (attribute in LOGGER_ATTRIBUTE_LOGGERS and _is_log_receiver(owner, names))
        )
    if isinstance(node, ast.Call):
        # `structlog.get_logger(__name__).info(...)`, `gl().info(...)`, `logger.bind(...).info(...)`
        # и `logging.getLogger(__name__).getChild("x").info(...)`: результат вызова — журнал
        # только у фабрики и у методов из `LOG_METHODS` / `LOGGER_RETURNING_METHODS` опознанного
        # получателя (`logging.StreamHandler(…)` — обработчик, а не журнал).
        if _is_factory_call(node, names):
            return True
        member = _member(node.func)
        return (
            member is not None
            and member[1] in (LOG_METHODS | LOGGER_RETURNING_METHODS)
            and _is_log_receiver(member[0], names)
        )
    return False


def _is_log_method_call(call: ast.Call, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """`<получатель>.<метод>(…)` и `getattr(<получатель>, "<метод>")(…)` с ЛЮБЫМ методом
    опознанного получателя (D-17 `logger.*` / `log.*` / `logging.*`, ревью WR-13), кроме
    вызова фабрики: фабрика — связывание, её начальные значения судит
    `_carries_initial_values`."""
    if _is_factory_call(call, names):
        return False
    member = _member(call.func)
    return member is not None and _is_log_receiver(member[0], names)


def _is_context_binding(call: ast.Call, names: ModuleLogNames = NO_MODULE_LOG_NAMES) -> bool:
    """Привязка к контексту structlog — по имени вызова при любом получателе (и строкой в
    `getattr`) или по псевдониму, под которым привязка ввезена в модуль."""
    return _binder_reference(call.func, names)


def _is_print(call: ast.Call) -> bool:
    return _is_print_reference(call.func)


def _is_log_function_call(call: ast.Call, names: ModuleLogNames) -> bool:
    """Вызов имени или атрибута, связанных с вызываемым журнала (`info(…)` после
    `from logging import info`, `warn_(…)`, `out(…)` после `out = print`), и вызов,
    применённый к `functools.partial(<вызываемое журнала>, …)`."""
    return _log_function_reference(call.func, names) or _is_log_partial(call.func, names)


def _carries_initial_values(call: ast.Call, names: ModuleLogNames) -> bool:
    """Фабрика журнала с начальными значениями — те же значения, что у `bind` (D-11).

    `structlog.get_logger(__name__, phone=…)`, `structlog.wrap_logger(base, phone=…)`,
    `logging.LoggerAdapter(logger, {"phone": …})` / `extra={…}`: значение уходит в каждую
    строку журнала. Начальное значение — второй позиционный аргумент или именованный
    аргумент вне `FACTORY_CONFIGURATION_KEYWORDS`; фабрика с одним именем журнала
    (`structlog.get_logger(__name__)`) вызовом журнала не считается.
    """
    if not _is_factory_call(call, names):
        return False
    return len(call.args) > 1 or any(
        keyword.arg is None or keyword.arg not in FACTORY_CONFIGURATION_KEYWORDS for keyword in call.keywords
    )


def _is_identified_log_call(call: ast.Call, names: ModuleLogNames) -> bool:
    """Вызов, который сам — вызов журнала: `print`, метод опознанного получателя, привязка к
    контексту, вызов функции журнала, `partial(<вызываемое журнала>, …)`, фабрика с
    начальными значениями."""
    return (
        _is_print(call)
        or _is_log_method_call(call, names)
        or _is_context_binding(call, names)
        or _is_log_function_call(call, names)
        or _is_log_partial(call, names)
        or _carries_initial_values(call, names)
    )


def _not_carriers(names: ModuleLogNames) -> frozenset[str]:
    """Применения, которые носителем не судятся: `getattr(…)(…)` и `methodcaller(…)(…)`."""
    return frozenset({"getattr"}) | names.methodcaller_names


def _applied_carriers(tree: ast.AST, names: ModuleLogNames) -> set[int]:
    """`id` вызовов `X(…)`, применённых как `X(…)(…)`: их ссылку и аргументы судит применение.

    Имя вызываемого `X` (`getattr`, `methodcaller` и его псевдоним — не носители) читает общий
    `reading_name` (план 16-43): псевдоним `methodcaller`, прочитанный getattr-строкой
    (`getattr(self, "mc")("info", …)(logger)`), — тот же `methodcaller`, что `self.mc(…)(…)`.
    """
    not_carriers = _not_carriers(names)
    return {
        id(node.func)
        for node in ast.walk(tree)
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Call)
        and reading_name(node.func.func) not in not_carriers
    }


def _carried_log_calls(call: ast.Call, names: ModuleLogNames) -> list[ast.Call]:
    """Вызовы журнала, которые носитель ссылки сделает за автора (ревью WR-17, WR-19, WR-20).

    Носитель — ЛЮБОЙ вызов, который сам вызовом журнала не опознан: `asyncio.to_thread`,
    `loop.run_in_executor`, `map`, `Context.run`, `run_sync`, `threading.Thread(target=…)`
    (`REFERENCE_CARRIERS` общего модуля — словарь шапок и матриц, а не закрытый перечень).
    Где стоит ссылка и какие аргументы носитель ей подаст, решает функция общего модуля
    `reference_arguments` (план 16-32, О-14 (а), О-15) — та же семантика, что у гейта
    писателя: ссылка — позиционным аргументом (литеральная распаковка `*[…]` раскрыта),
    ЛЮБЫМ именованным аргументом или внутри применённой обёртки `X(…)(…)`; аргументы —
    позиционные ЗА ссылкой (у именованной — все позиционные носителя) и литеральные
    аргументы того же вызова по общему правилу `literal_keyword_arguments` (литеральный
    кортеж или список — позиционные, литеральный словарь — именованные), затем аргументы
    применения; у поэлементного носителя (`ELEMENTWISE_CARRIERS`) — сами итерируемые, целиком
    (`keep_iterables=True`, ревью CR-02: имя итерируемой с `phone` краснит, comprehension
    судится с источником итерации). Тот же довод, что у
    `functools.partial`: эти аргументы уйдут в журнал. Синтетический вызов
    `<ссылка>(<аргументы>)` встаёт на место носителя (`ast.copy_location`). Ссылка без
    аргументов в журнал ничего не подаёт — судить нечего, и вызовом журнала она не
    считается; аргумент ДО позиционной ссылки (исполнитель у `run_in_executor`) в журнал не
    уходит.
    """
    if _is_identified_log_call(call, names):
        return []
    return [
        ast.copy_location(
            ast.Call(func=carried.reference, args=carried.args, keywords=carried.keywords), call
        )
        for carried in reference_arguments(
            call,
            lambda node: _is_log_callable(node, names),
            _not_carriers(names),
            keep_iterables=True,
        )
        if carried.args or carried.keywords
    ]


def _applied_log_methodcaller(
    call: ast.Call, names: ModuleLogNames, as_carrier: bool = True
) -> list[ast.Call]:
    """Вызовы журнала, которые сделает `operator.methodcaller`, применённый к журналу (WR-17).

    `methodcaller("<метод>", *a, **k)` зовёт `obj.<метод>(*a, **k)` у объекта, к которому
    его применили. Применение — прямое `methodcaller(…)(R)`; вызов имени или атрибута,
    связанных с `methodcaller(…)` любой формой общей грамматики (`emit(R)`,
    `self.emit(R)`); и носитель, которому `methodcaller` подан ссылкой: получатель — ПЕРВЫЙ
    аргумент, который носитель подаст ссылке, по той же семантике носителя, что у
    вызываемого журнала (`reference_arguments` общего модуля, план 16-32, ревью WR-19):
    позиционная ссылка и литеральная `*`-распаковка (`to_thread(mc, R)`,
    `to_thread(*[mc, R])`, `run_in_executor(None, mc, R)`, `partial(mc, R)`), ЛЮБОЙ
    именованный аргумент (`call(R, fn=mc)`, `Thread(target=mc, args=(R,))`), применённая
    обёртка носителя (`partial(asyncio.to_thread, mc)(R)`), у поэлементного носителя —
    элемент литеральной итерируемой, в том числе в обёртке (`map(mc, [R])`,
    `map(mc, list([R]))`), у построчного носителя (`ROW_CARRIERS`: `starmap`,
    `starmap_async`) — первый элемент каждой литеральной строки (`starmap(mc, [(R,)])`; его
    даёт построчное прочтение общей функции, ревью WR-25, план 16-38). Общая функция зовётся
    с `every_reading=True`, как у гейта писателя: получатель — первый аргумент любого
    прочтения, и именованная ссылка применённой обёртки получает аргументы применения
    (`partial(threading.Thread, target=mc)(args=(R,))`; сверка «база ↔ HEAD» плана 16-38). Когда получатель — опознанный журнал (`_is_log_receiver`), вызов
    — синтетический `R.<метод>(*a, **k)` на месте применения; судятся аргументы
    `methodcaller` после имени метода. Без опознанного получателя — пустой список: имя
    метода объект журналом не делает (D-17, угадывания по имени нет). `as_carrier=False` —
    вызов `X(…)` судит его применение `X(…)(…)`, и путь носителя здесь не идёт.

    Каждое связывание имени судится (ревью WR-18, план 16-31): синтетический вызов
    строится на КАЖДУЮ пару «`methodcaller` × получатель», чей получатель — опознанный
    журнал. До плана функция возвращала первого кандидата, и `emit =
    methodcaller("noop"); emit = methodcaller("info", …, account.phone); emit(logger)`
    судился как `logger.noop()` — номер уходил в журнал мимо гейта.
    """
    candidates: list[tuple[ast.Call, ast.expr]] = []
    grouped = _grouped(names.methodcallers)

    def named(node: ast.expr) -> list[ast.Call]:
        return _methodcaller_calls(node, names.methodcaller_names, grouped)

    applied = named(call.func)
    if applied:
        if len(call.args) == 1 and not isinstance(call.args[0], ast.Starred) and not call.keywords:
            candidates = [(methodcaller, call.args[0]) for methodcaller in applied]
    elif as_carrier and _last_name(call.func) not in names.methodcaller_names:
        # Каждое прочтение носителя (`every_reading`, как у гейта писателя): получатель — первый
        # аргумент ЛЮБОГО прочтения, в том числе именованной ссылки применённой обёртки без
        # позиционных `partial` (`partial(threading.Thread, target=mc)(args=(logger,))`; сверка
        # «база ↔ HEAD» плана 16-38, класс WR-25).
        for carried in reference_arguments(
            call, lambda node: bool(named(node)), _not_carriers(names), every_reading=True
        ):
            if not carried.args or isinstance(carried.args[0], ast.Starred):
                continue
            receivers = [carried.args[0]]
            # Литеральный кортеж или список, поданный ссылке первым, — и его первый элемент
            # (`pool.apply_async(mc, [logger])` зовёт `mc(logger)`; самопроверка 16-32, заход 1):
            # цена — в сторону лишней находки, получатель-список журналом не бывает.
            elements = iterable_elements(carried.args[0])
            if elements is not None and elements[0] and not elements[1]:
                receivers.append(elements[0][0])
            candidates += [
                (methodcaller, receiver) for methodcaller in named(carried.reference) for receiver in receivers
            ]
    found: list[ast.Call] = []
    for methodcaller, receiver in candidates:
        if not _is_log_receiver(receiver, names):
            continue
        method = methodcaller.args[0] if methodcaller.args else None
        attribute = (
            method.value
            if isinstance(method, ast.Constant) and isinstance(method.value, str)
            else "<метод>"
        )
        func = ast.copy_location(ast.Attribute(value=receiver, attr=attribute, ctx=ast.Load()), call)
        synthetic = ast.Call(func=func, args=list(methodcaller.args[1:]), keywords=list(methodcaller.keywords))
        # Одно и то же применение, пришедшее двумя путями (имя, связанное дважды с равным
        # `methodcaller(…)`), — один вызов: находки одного места не дублируются.
        if all(ast.dump(synthetic) != ast.dump(known) for known in found):
            found.append(ast.copy_location(synthetic, call))
    return found


def _grouped(pairs: tuple[tuple[str, ast.Call], ...]) -> dict[str, list[ast.Call]]:
    """Пары «имя → вызов» — словарём «имя → вызовы»."""
    grouped: dict[str, list[ast.Call]] = {}
    for name, call in pairs:
        grouped.setdefault(name, []).append(call)
    return grouped


def python_log_calls(source: str) -> list[ast.Call]:
    """Вызовы журнала в исходнике Python, в порядке строк.

    Прежние вызовы журнала (`_is_identified_log_call`) и синтетические вызовы, которые
    сделает носитель ссылки на вызываемое журнала (`_carried_log_calls`) и
    `operator.methodcaller`, применённый к опознанному журналу
    (`_applied_log_methodcaller`), — ревью WR-17; те же две функции судят каждое применение
    обёртки носителя, которое находит функция общего модуля `wrapper_applications` (ревью
    WR-24, WR-26, план 16-37).

    Судится каждое толкование узла (ревью CR-04, решение владельца О-20 (а), свойство 2, план
    16-46): вызов, опознанный вызовом журнала, судится и как применение `methodcaller` и обёртки
    носителя, связанных с тем же последним именем. До плана ветка закрытия после опознанного
    вызова не пускала эти пути: при `emit = print` и `self.emit = operator.methodcaller("info",
    "x %s", account.phone)` вызов `self.emit(logger)` судился только как `print(logger)`, и номер
    уходил в журнал мимо гейта (регрессия `a77263ad` против `e1d6587e` и `fb8fef72`; давний класс
    C5–C7). Одно место печатается один раз — дедупликация по узлу (строка, столбец, вид,
    предмет) в `python_log_offences`; путь носителя `_carried_log_calls` для опознанного вызова
    пуст сам.
    """
    tree = ast.parse(source)
    names = module_log_names(tree)
    applied = _applied_carriers(tree, names)
    wrappers_of = _log_wrappers_of(names)
    calls: list[ast.Call] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        # Опознанный вызов журнала — свой вызов, но не последнее толкование узла: путь
        # `methodcaller` и применения обёрток судятся и на нём (ревью CR-04, план 16-46).
        if _is_identified_log_call(node, names):
            calls.append(node)
        # `X(…)` в `X(…)(…)` носителем не судится: его ссылку и аргументы судит применение
        # (`partial(*[logger.info, …])()` — один вызов на месте, а не два).
        elif id(node) not in applied:
            calls.extend(_carried_log_calls(node, names))
        # Каждое связывание `methodcaller` с опознанным получателем — свой вызов (WR-18).
        calls.extend(_applied_log_methodcaller(node, names, as_carrier=id(node) not in applied))
        # Обёртка носителя судится везде, где её прочитали (ревью WR-24, WR-26; решение
        # владельца О-16 (а), свойства 2 и 3): вызванная (`w(…)`, `self.w(…)`,
        # `getattr(self, "w")(…)`), поданная другому носителю литералом или именем, обёрнутая
        # ещё одним `partial` или вложенная глубже — каждое применение находит функция общего
        # модуля `wrapper_applications` (рекурсивно, с защитой от цикла), и каждое судится как
        # носитель на месте внешнего вызова; на месте связывания обёртка судится всегда (выше).
        # `X(…)` в `X(…)(…)` носителем не судится — его судит применение.
        if id(node) in applied:
            continue
        # Поэлементному носителю обёртка подана — она получает и элементы, и итерируемые
        # целиком (`keep_iterables`, самопроверка исполнителя 16-38, заход 1; ревью CR-02).
        for item in wrapper_applications(node, wrappers_of, _not_carriers(names), keep_iterables=True):
            calls.extend(_carried_log_calls(item.application, names))
            calls.extend(_applied_log_methodcaller(item.application, names))
    return sorted(calls, key=lambda call: (call.lineno, call.col_offset))


def _is_presence_flag(value: ast.expr) -> bool:
    """Булева форма признака: сравнение с `None` или `bool(...)` (D-11)."""
    if isinstance(value, ast.Compare) and len(value.ops) == 1:
        if isinstance(value.ops[0], (ast.Is, ast.IsNot, ast.Eq, ast.NotEq)):
            sides = (value.left, *value.comparators)
            return any(isinstance(side, ast.Constant) and side.value is None for side in sides)
        return False
    return (
        isinstance(value, ast.Call)
        and isinstance(value.func, ast.Name)
        and value.func.id == "bool"
        and len(value.args) == 1
        and not value.keywords
    )


def _judge_arguments(call: ast.Call, *, mask_for_a_reader: bool) -> list[tuple[int, int, str, str]]:
    """Находки (строка, столбец, вид, предмет) во всём поддереве аргументов вызова журнала.

    Место находки — узел подачи номера, на котором она стоит: имя, атрибут, строковая
    константа, ключ словаря, вызов `mask_phone(…)`, именованный аргумент (у синтетического
    `ast.keyword` общего модуля — место его ключа, `ast.copy_location`). Строка и столбец —
    `lineno` и `col_offset` этого узла (ревью WR-27, решение владельца О-18 (а), свойство 4).
    """
    found: list[tuple[int, int, str, str]] = []
    stack: list[ast.AST] = [*call.args, *call.keywords]
    while stack:
        node = stack.pop()
        if isinstance(node, ast.keyword):
            if node.arg in PRESENCE_FLAG_NAMES and _is_presence_flag(node.value):
                continue
            if node.arg is not None and _mentions_phone(node.arg):
                found.append((node.lineno, node.col_offset, "имя", f"{node.arg}="))
            stack.append(node.value)
            continue
        if isinstance(node, ast.Dict):
            for key, value in zip(node.keys, node.values):
                if isinstance(key, ast.Constant) and isinstance(key.value, str):
                    if key.value in PRESENCE_FLAG_NAMES and _is_presence_flag(value):
                        continue
                    if _mentions_phone(key.value):
                        found.append((key.lineno, key.col_offset, "ключ", repr(key.value)))
                if key is not None:
                    stack.append(key)
                stack.append(value)
            continue
        if isinstance(node, ast.Call) and _callee_name(node.func) == MASK_FUNCTION:
            if not mask_for_a_reader:
                found.append((node.lineno, node.col_offset, "маска", f"{MASK_FUNCTION}(...)"))
            continue
        if isinstance(node, ast.Name) and _mentions_phone(node.id):
            found.append((node.lineno, node.col_offset, "имя", node.id))
        elif isinstance(node, ast.Attribute) and _mentions_phone(node.attr):
            found.append((node.lineno, node.col_offset, "имя", node.attr))
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            literal = phone_like(node.value)
            if literal is not None:
                found.append((node.lineno, node.col_offset, "литерал", literal))
        stack.extend(ast.iter_child_nodes(node))
    return found


def _function_ranges(tree: ast.AST) -> list[tuple[int, int, str]]:
    ranges = [
        (node.lineno, node.end_lineno or node.lineno, node.name)
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    ]
    return sorted(ranges, key=lambda item: item[1] - item[0])


def _owner(ranges: list[tuple[int, int, str]], line: int) -> str:
    for start, end, name in ranges:
        if start <= line <= end:
            return name
    return "<module>"


def python_log_offences(source: str, path: str) -> list[str]:
    """Находки «`путь:строка` — вид — предмет» в вызовах журнала исходника `path`.

    `path` — путь от корня проекта (`app/x.py`): по нему решается, читает ли вывод
    `print` человек (`scripts/`), и по нему же строится ключ реестра исключений.

    Одно место — одна находка в обе стороны (ревью WR-24 и WR-27, решение владельца О-18 (а),
    свойство 4): место — «строка, столбец, вид, предмет» узла подачи номера, на котором стоит
    находка. Обёртка носителя, судимая и на месте связывания, и на месте применения,
    указывает на тот же узел — одна находка, остаётся первая по порядку (до плана 16-37 здесь
    было две на одном месте: `w = partial(asyncio.to_thread, logger.info, "x %s",
    account.phone); await w()`, коммит `5e57325d`). Две разные подачи на одной строке — два
    узла — две находки, как у гейта писателя: дедупликация по тексту тройки «строка, вид,
    предмет» без столбца (коммит `51d0d766`, план 16-37) сливала их в одну (ревью WR-27). Текст
    находки прежний — две находки одной строки печатаются одинаково.
    """
    tree = ast.parse(source)
    ranges = _function_ranges(tree)
    in_scripts = PurePosixPath(path).parts[:1] == ("scripts",)
    offences: list[str] = []
    places: set[tuple[int, int, str, str]] = set()
    for call in python_log_calls(source):
        if f"{path}::{_owner(ranges, call.lineno)}" in PHONE_LOG_EXCEPTIONS:
            continue
        mask_for_a_reader = in_scripts and _is_print(call)
        for place in sorted(_judge_arguments(call, mask_for_a_reader=mask_for_a_reader)):
            if place in places:
                continue
            places.add(place)
            line, _column, kind, subject = place
            offences.append(f"{path}:{line} — {kind} — {subject} (владелец {_owner(ranges, call.lineno)})")
    return offences


@dataclass(frozen=True)
class TreeScan:
    tree: str
    files: int
    calls: int


def scan_python_trees(root: Path) -> tuple[list[TreeScan], list[str]]:
    """Обход Python-деревьев под `root`: число файлов и вызовов по дереву и находки."""
    scans: list[TreeScan] = []
    offences: list[str] = []
    for tree, paths in python_sources(root).items():
        calls = 0
        for path in paths:
            source = path.read_text(encoding="utf-8")
            calls += len(python_log_calls(source))
            offences.extend(python_log_offences(source, path.relative_to(root).as_posix()))
        scans.append(TreeScan(tree=tree, files=len(paths), calls=calls))
    return scans, offences


