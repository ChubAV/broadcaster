"""Отрицательный греп-гейт: имена снятой метрической модели в приложение НЕ ВЕРНУЛИСЬ.

ПРЕДМЕТ. Фаза 05.1 сняла из кода прейскурант тарифов, объявленный порядок планов,
четыре метра осей и списание сообщений. Удаление — не свойство: оно верно ровно в
момент коммита и не мешает следующему плану ввезти любое из этих имён обратно,
потому что ни одно поведенческое утверждение суиты на ОТСУТСТВИЕ имени не
опирается. Этот файл переводит «мы это удалили» в «оно не может вернуться молча».

ПОЧЕМУ ЧИТАЕТСЯ ИСХОДНИК, А НЕ ИМПОРТИРУЕТСЯ МОДУЛЬ. Цель — поймать имя,
оставшееся в комментарии, в докстринге или в мёртвой ветке, до которой исполнение
не доходит. Импорт такого не покажет вовсе: он видит только то, что модуль
объявил, а вернувшаяся матрица тарифов начинается не с объявления, а с абзаца,
объясняющего, «как это было раньше».

МНОЖЕСТВО ПРОВЕРЯЕМЫХ ФАЙЛОВ ВЫВОДИТСЯ ОБХОДОМ КАТАЛОГА, А НЕ ВЫПИСЫВАЕТСЯ
ПЕРЕЧНЕМ. Правило гейта сформулировано как «модуль, добавленный СЛЕДУЮЩИМ планом,
попадает под гейт сам», и перечень его нарушает: он протух бы МОЛЧА в тот момент,
когда имя вернулось бы в файл, которого в перечне нет. Что множество действительно
выводится, а не выписано, доказывает
`test_the_gate_derives_its_files_from_the_tree_and_not_from_a_list` —
он подкладывает НОВЫЙ файл в синтетическое дерево и требует, чтобы гейт его нашёл.

⚠️ ФАЙЛЫ СУИТЫ ПОД ГЕЙТ НЕ ПОПАДАЮТ, И ЭТО НЕ ПОБЛАЖКА, А УСЛОВИЕ НЕПРОТИВОРЕЧИ-
ВОСТИ. Перечень запрещённых имён обязан жить В ТЕСТЕ — иначе его не на чем
записать, — и обход, включивший бы себя, ронял бы собственный запрет своим же
текстом. Обход поэтому идёт по `app/`, и ни один каталог тестов в него не входит.

⚠️ ПРИЗНАК БЕСПЛАТНОГО ДОСТУПА АДМИНИСТРАТОРА ДОПИСАН ПЛАНОМ `05.1-08`, И ЗАПРЕТ
СТОИТ НА СТАРОМ ИМЕНИ, А НЕ НА НОВОМ. Ревизия `0020` завела
`subscriptions.has_free_access` и уронила таблицы валюты сообщений, на одной из
которых жил ПРЕЖНИЙ признак того же права — колонка безлимита. Запрещать новое
имя было бы бессмысленно: оно и должно встречаться в коде. Запрещается старое —
то, чьё возвращение означало бы, что право администратора снова описано ДВУМЯ
величинами, и вторая из них лежит на таблице, которой нет. Вместе с ним запрещены
имена двух снятых моделей и двух снятых читателей остатка.

⚠️ ОБЪЯСНЕНИЯ В `app/` НАБИРАЮТСЯ В ОБХОД ЭТИХ ИМЁН, И ЭТО УСЛОВИЕ, А НЕ СТИЛЬ.
Гейт читает ИСХОДНИКИ, поэтому комментарий, называющий снятую колонку по имени,
уронил бы запрет собственным текстом (находка плана 05.1-04). Места, где это
правило применено, называют его прямо: `app/pages/admin.py` и
`app/services/billing_service.py`.
"""

from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]

APPLICATION_ROOT = PROJECT_ROOT / "app"

# СНЯТЫЕ ИМЕНА — ОДНОЙ ОБЪЯВЛЕННОЙ ПОСЛЕДОВАТЕЛЬНОСТЬЮ, чтобы её можно было
# дополнить ОДНОЙ строкой. Пара «имя, чем оно было» обязательна: голый перечень
# строк через год читается как список опечаток, и следующий читатель снимет из
# него запись, не поняв, что именно она держит.
FORBIDDEN_NAMES = (
    ("plan_limits", "прейскурант трёх тарифов в настройках (снят планом 05.1-07)"),
    ("parsed_plan_limits", "свойство разбора прейскуранта (снято планом 05.1-07)"),
    ("parsed_packages", "свойство разбора пакетов сообщений (снято планом 05.1-06)"),
    ("PLAN_ORDER", "объявленный порядок тарифов от младшего к старшему"),
    ("plan_axes(", "вызов метров четырёх осей тарифа"),
    ("deduct_message(", "вызов списания сообщения с баланса"),
    (
        "is_unlimited",
        "ПРЕЖНИЙ признак бесплатного доступа администратора — колонка безлимита "
        "на остатке сообщений; её место занял `subscriptions.has_free_access` "
        "(ревизия 0020, план 05.1-08)",
    ),
    ("MessageBalance", "модель остатка сообщений (снята вместе с таблицей, 05.1-08)"),
    (
        "BalanceTransaction",
        "модель журнала операций по остатку (снята вместе с таблицей, 05.1-08)",
    ),
    (
        "get_or_create_balance(",
        "вызов читателя остатка, заводившего строку прямо в GET-е (снят 05.1-08)",
    ),
    (
        "get_balance_info(",
        "вызов сборщика словаря остатка для админской карточки (снят 05.1-08)",
    ),
)


def application_sources(root: Path) -> list[Path]:
    """Все исходники приложения — ОБХОДОМ каталога, а не перечнем.

    Отдельная функция с параметром `root`, а не выражение в теле теста, именно
    затем, чтобы её можно было натравить на СИНТЕТИЧЕСКОЕ дерево. Помощник,
    применимый только к настоящему `app/`, проверяем лишь собой: доказать, что он
    находит новый файл, можно было бы только одноразовой правкой приложения,
    удаляемой до коммита, — то есть доказательства не осталось бы вовсе.
    """
    return sorted(root.rglob("*.py"))


def occurrences(root: Path) -> list[str]:
    """Перечень находок «файл :: имя :: чем оно было». Пустой — значит чисто."""
    found: list[str] = []
    for path in application_sources(root):
        source = path.read_text(encoding="utf-8")
        for name, what in FORBIDDEN_NAMES:
            if name in source:
                relative = path.relative_to(root).as_posix()
                found.append(f"{relative} :: {name} :: {what}")
    return found


def test_no_metering_remains_in_the_application_sources():
    """Ни одного снятого имени метрической модели в `app/` не осталось."""
    hits = occurrences(APPLICATION_ROOT)

    assert hits == [], (
        "имена снятой метрической модели вернулись в приложение — матрица "
        "тарифов восстанавливается по коду, а решения D-A и D-D говорят "
        "обратное:\n" + "\n".join(f"  {hit}" for hit in hits)
    )


def test_the_gate_derives_its_files_from_the_tree_and_not_from_a_list(tmp_path):
    """НЕГАТИВНЫЙ КОНТРОЛЬ: файл, которого гейт не знал, попадает под него сам.

    Без этого контроля предыдущий тест зелен и при пустом множестве файлов, и при
    перечне, из которого выпал нужный модуль, — то есть проверял бы ничто. Здесь
    в синтетическое дерево кладётся модуль, о котором гейт узнать ниоткуда не мог,
    и требуется, чтобы обход его нашёл, а находка НАЗВАЛА и файл, и имя.
    """
    package = tmp_path / "billing"
    package.mkdir()
    (package / "__init__.py").write_text("", encoding="utf-8")
    newcomer = package / "tariff_matrix_returned.py"
    # Имя стоит в КОММЕНТАРИИ, а не в объявлении: гейт обязан ловить и мёртвую
    # ветку, и объяснение «как это было раньше», а не только исполняемый код.
    newcomer.write_text(
        "# исторически ранг тарифа брался из PLAN_ORDER\n", encoding="utf-8"
    )

    assert newcomer in application_sources(tmp_path), (
        "обход не нашёл нового файла: множество выписано перечнем, и модуль, "
        "добавленный следующим планом, под гейт не попадёт"
    )

    hits = occurrences(tmp_path)

    assert len(hits) == 1, hits
    assert "tariff_matrix_returned.py" in hits[0]
    assert "PLAN_ORDER" in hits[0]


