# ПОЛОЖИТЕЛЬНАЯ ПОЛОВИНА ГЕЙТА (план 05.1-09, критерий 5b)
# =============================================================================
#
# ⚠️ ЗДЕСЬ ПРОВЕРЯЕТСЯ НЕ ОТСУТСТВИЕ ИМЕНИ, А ЕГО МЕСТО, И ЭТО ДРУГОЙ ВОПРОС.
# Всё выше отвечает «снятое не вернулось»; ниже — «ВВЕДЁННОЕ стоит там, где
# объявлено, и не расползлось». Предмет — признак `has_free_access`, и он же
# единственное, чем закрывается критерий 5b: флаг освобождает от оплаты
# ДОСТУПА, а не от чего бы то ни было, связанного с СООБЩЕНИЯМИ.
#
# ПОЧЕМУ ОБЕ СТОРОНЫ ОБЯЗАТЕЛЬНЫ. Отрицательная (нет в воркере и в планировщике
# отправок) без положительной зелена и при полностью снятом признаке: удалить
# ветку из предиката — и запрет выполнен идеально, а льготы не существует.
# Положительная (ровно один файл прикладной логики) без отрицательной зелена
# при втором чтении в пакете отправки. Вместе они и означают «одно правило, одно
# выражение, и оно про доступ».
#
# Прежний признак того же права жил на ОСТАТКЕ СООБЩЕНИЙ, то есть освобождал от
# списания сообщений; в новой модели сообщения бесплатны у всех, и перенос
# смысла на доступ — единственное, что делает признак осмысленным (допущение C5
# планировщика). Эти два теста и есть его двусторонняя проверка.

FREE_ACCESS_FLAG = "has_free_access"

# Пакеты, которым признак НЕ ПРИНАДЛЕЖИТ ни при каких условиях. Оба про
# СООБЩЕНИЯ: такт планировщика отправок и исполнитель отправки. Признак,
# прочитанный там, означал бы возвращение прежнего смысла — освобождения от
# платы за сообщение.
MESSAGE_PATH_PACKAGES = ("worker", "application/scheduling")

# Единственный файл прикладной логики, которому признак принадлежит: объявление
# правила доступа. Путь выписан относительно `app/` и проверяется на
# существование — опечатка дала бы тест, зелёный от несуществующего пути.
ACCESS_PREDICATE_MODULE = "application/billing/subscription_period.py"


def test_the_free_access_flag_is_absent_from_the_message_path():
    """Признак не встречается НИ в пакете воркера, НИ в планировщике отправок.

    Критерий 5b, отрицательная половина. Флаг про ДОСТУП: прочитанный на пути
    отправки, он снова стал бы освобождением от платы за сообщение — то есть
    вернул бы величину, которую фаза сняла, под новым именем.
    """
    hits: list[str] = []
    for package in MESSAGE_PATH_PACKAGES:
        root = APPLICATION_ROOT / package
        assert root.is_dir(), (
            f"пакета `app/{package}` не существует — тест проверяет пустое "
            "множество и зелен всегда"
        )
        for path in application_sources(root):
            if FREE_ACCESS_FLAG in path.read_text(encoding="utf-8"):
                hits.append(path.relative_to(APPLICATION_ROOT).as_posix())

    assert hits == [], (
        "признак бесплатного доступа прочитан на пути сообщений: "
        + ", ".join(hits)
        + " — флаг освобождает от оплаты ДОСТУПА, а не сообщений (критерий 5b)"
    )


def test_the_free_access_flag_is_read_in_exactly_one_place_of_the_decision():
    """В `app/application/` признак читает РОВНО один файл — предикат доступа.

    Критерий 5b, положительная половина, и одновременно смягчение T-05.1-31.
    Правило доступа объявлено один раз; второе его чтение в прикладной логике
    развело бы одно правило по двум выражениям, и разойтись им было бы на чем —
    достаточно, чтобы одно из двух забыло спросить про активность строки.

    Поверхности показа (`app/pages/`, шаблоны) под это утверждение НЕ попадают
    и не должны: они признак ПОКАЗЫВАЮТ, а не решают по нему, и словарь шелла
    обязан нести его вместе со своей колонкой (UI-контракт C3).

    ⚠️ ГРАНИЦА УТВЕРЖДЕНИЯ НАЗВАНА ПРЯМО: гейт читает ТЕКСТ, поэтому он зелен и
    от одного упоминания имени в комментарии — про «а он вправду читается?» этот
    тест не говорит НИЧЕГО и не обязан. Зубы у второй половины: разбор тела
    предиката по синтаксическому дереву
    (`test_subscription_period.py::test_the_free_access_check_stands_before_the_liveness_call`).
    Здесь утверждается ровно «и больше нигде», и именно это не поймать деревом.
    """
    readers = sorted(
        path.relative_to(APPLICATION_ROOT / "application").as_posix()
        for path in application_sources(APPLICATION_ROOT / "application")
        if FREE_ACCESS_FLAG in path.read_text(encoding="utf-8")
    )
    expected = ACCESS_PREDICATE_MODULE.removeprefix("application/")

    assert (APPLICATION_ROOT / ACCESS_PREDICATE_MODULE).is_file(), (
        f"модуля `app/{ACCESS_PREDICATE_MODULE}` не существует — путь протух, и "
        "утверждение ниже проверяет не тот файл"
    )
    assert readers == [expected], (
        f"признак бесплатного доступа читается в {readers}, а обязан ровно в "
        f"[{expected!r}]: правило доступа объявлено ОДИН раз (T-05.1-31)"
    )


def test_the_gate_reads_a_real_and_non_empty_tree():
    """Опечатка в пути дала бы гейт, проверяющий пустое множество и зелёный всегда."""
    sources = application_sources(APPLICATION_ROOT)

    assert len(sources) > 20, (
        f"обход `app/` дал {len(sources)} файлов — гейт проверяет почти ничто, "
        "и его зелень ничего не значит"
    )
    assert any(path.name == "config.py" for path in sources), (
        "в множество не попал модуль настроек — именно он нёс прейскурант"
    )
    assert any(
        path.parent.name == "billing" for path in sources
    ), "в множество не попал пакет денежного пути"
