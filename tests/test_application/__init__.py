# СБОРКЕ («import file mismatch»), не выполнив ни одного утверждения. Пара
# `tests/test_application/test_admin_payments.py` и
# `tests/test_pages/test_admin_payments.py` — первая такая пара в проекте:
# прикладной модуль и его страничный потребитель называются одинаково по
# предмету, и переименовывать один из них ради механики импорта значило бы
# спрятать предмет за особенностью инструмента.
#
# Восемь из десяти каталогов суиты такой файл УЖЕ НЕСУТ (test_models,
# test_routes, test_services, test_repositories, test_worker, test_messengers,
# test_migrations, test_templates). Эти два были исключением, и исключение
# держалось ровно до первого совпадения имён.
