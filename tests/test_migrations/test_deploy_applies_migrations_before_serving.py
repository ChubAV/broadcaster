"""Свойство боевого старта: очередь миграций доводится до головы ДО обслуживания.

ЗАЧЕМ. Приложение, поднятое на схеме, до которой очередь ревизий не доведена,
отвечает 500 на КАЖДОЕ чтение таблицы платежей — включая уведомление ЮKassa,
падающее до ветвления по предмету покупки (см. докстринг
`alembic/versions/0019_payment_switch_authorized.py`). Цена — списанные и не
зачтённые деньги. Значит момент «приложение начало принимать запросы» обязан
наступать ПОСЛЕ момента «очередь доведена до головы», и порядок этих двух
моментов обязан держаться машиной, а не вниманием читателя.

Свойство сегодня ДЕРЖИТСЯ: `entrypoint.sh` доводит очередь и только потом
передаёт управление процессу приложения, а `set -e` останавливает старт на
отказе миграции. Файл не правился — он закрепляется. Причина закрепления:
свойство обеспечено ПОРЯДКОМ трёх строк сценария, и одна правка снимет его
молча, ничего не сломав в тот же момент.

⚠️ ЧЕГО ЭТОТ ФАЙЛ НЕ ДОКАЗЫВАЕТ. Он утверждает о СЦЕНАРИИ И ОПИСАНИИ СЕРВИСОВ,
ЛЕЖАЩИХ В РЕПОЗИТОРИИ. Он не знает и не может знать: (1) что боевой стенд
запускается именно этим сценарием и именно этим файлом compose — то, что там
исполняется, суите недоступно; (2) что миграция, запущенная на боевой базе,
завершится успешно; (3) какая ревизия на боевой базе сейчас (решением D-26 —
`0012`). Все три остаются человеческими фактами решения D-26 и живут в
`.planning/STATE.md`, а не здесь.

Утверждения написаны ПО ПОЗИЦИИ СТРОК ОТНОСИТЕЛЬНО ДРУГ ДРУГА, а не по точному
тексту: правка формулировки `echo` не имеет права ронять тест — хрупкий тест
отключают, и вместе с ним отключается свойство.
"""

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ENTRYPOINT = REPO_ROOT / "entrypoint.sh"
COMPOSE_PROD = REPO_ROOT / "docker-compose.prod.yml"


def _entrypoint_lines() -> list[str]:
    return ENTRYPOINT.read_text(encoding="utf-8").splitlines()


def _first_line_index(lines: list[str], *, contains: list[str]) -> int:
    """Номер первой строки, содержащей ВСЕ подстроки, либо -1.

    Совпадение по набору значимых подстрок, а не по всей строке целиком: так
    утверждение переживает добавление флага или смену обёртки запуска и падает
    только тогда, когда пропадает сам шаг.
    """
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("#"):
            continue
        if all(part in stripped for part in contains):
            return index
    return -1


def test_the_migration_queue_is_drained_before_the_app_serves():
    """ШАГ ДОВЕДЕНИЯ ОЧЕРЕДИ СТОИТ РАНЬШЕ ПЕРЕДАЧИ УПРАВЛЕНИЯ ПРИЛОЖЕНИЮ.

    Проверяется именно ПОРЯДОК, а не присутствие обоих шагов: сценарий, в
    котором `alembic upgrade head` стоит ПОСЛЕ `exec`, содержит оба шага и не
    выполняет второй никогда — `exec` замещает процесс оболочки, и до строки
    ниже управление не возвращается.
    """
    lines = _entrypoint_lines()

    upgrade_at = _first_line_index(lines, contains=["alembic", "upgrade", "head"])
    serve_at = _first_line_index(lines, contains=["exec"])

    assert upgrade_at != -1, "в сценарии старта нет шага доведения очереди до головы"
    assert serve_at != -1, "в сценарии старта нет передачи управления приложению"
    assert upgrade_at < serve_at, (
        "очередь миграций доводится ПОСЛЕ передачи управления приложению: "
        f"upgrade на строке {upgrade_at + 1}, exec на строке {serve_at + 1}"
    )


def test_a_failed_migration_stops_the_start():
    """ОТКАЗ МИГРАЦИИ ОСТАНАВЛИВАЕТ СТАРТ, А НЕ ПРОПУСКАЕТСЯ.

    Без режима остановки на первой ошибке `sh` продолжил бы сценарий после
    упавшего `alembic upgrade` и дошёл бы до `exec` — то есть поднял бы
    приложение на схеме, до которой очередь не доведена. Это ровно тот исход,
    ради недопущения которого шаг и стоит первым.

    Режим обязан быть включён ДО шага миграции: включённый после он не покрывал
    бы сам этот шаг.
    """
    lines = _entrypoint_lines()

    fail_fast_at = _first_line_index(lines, contains=["set -e"])
    upgrade_at = _first_line_index(lines, contains=["alembic", "upgrade", "head"])

    assert fail_fast_at != -1, (
        "в сценарии старта не включён режим остановки на первой ошибке: "
        "отказ миграции не остановит старт"
    )
    assert fail_fast_at < upgrade_at, (
        "режим остановки на первой ошибке включён ПОСЛЕ шага миграции и его "
        f"не покрывает: set -e на строке {fail_fast_at + 1}, "
        f"upgrade на строке {upgrade_at + 1}"
    )


def test_the_service_that_terminates_the_money_paths_starts_through_the_script():
    """СЕРВИС, ПРИНИМАЮЩИЙ ДЕНЬГИ, ПОДНИМАЕТСЯ ИМЕННО ЭТИМ СЦЕНАРИЕМ.

    Свойство двух тестов выше стоит ровно столько, сколько стоит связь сценария
    с сервисом: правильный сценарий, не подключённый к `web`, не защищает
    ничего. Денежные пути — `POST /api/billing/webhook` и раздел «Тарифы» —
    терминируются web-процессом, и только у него в боевом артефакте объявлен
    собственный `entrypoint`.

    Celery-сервисы своего `entrypoint` не имеют и стартуют по умолчанию образа,
    в обход сценария; на схеме без очереди они падали бы так же. Их старт
    держится другим звеном — `depends_on: web: condition: service_healthy`, —
    и это звено здесь НЕ проверяется: оно принадлежит описанию сервисов, а не
    сценарию старта. Факт записан в `05-20-SUMMARY.md`.
    """
    compose_lines = COMPOSE_PROD.read_text(encoding="utf-8").splitlines()

    def _is_service_key(line: str) -> bool:
        # Ключ сервиса — ровно два пробела отступа. Сравнение по отступу, а не
        # по имени: без него `web:` нашёлся бы внутри `depends_on:` соседнего
        # сервиса, то есть тест читал бы чужой блок и утверждал о нём.
        return (
            line.startswith("  ")
            and not line.startswith("   ")
            and line.rstrip().endswith(":")
        )

    web_at = -1
    for index, line in enumerate(compose_lines):
        if _is_service_key(line) and line.strip() == "web:":
            web_at = index
            break
    assert web_at != -1, "в боевом артефакте нет сервиса web"

    # Блок сервиса — до следующего ключа того же уровня вложенности.
    block_end = len(compose_lines)
    for index in range(web_at + 1, len(compose_lines)):
        if _is_service_key(compose_lines[index]):
            block_end = index
            break

    block = "\n".join(compose_lines[web_at:block_end])
    assert "entrypoint.sh" in block, (
        "сервис web не подключён к сценарию старта: очередь миграций перед "
        "обслуживанием денежных путей никем не доводится"
    )
