def test_control_negative_a_renamed_service_reddens_the_block_search(tmp_path):
    """ЧТО ДОКАЗЫВАЕТ: переименованный сервис не даёт ВАКУУМНО-ЗЕЛЁНЫХ проверок.

    Область, не найденная поиском, пуста, и все утверждения о её содержимом
    истинны. Тест поиска области существует ровно затем, чтобы этот способ
    потерять свойство был громким.
    """
    original = _compose_text()
    changed = re.sub(
        rf"^  {re.escape(WEB_SERVICE)}:$",
        "  application:",
        original,
        count=1,
        flags=re.M,
    )
    assert changed != original, "подмена ничего не изменила — область сервиса не найдена"

    text = _compose_with(tmp_path, changed)

    assert _service_block(text, WEB_SERVICE) == [], (
        "область переименованного сервиса всё ещё находится — поиск идёт не по "
        "имени, и контроль ничего не доказывает"
    )
    assert _service_block(text, "application") != [], (
        "область под новым именем не найдена — подмена сломала файл, а не "
        "переименовала сервис"
    )


