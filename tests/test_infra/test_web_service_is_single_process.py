"""Гейт артефакта развёртывания: у боевого сервиса приложения ОДИН процесс.

ЭТОТ ФАЙЛ ЗАЩИЩАЕТ НЕ КОД, А РЕШЕНИЕ, поэтому рассуждение выписано целиком, а
не сокращено до «проверяем, что нет флага».

1. СЕГОДНЯ УДЕРЖАНИЕ ПУТИ РАССЫЛКИ ЖИВЁТ В ПАМЯТИ ПРОЦЕССА И РАБОТАЕТ. Повтор
   отправки держится реестром окон в словаре модуля `app/pages/history.py`:
   нажатие открывает окно, окно переживает ответ, второе последовательное
   нажатие по той же записи второй задачи не ставит. Это единственная линия
   защиты, работающая при ВЫКЛЮЧЕННОМ JavaScript, когда панель подтверждения не
   открывается и клиентская блокировка кнопки не существует вовсе.

2. ОНО МОЛЧА ПЕРЕСТАНЕТ РАБОТАТЬ В ДЕНЬ, КОГДА ПРОЦЕССОВ СТАНЕТ ДВА. Два
   процесса сервера приложений не видят реестров друг друга: два нажатия,
   попавшие в разные процессы, откроют по своему окну каждое и обе задачи
   поставят. Цена — вторая необратимая отправка в чужую группу и второе
   списание с баланса. Ни одного отказа, ни одной записи в журнале, ни одного
   красного теста при этом не появится: свойство исчезает от правки строки
   запуска, а не от правки кода.

3. СОБСТВЕННЫЙ ДОКСТРИНГ УДЕРЖАНИЯ ЭТО УСЛОВИЕ НАЗЫВАЕТ — И НИГДЕ НЕ ПРОВЕРЯЕТ.
   До этого файла условие было ЗАПИСАННЫМ, но не МАШИННЫМ, а записанное условие
   защищает ровно до того момента, как правку делает человек, который абзац не
   читал. Здесь оно становится утверждением.

4. ПЕРЕЕЗД УДЕРЖАНИЯ В ОБЩЕЕ ХРАНИЛИЩЕ ОТЛОЖЕН ОСОЗНАННО (D-07), А НЕ ЗАБЫТ.
   Условие возврата к решению названо прямо: второй процесс или вторая реплика
   у сервиса приложения. ЭТОТ ГЕЙТ И ЕСТЬ ТОТ СИГНАЛ, который условие
   обнаружит, — он покраснеет в том же коммите, которым условие наступит, а не
   в тот день, когда пользователь получит вторую отправку.

ПОЧЕМУ УТВЕРЖДЕНИЯ ДЕЛАЮТСЯ ПО ОБЛАСТИ, А НЕ ПО ВСЕМУ ФАЙЛУ. Извлекается блок
сервиса приложения — от строки его объявления до следующего объявления сервиса
того же отступа, — и всё утверждается ВНУТРИ него. Прочие сервисы файла имеют
полное право объявлять и число процессов, и число реплик: рабочие Celery делают
это прямо сейчас (`--concurrency`). Запрет на весь файл был бы неисполним и
неверен, а неверный запрет снимают вместе со свойством.

⚠️ РАЗБОР ВЕДЁТСЯ ТЕКСТОМ, А НЕ БИБЛИОТЕКОЙ РАЗБОРА YAML, И ЭТО НЕ ЛЕНЬ. Рамка
вехи запрещает новые зависимости. Такая библиотека сегодня доступна в окружении
лишь ТРАНЗИТИВНО — её присутствие не объявлено ни одной строкой манифеста и
исчезнет с чужим обновлением, — а гейт, падающий на импорте, защищает ровно
ничего: красный по недоступности неотличим для читателя от красного по существу,
и снимают его одинаково.

⚠️ ЧЕГО ГЕЙТ НЕ ВИДИТ — ВЫПИСАНО ЗДЕСЬ, А НЕ ОСТАВЛЕНО НА ДОГАДКУ. Он утверждает
об ОПИСАНИИ СЕРВИСОВ, ЛЕЖАЩЕМ В РЕПОЗИТОРИИ, и не знает: развёртывания,
выполненного не этим файлом (ручной запуск процесса, оркестратор контейнеров,
второй файл композиции, масштабирование командой снаружи файла). Это ПРИНЯТАЯ
граница — то же ограничение и по той же причине записано в
`tests/test_migrations/test_deploy_applies_migrations_before_serving.py`. Закрыть
её суите нечем: что исполняется на боевом стенде, ей недоступно. Записана она
затем, чтобы зелёный цвет здесь не читался как «второго процесса не бывает».

ЗУБЫ ГЕЙТА ДОКАЗАНЫ, А НЕ ЗАЯВЛЕНЫ. Пять контролей (`-k control`) подают
разбору изменённые копии файла композиции: гейт краснеет на объявленном числе
рабочих процессов, на объявленном числе реплик и на переименованном сервисе — и
ОСТАЁТСЯ ЗЕЛЁНЫМ, когда то же самое объявление стоит в области ДРУГОГО сервиса.
Последнее — не украшение: правило, срабатывающее и на рабочем Celery, было бы не
строже, а просто неверным.
"""

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

COMPOSE_PROD = "docker-compose.prod.yml"

# Модуль, чей докстринг НАЗЫВАЕТ условие словами. Гейт и объяснение обязаны
# существовать вместе: без объяснения гейт через один рефакторинг останется без
# предмета, без гейта объяснение остаётся благим пожеланием.
HOLD_MODULE = "app/pages/history.py"
HOLD_REGISTRY = "_RETRY_IN_FLIGHT"

# Имя сервиса приложения в файле композиции.
WEB_SERVICE = "web"

# Объявления ЧИСЛА РАБОЧИХ ПРОЦЕССОВ сервера приложений. Перечень именованный:
# отказ обязан называть, ЧТО именно найдено, иначе читатель отправлен искать по
# всему блоку.
#
# `--concurrency` сюда НЕ входит намеренно: это число рабочих Celery, к процессам
# сервера приложений отношения не имеющее, и внутри области сервиса приложения
# его не бывает.
WORKER_DECLARATIONS = (
    (re.compile(r"--workers\b"), "флаг числа рабочих процессов сервера приложений"),
    (re.compile(r"(?<![\w-])-w\s+\d"), "короткая форма флага числа рабочих процессов"),
    (re.compile(r"\bWEB_CONCURRENCY\b"), "переменная окружения числа процессов"),
    (re.compile(r"\bUVICORN_WORKERS\b"), "переменная окружения числа процессов uvicorn"),
    (re.compile(r"\bGUNICORN_CMD_ARGS\b"), "аргументы gunicorn, способные нести число процессов"),
)

# Объявления ЧИСЛА РЕПЛИК сервиса.
REPLICA_DECLARATIONS = (
    (re.compile(r"^\s*replicas\s*:"), "число реплик сервиса"),
    (re.compile(r"^\s*scale\s*:"), "число экземпляров сервиса"),
)

# Значимые части абзаца, которым условие названо словами. Совпадение по НАБОРУ
# подстрок, а не по всей формулировке: правка слова не имеет права ронять тест —
# хрупкий тест отключают, и вместе с ним отключается свойство.
PRECONDITION_MARKERS = ("памяти", "процесс")
PRECONDITION_PLURALITY = (
    "нескольких процессов",
    "второй процесс",
    "двух процессов",
    "не переживает",
)


def _compose_text() -> str:
    return (REPO_ROOT / COMPOSE_PROD).read_text(encoding="utf-8")


def _service_block(text: str, service: str) -> list[str]:
    """Строки области одного сервиса: от его объявления до следующего сервиса.

    Поиск СНАЧАЛА сужается до раздела сервисов, и это не педантизм: имя `web`
    встречается в файле ещё трижды — внутри `depends_on` соседних сервисов, — а
    у файла есть и якорь общих настроек, чьи ключи стоят на том же отступе, что
    и сервисы. Область, найденная поиском по всему файлу, однажды оказалась бы
    не той, и утверждения о ней стали бы утверждениями ни о чём.

    Пустой список означает «область не найдена», и это отдельное утверждение, а
    не тихое основание для вакуумно-зелёных проверок ниже.
    """
    lines = text.splitlines()

    start = None
    for index, line in enumerate(lines):
        if re.match(r"^services\s*:\s*$", line):
            start = index + 1
            break
    if start is None:
        return []

    # Конец раздела сервисов — первая непустая строка нулевого отступа.
    end = len(lines)
    for index in range(start, len(lines)):
        line = lines[index]
        if line.strip() and not line.startswith(" "):
            end = index
            break

    block_start = None
    for index in range(start, end):
        if re.match(rf"^  {re.escape(service)}\s*:\s*$", lines[index]):
            block_start = index + 1
            break
    if block_start is None:
        return []

    block_end = end
    for index in range(block_start, end):
        line = lines[index]
        if line.strip() and re.match(r"^  \S", line):
            block_end = index
            break

    return lines[block_start:block_end]


def _significant(lines: list[str]) -> list[str]:
    """Строки без комментариев и пустот.

    Комментарии отбрасываются намеренно: абзац, ОБЪЯСНЯЮЩИЙ, почему числа
    процессов здесь нет, содержал бы ровно те слова, которые гейт ищет, и гейт
    покраснел бы на собственном объяснении.
    """
    return [line for line in lines if line.strip() and not line.strip().startswith("#")]


def _worker_declarations(block: list[str]) -> list[str]:
    """Найденные в области объявления числа рабочих процессов, с названием."""
    found: list[str] = []
    for line in _significant(block):
        for pattern, name in WORKER_DECLARATIONS:
            if pattern.search(line):
                found.append(f"{name}: {line.strip()}")
    return found


def _replica_declarations(block: list[str]) -> list[str]:
    """Найденные в области объявления числа реплик, с названием."""
    found: list[str] = []
    for line in _significant(block):
        for pattern, name in REPLICA_DECLARATIONS:
            if pattern.search(line):
                found.append(f"{name}: {line.strip()}")
    return found


def _hold_precondition_paragraph() -> str:
    """Абзац объяснения, стоящий над реестром удержаний повтора.

    Читается именно то, что стоит НАД объявлением реестра: объяснение, уехавшее
    в другой конец файла, перестаёт быть объяснением этой структуры, и находить
    его поиском по всему модулю значило бы утверждать, что слова где-то есть.
    """
    lines = (REPO_ROOT / HOLD_MODULE).read_text(encoding="utf-8").splitlines()

    declaration = None
    for index, line in enumerate(lines):
        if line.startswith(f"{HOLD_REGISTRY}"):
            declaration = index
            break
    if declaration is None:
        return ""

    start = declaration
    while start > 0 and lines[start - 1].lstrip().startswith("#"):
        start -= 1
    return "\n".join(lines[start:declaration])


