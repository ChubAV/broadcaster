def test_the_web_service_block_is_found():
    """Область сервиса приложения НАЙДЕНА и непуста.

    ⚠️ БЕЗ ЭТОГО УТВЕРЖДЕНИЯ ВСЕ ОСТАЛЬНЫЕ БЫЛИ БЫ ВАКУУМНО-ЗЕЛЁНЫМИ. Сервис,
    переименованный при правке композиции, оставил бы пустую область, а «в
    пустом списке нет флага числа процессов» — утверждение истинное и
    бессмысленное. Именно так гейт и перестаёт защищать: не краснея, а находя
    ничто.
    """
    block = _service_block(_compose_text(), WEB_SERVICE)

    assert block, (
        f"в разделе сервисов `{COMPOSE_PROD}` не найдена область сервиса "
        f"`{WEB_SERVICE}`. Сервис переименован или раздел перестроен — пока "
        "область не найдена, все утверждения ниже ничего не значат: обнови имя "
        f"в `WEB_SERVICE` вместе с решением о том, где теперь живёт приложение."
    )


def test_the_web_service_runs_a_single_process():
    """В области сервиса приложения НЕТ объявления числа рабочих процессов.

    Второй процесс сервера приложений снимает удержание повтора отправки МОЛЧА:
    реестр окон живёт в памяти процесса, и два процесса не видят реестров друг
    друга.
    """
    block = _service_block(_compose_text(), WEB_SERVICE)
    assert block, "область сервиса приложения не найдена — см. соседнее утверждение"

    declarations = _worker_declarations(block)

    assert not declarations, (
        f"у сервиса `{WEB_SERVICE}` объявлено число рабочих процессов:\n  "
        + "\n  ".join(declarations)
        + "\n\nУДЕРЖАНИЕ ПОВТОРА ОТПРАВКИ ПЕРЕСТАЛО РАБОТАТЬ. Реестр окон живёт "
        f"в памяти ОДНОГО процесса (`{HOLD_MODULE}`), и два процесса не видят "
        "реестров друг друга: два нажатия, попавшие в разные процессы, обе "
        "задачи поставят — вторая необратимая отправка и второе списание. Это "
        "и есть названное условие возврата к решению D-07: перед тем как "
        "поднимать число процессов, удержание обязано переехать в общее "
        "хранилище."
    )


def test_the_web_service_runs_a_single_replica():
    """В области сервиса приложения НЕТ объявления числа реплик.

    Вторая реплика ломает удержание ровно тем же способом, что и второй процесс,
    и заводится другой строкой — поэтому утверждений два, а не одно.
    """
    block = _service_block(_compose_text(), WEB_SERVICE)
    assert block, "область сервиса приложения не найдена — см. соседнее утверждение"

    declarations = _replica_declarations(block)

    assert not declarations, (
        f"у сервиса `{WEB_SERVICE}` объявлено число реплик:\n  "
        + "\n  ".join(declarations)
        + "\n\nВторая реплика — второй процесс с собственным реестром окон: "
        "удержание повтора отправки перестаёт держать, не сообщив об этом "
        "ничем. Условие возврата к решению D-07 наступило."
    )


def test_the_hold_precondition_is_named_in_the_source():
    """Абзац над реестром удержаний ПО-ПРЕЖНЕМУ называет условие словами.

    ⚠️ ГЕЙТ И ОБЪЯСНЕНИЕ ОБЯЗАНЫ СУЩЕСТВОВАТЬ ВМЕСТЕ. Гейт без объяснения через
    один рефакторинг остаётся без предмета: человек, наткнувшийся на красный
    цвет, прочтёт «нельзя объявлять число процессов» и не узнает ПОЧЕМУ — а
    правило без причины снимают. Объяснение без гейта, наоборот, остаётся благим
    пожеланием, и ровно этим оно было до сегодняшнего дня.

    Совпадение по НАБОРУ значимых подстрок, а не по формулировке целиком: правка
    слова не имеет права ронять тест.
    """
    paragraph = _hold_precondition_paragraph().lower()

    assert paragraph, (
        f"над объявлением `{HOLD_REGISTRY}` в `{HOLD_MODULE}` не осталось "
        "объяснения вовсе — либо реестр переименован. Условие, которое держит "
        "этот файл, перестало быть названным в том месте, где оно действует."
    )

    absent = [marker for marker in PRECONDITION_MARKERS if marker not in paragraph]
    assert not absent, (
        f"объяснение над `{HOLD_REGISTRY}` перестало называть условие: не "
        f"хватает слов {absent}. Гейт `{COMPOSE_PROD}` остался без предмета — "
        "верни абзац или перепиши гейт вместе с решением."
    )
    assert any(marker in paragraph for marker in PRECONDITION_PLURALITY), (
        "объяснение больше не говорит, что реестр НЕ ПЕРЕЖИВАЕТ второго "
        f"процесса: ни одна из формулировок {list(PRECONDITION_PLURALITY)} не "
        "найдена. Именно эта половина абзаца и есть условие, которое сторожит "
        "этот файл."
    )


