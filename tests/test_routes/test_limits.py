"""Количественных лимитов нет ни по одной оси; единственный отказ — закрытый доступ.

⚠️ ДОКСТРИНГ ПЕРЕПИСАН ПЛАНОМ 05.1-07, И ПРЕЖНЕЕ ЕГО УТВЕРЖДЕНИЕ НАЗВАНО, А НЕ
СТЁРТО. Он говорил, что единственный лимит в системе — проверка БАЛАНСА,
отвечающая «разрешено» на любое действие, кроме отправки. Это перестало быть
правдой дважды. Сначала план 05.1-06 снял валюту сообщений целиком: считать
остаток стало нечего, и «лимит» перестал быть лимитом. Затем плоская модель
доступа (D-A) оставила ровно один отказ на весь продукт — ПО ЗАКРЫТОМУ ДОСТУПУ, —
и он не считает ни сущностей, ни сообщений, а спрашивает, оплачен ли срок.

ЧТО УТВЕРЖДАЕТ ЭТОТ ФАЙЛ СЕГОДНЯ — ОБЕ СТОРОНЫ ОДНОГО ПРАВИЛА, А НЕ ОДНУ.
Открытый доступ не имеет ПОТОЛКА: количество объявлений и мессенджер-аккаунтов
ничем не ограничено (D-D, критерий 1), и число, заведомо перекрывающее ЛЮБОЙ из
прежних тарифных порогов, проходит целиком. Закрытый доступ отвергает тот же
самый вызов. Один тест без другого утверждает половину: «всё разрешено» без
антипода зелен и на сломанном гейте, «всё запрещено» без первого — на гейте,
запирающем оплативших.

⚠️ ОСЬ ГРУПП ПРОВЕРЯЕТСЯ ЗДЕСЬ НЕ КОЛИЧЕСТВОМ, И ЭТО СВОЙСТВО ПРОДУКТА, А НЕ
ПРОПУСК. Прикладного входа «создать группу» не существует — GRP-08 снято решением
владельца (D-13/D-14), маршрута нет ни в одном роутере, — и посев групп прямо
через ORM проверял бы, что вставка семи строк вставляет семь строк, то есть
утверждал бы о SQLAlchemy, а не о продукте. Отсутствие порога по группам держит
греп-гейт `tests/test_application/test_no_metering_remains.py`: имя метра осей в
приложении не встречается ни разу.

⚠️ ГЕЙТ ДОСТУПА НА JSON-ВХОДАХ (`get_current_user_id_with_access`, план 05.1-03)
ЛИМИТОМ НЕ ЯВЛЯЕТСЯ И ЭТОТ ФАЙЛ ЕГО НЕ ДУБЛИРУЕТ. Он отвечает на вопрос «оплачен
ли доступ», а не «сколько сущностей уже создано»: его собственные свидетели живут
в `tests/test_pages/test_access_gate.py`, группа `api`. Здесь он появляется ровно
одним антиподом — как единственная причина, по которой создание вообще может
получить отказ.
"""
import pytest

# ЧИСЛО ЗАВЕДОМО ПЕРЕКРЫВАЕТ ЛЮБОЙ ПРЕЖНИЙ ТАРИФНЫЙ ПОРОГ, и это его единственное
# основание. Самые высокие пороги снятого прейскуранта — 15 объявлений (Basic) и
# 20 аккаунтов (Pro); двадцать пять больше обоих. Круглое «десять» прошло бы и при
# вернувшемся тарифе Basic, то есть зеленело бы на восстановленном лимите.
BEYOND_EVERY_FORMER_THRESHOLD = 25


@pytest.mark.asyncio
async def test_create_ads_no_limit(client, auth_headers):
    """Объявления не упираются в потолок: двадцать пять создаются подряд."""
    for index in range(BEYOND_EVERY_FORMER_THRESHOLD):
        resp = await client.post("/api/ads", headers=auth_headers, json={
            "title": f"Ad {index}", "text": "text"
        })
        assert resp.status_code == 201, (
            f"создание объявления №{index + 1} отвергнуто ({resp.status_code}): "
            "количественный лимит вернулся"
        )


@pytest.mark.asyncio
async def test_create_accounts_no_limit(client, auth_headers):
    """Мессенджер-аккаунты не упираются в потолок: прежний максимум был двадцать."""
    for index in range(BEYOND_EVERY_FORMER_THRESHOLD):
        resp = await client.post("/api/accounts", headers=auth_headers, json={
            "type": "wa", "credentials": f"creds-{index}"
        })
        assert resp.status_code == 201, (
            f"создание аккаунта №{index + 1} отвергнуто ({resp.status_code}): "
            "количественный лимит вернулся"
        )


@pytest.mark.asyncio
async def test_creation_is_refused_when_the_access_period_has_ended(
    expired_client, auth_headers
):
    """АНТИПОД: тот же вызов у пользователя с ИСТЁКШИМ доступом отвергается.

    Без него соседние тесты зелены и на гейте, отвечающем «разрешено» ВСЕГДА, —
    то есть доказывали бы отсутствие лимита ценой отсутствия единственного
    работающего отказа. Код 402, а не 403: «не оплачено» есть причина, на которую
    у человека ровно одно действие, и различимость двух причин отказа стоит
    одного кода состояния.
    """
    resp = await expired_client.post(
        "/api/ads", headers=auth_headers, json={"title": "Ad", "text": "text"}
    )

    assert resp.status_code == 402, (
        f"создание при закрытом доступе не отвергнуто ({resp.status_code}): "
        "единственный работающий отказ продукта не сработал"
    )
