"""Отсутствие тарифных лимитов на создание сущностей.

Тест `test_create_groups_no_limit` УДАЛЁН планом 03-07 вместе с входом, через
который он утверждал. Он создавал семь групп запросами к JSON-маршруту создания
группы и проверял, что ни один не отвергнут. Входа больше нет (GRP-08 снято решением
владельца, D-13/D-14), а точки применения лимита за ним никогда не стояло.
Переписать тест на прямой посев через ORM означало бы проверять, что вставка
семи строк в таблицу вставляет семь строк, — утверждение о SQLAlchemy, а не о
продукте.

⚠️ КОЛИЧЕСТВЕННОГО ЛИМИТА В СИСТЕМЕ НЕ ОСТАЛОСЬ НИ ОДНОГО. Прежняя редакция
называла таким кэшированный гейт пути отправки, и это было верно ровно до
снятия валюты сообщений: считался ОСТАТОК, и «сколько уже отправлено» влияло
на ответ. Сегодня гейт (`check_access_cached`, `app/services/billing_cache.py`)
отвечает на вопрос «оплачен ли доступ», ничего не считая, и отвечает
«разрешено» на любое действие, кроме `send`. Число отправленных сообщений не
влияет на сумму и ничем не ограничено (D-D, критерий 1).

⚠️ ГЕЙТ ДОСТУПА НА JSON-ВХОДАХ (`get_current_user_id_with_access`, план 05.1-03)
ЛИМИТОМ НЕ ЯВЛЯЕТСЯ И ЭТОТ ФАЙЛ НЕ ОТМЕНЯЕТ. Он отвечает на вопрос «оплачен ли
доступ», а не «сколько сущностей уже создано», и у пользователя с живым сроком
пропускает любое их число. Его собственные свидетели живут в
`tests/test_pages/test_access_gate.py`, группа `api`.

ФАКТ, который тест документировал, остаётся верным и зафиксирован здесь:
тарифного лимита на количество групп в системе нет. Появление такого лимита —
решение вне рамок фазы 3; вместе с ним вернётся и его тест, но уже к настоящей
точке применения.
"""
import pytest


@pytest.mark.asyncio
async def test_create_ads_no_limit(client, auth_headers):
    """No limit on ads — creating many should succeed."""
    for i in range(5):
        resp = await client.post("/api/ads", headers=auth_headers, json={
            "title": f"Ad {i}", "text": "text"
        })
        assert resp.status_code == 201
