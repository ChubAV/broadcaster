def test_no_planning_gate_asserts_a_live_verdict_literal():
    """НЕСУЩЕЕ ПРАВИЛО: гейт записи не судит вердикт отчёта СВОЕЙ фазы.

    ⚠️ ИМЯ ПРАВИЛА ОСТАВЛЕНО ПРЕЖНИМ НАМЕРЕННО, А ЕГО ПРЕДМЕТ ЗДЕСЬ РАСШИРЕН ДО
    КЛАССА: судимо не только СЛИЧЕНИЕ С ЛИТЕРАЛОМ (признак A), но и всякое
    УТВЕРЖДЕНИЕ О ВЕРДИКТЕ отчёта живого дерева, ВКЛЮЧАЯ УТВЕРЖДЕНИЕ О ЕГО
    ОТСУТСТВИИ (признак B). Имя, гоняющееся за каждым расширением предмета, ломает
    ссылки соседних планов на него; расхождение имени с предметом закрывается
    докстрингом, а не переименованием.

    Отдельными утверждениями — НЕПУСТОТА ОБХОДА двумя величинами. Без них правило
    зеленело бы ВАКУУМОМ при первом же переименовании каталога, и выключение вышло бы
    молчаливым.
    """
    sources = planning_gate_sources()
    assert sources, (
        "в каталоге гейтов записи не найдено ни одного модуля — обход выродился в "
        "пустой, и правило зеленело бы ВАКУУМОМ"
    )

    parsed_functions = 0
    offences: list[Offence] = []
    for module_name, source in sources:
        parsed_functions += sum(
            1
            for node in ast.parse(source).body
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_")
        )
        offences += offending_functions(module_name, source)

    assert parsed_functions, (
        "в модулях каталога не разобрано ни одной тестовой функции — разбор "
        "выродился, и правило зеленело бы ВАКУУМОМ"
    )

    assert not offences, (
        "гейты записи, судящие вердикт отчёта ЖИВОГО дерева:\n"
        + _report(offences)
        + "\n\nЧТО ДЕЛАТЬ: питать контроль СИНТЕТИЧЕСКИМ корнем в `tmp_path`, а не "
        "живым деревом, — предмет отрицательного контроля обязан задаваться самим "
        "контролем, иначе прогон зеленеет ровно при условии, что фаза НЕ достигла "
        "цели, и чинить его придётся правкой утверждений"
    )


