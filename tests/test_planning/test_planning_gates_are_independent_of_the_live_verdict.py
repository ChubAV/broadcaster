# ⚠️ ЧЕТЫРЕ ПОЛОВИНЫ, ПО ОДНОЙ НА КАЖДУЮ ВЕТВЬ ОПРЕДЕЛЕНИЯ И ЕЁ ГРАНИЦУ. Определение
