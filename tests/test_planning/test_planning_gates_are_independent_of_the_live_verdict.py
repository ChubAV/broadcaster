def test_control_a_synthetic_offender_is_named_by_the_rule():
    """ЗУБЫ ПРАВИЛА — НА СИНТЕТИЧЕСКОМ ИСХОДНИКЕ, ЧЕТЫРЬМЯ РАЗДЕЛЬНЫМИ ПОЛОВИНАМИ.

    (а) признак A ловится; (б) чистый исходник пропускается; (в) литерал БЕЗ живого
    корня пропускается; (г) НЕСУЩАЯ — признак B ловится на `assert …verdict is None`
    БЕЗ ЕДИНОГО вердиктного литерала; (д) ГРАНИЦА признака B — упоминание поля ВНЕ
    утверждения нарушителем не является.

    ⚠️ БЕЗ ПОЛОВИНЫ (г) ПРИЗНАК B ВОШЁЛ БЫ В ПРАВИЛО НЕПРОВЕРЕННЫМ — а именно он
    закрывает ту ветвь класса, ради которой написан четвёртый пункт `missing`, и
    именно он делает приёмочный критерий «названы ОБА прежних нарушителя»
    достижимым, а не невыполнимым по построению.
    """
    # (а) ПРИЗНАК A ЛОВИТСЯ.
    caught_a = offending_functions("синтетика-A.py", _OFFENDER_BY_LITERAL)
    assert len(caught_a) == 1, _report(caught_a)
    assert caught_a[0].function == "test_a_gate_that_compares_the_live_verdict_with_a_literal"
    assert caught_a[0].trait == TRAIT_LITERAL, str(caught_a[0])
    assert "gaps_found" in str(caught_a[0]), str(caught_a[0])

    # (б) ЧИСТЫЙ ИСХОДНИК ПРОПУСКАЕТСЯ.
    caught_b = offending_functions("синтетика-чистая.py", _CLEAN_SOURCE)
    assert not caught_b, _report(caught_b)

    # (в) ЛИТЕРАЛ БЕЗ ЖИВОГО КОРНЯ ПРОПУСКАЕТСЯ.
    caught_c = offending_functions("синтетика-без-корня.py", _LITERAL_WITHOUT_THE_LIVE_ROOT)
    assert not caught_c, _report(caught_c)

    # (г) ПРИЗНАК B ЛОВИТСЯ — БЕЗ ЕДИНОГО ВЕРДИКТНОГО ЛИТЕРАЛА.
    caught_d = offending_functions("синтетика-B.py", _OFFENDER_BY_ASSERTED_ABSENCE)
    assert not any(
        verdict in _OFFENDER_BY_ASSERTED_ABSENCE for verdict in VERIFICATION_VERDICTS
    ), (
        "синтетический нарушитель признака B несёт вердиктный литерал — тогда его "
        "поймал бы признак A, и половина (г) не проверяла бы НИЧЕГО"
    )
    assert len(caught_d) == 1, _report(caught_d)
    assert caught_d[0].function == "test_a_gate_that_asserts_the_absence_of_a_report"
    assert caught_d[0].trait == TRAIT_ASSERTED_VERDICT, str(caught_d[0])

    # (д) ГРАНИЦА ПРИЗНАКА B: поле вердикта ВНЕ утверждения — не нарушение.
    caught_e = offending_functions(
        "синтетика-граница.py", _VERDICT_MENTIONED_OUTSIDE_AN_ASSERTION
    )
    assert not caught_e, (
        "упоминание поля вердикта ВНЕ утверждения засчиталось нарушением — тогда "
        "признак B неотличим от «любое упоминание поля», и правило краснело бы на "
        "ПОСТРОЕНИИ отчёта, а не на суждении о нём:\n" + _report(caught_e)
    )
