def test_the_gate_reads_sources_not_the_rendered_document() -> None:
    """Гейт читает ИСХОДНИКИ и одно свойство окружения; приложение не поднимает.

    ⚠️ ЭТО ЗАПРЕТ, А НЕ СТИЛЬ. Гейт, поднимающий приложение, перестаёт быть
    исполнимым в дереве, которое собрать нельзя, — а это ровно то дерево, где
    он нужнее всего. Форма запрета взята у
    ``tests/test_pages/test_money_perimeter_gate.py``, где то же свойство
    утверждается разбором собственного дерева файла.

    ОТЛИЧИЕ ОТ ОБРАЗЦА НАЗВАНО ПРЯМО, А НЕ ОБОЙДЕНО. Образец запрещает ВСЯКИЙ
    ввоз из приложения — там ожидания могли бы быть выведены из проверяемого.
    Здесь ввоз ОДИН и именованный: окружение шаблонов, у которого читается
    признак автоматического экранирования. Вывести из него ожидания трёх
    инвентарей нельзя — они выписаны литералами, а обходы читают файлы как
    текст и как дерево разбора. Допущение ровно одно, и второе потребует
    решения, а не правки списка.
    """
    tree = ast.parse(Path(__file__).read_text(encoding="utf-8"))

    imported: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.append(node.module)

    from_application = sorted(
        {name for name in imported if name == "app" or name.startswith("app.")}
    )
    assert from_application == ["app.pages.common"], (
        f"гейт ввозит из приложения {from_application}, а именованное допущение "
        "ровно одно — окружение шаблонов. Второй ввоз означает, что ожидания "
        "могли быть выведены из проверяемого, и тест согласился бы с правкой"
    )

    forbidden = {"AsyncClient", "TestClient", "create_app", "TemplateResponse"}
    used: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and node.id in forbidden:
            used.add(node.id)
        elif isinstance(node, ast.Attribute) and node.attr in forbidden | {"render"}:
            used.add(node.attr)

    assert used == set(), (
        f"гейт поднимает приложение или рендерит шаблон ({sorted(used)}) — он "
        "перестал быть исполнимым в дереве, которое собрать нельзя, а это ровно "
        "то дерево, где он нужнее всего"
    )


# =============================================================================
# КОНТРОЛИ: доказательство того, что гейт КРАСНЕЕТ (`-k control`)
#
# ⚠️ ЗАЧЕМ ОНИ, ЕСЛИ ВЫШЕ УЖЕ ШЕСТЬ ТЕСТОВ. Три нуля, полученные обходом, и три
# нуля, полученные СЛОМАННЫМ обходом, выглядят одинаково, и различие
# обнаруживается в тот единственный день, когда снятие экранирования проходит
# мимо. Утверждения выше говорят «сегодня мест нет»; контроли ниже говорят «а
# когда появятся — я это увижу» и «а когда НЕ появятся — не покраснею зря». Это
# три разных высказывания, и ни одно не следует из остальных.
#
# НИ ОДИН КОНТРОЛЬ НЕ ТРОГАЕТ ФАЙЛОВ ПРОЕКТА. Изменённый исходник пишется во
# ВРЕМЕННЫЙ файл (`tmp_path`) и оттуда подаётся разбору; боевое дерево читается
# только на чтение.
#
# КАЖДАЯ ПОДМЕНА НЕСЁТ УТВЕРЖДЕНИЕ «ПОДМЕНА ЧТО-ТО ИЗМЕНИЛА». Урок плана 08-10:
# подстрока, разошедшаяся с настоящим объявлением, превращает контроль в
# зелёный ПО ПОСТРОЕНИЮ — он проверяет неизменённый исходник и молчит об этом.
# =============================================================================


def _sources_with(
    tmp_path, sources: dict[str, str], key: str, text: str
) -> dict[str, str]:
    """Копия поданных исходников, в которой ОДИН файл подменён — через файл.

    Подмена идёт по-настоящему через файловую систему, а не строкой в памяти:
    так контроль проверяет тот же путь чтения, которым гейт ходит по боевому
    дереву, и не может разойтись с ним из-за кодировки или переносов строк.
    """
    scratch = tmp_path / Path(key).name
    scratch.write_text(text, encoding="utf-8")

    changed = dict(sources)
    changed[key] = scratch.read_text(encoding="utf-8")
    return changed


