# =============================================================================
# ИСКОМЫЕ КОНСТРУКЦИИ. Каждая — именованная регулярка с абзацем о том, ЧТО она
# закрывает и почему её граница проведена именно так.
# =============================================================================

# Фильтр снятия экранирования. Правая граница закрыта ОТРИЦАТЕЛЬНЫМ ПРОСМОТРОМ
# ВПЕРЁД: без него выражение совпало бы внутри более длинного имени фильтра
# (`safe_join`, `safelist`), то есть гейт краснел бы на фильтре, никакого
# экранирования не снимающем, и его сняли бы первой же правкой вместе со
# свойством. Левая граница закрыта самим символом канала: имя фильтра в Jinja
# стоит только после него.
UNESCAPE_FILTER = re.compile(r"\|\s*safe(?![\w])")

# Отключение автоматического экранирования БЛОКОМ. Второй способ снять
# экранирование, и он опаснее первого: снимается не с одного значения, а со
# всего, что попало между открытием и закрытием блока. Гейт, знающий только
# фильтр, прошёл бы мимо целого блока разметки.
UNESCAPE_BLOCK = re.compile(r"\{%-?\s*autoescape\s+(?:false|off)(?![\w])")

# Блочный фильтр снятия экранирования — третья форма того же: фильтр,
# применённый к блоку разметки, а не к значению.
UNESCAPE_FILTER_BLOCK = re.compile(r"\{%-?\s*filter\s+safe(?![\w])")

UNESCAPE_CONSTRUCTS = (
    ("фильтр снятия экранирования", UNESCAPE_FILTER),
    ("отключение автоматического экранирования блоком", UNESCAPE_BLOCK),
    ("блочный фильтр снятия экранирования", UNESCAPE_FILTER_BLOCK),
)

# Имя сборки безопасной разметки и модули, из которых она ввозится. Модуля два:
# ввоз из библиотеки экранирования и ввоз из самого шаблонизатора — гейт,
# знающий один, прошёл бы мимо второго.
MARKUP_NAME = "Markup"
MARKUP_MODULES = frozenset({"markupsafe", "jinja2"})

# Атрибут дополнительных параметров запроса. ОТРИЦАТЕЛЬНЫЙ ПРОСМОТР НАЗАД
# отсекает атрибуты, у которых искомое имя — лишь хвост более длинного
# (`data-hx-vals`): граница слова его бы НЕ отсекла, потому что дефис сам по
# себе не буква. Форма границы взята у `HX_GET_ATTR` из инвентаря разметки.
REQUEST_PARAM_ATTR = re.compile(
    r"(?<![-\w])hx-vals\s*=\s*(\"[^\"]*\"|'[^']*')"
)

# Атрибут, объявляющий обработчик события ПРЯМО В РАЗМЕТКЕ. Содержимое такого
# атрибута — исполняемое выражение рантайма, то есть ВТОРОЙ слой экранирования
# поверх слоя разметки: автоматическое экранирование шаблонизатора закрывает
# только первый. Необязательная часть выражения ловит обе записи семейства —
# и с одним двоеточием (событие браузера), и с двумя (событие рантайма).
INLINE_HANDLER_ATTR = re.compile(r"(?<![-\w])hx-on(?:::?[\w.:-]+)?\s*=")

# Сериализация значения в JSON — единственная разрешённая форма подстановки в
# атрибут параметров запроса (правило на вырост, см. соответствующий тест).
JSON_SERIALISATION = re.compile(r"\|\s*tojson(?![\w])")

# Значение атрибута, объявленное ИСПОЛНЯЕМЫМ ВЫРАЖЕНИЕМ. Запрещено безусловно:
# такое значение вычисляется рантаймом, и никакая сериализация его не закрывает.
EXECUTABLE_VALUE = re.compile(r"^\s*(?:js:|javascript:)", re.IGNORECASE)

# Подстановка шаблонизатора внутри значения атрибута.
JINJA_INTERPOLATION = re.compile(r"\{\{.*?\}\}", re.DOTALL)


