def _template_sources() -> dict[str, str]:
    """Все шаблоны проекта: путь относительно ``app/templates`` → исходник.

    Обход РЕКУРСИВНЫЙ (``rglob``) и по ОТСОРТИРОВАННОМУ списку путей. Первое —
    потому что плоский обход не увидел бы подкаталогов ``includes/``,
    ``components/`` и ``*/partials/``, где живут в том числе области
    уведомления, ради которых гейт и написан. Второе — чтобы сообщение об
    отказе было воспроизводимо от прогона к прогону.
    """
    return {
        path.relative_to(TEMPLATES_DIR).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(TEMPLATES_DIR.rglob("*.html"))
    }


def _python_sources() -> dict[str, str]:
    """Все модули ``app/``: путь от корня проекта → исходник.

    Область поиска — РОВНО ``app/``. Каталог ``tests/`` в неё не входит, и это
    несущее свойство гейта, а не удобство: см. соответствующий абзац шапки.
    """
    return {
        path.relative_to(PROJECT_ROOT).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(APP_ROOT.rglob("*.py"))
    }


def _escape_escapes(templates_: dict[str, str]) -> dict[str, str]:
    """Места снятия экранирования в шаблонах: ключ → чем именно снято.

    Комментарии обоих видов вырезаются ДО счёта. Это несущее решение, а не
    удобство разбора: кодовая база проекта несёт комментарии-обоснования
    объёмные, и абзац о том, почему снятие экранирования здесь запрещено,
    свободно содержит имя самой конструкции. Гейт, считающий прозу, получил бы
    два отказа сразу — он краснел бы на правку документации и, что хуже,
    позволил бы комментарию ЗАМЕНИТЬ собой исчезнувшее место, оставив число
    верным (тот же довод, что у ``_strip_comments`` в инвентаре разметки).

    Ключ — ПУТЬ ФАЙЛА ПЛЮС ПОРЯДКОВЫЙ НОМЕР ВХОЖДЕНИЯ, а не текст найденного:
    два одинаковых снятия в одном файле обязаны остаться двумя записями.
    Нумерация идёт по ПОЛОЖЕНИЮ в исходнике, а не по порядку перебора
    конструкций, — иначе номер записи менялся бы от перестановки строк в
    ``UNESCAPE_CONSTRUCTS``.
    """
    found: dict[str, str] = {}
    for rel, source in sorted(templates_.items()):
        body = _strip_comments(source)
        hits: list[tuple[int, str]] = []
        for label, pattern in UNESCAPE_CONSTRUCTS:
            for match in pattern.finditer(body):
                snippet = body[match.start() : match.end() + 30].replace("\n", " ")
                hits.append((match.start(), f"{label}: {snippet!r}"))
        for ordinal, (_position, description) in enumerate(sorted(hits)):
            found[f"{rel}#{ordinal}"] = description
    return found


def _markup_builders(python_sources: dict[str, str]) -> dict[str, str]:
    """Места сборки безопасной разметки в коде приложения: ключ → что найдено.

    ⚠️ ГЕЙТ ЧИТАЕТ ДЕРЕВО РАЗБОРА, А НЕ ТЕКСТ, И ЭТО НЕСУЩЕЕ РЕШЕНИЕ. Текстовый
    поиск считал бы упоминания имени в строках документации — а они здесь
    обязательны и объёмны, — то есть краснел бы на правку ДОКУМЕНТАЦИИ и молчал
    бы на переезд вызова в переменную. Прецедент того же решения —
    ``_status_code_literals`` в ``test_htmx_response_contract.py``.

    Ищутся ОБА способа завести место, и второй важнее первого:
      * ВЫЗОВ по имени — прямая сборка;
      * ВВОЗ имени из библиотеки экранирования или шаблонизатора, в том числе
        ПОД ПСЕВДОНИМОМ. Ввоз под псевдонимом с последующим вызовом псевдонима
        прошёл бы мимо гейта, знающего только имя, — та же слепая зона, которую
        план 08-10 закрыл запретом псевдонима импорта создания платежа. Имя,
        связанное ввозом, добавляется к искомым, и вызов псевдонима находится.

    Ключ — ПУТЬ ПЛЮС СТРОКА И СТОЛБЕЦ: ввоз и вызов на одной строке остаются
    двумя записями и не схлопываются в одну.
    """
    found: dict[str, str] = {}
    for rel, source in sorted(python_sources.items()):
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:  # pragma: no cover - защитная ветка
            found[f"{rel}#unparsed"] = f"модуль не разобран: {exc}"
            continue

        bound: set[str] = set()
        for node in ast.walk(tree):
            if not isinstance(node, ast.ImportFrom) or node.module not in MARKUP_MODULES:
                continue
            for alias in node.names:
                if alias.name != MARKUP_NAME:
                    continue
                local = alias.asname or alias.name
                bound.add(local)
                found[f"{rel}:{node.lineno}:{node.col_offset}"] = (
                    f"ввоз {node.module}.{MARKUP_NAME} под именем {local}"
                )

        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            if isinstance(func, ast.Name):
                name = func.id
            elif isinstance(func, ast.Attribute):
                name = func.attr
            else:
                continue
            if name == MARKUP_NAME or name in bound:
                found[f"{rel}:{node.lineno}:{node.col_offset}"] = (
                    f"вызов сборки безопасной разметки {name}(...)"
                )
    return found


def _request_param_attrs(templates_: dict[str, str]) -> dict[str, str]:
    """Атрибуты параметров запроса и атрибуты обработчиков событий: ключ → что.

    Оба семейства сведены в ОДИН инвентарь, потому что закрывают они одну
    поверхность: содержимое такого атрибута разбирается рантаймом htmx как
    выражение, то есть проходит ВТОРОЙ слой экранирования, которого
    автоматическое экранирование шаблонизатора не касается.
    """
    found: dict[str, str] = {}
    for rel, source in sorted(templates_.items()):
        body = _strip_comments(source)
        hits: list[tuple[int, str]] = []
        for match in REQUEST_PARAM_ATTR.finditer(body):
            hits.append((match.start(), f"атрибут параметров запроса: {match.group(0)!r}"))
        for match in INLINE_HANDLER_ATTR.finditer(body):
            snippet = body[match.start() : match.end() + 30].replace("\n", " ")
            hits.append((match.start(), f"обработчик события в разметке: {snippet!r}"))
        for ordinal, (_position, description) in enumerate(sorted(hits)):
            found[f"{rel}#{ordinal}"] = description
    return found


def _unserialised_request_param_attrs(templates_: dict[str, str]) -> dict[str, str]:
    """Атрибуты параметров запроса, чьё значение НЕ прошло сериализацию в JSON.

    ПРАВИЛО НА ВЫРОСТ, И ОНО ИСПОЛНИМО СЕГОДНЯ, А НЕ ЗАПИСАНО ПРОЗОЙ. Инвентарь
    таких атрибутов пуст, поэтому помощник возвращает пустоту, — но возвращает
    он её ОБХОДОМ, а не константой. В тот день, когда первый такой атрибут
    появится, правило начнёт работать само, без правки этого файла.

    Отказов два, и они разной природы:
      * значение, объявленное ИСПОЛНЯЕМЫМ ВЫРАЖЕНИЕМ, запрещено безусловно:
        оно вычисляется рантаймом, и сериализация его не закрывает;
      * значение с подстановкой шаблонизатора обязано пройти через сериализацию
        в JSON. Без неё кавычка внутри подставленного значения закрывает
        значение атрибута и открывает следующее — то самое второе экранирование,
        которого автоматическое экранирование разметки не делает.
    """
    offenders: dict[str, str] = {}
    for rel, source in sorted(templates_.items()):
        body = _strip_comments(source)
        for ordinal, match in enumerate(REQUEST_PARAM_ATTR.finditer(body)):
            value = match.group(1)[1:-1]
            key = f"{rel}#{ordinal}"
            if EXECUTABLE_VALUE.search(value):
                offenders[key] = (
                    "значение атрибута объявлено исполняемым выражением: "
                    f"{value!r} — запрещено безусловно"
                )
                continue
            for interpolation in JINJA_INTERPOLATION.findall(value):
                if JSON_SERIALISATION.search(interpolation):
                    continue
                offenders[key] = (
                    f"подстановка {interpolation!r} уезжает в атрибут параметров "
                    "запроса без сериализации в JSON"
                )
                break
    return offenders


