# ⚠️ НАЧАЛО ВЫРАЖЕНИЯ — ОТДЕЛЬНОЕ МНОЖЕСТВО, И ОНО НЕ РАВНО ЗАКОННОМУ. Выражение,
# состоящее из законных знаков, но начинающееся дефисом, цифрой или знаком равенства,
# в консоли даёт тот же отказ разборщика, что и проза, — а чинится ИНАЧЕ, потому что
# это не «в поле уехала проза», а «в поле уехало НЕ ВЫРАЖЕНИЕ».
SELECTOR_START_CHARS = frozenset(
    "#.[:*" + "abcdefghijklmnopqrstuvwxyz" + "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
)

# Цифра, которой заменяется объявленный заполнитель при построении консольной формы.
# ⚠️ ИМЕННО ЦИФРА: все четыре заполнителя реестра суть первичные ключи, и подстановка
# буквы дала бы выражение, которое в консоли законно, а в живом документе никогда не
# встретится — то есть правило зеленело бы на форме, продукту не соответствующей.
PLACEHOLDER_SUBSTITUTE = "1"

# ⚠️ ТРИ ОСНОВАНИЯ, А НЕ ОДНО, И ЭТО ТА ЖЕ ДОКТРИНА, ЧТО У `NO_SOURCE_FILE` /
# `NO_ANCHOR_IN_FILE`: «проза в поле», «необъявленный заполнитель» и «это вообще не
# выражение» чинятся ПО-РАЗНОМУ, и слитый отказ заставил бы следующего читателя
# разбирать, какое из трёх событий случилось.
PROSE_IN_SELECTOR = "проза в поле выражения: консольная форма несёт знаки вне законного множества"
PLACEHOLDER_NOT_DECLARED = "заполнитель не объявлен: фигурные скобки в выражении либо объявление, ни на что не указывающее"
NOT_A_SELECTOR = "это не выражение селектора: консольная форма начинается знаком, которым выражение начинаться не может"


def _console_form(anchor: Anchor) -> str:
    """КОНСОЛЬНАЯ ФОРМА записи — ровно то, что человек наберёт после подстановки.

    Заполнитель объявлен — он заменяется цифрой; не объявлен — выражение уходит в
    проверку как есть, и фигурная скобка в нём краснит ПЕРВОЕ основание.
    """
    if anchor.placeholder:
        return anchor.selector.replace(anchor.placeholder, PLACEHOLDER_SUBSTITUTE)
    return anchor.selector


@dataclass(frozen=True)
class TypeabilityFinding:
    """Одна ненабираемая запись, ЧЕМ именно ненабираемая и что при этом наберётся."""

    anchor: Anchor
    reason: str
    console_form: str
    detail: str = ""

    def __str__(self) -> str:
        tail = f" ({self.detail})" if self.detail else ""
        return f"{self.anchor}: {self.reason}{tail}; в консоли наберётся `{self.console_form}`"


def typeability_findings(anchors: tuple[Anchor, ...]) -> list[TypeabilityFinding]:
    """ВСЕ ненабираемые записи одним списком, а не первая.

    РЕЕСТР ПРИХОДИТ ПАРАМЕТРОМ по основанию, уже записанному у `missing_anchors`
    выше, и оно переносится сюда ССЫЛКОЙ, а не второй копией: без параметра контроль
    зубов был бы невыразим, и зубы правила пришлось бы ЗАЯВЛЯТЬ вместо того, чтобы
    их ПОКАЗЫВАТЬ.

    ⚠️ ПОРЯДОК ПРОВЕРОК НЕСУЩИЙ, А НЕ СЛУЧАЙНЫЙ. Сперва заполнитель, затем знаки
    консольной формы, затем её начало. Выражение с НЕОБЪЯВЛЕННЫМ заполнителем упало
    бы и на знаках тоже (фигурная скобка вне законного множества), и отказ назвал бы
    не ту починку: читателю сказали бы «убери прозу» там, где надо «объяви
    заполнитель». Одна запись даёт РОВНО ОДНУ находку — по ПЕРВОМУ сработавшему
    основанию.
    """
    findings: list[TypeabilityFinding] = []
    for anchor in anchors:
        console = _console_form(anchor)

        if "{" in anchor.selector and not anchor.placeholder:
            findings.append(
                TypeabilityFinding(
                    anchor,
                    PLACEHOLDER_NOT_DECLARED,
                    console,
                    "в выражении есть фигурная скобка, а поле заполнителя пусто",
                )
            )
            continue
        if anchor.placeholder and anchor.placeholder not in anchor.selector:
            findings.append(
                TypeabilityFinding(
                    anchor,
                    PLACEHOLDER_NOT_DECLARED,
                    console,
                    f"объявлен заполнитель `{anchor.placeholder}`, а в выражении его НЕТ",
                )
            )
            continue

        illegal = sorted({char for char in console if char not in SELECTOR_LEGAL_CHARS})
        if illegal:
            findings.append(
                TypeabilityFinding(
                    anchor,
                    PROSE_IN_SELECTOR,
                    console,
                    "знаки вне множества: " + " ".join(f"`{char}`" for char in illegal),
                )
            )
            continue

        if not console or console[0] not in SELECTOR_START_CHARS:
            findings.append(
                TypeabilityFinding(
                    anchor,
                    NOT_A_SELECTOR,
                    console,
                    f"первый знак — `{console[:1]}`",
                )
            )
    return findings


