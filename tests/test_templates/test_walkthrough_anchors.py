class ModalTagNotParsed(Exception):
    """Открывающий тег рычага не разобран, и основание названо своим текстом."""


def _lever_source() -> str:
    """Исходник рычага одним чтением. Читается ТОЛЬКО на чтение — дерево не правится."""
    return (TEMPLATES_DIR / MODAL_LEVER_SOURCE).read_text(encoding="utf-8")


def _naive_first_bracket_tag(source: str) -> str:
    """НАИВНЫЙ разбор — до ПЕРВОЙ закрывающей скобки, без учёта кавычек.

    ⚠️ ЭТО НЕ РАБОЧИЙ РАЗБОРЩИК, А ПРЕДМЕТ КОНТРОЛЯ. Ровно так разбирает пример
    починки, приведённый ревизией (`10-REVIEW.md`, `WR-01`), и ровно этим он на
    сегодняшнем дереве теряет признак роли диалога.
    """
    start = source.index(MODAL_TAG_START)
    return source[start : source.index(">", start) + 1]


def _modal_opening_tag(source: str) -> str:
    """Открывающий тег `.modal` ЦЕЛИКОМ — разбор С УЧЁТОМ КАВЫЧЕК.

    ⚠️ УЧЁТ КАВЫЧЕК ЗДЕСЬ НЕ ОСТОРОЖНОСТЬ, А ЗАМЕР. Прогон 2026-09-09 по
    `app/templates/components/modal.html`: НАИВНЫЙ разбор — от литерала начала тега
    до ПЕРВОЙ закрывающей угловой скобки — даёт кусок в 710 символов,
    обрывающийся ВНУТРИ значения атрибута `x-data`, на стрелочной функции в теле
    `show()`; `id="{{ id }}"` в нём ЕСТЬ, `role="dialog"` — НЕТ. Разбор с учётом
    кавычек даёт 2008 символов, и в нём есть ОБА признака.

    ⚠️ ЗНАЧИТ, ПРАВИЛО, НАПИСАННОЕ НАИВНО, КРАСНЕЛО БЫ СЕГОДНЯ НА РАБОТАЮЩЕЙ
    РАЗМЕТКЕ — то есть требовало бы чинить ПРОДУКТ там, где сломан РАЗБОРЩИК, и
    первый же читатель выключил бы правило вместе со свойством. Ровно так разбирает
    пример починки, приведённый ревизией (`10-REVIEW.md`, `WR-01`), — на ЭТОМ дереве
    он не работает.

    ⚠️ СНЯТЬ ЭТУ «ЛИШНЮЮ СЛОЖНОСТЬ» БЕЗ ЗАМЕРА НЕЛЬЗЯ: основание записано
    ИСПОЛНЕНИЕМ — `test_control_a_naive_first_bracket_scan_would_misread_this_markup`.

    ⚠️ КАВЫЧКА ОТКРЫВАЕТ ЗНАЧЕНИЕ ТОЛЬКО ПОСЛЕ ЗНАКА ПРИСВАИВАНИЯ, И ЭТО СУЖЕНИЕ,
    А НЕ ОТМЕНА УЧЁТА КАВЫЧЕК. До восьмого круга ревизии (`IN-02`, `10-REVIEW.md`,
    2026-09-10) разбор переключал состояние на ЛЮБОЙ кавычке вне кавычек, и апостроф
    внутри НЕЗАКАВЫЧЕННОГО значения (`data-owner=it's`) уводил разбор в мнимое
    значение до конца исходника — то есть поднимал «тег не замкнут» на ИСПРАВНОЙ
    разметке. ОБА ЗАМЕРА ВЫШЕ ПРИ ЭТОМ ОСТАЛИСЬ ВЕРНЫМИ: прогон 2026-09-10 даёт те же
    710 и 2008 символов, потому что все ДЕСЯТЬ знаков присваивания открывающего тега
    рычага ведут к ЗАКАВЫЧЕННЫМ значениям.

    ⚠️ ГРАНИЦА СУЖЕНИЯ НАЗЫВАЕТСЯ, А НЕ ЗАКРЫВАЕТСЯ МОЛЧА. Незакавыченное значение,
    содержащее УГЛОВУЮ СКОБКУ, разбор по-прежнему ОБОРВЁТ на ней. Ветви для него не
    заводится намеренно: такое значение в разметке невыразимо без экранирования, а
    замер 2026-09-10 по открывающему тегу рычага даёт вхождений незакавыченных
    значений — НОЛЬ (знаков присваивания вне значения десять, все ведут к
    закавыченным). Заводить разбор под форму, которой в дереве нет, значило бы
    стеречь ПУСТОТУ.

    Ненайденный литерал начала и незамкнутый тег — ДВА РАЗНЫХ основания с РАЗНЫМИ
    текстами.
    """
    occurrences = source.count(MODAL_TAG_START)
    if occurrences != 1:
        raise ModalTagNotParsed(
            f"{TAG_START_NOT_UNIQUE}: вхождений {occurrences}, а разбор ведётся по "
            f"РОВНО ОДНОМУ. Ноль означает, что корневой узел рычага переименован; "
            f"больше одного — что тег перестал быть единственным, и правило молча "
            f"разбирало бы ПЕРВЫЙ попавшийся"
        )

    start = source.index(MODAL_TAG_START)
    quote: str | None = None
    for position in range(start, len(source)):
        char = source[position]
        if quote is not None:
            if char == quote:
                quote = None
            continue
        if char in "\"'":
            # ⚠️ КАВЫЧКА ОТКРЫВАЕТ ЗНАЧЕНИЕ ТОЛЬКО ПОСЛЕ ЗНАКА ПРИСВАИВАНИЯ.
            # Апостроф внутри незакавыченного значения знаком открытия не является:
            # ближайший предшествующий непробельный знак у него — буква значения, а
            # не `=`. Выход из значения — на ПАРНОЙ кавычке того же рода, как и был.
            if source[start:position].rstrip().endswith("="):
                quote = char
            continue
        if char == ">":
            return source[start : position + 1]

    raise ModalTagNotParsed(
        f"{TAG_NOT_CLOSED}: от литерала начала до конца исходника закрывающей "
        f"угловой скобки ВНЕ кавычек не встретилось — разметка рычага сломана "
        f"либо кавычка в значении атрибута не закрыта"
    )


def dialog_role_findings(source: str) -> list[str]:
    """Расхождения конъюнкции — ВСЕ, а не первое, и НА ПРИЗНАК, а не на файл.

    ИСХОДНИК ПРИХОДИТ ПАРАМЕТРОМ по той же причине, по какой параметром приходит
    реестр у `missing_anchors`: без параметра контроль зубов был бы невыразим, и
    зубы правила пришлось бы ЗАЯВЛЯТЬ вместо того, чтобы их ПОКАЗЫВАТЬ.

    Ушедший идентификатор и ушедшая роль ломают счёт ПО-РАЗНОМУ, и слитое
    сообщение назвало бы одно вместо двух.
    """
    tag = _modal_opening_tag(source)
    findings: list[str] = []
    if MODAL_ID_MARKER not in tag:
        findings.append(ID_LEFT_THE_TAG)
    if MODAL_ROLE_MARKER not in tag:
        findings.append(ROLE_LEFT_THE_TAG)
    return findings


