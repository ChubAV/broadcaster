        # ⚠️ ПОЯСНЕНИЕ ВЫНОСИТСЯ В ОТКАЗ, А НЕ ПРЯЧЕТСЯ В ДАННЫХ: до переезда прозы
        # оно стояло В ПОЛЕ ВЫРАЖЕНИЯ и попадало в отказ само собой. Форма склейки
        # сохраняет обе половины — выражение (набираемое) и пояснение (читаемое).
        explained = f" — {self.note}" if self.note else ""
