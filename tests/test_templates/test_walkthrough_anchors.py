# --- набираемость: поле, которое человек НАБИРАЕТ, содержит выражение, а не прозу ---
#
# ЗАЧЕМ ПРАВИЛО, ЕСЛИ ДОГОВОР УЖЕ ЗАПИСАН В ДОКСТРИНГЕ ЗАПИСИ. Договор поля
