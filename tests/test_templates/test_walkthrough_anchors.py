    marker: str
    source: str
    step: str
    # ⚠️ ПОЛЕ С УМОЛЧАНИЕМ, И УМОЛЧАНИЕ НЕСУЩЕЕ: `test_control_a_missing_anchor_is_named_by_the_rule`
    # собирает записи ИМЕНОВАННЫМИ аргументами без этого поля, и обязательное
    # поле уронило бы его НА СБОРКЕ — то есть краснотой, к предмету того контроля
    # отношения не имеющей.
    placeholder: str = ""
    # ⚠️ ТО ЖЕ УМОЛЧАНИЕ И ПО ТОМУ ЖЕ ОСНОВАНИЮ, ЧТО У ПОЛЯ ВЫШЕ.
    note: str = ""

