def test_every_disabled_elt_exception_is_actually_an_exception() -> None:
    """НЕСУЩЕЕ, третье утверждение SP-1: запись правда в исключаемом положении.

    Краснеет в трёх случаях, и каждый — свой вид устаревания перечня:

    * запись с пустыми ``callers`` относится к месту, у которого атрибут
      ПОЯВИЛСЯ — то есть место давно живёт по общему правилу, а перечень всё
      ещё выводит его из-под проверки наличия;
    * запись с непустыми ``callers`` относится к месту с ЛИТЕРАЛЬНЫМ значением —
      значит переопределять его вызывающему нечего, и снятие проверки значения
      больше ничем не оправдано;
    * объявленное множество вызывающих разошлось с ИЗМЕРЕННЫМ: забытый
      вызывающий краснеет, лишний краснеет.

    Без этого утверждения перечень был бы декорацией: устаревшая запись жила бы
    вечно и молча выводила бы из-под правила место, которое правилу подчиняется.
    """
    templates = _all_templates()
    sources = dict(templates)
    by_template = {site.template: site for site in _post_sites(templates)}

    offenders: dict[str, str] = {}
    for template, entry in DISABLED_ELT_EXCEPTIONS.items():
        site = by_template.get(template)
        if site is None:
            offenders[template] = "места отправки htmx в этом файле больше нет"
            continue
        value = _attr_value(site.tag, HX_DISABLED_ELT_VALUE)

        if not entry.callers:
            if value is not None:
                offenders[template] = (
                    f"запись объявляет «атрибута нет вовсе», но он есть: "
                    f"{value!r} — место живёт по общему правилу, а перечень "
                    f"продолжает выводить его из-под проверки наличия"
                )
            continue

        if value is None:
            offenders[template] = (
                "запись объявляет переопределение вызывающим, но атрибута на "
                "месте нет вовсе"
            )
            continue
        if "{{" not in value:
            offenders[template] = (
                f"значение на месте ЛИТЕРАЛЬНО ({value!r}) — переопределять его "
                f"вызывающему нечем, и снятие проверки значения не оправдано"
            )
            continue

        measured: set[str] = set()
        for macro_name in MACRO_DECLARATION.findall(sources.get(template, "")):
            measured |= set(
                _macro_callers(templates, macro_name, DISABLED_ELT_ARGUMENT)
            )
        if measured != set(entry.callers):
            offenders[template] = (
                f"объявленные вызывающие {sorted(entry.callers)} разошлись с "
                f"измеренными {sorted(measured)}"
            )

    assert not offenders, (
        f"запись перечня исключений НЕ находится в исключаемом положении: "
        f"{offenders} — перечень выводит из-под общего правила блокировки "
        f"место, которое этому правилу подчиняется"
    )


