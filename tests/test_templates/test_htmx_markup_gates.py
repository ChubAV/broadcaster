def _offenders_indicator_threshold(css: str) -> dict[str, str]:
    """У индикатора есть порог видимости, и он висит на состоянии «запрос идёт»."""
    busy_selector = f".{INDICATOR_CLASS}.{RUNTIME_REQUEST_CLASS}"
    resting_selector = f".{INDICATOR_CLASS}"

    busy: str | None = None
    resting: str | None = None
    for selector, body in _css_rules(css):
        if selector == busy_selector:
            busy = body
        elif selector == resting_selector:
            resting = body

    offenders: dict[str, str] = {}
    if busy is None:
        offenders[busy_selector] = (
            "СОСТАВНОГО правила состояния «запрос идёт» нет. Потомковый селектор "
            "здесь не работает НИКОГДА: рантайм вешает свой класс на сам узел "
            "индикатора, найденный по селектору, а не на предка"
        )
    elif _is_zero(_transition_delay(busy, "opacity")):
        offenders[busy_selector] = (
            "у появления индикатора нет задержки — он мигал бы на каждое "
            "нажатие, в том числе там, где ответ приходит мгновенно"
        )

    if resting is None:
        offenders[resting_selector] = "базового правила покоя нет"
    elif not _is_zero(_transition_delay(resting, "opacity")):
        offenders[resting_selector] = (
            "задержка появления записана в правиле ПОКОЯ — она задержит и "
            "обратный ход, и индикатор повиснет ещё на порог ПОСЛЕ ответа"
        )
    return offenders


