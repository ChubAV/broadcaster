    templates = _all_templates()

    # ⚠️ АНТИВАКУУМНОЕ УТВЕРЖДЕНИЕ, И ОНО ЧАСТЬ ПРАВИЛА, А НЕ ПРЕДОСТОРОЖНОСТЬ.
    # Множество берётся вызовом `_swap_declaring_templates(templates)`; потеряй
    # перечень параметрических целей своё поле `callers` — множество сведётся к
    # обёртке, в которой `x-data` нет вовсе, правило станет зелёным НА ПУСТОМ
