def _balanced_call_arguments(source: str, macro: str) -> list[str]:
    """Списки аргументов КАЖДОГО вызова ``macro`` в исходнике вызывающего.

    ⚠️ РАЗБОР ОГРАНИЧЕН СКОБКАМИ ВЫЗОВА, А НЕ ИЩЕТ ИМЯ ПАРАМЕТРА ПО ВСЕМУ ФАЙЛУ,
    И РАЗНИЦА НЕ СТИЛИСТИЧЕСКАЯ. Строка группы аккаунта несёт, кроме двух
    вызовов макросов, ещё и ОБЫЧНУЮ форму-триггер с собственным атрибутом
    адреса. Поиск имени параметра по файлу подобрал бы и её значение — значение
    АТРИБУТА, а не аргумента, — и правила проверяли бы смесь двух разных форм
    записи, о которой не сказано нигде.

    Границы держатся по вложенности скобок и по кавычкам обоих видов: адрес,
    собранный вызовом внутри вызова, оборвался бы на первой же внутренней
    запятой, а обрубок дал бы молчаливо пустое множество нарушителей.
    """
    body = _strip_comments(source)
    call = re.compile(rf"(?<![-\w]){re.escape(macro)}\s*\(")
    found: list[str] = []
    for match in call.finditer(body):
        depth = 0
        quote: str | None = None
        start = match.end()
        index = start
        while index < len(body):
            char = body[index]
            if quote is not None:
                if char == quote:
                    quote = None
            elif char in "\"'":
                quote = char
            elif char in ARGUMENT_OPENERS:
                depth += 1
            elif char in ARGUMENT_CLOSERS:
                if depth == 0:
                    found.append(body[start:index])
                    break
                depth -= 1
            index += 1
    return found


def _named_argument_expression(arguments: str, argument: str) -> str | None:
    """СЫРОЕ выражение, переданное именованным параметром ``argument``.

    Сырое — то есть выражение шаблонизатора целиком, со склейками и ветвлением,
    от знака равенства до запятой ВЕРХНЕГО УРОВНЯ либо до конца списка.

    ⚠️ ПОМОЩНИК `_caller_argument_values` ДЛЯ ЭТОГО НЕ ГОДИТСЯ, И ЭТО НЕ
    ДУБЛИРОВАНИЕ, А РАЗНЫЕ ПРЕДМЕТЫ. Тот вытаскивает значения, набранные ЦЕЛИКОМ
    в кавычках (имя цели блокировки, имя цели подмены), и на адресе даёт
    ОБРУБОК: адреса вызовов набраны КОНКАТЕНАЦИЕЙ, первый литерал в них —
    `'/accounts/'`, и правило, построенное на нём, сверяло бы с маршрутами
    обрубок, никогда ни с чем не совпадающий... либо, наоборот, всегда пустое
    множество нарушителей. То есть правило было бы зелено ПО ПОСТРОЕНИЮ — ровно
    тем же способом, которым в этой фазе уже один раз позеленел тест. Измерено
    исполнением: на строке группы аккаунта тот помощник возвращает `'/accounts/'`
    и ни одного полного адреса.
    """
    pattern = re.compile(rf"(?<![-\w]){re.escape(argument)}\s*=(?!=)")
    match = pattern.search(arguments)
    if match is None:
        return None
    depth = 0
    quote: str | None = None
    start = match.end()
    index = start
    while index < len(arguments):
        char = arguments[index]
        if quote is not None:
            if char == quote:
                quote = None
        elif char in "\"'":
            quote = char
        elif char in ARGUMENT_OPENERS:
            depth += 1
        elif char in ARGUMENT_CLOSERS:
            depth -= 1
        elif char == "," and depth == 0:
            return arguments[start:index].strip()
        index += 1
    return arguments[start:].strip()


def _caller_action_sites(templates: list[tuple[str, str]]) -> list[ActionSite]:
    """Адреса, переданные ВЫЗЫВАЮЩИМИ в места определения макросов.

    Зеркало ``_action_sites`` для той стороны, которую то исключение не видит.
    Вызывающих находит существующий ``_macro_callers``, ветви и склейки —
    существующий ``_literal_paths``.

    ⚠️ СЫРОЕ ВЫРАЖЕНИЕ ОБОРАЧИВАЕТСЯ В СКОБКИ ШАБЛОНИЗАТОРА ПЕРЕД РАЗБОРОМ, И
    ЭТО НЕ ХИТРОСТЬ, А ПРИВЕДЕНИЕ К ОДНОМУ ПРЕДМЕТУ. ``_literal_paths`` читает
    ЗНАЧЕНИЕ АТРИБУТА — чередование текста и выражений; аргумент же есть
    выражение целиком. Без обёртки разборщик принял бы его за голый текст и
    вернул бы сам аргумент строкой — то есть путь, не начинающийся с корня, и
    правила краснели бы на исправном дереве. Обёртка ставит аргумент ровно в то
    положение, для которого разборщик написан, и второго разборщика заводить не
    приходится.

    ⚠️ ВЫЗОВ БЕЗ ПАРАМЕТРА АДРЕСА ПРОПУСКАЕТСЯ, И ЭТО НЕ ДЫРА: адреса он не
    передаёт, проверять нечего. Файл при этом остаётся в перечне вызывающих —
    сканер считает ФАЙЛЫ, и его граница записана у него же.
    """
    sources = dict(templates)
    sites: list[ActionSite] = []
    for entry in MACRO_DEFINITION_SITES_CALLERS.values():
        for rel in _macro_callers(templates, entry.macro, ACTION_ARGUMENT):
            for arguments in _balanced_call_arguments(sources[rel], entry.macro):
                raw = _named_argument_expression(arguments, ACTION_ARGUMENT)
                if raw is None:
                    continue
                sites.append(
                    ActionSite(
                        f"{rel} → {entry.macro}", raw, _literal_paths("{{" + raw + "}}")
                    )
                )
    return sites


def _extracted_caller_paths(templates: list[tuple[str, str]]) -> set[str]:
    return {
        path
        for site in _caller_action_sites(templates)
        if site.paths
        for path in site.paths
    }


def _offenders_caller_action_path(templates: list[tuple[str, str]]) -> dict[str, str]:
    """Нарушители СО СТОРОНЫ ВЫЗЫВАЮЩЕГО: адрес не есть объявленный маршрут.

    Неизвлекаемый адрес считается нарушением здесь же, а не относится молча к
    остатку: адрес, которого гейт прочитать не может, был бы способом обойти оба
    правила ниже разом — ровно та граница, которую правило
    ``test_no_action_is_assembled_from_an_unknown_value`` проводит на стороне
    места отправки.
    """
    declared = {route.path for route in PAGE_ROUTES if route.method == "POST"}
    offenders: dict[str, str] = {}
    for site in _caller_action_sites(templates):
        if site.paths is None:
            offenders[site.template] = f"{site.raw!r}: путь не извлекается"
            continue
        for path in site.paths:
            if path not in declared:
                offenders[f"{site.template}:{path}"] = "объявления маршрута нет"
    return offenders


def _offenders_caller_action_hits_a_fragment_route(
    templates: list[tuple[str, str]],
) -> set[str]:
    fragments = {route.path for route in FRAGMENT_ROUTES}
    return _extracted_caller_paths(templates) & fragments


