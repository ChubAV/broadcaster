# Элементы, у которых закрывающего тега не бывает: они не открывают уровня
# вложенности, и счётчик глубины ниже обязан их не считать. Без этого перечня
# скрытое поле идентификатора объявления, объявленное внеполосным блоком
# (`<input … hx-swap-oob="true">`), навсегда оставило бы всё, что стоит после
# него, «вложенным» — правило краснело бы на работающем ответе.
VOID_ELEMENTS = frozenset(
    {
        "area", "base", "br", "col", "embed", "hr", "img", "input",
        "link", "meta", "param", "source", "track", "wbr",
    }
)

ANY_TAG = re.compile(r"<[^<>]+>")
CLOSING_TAG = re.compile(r"<\s*/")


def _offenders_oob_not_top_level(templates: list[tuple[str, str]]) -> dict[str, str]:
    """Внеполосный узел обязан быть узлом ВЕРХНЕГО УРОВНЯ своего файла.

    Обход идёт по тегам исходника с вырезанными комментариями и держит глубину
    вложенности; у каждого тега, несущего признак внеполосной подмены, глубина
    обязана быть нулевой. Файлы берутся ТЕМ ЖЕ обходом ``_oob_sites``, а не
    выписываются руками: перечень каталогов ответов устарел бы на первом же
    новом шаблоне и молча объявил бы его неопасным.

    ⚠️ ВЕТВИ ШАБЛОНИЗАТОРА ГЛУБИНЫ НЕ МЕНЯЮТ, И ЭТО ВЕРНО ПО СУЩЕСТВУ.
    ``{% if %}`` вокруг двух альтернативных узлов (внеполосная форма
    уведомления) не делает ни один из них вложенным: в документ приезжает ровно
    одна ветка, и она — верхнеуровневая.

    ⚠️ ГРАНИЦА, КОТОРУЮ ПРАВИЛО НЕ ПЕРЕСЕКАЕТ, НАЗЫВАЕТСЯ ЧЕСТНО. Обход ходит
    по ФАЙЛАМ и не разворачивает ``{% include %}``, поэтому каждый файл ответа
    проверяется отдельно. Это не дыра: включение, которое само свой узел не
    оборачивает, остаётся верхнеуровневым и после подстановки в объемлющий
    шаблон, а объемлющий шаблон проверяется этим же правилом. Дырой было бы
    обратное — обёртка, добавленная объемлющим шаблоном ВОКРУГ места включения;
    её ловит проверка самого объемлющего файла, если он несёт свой признак, и
    не ловит, если не несёт. Случай в дереве сегодня отсутствует и требует
    решения человека, если появится.
    """
    offenders: dict[str, str] = {}
    for rel, source in templates:
        body = _strip_comments(source)
        if not HX_SWAP_OOB_ATTR.search(body):
            continue
        depth = 0
        for tag in ANY_TAG.finditer(body):
            text = tag.group(0)
            if HX_SWAP_OOB_ATTR.search(text) and depth != 0:
                # РАННИЙ ВЫХОД: первое нарушение в файле называет файл, и
                # перечислять остальные узлы того же файла незачем — они все
                # вложены в тот же чужой тег.
                offenders[rel] = (
                    f"внеполосный узел лежит на глубине {depth}: {text[:120]}"
                )
                break
            if CLOSING_TAG.match(text):
                depth -= 1
            elif not text.rstrip().endswith("/>") and _tag_name(text) not in VOID_ELEMENTS:
                depth += 1
    return offenders


# --- СВОЙСТВА КАЧЕСТВА: ИНДИКАТОР И ЦЕЛЬ БЛОКИРОВКИ -------------------------
#
# Два правила ниже читают ФАЙЛ СТИЛЕЙ, а не дерево шаблонов, и потому им нужна
# собственная пара помощников: обход шаблонов подменить копией умеет, а стили —
# нет, и без этого оба правила были бы зелены по построению.

# Имя класса индикатора «запрос идёт». Объявлено КОНСТАНТОЙ, потому что его
# знают трое: макрос-обёртка (печатает селектор), файл стилей (объявляет два
# правила) и эти два правила гейта.
#
# ⚠️ ИМЯ НЕ СОВПАДАЕТ С ИМЕНЕМ РАНТАЙМА, И ЭТО ВЫНУЖДЕННО, А НЕ КРАСИВО.
# Рантайм htmx дописывает СОБСТВЕННЫЙ стиль для своего имени класса в конец
# документа — то есть ПОСЛЕ файла стилей проекта, — и при равной специфичности
# выигрывает он. Порог 300 мс пропал бы молча: индикатор мигал бы на каждое
# нажатие, и ни один автоматический признак отказа не сработал бы. Заглушить
# рантайм седьмым ключом блока конфигурации нельзя — состав ключей утверждён
# ТОЧНЫМ РАВЕНСТВОМ МНОЖЕСТВ в tests/test_pages/test_shell.py (Фаза 7), то есть
# лишний ключ покрасил бы гейт шелла.
INDICATOR_CLASS = "form-busy"

# Имя, которым класс НАЗЫВАТЬСЯ НЕ ДОЛЖЕН.
RUNTIME_INDICATOR_CLASS = "htmx-indicator"

# Класс, который рантайм вешает на САМ узел индикатора, найденный по селектору
# (не на предка) — отсюда требование СОСТАВНОГО селектора ниже.
RUNTIME_REQUEST_CLASS = "htmx-request"

CSS_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
CSS_RULE = re.compile(r"([^{}]+)\{([^{}]*)\}", re.DOTALL)
CSS_TIME = re.compile(r"^-?[\d.]+m?s$")


def _app_css(path: Path | None = None) -> str:
    """Файл стилей БЕЗ комментариев, из указанного пути или из настоящего.

    ⚠️ ПУТЬ ПРИНИМАЕТСЯ ПАРАМЕТРОМ ПО ТОЙ ЖЕ ПРИЧИНЕ, ПО КОТОРОЙ ЕГО ПРИНИМАЕТ
    ``_all_templates``: без параметра группа контроля для правил индикатора
    НЕВЫРАЗИМА, и зубы этих правил пришлось бы ЗАЯВЛЯТЬ вместо того, чтобы их
    показывать. Зашитая константа пути сделала бы оба правила зелёными по
    построению — ровно то, что раздел ГРУППЫ КОНТРОЛЯ запрещает.

    ⚠️ КОММЕНТАРИИ ВЫРЕЗАЮТСЯ, И ЭТО НЕ ГИГИЕНА, А УСЛОВИЕ НЕПРОТИВОРЕЧИВОСТИ.
    Комментарий раздела ОБЯЗАН назвать имя класса рантайма словами — иначе
    следующий читатель переименует класс обратно, не зная, почему он назван
    иначе. Правило, ищущее подстроку в сыром файле, покраснело бы ровно на
    ИСПОЛНЕННОМ требовании, то есть было бы самоопровергающимся. Поэтому оба
    правила говорят о ПРАВИЛАХ CSS — селекторе, за которым следует тело, — а не
    о подстроках.
    """
    source = (APP_CSS if path is None else path).read_text(encoding="utf-8")
    return CSS_COMMENT.sub("", source)


def _css_with(tmp_path: Path, old: str, new: str) -> Path:
    """Копия файла стилей с подстановкой, во временном каталоге.

    Тот же ДВОЙНОЙ ПРЕДОХРАНИТЕЛЬ, что у ``_tree_with``, и по той же причине:
    образец обязан встретиться РОВНО ОДИН раз, а результат обязан отличаться от
    исходника. Контроль, чей образец не нашёлся, «проходит» на нетронутых стилях
    и утверждает ровно ничего; образец, встретившийся дважды, меняет не то
    место, что имел в виду автор, и контроль краснеет по чужой причине.
    """
    source = APP_CSS.read_text(encoding="utf-8")
    occurrences = source.count(old)
    assert occurrences == 1, (
        f"образец подстановки встречается в файле стилей {occurrences} раз(а), "
        f"а не один: {old!r} — контроль меняет не то место, что имел в виду "
        f"автор, либо не меняет ничего"
    )
    changed = source.replace(old, new)
    assert changed != source, (
        f"подстановка в файл стилей ничего не изменила: {old!r} → {new!r}"
    )
    path = tmp_path / "app.css"
    path.write_text(changed, encoding="utf-8")
    return path


def _css_rules(css: str) -> list[tuple[str, str]]:
    """Правила стилей парами «селектор — тело».

    Разбор нарочно грубый и текстовый: вложенные блоки (`@media`) целиком не
    разбираются, но правила ВНУТРИ них находятся — выражение просто начинает
    совпадение после открывающей скобки блока. Правилам индикатора этого
    достаточно, а полноценный разборщик CSS завёл бы в гейт зависимость, из-за
    которой суита перестала бы исполняться на одном дереве исходников.
    """
    return [
        (match.group(1).strip(), match.group(2).strip())
        for match in CSS_RULE.finditer(css)
    ]


def _transition_delay(body: str, prop: str) -> str | None:
    """Задержка перехода для свойства ``prop`` в теле правила, если она есть.

    Разбирается сокращённая запись `transition: <свойство> <длительность>
    <функция> <задержка>`: времён в части ДВА, и задержка — второе. Части
    разделяются запятой, потому что переходов в одной записи может быть
    несколько, а спрашивают всегда про конкретное свойство.
    """
    for declaration in body.split(";"):
        name, _, value = declaration.partition(":")
        if name.strip() != "transition":
            continue
        for part in value.split(","):
            tokens = part.split()
            if not tokens or tokens[0] != prop:
                continue
            times = [token for token in tokens if CSS_TIME.match(token)]
            return times[1] if len(times) > 1 else None
    return None


def _is_zero(time: str | None) -> bool:
    if time is None:
        return True
    return float(time.rstrip("ms").rstrip("s") or 0) == 0


def _offenders_runtime_indicator_class(css: str) -> dict[str, str]:
    """Класс индикатора не назван именем рантайма и правил под ним не объявлено."""
