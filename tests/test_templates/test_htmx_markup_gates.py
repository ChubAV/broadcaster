def test_the_number_of_hidden_callers_is_the_declared_one() -> None:
    """Вызывающих, скрытых за исключениями, ровно столько, сколько объявлено.

    Утверждение о ДВУХ перечнях сразу, и это не смешение предметов: оба
    объявляют «за этим согласием гейта не смотреть спрятано столько-то форм», и
    оба до плана 09-07 числа вызывающих не несли вовсе. Разъединять их в два
    правила значило бы завести два места, где одно и то же свойство проверяется
    по-разному.

    Проверяется ТРИ вещи, и убрать можно только все три сразу:

    (i)   у каждой записи написано, почему она в перечне (первое утверждение
          SP-1) — перечень без обоснований через фазу превращается в «наверное,
          так надо»;
    (ii)  ОБЪЯВЛЕННЫЕ вызывающие совпадают с ИЗМЕРЕННЫМИ сканером — запись,
          отставшая от дерева, объявляла бы спрятанным не то, что спрятано;
    (iii) общее число совпадает с объявленной константой — беззвучный рост
          означает, что за исключением спряталась ещё одна форма, а решения о
          ней никто не принимал.
    """
    templates = _all_templates()

    unexplained = {
        template
        for template, entry in MACRO_DEFINITION_SITES_CALLERS.items()
        if not entry.reason.strip()
    }
    assert not unexplained, (
        f"перечень вызывающих, скрытых за местом определения макроса, не несёт "
        f"обоснования: {sorted(unexplained)} — читатель через фазу не отличит "
        f"принятое решение от забытой работы"
    )

    assert set(MACRO_DEFINITION_SITES_CALLERS) == set(MACRO_DEFINITION_SITES), (
        f"перечень вызывающих разошёлся с перечнем мест определения: "
        f"{sorted(MACRO_DEFINITION_SITES_CALLERS)} против "
        f"{sorted(MACRO_DEFINITION_SITES)} — место, выведенное из-под правил "
        f"адреса, обязано нести счёт спрятанных за ним форм, иначе исключение "
        f"снова становится глухим"
    )

    mismatched: dict[str, str] = {}
    for template, entry in MACRO_DEFINITION_SITES_CALLERS.items():
        measured = _macro_callers(templates, entry.macro, ACTION_ARGUMENT)
        if measured != entry.callers:
            mismatched[template] = f"объявлено {entry.callers}, измерено {measured}"
    assert not mismatched, (
        f"объявленные вызывающие разошлись с измеренными: {mismatched} — за "
        f"исключением появилась либо исчезла форма, и решения об этом никто не "
        f"принимал"
    )

    hidden = sum(
        len(entry.callers) for entry in MACRO_DEFINITION_SITES_CALLERS.values()
    )
    assert hidden == MACRO_DEFINITION_SITES_CALLERS_DECLARED, (
        f"за перечнем мест определения макросов спрятано вызывающих {hidden}, "
        f"объявлено {MACRO_DEFINITION_SITES_CALLERS_DECLARED} — число, выросшее "
        f"молча, есть молчаливое расширение исключения на новые формы"
    )

    parametric = sum(
        len(entry.callers) for entry in PARAMETRIC_SWAP_TARGETS.values()
    )
    assert parametric == PARAMETRIC_SWAP_TARGETS_CALLERS_DECLARED, (
        f"за перечнем параметрических целей подмены спрятано вызывающих "
        f"{parametric}, объявлено {PARAMETRIC_SWAP_TARGETS_CALLERS_DECLARED} — "
        f"с каждым таким вызывающим снимаются G-9, G-11 и G-12 разом, и снимать "
        f"их с растущего множества молча нельзя"
    )


