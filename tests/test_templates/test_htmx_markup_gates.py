def _macro_callers(
    templates: list[tuple[str, str]], macro: str, argument: str
) -> tuple[str, ...]:
    """Шаблоны, зовущие ``macro`` и упоминающие параметр ``argument``.

    ЕДИНСТВЕННЫЙ НА ФАЗУ СКАНЕР ВЫЗЫВАЮЩИХ. Два разных резолвера были бы хуже,
    чем отсутствие правила: они разошлись бы молча, и каждое правило говорило бы
    о своём дереве. Потребители — перечень исключений ниже и, через него,
    правила планов 09-02 и 09-03.

    ⚠️ ГРАНИЦА НАЗЫВАЕТСЯ ЧЕСТНО, А НЕ ОСТАВЛЯЕТСЯ НА ДОГАДКУ. Сканер НЕ
    разбирает границы вызова: совпадение «файл зовёт макрос И упоминает имя
    параметра» принято достаточным для фазы, где вызывающий ровно один. Файл, в
    котором два вызова одного макроса и лишь один передаёт параметр, сканер
    признал бы вызывающим целиком. Фаза 10, доводящая число вызовов до
    шестнадцати, обязана эту границу пересмотреть — и это записано ЗДЕСЬ.

    Файл ОПРЕДЕЛЕНИЯ макроса из результата исключается: определение вызовом не
    является, и включив его, перечень объявил бы место исключения его же
    собственным вызывающим.
    """
    call = re.compile(rf"(?<![-\w]){re.escape(macro)}\s*\(")
    declaration = re.compile(rf"\{{%-?\s*macro\s+{re.escape(macro)}\s*\(")

    found: list[str] = []
    for rel, source in templates:
        body = _strip_comments(source)
        if declaration.search(body):
            continue
        if f"{argument}=" not in body:
            continue
        if call.search(body):
            found.append(rel)
    return tuple(sorted(found))


