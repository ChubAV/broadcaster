# Признак ВЫРАЖЕНИЯ клиентского состояния — то есть узла, который состояние
# ХРАНИТ, а не просто открывает область видимости Alpine. Голый `x-data` без
# знака равенства состояния не несёт: он нужен, чтобы на узле работал `x-init`
# или `x-on`, и подмена такого узла не теряет ничего.
CLIENT_STATE_EXPRESSION = re.compile(r"(?<![-\w])x-data(?![-\w])\s*=")
CLIENT_STATE_VALUE = _value_pattern("x-data")


def _offenders_client_state_expression(
    templates: list[tuple[str, str]],
) -> dict[str, str]:
    """D-08a: в шаблоне, объявляющем цель подмены, каждый ``x-data`` голый.

    ⚠️ МНОЖЕСТВО ШАБЛОНОВ БЕРЁТСЯ ВЫЗОВОМ ``_swap_declaring_templates`` И
    ЗДЕСЬ НЕ ПЕРЕСОБИРАЕТСЯ. Правило не читает ``PARAMETRIC_SWAP_TARGETS``
    напрямую, не обходит ``_target_sites`` заново и не заводит собственного
    сканера вызывающих: и ключ перечня, и поле ``callers``, и их согласие с
    ``_macro_callers`` — предмет плана 09-02, и здесь только потребляются. Два
    описания одного множества разошлись бы МОЛЧА, и каждое правило говорило бы
    о своём дереве.
    """
    declaring = _swap_declaring_templates(templates)
    offenders: dict[str, str] = {}
    for site in _client_state_sites(templates):
        if site.template not in declaring:
            continue
        if not CLIENT_STATE_EXPRESSION.search(site.tag):
            continue
        match = CLIENT_STATE_VALUE.search(site.tag)
        value = match.group(1) if match else "<без кавычек>"
        offenders[f"{site.template}:<{_tag_name(site.tag)}>:{value}"] = (
            "узел ХРАНИТ клиентское состояние и лежит в шаблоне, объявляющем "
            "цель подмены"
        )
    return offenders


