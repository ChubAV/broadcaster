# ⚠️ ПЕРВАЯ ЦЕЛЬ ПОДМЕНЫ ВЕХИ ДЛЯ ГЕЙТА НЕВИДИМА, И ЭТО ОБЪЯВЛЯЕТСЯ, А НЕ
# ОСТАВЛЯЕТСЯ НА ДОГАДКУ. `_swap_target_ids` кладёт в множество только остаток
# значения, начинающегося с решётки, а макрос-обёртка печатает
# `hx-target="{{ target }}"`: фактическую цель передаёт ВЫЗЫВАЮЩИЙ в момент
# рендера. Значит про эту цель молчат ВСЕ ТРИ правила — существования (G-9),
# двух ролей (G-11) и границы клиентского состояния (G-12).
#
# ⚠️ ПРОПУСК ШАБЛОНИЗИРОВАННЫХ ЗНАЧЕНИЙ ВНУТРИ `_swap_target_ids` ЗАПРЕЩЁН И НЕ
# ЗАВЕДЁН. Условие, отбрасывающее значение с выражением шаблонизатора, сняло бы
# правила со ВСЕХ построчных целей вехи разом — то есть с того самого класса,
# которым Фазы 10-15 наполнят проект. Невидимость объявляется ПЕРЕЧНЕМ, каждая
# запись которого обоснована и посчитана.
#
# ⚠️ САМО УСЛОВИЕ ЗДЕСЬ НЕ НАБРАНО, И ЭТО НЕ СТИЛЬ. Его отсутствие проверяется
# грепом по этому файлу, и запрет, набравший условие дословно, удовлетворил бы
# греп сам — проверка краснела бы на комментарии о запрете вместо его нарушения.
#
# ⚠️ ФОРМА КЛЮЧА ЗАДАНА ПЛАНОМ 09-01 (§«Форма ключа параметрической записи») И
# ЗДЕСЬ ТОЛЬКО ПРИМЕНЯЕТСЯ. Ключ — ФАЙЛ, который вернул разборщик, а не место
# вызова: ключа вида `файл::имя` разборщик не производит, и запись с ним не
# совпала бы ни с чем никогда. До вызывающего правило доходит ТОЛЬКО через
# объявленное поле `callers`, утверждаемое сканером `_macro_callers`.
#
# ⚠️ ИЗМЕРЕНИЕ G-11, ВЫПОЛНЕННОЕ НА ИТОГОВОМ ДЕРЕВЕ (план 09-02, задача 2,
# шаг 1). Множество целей подмены оказалось ПУСТЫМ, множество внеполосных целей
# — девять значений, ПЕРЕСЕЧЕНИЕ ПУСТО. Разведка предсказывала столкновение на
# строке группы при допущении, что цель записана в шаблоне литерально; под
# макросом-обёрткой цель стала параметрической и в множество целей подмены не
# попадает вовсе. Поэтому второй перечень — «идентификатор в двух ролях по
# замыслу» — НЕ ЗАВЕДЁН: его несущее утверждение («каждая запись ФАКТИЧЕСКИ
# лежит в пересечении») было бы ложью на первой же записи. Пустой результат
# записан здесь и в сводке плана с основанием, а не умолчан.


class ParametricTarget(NamedTuple):
    """Запись перечня целей подмены, печатаемых параметром макроса.

    ``macro`` — имя макроса, печатающего цель; ``callers`` — шаблоны, зовущие
    его с параметром цели. Голый ``dict[str, str]`` здесь не годится: множество
    вызывающих есть ПРОВЕРЯЕМЫЙ ФАКТ и предмет правил соседних планов, а не
    проза, и обязано лежать полем, которое читает тест.
    """

    macro: str
    callers: tuple[str, ...]
    reason: str


# Имя параметра цели у макроса-обёртки. Объявлено константой по той же причине,
