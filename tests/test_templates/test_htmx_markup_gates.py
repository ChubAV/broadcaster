# --- ГРУППА КОНТРОЛЯ ---------------------------------------------------------
#
# Зубы гейта ДОКАЗЫВАЮТСЯ, а не заявляются. Каждый случай ниже подаёт обходу
# изменённую копию дерева шаблонов во временном каталоге и требует, чтобы
# правило на ней покраснело. Настоящее дерево при этом не трогается ни одним
# байтом: подстановки применяются к прочитанным исходникам, а пишется копия.
#
# ⚠️ ПОДСТАНОВКА ОБЯЗАНА ДОКАЗАТЬ, ЧТО ОНА ЧТО-ТО ИЗМЕНИЛА, И ЧТО ИЗМЕНИЛА
# ИМЕННО ТО. Контроль, чей образец в шаблоне не нашёлся, «проходит» на
# нетронутом дереве и утверждает ровно ничего — то есть притворяется
# доказательством зубов, не будучи им. Хуже того, образец, встретившийся
# ДВАЖДЫ, меняет не то место, что имел в виду автор, и контроль краснеет по
# чужой причине. Поэтому ``_tree_with`` требует РОВНО ОДНОГО вхождения образца
# и отдельно проверяет, что результат отличается от исходника.
#
# --- КРУГ КОНТРОЛЕЙ ФАЗЫ 9: ПРАВИЛО → ЕГО КОНТРОЛЬ --------------------------
#
# Перечень выписан затем, чтобы «правило без контроля» было ВИДНО списком, а не
# обнаруживалось пересчётом. Правило, у которого контроля нет, доказывает
# ровно ничего: красным оно не бывало никогда, и отличить его зубы от его
# слепоты нечем.
#
#   test_every_htmx_post_declares_a_disabled_elt (09-01)
#     → test_control_negative_a_post_without_a_disabled_elt_reddens_the_gate
#   test_the_indicator_class_is_not_the_runtime_one (09-01)
#     → test_control_negative_the_runtime_indicator_class_reddens_the_gate
#   test_the_indicator_class_carries_a_visibility_threshold (09-01)
#     → test_control_negative_a_threshold_on_the_resting_rule_reddens_the_gate
#   test_every_swap_target_is_either_literal_or_declared_parametric (09-02)
#     → test_control_negative_an_undeclared_parametric_target_reddens_the_gate
#   test_cancel_is_never_disabled (09-02)
#     → test_control_negative_a_disabled_cancel_reddens_the_gate
#   test_every_htmx_post_is_born_of_a_component_macro (09-03)
#     → test_control_negative_a_post_outside_a_macro_reddens_the_gate
#   test_no_client_state_expression_lives_inside_a_swap_declaring_template (09-03)
#     → test_control_negative_an_expression_x_data_in_a_swap_template_reddens_the_gate
#
# ⚠️ ДВА КОНТРОЛЯ ИЗ ЭТОГО СПИСКА ЧИТАЮТ НЕ ШАБЛОНЫ, А СТИЛИ, И ПОТОМУ ПОДАЮТ
# ИЗМЕНЁННУЮ КОПИЮ `app.css` ЧЕРЕЗ `_css_with`, А НЕ ДЕРЕВО ЧЕРЕЗ `_tree_with`
# (оба — план 09-01). Механизм подмены у них другой не по небрежности: правила
# индикатора утверждают о файле стилей, и `_tree_with`, подменяющий только
# шаблоны, не покраснил бы их ни на чём — то есть оба правила были бы зелены
# ПО ПОСТРОЕНИЮ, а список контролей выглядел бы полным.
#
# ⚠️ ТРИ ПЕРЕЧНЯ ФАЗЫ КОНТРОЛЯ ЧЕРЕЗ `_tree_with` НЕ ИМЕЮТ И ИМЕТЬ НЕ ДОЛЖНЫ:
# MACRO_DEFINITION_SITES, DISABLED_ELT_EXCEPTIONS и MACRO_BORN_EXCEPTIONS —
# перечни идиомы SP-1, и роль контроля у них исполняет ТРЕТЬЕ, несущее
# утверждение («запись правда в исключаемом положении»), которое краснеет на
# устаревшей записи. Это не пропуск в круге, а другая идиома, и записано это
# здесь затем, чтобы следующая уборка не сочла их непокрытыми.


class Substitution(NamedTuple):
    template: str
    old: str
    new: str


def _tree_with(tmp_path: Path, *substitutions: Substitution) -> Path:
    """Копия дерева шаблонов с подстановками, во временном каталоге."""
    sources = dict(_all_templates())
    for substitution in substitutions:
        assert substitution.template in sources, (
            f"шаблон {substitution.template} в дереве не найден: контроль "
            f"подаёт подстановку в несуществующий файл и потому ничего не "
            f"доказывает"
        )
        source = sources[substitution.template]
        occurrences = source.count(substitution.old)
        assert occurrences == 1, (
            f"образец подстановки встречается в {substitution.template} "
            f"{occurrences} раз(а), а не один: {substitution.old!r} — контроль "
            f"меняет не то место, что имел в виду автор, либо не меняет ничего"
        )
        changed = source.replace(substitution.old, substitution.new)
        assert changed != source, (
            f"подстановка в {substitution.template} ничего не изменила: "
            f"{substitution.old!r} → {substitution.new!r}"
        )
        sources[substitution.template] = changed

    root = tmp_path / "templates"
    for rel, source in sources.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")
    return root


