    # ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НЕ ОТСТАВАЛ ОТ ОТРИЦАТЕЛЬНЫХ. Перечень, чьё число
    # никто здесь не читает, живёт вне круга: его можно молча подвинуть, и ни
    # один контроль об этом не скажет. Пропущенное обновление этого места
    # краснеет само.
    assert len(MACRO_DEFINITION_SITES) == MACRO_DEFINITION_SITES_DECLARED
    assert len(DISABLED_ELT_EXCEPTIONS) == DISABLED_ELT_EXCEPTIONS_DECLARED
    assert len(MACRO_BORN_EXCEPTIONS) == MACRO_BORN_EXCEPTIONS_DECLARED
    assert len(PARAMETRIC_SWAP_TARGETS) == PARAMETRIC_SWAP_TARGETS_DECLARED

    # ⚠️ ДВА ЧИСЛА ВЫЗЫВАЮЩИХ И СБОРЩИК ИХ АДРЕСОВ ЧИТАЮТСЯ ЗДЕСЬ ПОИМЁННО
    # (план 09-07), И ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО И ЧЕТЫРЕ ЧИСЛА ВЫШЕ. Перечень, чьё
    # число никто здесь не читает, живёт вне круга: его можно молча подвинуть, и
