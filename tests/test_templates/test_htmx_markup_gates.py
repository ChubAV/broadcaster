# ⚠️ ЧИСЛО ВЫПИСАНО ОТДЕЛЬНОЙ КОНСТАНТОЙ НАМЕРЕННО. Каждая запись объявляет цель
# невидимой сразу для ТРЁХ правил, поэтому беззвучно выросшее число есть
# беззвучное ослабление гейта втрое; беззвучно упавшее означает, что цель стала
# литеральной, и это обязано быть записано летописью, а не обнаружено через фазу.
#
# ЛЕТОПИСЬ: 0 → 1, Фаза 9, план 09-02 (макрос-обёртка формы). Фаза 10,
# переносящая проверку цели на вызывающих, обязана его пересмотреть.
PARAMETRIC_SWAP_TARGETS_DECLARED = 1

TARGET_RANKS = ("literal", "relative", "parametric", "unknown")


def _classified_target_sites(
    templates: list[tuple[str, str]],
) -> dict[str, list[Site]]:
    """МЕСТА объявления цели, разложенные по разрядам ЗНАЧЕНИЯ.

    ⚠️ РАЗБИРАЮТСЯ МЕСТА, А НЕ ИДЕНТИФИКАТОРЫ, И В ЭТОМ ВЕСЬ СМЫСЛ РАЗБОРА. Две
    цели на один и тот же литеральный `id` — это ДВА места и ОДИН
    идентификатор; арифметика, складывающая места с идентификаторами, на таком
    дереве краснела бы на работающем коде.

    Разряды взаимоисключающие и проверяются В ЭТОМ порядке: значение,
    начинающееся с решётки, — литеральная цель; значение, начинающееся с
    объявленного относительного префикса, — относительная (её существование по
    исходнику не проверяется и проверяться не может); значение, содержащее
    выражение шаблонизатора, — параметрическая. Всё прочее попадает в разряд
    ``unknown`` и обязано быть ЗАМЕЧЕНО: незаявленная форма значения — это цель,
    о которой гейт не знает ничего, и относить её к остатку нельзя.
    """
    ranks: dict[str, list[Site]] = {rank: [] for rank in TARGET_RANKS}
    for site in _target_sites(templates):
        value = (_attr_value(site.tag, HX_TARGET_VALUE) or "").strip()
        if value.startswith("#"):
            ranks["literal"].append(site)
        elif any(value.startswith(prefix) for prefix in RELATIVE_TARGET_PREFIXES):
            ranks["relative"].append(site)
        elif "{{" in value or "{%" in value:
            ranks["parametric"].append(site)
        else:
            ranks["unknown"].append(site)
    return ranks


def _offenders_undeclared_parametric_target(
    templates: list[tuple[str, str]],
) -> dict[str, str]:
    """Каждое МЕСТО цели — литеральное, относительное либо ОБЪЯВЛЕННОЕ.

    Множество файлов параметрического разряда обязано быть ВЛОЖЕНО в ключи
    перечня. Незаявленная форма значения тоже считается нарушением здесь, а не
    молча относится к остатку.
    """
    ranks = _classified_target_sites(templates)
    offenders: dict[str, str] = {
        f"{site.template}:{(_attr_value(site.tag, HX_TARGET_VALUE) or '')!r}": (
            "незаявленная форма значения цели"
        )
        for site in ranks["unknown"]
    }
    for site in ranks["parametric"]:
        if site.template not in PARAMETRIC_SWAP_TARGETS:
            offenders[site.template] = (
                "цель печатается параметром макроса, в множество литеральных "
                "целей не попадает, и записи о ней в перечне нет"
            )
    return offenders


def _swap_declaring_templates(templates: list[tuple[str, str]]) -> set[str]:
    """Шаблоны, ОБЪЯВЛЯЮЩИЕ цель подмены, — вместе с вызывающими.

    ⚠️ ВТОРОЕ СЛАГАЕМОЕ НЕСУЩЕЕ, И БЕЗ НЕГО МНОЖЕСТВО ВЫРОЖДАЕТСЯ. Мест
    объявления цели в дереве сегодня ровно одно — определение макроса-обёртки, а
    в нём нет ни одного узла с признаком клиентского состояния. Правило,
    собирающее множество без ``callers``, зеленело бы ПО ПОСТРОЕНИЮ, и его
    контроль не покраснел бы ни на чём: файл, реально объявляющий цель
    `#group-row-{{ group.id }}` и реально несущий клиентское состояние, —
    ВЫЗЫВАЮЩИЙ, и дойти до него можно только объявленным полем.

    ⚠️ ЕДИНСТВЕННОЕ ОПИСАНИЕ ЭТОГО МНОЖЕСТВА НА ФАЗУ. Потребитель — правило
    границы клиентского состояния плана 09-03; оно ВЫЗЫВАЕТ эту функцию, а не
    пересобирает множество по собственному описанию: два описания одного
    множества разошлись бы молча, и каждое правило говорило бы о своём дереве.
    """
    declared = {site.template for site in _target_sites(templates)}
    for entry in PARAMETRIC_SWAP_TARGETS.values():
        declared.update(entry.callers)
    return declared


def _client_state_ids(templates: list[tuple[str, str]]) -> set[str]:
    """Литеральные идентификаторы узлов с признаком клиентского состояния.

    Идентификатор, СОБРАННЫЙ шаблонизатором, из множества исключён по той же
    причине, что и в счёте объявлений: сверять с ним цель подмены нечем, его
    значение известно только в момент рендера. Сегодня таких узлов в проекте
    большинство (компонент отбора и компонент модального окна принимают
    идентификатор параметром макроса), поэтому множество литеральных целей
    клиентского состояния пусто — и именно поэтому число узлов объявлено
    отдельной константой: без него граница была бы вакуумной дважды.
    """
    found: set[str] = set()
    for site in _client_state_sites(templates):
        own = _attr_value(site.tag, ID_VALUE)
        if own and "{{" not in own and "{%" not in own:
            found.add(own)
    return found


