# ничего не ломающей.
#
# ЗАЧЕМ ВООБЩЕ ДЕЛИТЬ. Опрос, который никогда не останавливается, множится на
# число открытых вкладок и на время, которое вкладка провисела открытой. Это не
# гипотеза о будущем: экраны подключения несут по два опроса каждый с
# периодом в три секунды. Разделение объявляет, какие из них таковы ПО
# ЗАМЫСЛУ — и тем самым делает видимым опрос, который таким стал случайно.
# =============================================================================

# Признак опроса, искомый ШИРЕ, чем `POLL_TRIGGER` выше. Тот привязан к началу
# значения (`hx-trigger="every …"`) и к механизму 2 инвентаря `hx-get`; здесь
# опрашивающим считается ЛЮБОЙ тег, чьё срабатывание содержит расписание, — в
# том числе будущий, объявленный не через `hx-get`. Отрицательный просмотр назад
# отсекает атрибуты, у которых искомое имя лишь хвост более длинного.
POLL_TRIGGER_ATTR = re.compile(r'(?<![-\w])hx-trigger\s*=\s*"[^"]*\bevery\b')

# Закрытие условия шаблонизатора. Пара к `JINJA_CONDITION_OPEN` выше: останов
# опроса доказывается ПОЛОЖЕНИЕМ признака МЕЖДУ открытием и закрытием, а одно
# открытие без закрытия ничего не ограничивает.
JINJA_CONDITION_CLOSE = re.compile(r"\{%-?\s*endif\s*-?%\}")

# Любой тег разметки. Границы те же, что у `HX_GET_TAG` (`[^<>]`), но без
# привязки к конкретному атрибуту: предмет этой группы — опрашивающий фрагмент,
# а не место `hx-get`.
ANY_TAG = re.compile(r"<[^<>]*>", re.DOTALL)

# Ручная сборка запроса в шаблоне. Точка перед именем отсечена просмотром назад:
# вызов-метод чужого объекта ручной сборкой запроса не является.
MANUAL_FETCH_CALL = re.compile(r"(?<![-\w.])fetch\s*\(")


def _template_sources() -> dict[str, str]:
    """Те же шаблоны, что и у `_all_templates`, но СЛОВАРЁМ.

    Форма заведена ради группы контроля: только приняв исходники словарём,
    разборщик может получить ИЗМЕНЁННУЮ копию дерева и доказать, что гейт
    краснеет, не тронув ни одного файла проекта (образец —
    `tests/test_pages/test_money_perimeter_gate.py`). Порядок ключей наследуется
    у `_all_templates`, то есть идёт по ОТСОРТИРОВАННОМУ списку путей: сообщение
    об отказе обязано быть воспроизводимо от прогона к прогону.
    """
    return dict(_all_templates())


def _poll_fragments(templates_: dict[str, str]) -> dict[str, str]:
    """Опрашивающие фрагменты: ключ → текст тега.

    ⚠️ КЛЮЧ — ПУТЬ ФАЙЛА ПЛЮС ПОРЯДКОВЫЙ НОМЕР ВХОЖДЕНИЯ, А НЕ ТЕКСТ ТЕГА, И
    ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ГЕЙТ МОГ БЫ ПОТЕРЯТЬ ФРАГМЕНТ БЕСШУМНО. Оба
    экрана подключения несут ПО ДВА опроса, и внутри каждого файла эти два тега
    СОВПАДАЮТ ПОСИМВОЛЬНО — они различаются только веткой состояния, в которой
    стоят. Ключ по тексту схлопнул бы их в одну запись, и решение о втором не
    принимал бы никто; утверждение о ЧИСЛЕ такую пропажу не поймало бы, потому
    что считает тот же словарь и согласилось бы само с собой. Форма ключа
    унаследована у `test_no_two_mutating_routes_collapse_into_one_key`.

    Комментарии обоих видов вырезаются ДО разбора — по тому же доводу, по
    которому это делает `_hx_get_tags`: проза не имеет права ни создать
    фрагмент, ни заменить собой исчезнувший.
    """
    found: dict[str, str] = {}
    for rel, source in templates_.items():
        ordinal = 0
        for match in ANY_TAG.finditer(_strip_comments(source)):
            tag = match.group(0)
            if not POLL_TRIGGER_ATTR.search(tag):
                continue
            found[f"{rel}#{ordinal}"] = tag
            ordinal += 1
    return found


def _polls_without_a_proven_stop(
    templates_: dict[str, str], terminating: dict[str, str]
) -> dict[str, str]:
    """Объявленные опросы до завершения, у которых останов НЕ доказан.

    ЧТО СЧИТАЕТСЯ ДОКАЗАННЫМ ОСТАНОВОМ. Признак опроса стоит ВНУТРИ условия
    шаблонизатора В ТОМ ЖЕ ТЕГЕ: между открытием условия и его закрытием.
    Следствие проверяемо и не требует исполнения ни строчки JS — ответ,
    пришедший в состоянии «готово», условия не удовлетворяет, признака опроса не
    несёт, и подменённый узел перестаёт опрашивать сам. Опрос, чей признак стоит
    вне условия, останавливается только тем, что кто-то уберёт вкладку.

    ⚠️ ПУСТОЕ МНОЖЕСТВО КАНДИДАТОВ ДАЁТ ЗЕЛЁНЫЙ. Помощник обходит ОБЪЯВЛЕННЫЕ
    записи, а не найденные: дерево без единого опрашивающего фрагмента правило
    не роняет — там просто нечего доказывать. Полнота классификации есть
    ОТДЕЛЬНОЕ утверждение (`test_every_polling_fragment_is_classified`), и
    сливать два разных высказывания в одно значило бы получить гейт, который
    краснеет по двум причинам сразу и не называет ни одной.
    """
    offenders: dict[str, str] = {}
    fragments = _poll_fragments(templates_)

    for key in sorted(terminating):
        tag = fragments.get(key)
        if tag is None:
            offenders[key] = (
                "объявлен опросом до завершения, но обходом НЕ НАЙДЕН — запись "
                "пережила фрагмент, и правило держит пустоту"
            )
            continue

        trigger = POLL_TRIGGER_ATTR.search(tag)
        opened = JINJA_CONDITION_OPEN.search(tag)
        closed = JINJA_CONDITION_CLOSE.search(tag)

        if opened is None or closed is None:
            offenders[key] = (
                "признак опроса стоит ВНЕ условия шаблонизатора: в теге нет "
                "условия вовсе, значит ответ несёт признак всегда и опрос не "
                "останавливается никогда"
            )
            continue

        if not opened.start() < trigger.start() < closed.start():
            offenders[key] = (
                "условие в теге есть, но признак опроса стоит СНАРУЖИ него — "
                "ответ несёт признак при любом состоянии, и останов не доказан"
            )
    return offenders


def _unclassified_poll_fragments(
    templates_: dict[str, str],
    permanent: dict[str, str],
    terminating: dict[str, str],
) -> dict[str, str]:
    """Расхождение объявленных множеств с найденным: ключ → в чём расхождение.

    Замыкает гейт на себя. Фрагмент, добавленный будущей фазой, не попадёт ни в
    одно объявленное множество и уронит тест — вместо того чтобы оказаться
    бессрочным ПО УМОЛЧАНИЮ. Обратное расхождение (запись есть, фрагмента нет)
    ловится тем же обходом: перечень, переживший разметку, держит пустоту и
    выглядит при этом исправным.
    """
    found = _poll_fragments(templates_)
    declared = set(permanent) | set(terminating)

    offenders: dict[str, str] = {}
    for key in sorted(declared | set(found)):
        if key not in declared:
            offenders[key] = (
                "опрашивающий фрагмент НЕ КЛАССИФИЦИРОВАН: он не объявлен ни "
                "бессрочным, ни опросом до завершения — решения о нём не "
                "принимал никто, и по умолчанию он бессрочный"
            )
        elif key not in found:
            offenders[key] = (
                "объявлен опросом, но обходом НЕ НАЙДЕН — запись пережила "
                "фрагмент"
            )
    return offenders


