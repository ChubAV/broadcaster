# Тег, несущий атрибут: от открывающей угловой скобки до закрывающей, без
# пересечения чужих границ (`[^<>]`). Тег, внутри которого угловая скобка
# всё-таки встретилась, этим выражением НЕ найдётся — и это не молчаливая
# потеря: число найденных тегов утверждается равным числу вхождений атрибута
# отдельным тестом, который такой случай и назовёт.
HX_GET_TAG = re.compile(r"<[^<>]*?(?<![-\w])hx-get\s*=[^<>]*>")

JINJA_COMMENT = re.compile(r"\{#.*?#\}", re.DOTALL)
HTML_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)


