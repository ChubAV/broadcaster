# ПЕРЕЧЕНЬ КОДОВ ВЫПИСАН ЗДЕСЬ, А НЕ ВЫВЕДЕН ИЗ ПРОВЕРЯЕМОГО МОДУЛЯ.
# Собери его гейт из самого реестра — и запись, добавленная без решения,
# оказалась бы «объявленной» в тот же момент, как появилась. Довод дословно
