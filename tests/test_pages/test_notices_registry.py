def test_control_negative_a_duplicate_code_reddens_the_builder() -> None:
    """Сборщику подан кортеж с повторённым кодом — сборка обязана упасть.

    ⚠️ ИМЕННО РАДИ ЭТОГО РЕЕСТР СОБИРАЕТСЯ ИЗ ПАР, А НЕ ЛИТЕРАЛОМ СЛОВАРЯ.
    Литерал словаря Python при дубле ключа МОЛЧА перезаписывает первую запись:
    исход, о котором пользователю сообщали, исчез бы вместе со своим текстом, и
    ни один тест этого бы не заметил.
    """
    duplicated = (
        notices.Notice("same_code", "первый текст", "info"),
        notices.Notice("same_code", "второй текст", "error"),
    )

    with pytest.raises(ValueError) as failure:
        notices._index(duplicated)

    assert "same_code" in str(failure.value), (
        "сборка упала, но не назвала повторившийся код — читатель отказа не "
        "узнает, какую запись искать"
    )


def test_control_negative_a_changed_text_reddens_the_move_gate() -> None:
    """Гейту переноса подана изменённая копия записи — он обязан покраснеть.

    ⚠️ БЕЗ ЭТОГО КОНТРОЛЯ ГЕЙТ ПЕРЕНОСА НЕДОКАЗУЕМ. Он сравнивает две копии,
    выписанные одной рукой в один день, и зелен ровно потому, что руки было
    две одинаковые. Здесь подаётся третья — с одним изменённым словом, — и
    утверждение о том, что расхождение ВИДНО, становится проверенным.
    """
    tampered = tuple(
        record._replace(text=record.text + " и ещё одна фраза")
        if record.code == "retry_gone"
        else record
        for record in notices.NOTICES
    )

    failures = _move_gate_failures(tampered)

    assert failures, (
        "гейт переноса согласился с изменённым текстом — значит, он согласится "
        "и с переформулировкой при консолидации, ради поимки которой заведён"
    )
    assert any("retry_gone" in failure for failure in failures), (
        f"гейт покраснел, но не на изменённой записи: {failures}"
    )


def test_control_negative_a_missing_record_reddens_the_move_gate() -> None:
    """Из реестра изъята перенесённая запись — гейт переноса обязан покраснеть.

    Пропажа и переписывание — разные способы потерять исход, и второй из них
    предыдущий контроль не покрывает: запись, снятая целиком, не отличается от
    переписанной ничем, кроме того, что сравнивать нечего. Гейт, молчащий на
    пропаже, позволил бы консолидации «потерять» исход, о котором пользователю
    сообщали.
    """
    without_payment_pending = tuple(
        record for record in notices.NOTICES if record.code != "payment_pending"
    )

    failures = _move_gate_failures(without_payment_pending)

    assert any("payment_pending" in failure for failure in failures), (
        f"гейт переноса не заметил пропажи перенесённой записи: {failures}"
    )


