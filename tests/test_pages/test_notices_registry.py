"""Гейты ЗАКРЫТОГО РЕЕСТРА УВЕДОМЛЕНИЙ (FOUND-05, D-10, D-11).

ПОЧЕМУ ЭТОТ ФАЙЛ ЖИВЁТ В ``tests/test_pages/``, А НЕ В ``tests/test_templates/``.
Предмет проверки — множество на Python, а не разметка. Каноническое деление уже
записано в ``tests/test_templates/test_htmx_inventory.py``: гейты РАЗМЕТКИ
читают шаблоны и живут там, гейты МНОЖЕСТВ по Python-коду живут рядом с
``test_access_gate.py`` и ``test_impersonation_gate.py``. Реестр уведомлений —
второе.

ПОЧЕМУ ФАЙЛ НЕ ИМПОРТИРУЕТ НИ ОДНОГО МОДУЛЯ ПРИЛОЖЕНИЯ, КРОМЕ ПРОВЕРЯЕМОГО.
Довод дословно наследуется у ``test_impersonation_gate.py``: тест, выводящий
ожидание из проверяемого, согласился бы с любой правкой. Тексты и перечень
кодов выписаны ЗДЕСЬ литералами, и именно поэтому расхождение видно. Взять
ожидаемый текст из модуля-источника значило бы сравнить копию с самой собой.
Изменение множества кодов обязано быть РЕШЕНИЕМ, записанным в двух местах
сразу, а не правкой одного файла.

⚠️ ЧЕГО ЭТОТ ГЕЙТ НЕ ВИДИТ — ВЫПИСАНО ЗДЕСЬ, А НЕ ОСТАВЛЕНО НА ДОГАДКУ (WR-08).
Ненаписанная граница через один рефакторинг становится границей НЕИЗВЕСТНОЙ, и
файл начинает читаться как более полный, чем он есть. Границ три:

1. ГЕЙТ НЕ ВИДИТ, ЧТО КОД КЕМ-ТО ЗАПИСЫВАЕТСЯ. Он утверждает состав таблицы, а
   не то, что каждый записанный обработчиком код в этой таблице есть.
   Обработчик, отправивший человека с кодом, которого в реестре нет, отсюда
   выглядит совершенно обычно — он вообще не в поле зрения. Полноту «каждый
   записанный код зарегистрирован» закрывает обход плана 08-06.

2. ГЕЙТ НЕ ВИДИТ, ЧТО У КОДА ЕСТЬ МЕСТО ОТРИСОВКИ. Запись может быть
   безупречной и не показываться нигде — ровно то состояние, в котором сегодня
   находится молчащий исход сохранения профиля. Наличие области уведомления в
   шелле — свойство разметки, и его закрывает план 08-04.

3. ГЕЙТ ПЕРЕНОСА ДЕРЖИТ ОДИННАДЦАТЬ СТРОК, А НЕ ЧЕТЫРНАДЦАТЬ. Одиннадцать —
   это те, что переехали из отображений «код → текст» на Python. Оставшиеся три
   имеют другое происхождение и другим гейтом не покрываются: текст смены
   пароля жил в разметке экрана входа, текст отказа под чужой учётной записью
   уезжал телом ответа 403, а текст сохранения профиля НОВЫЙ — переносить было
   нечего.
"""

import ast
import re
