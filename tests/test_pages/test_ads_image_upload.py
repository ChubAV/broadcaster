def refusal_rows(html: str) -> list[tuple[str, str]]:
    """Строки отказа фрагмента парами «показанное имя, причина».

    Отказ БЕЗ имени файла (подделанный ключ вложения — отказ относится к ключу,
    а файла за ним нет; превышенное число частей — отказ относится к запросу
    целиком) возвращается парой с пустым именем.

    ⚠️ ПРЕЖНЯЯ РЕДАКЦИЯ ЭТОГО РАЗБОРА НАЗЫВАЕТСЯ, А НЕ СТИРАЕТСЯ (план 12-09).
    Здесь стояло: «разделителя в такой строке нет вовсе, и `partition` отдаёт
    весь текст правой частью». Первая половина НЕВЕРНА, и неверна она была
    всегда — просто до этого плана недостижимо: разделитель есть законный знак
    препинания, и ПРИЧИНА вправе его содержать. Безымянный отказ, чья причина
    несёт тире, разбирался бы как ИМЕНОВАННЫЙ, отдавая половину причины за имя
    файла — то есть правило падало бы (или, хуже, зеленело) на разборе, а не на
    предмете. Достижимость названа поимённо: `upload_parts_message` (безымянный
    отказ с тире) и `STORAGE_UNAVAILABLE_MESSAGE` (тире в причине; сегодня
    приходит с именем, и потому прежний разбор на нём был верен случайно).

    ЧЕМ РАЗЛИЧАЮТСЯ ДВЕ ФОРМЫ. Имя ПРОХОДИТ `safe_filename`, а он сводит набор
    символов к латинице, цифрам, точке, дефису и подчёркиванию — ПРОБЕЛА в
    нормализованном имени нет по построению, и пустым оно не бывает (есть
    значение по умолчанию). Поэтому левая часть с пробелом именем быть не может,
    и строка целиком есть причина. Разбор опирается на КОНТРАКТ нормализации, а
    не на состав сегодняшних текстов: заведут завтра причину с тире — разбор не
    двинется.
    """
    rows: list[tuple[str, str]] = []
    for row in REFUSAL_ROW.findall(html):
        left, separator, right = row.partition(NAME_REASON_SEPARATOR)
        named = bool(separator) and left != "" and not any(c.isspace() for c in left)
        rows.append((left, right) if named else ("", row))
    return rows


# Любой тег ответа и идентификатор внутри него — для разбора блоков СНЯТИЯ.
_ANY_TAG = re.compile(r"<[^<>]+>")
_TAG_ID = re.compile(r'\bid="([^"]+)"')


def removed_dom_ids(html: str) -> list[str]:
    """Идентификаторы, названные ответом к СНЯТИЮ, в порядке появления.

    ⚠️ ОБРАЗЕЦ ПРИШПИЛЕН К СПОСОБУ ПОДМЕНЫ `delete`, И ЭТО НЕСУЩЕЕ ТРЕБОВАНИЕ,
    А НЕ АККУРАТНОСТЬ (план 12-11). Перечень, собранный с ЛЮБОГО внеполосного
    блока ответа, краснел бы на ЗАКОННОЙ работе соседей по партии: тем же
    ответом приезжают плитка добавления (`media-add-tile`, задача 2 этого
    плана) и вычитающая метка убирания (`media-tombstones`, план 12-12). Оба —
    ровно при том же условии, что и блоки снятия: состав вложений изменён ЭТИМ
    запросом. Попав в перечень, они сделали бы равенство ложным, не тронув
    предмета правила ни на символ.

    Поэтому перечень измеряет «кого этот ответ УНОСИТ», а не «сколько блоков он
    вообще несёт». Ровно это и есть предмет: ВЛАСТЬ ОТВЕТА НАД ЧУЖИМ
    СОСТОЯНИЕМ. Следующему читателю: не «чинить» образец, расширив его до всех
    внеполосных блоков.

    Написан ЗДЕСЬ ПО МЕСТУ, а не ввезён из модуля тестов редактора, где живёт
    его близнец: тестовый модуль не библиотека, и перекрёстный ввоз связал бы
    два файла порядком сборки — тот же довод записан у построителей выше.
    """
    found: list[str] = []
    for tag in _ANY_TAG.findall(html):
        if 'hx-swap-oob="delete"' not in tag:
            continue
        match = _TAG_ID.search(tag)
        found.append(match.group(1) if match else "")
    return found


def _attr_value(html: str, anchor: str, attr: str) -> str:
    """Значение атрибута элемента, опознанного по подстроке `anchor`.

    Разбор строкой — тот же приём, что применяют соседние файлы тестов страниц
    (`tests/test_pages/test_ads_editor.py`): новой зависимости разбора HTML ради
    одного атрибута не заводится. Отсутствие элемента или атрибута поднимает
    ValueError — тест падает, а не молча меряет пустоту.
    """
    start = html.index(anchor)
    opened = html.index(f'{attr}="', start) + len(attr) + 2
    return html[opened : html.index('"', opened)]


