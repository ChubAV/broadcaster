"""Правило конфигурации и тело ответа сервера сведены в одном месте.

ПОЧЕМУ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Правило `{"code":"422","swap":true,"error":true}` в
`app/templates/includes/htmx_config.html` несёт ПОСЫЛКУ о теле ответа сервера:
оно предписывает подменить содержимое страницы тем, что пришло с кодом 422.
Сегодня посылка НЕ ВЫПОЛНЕНА. В приложении нет ни одного маршрута, отдающего
этот код с фрагментом разметки, и обработчика ошибок валидации среди
зарегистрированных в `app/main.py` нет — там только четыре доменных исключения и
общее. Значит всякий ответ 422, который приложение сегодня способно отдать, есть
умолчание веб-фреймворка: машинное тело вида
`{"detail":[{"type":"int_parsing","loc":["query","page"],...}]}` с внутренними
именами маршрута и параметра.

Две стороны этого расхождения живут в РАЗНЫХ файлах и правятся разными людьми в
разное время: правило — в шаблоне, тело — в маршрутах. Файл есть место, где они
сведены и где расхождение краснеет, а не обнаруживается пользователем.

ЧТО ЗАКРЫВАЕТ ПРИЗНАК ОШИБКИ, А ЧТО НЕТ. Признак ошибки помечает такой ответ
неуспешным и поднимает `htmx:responseError` — то есть ответ перестаёт быть
неотличимым от успешного. Он НЕ делает тело ответа фрагментом разметки: это
предмет Фазы 8 (слой ответа и канал видимости отказов), и гейт ниже стережёт
ровно момент, когда первое такое место появится.

ОГРАНИЧЕНИЕ ДЛЯ БУДУЩЕГО КАНАЛА ВИДИМОСТИ ОТКАЗОВ записано словами в шапке
`app/templates/includes/htmx_config.html` — там, где его прочтёт тот, кто будет
править конфигурацию, а не только тот, кто откроет тесты.
"""
import ast
from pathlib import Path

import pytest
from httpx import AsyncClient

# Разборщик значения атрибута конфигурации берётся ИМПОРТОМ, а не второй копией
# регулярного выражения: два разборщика одного атрибута разъехались бы молча —
# та же доктрина единственного источника, по которой и сам блок конфигурации
# выписан в проекте один раз (D-01).
from tests.test_pages.test_shell import _htmx_config_of

PROJECT_ROOT = Path(__file__).resolve().parents[2]
APP_ROOT = PROJECT_ROOT / "app"

# Код ответа, о котором правило конфигурации несёт посылку.
VALIDATION_STATUS_CODE = 422

# Исключения, регистрация обработчика которых есть ВТОРОЙ способ завести в
# приложении источник этого кода — не через литерал статуса, а через обработчик.
# Оба способа обязаны быть видны гейту: закрыв один, правка прошла бы вторым.
VALIDATION_EXCEPTIONS = ("RequestValidationError", "ValidationError")


# ЛЕТОПИСЬ СОСТАВА. Число ниже выписано ЗДЕСЬ литералом, а не выведено обходом в
# момент прогона: гейт, считающий ожидание по проверяемому охвату, узаконил бы
# собственным зелёным цветом любое появление нового места — то есть ровно тот
# отказ, ради которого инвентарные гейты в проекте и заведены (форма записи — с
# tests/test_templates/test_htmx_inventory.py:61 и
# tests/test_pages/test_access_gate.py).
#
# 2026-08-27, план 07-05: НОЛЬ мест при 95 разобранных модулях `app/`. Измерено
# обходом дерева разбора ДО написания гейта, а не перенесено из отчёта.
#
# ЧТО ОБЯЗАН СДЕЛАТЬ ТОТ, КТО ЭТО ЧИСЛО УВЕЛИЧИТ. Появление первого места —
# решение, записываемое В ДВУХ МЕСТАХ СРАЗУ, и увеличить здесь число, не сделав
# второго, значит отгрузить пользователю машинное тело в карточку:
#   1. Тело такого ответа делается ФРАГМЕНТОМ РАЗМЕТКИ, годным к подмене, —
#      правило конфигурации именно это и предписывает; ЛИБО
#   2. принимается решение о самом правиле (снятие свопа), и тогда правится
#      `app/templates/includes/htmx_config.html` вместе с ожидаемой
#      конфигурацией в `tests/test_pages/test_shell.py`, ОДНИМ коммитом.
# Уменьшение числа обратно к нулю допустимо и означает снятие места, записанное
# следующей записью этой летописи.
SERVER_SIDE_VALIDATION_RESPONSES = 0


def _status_code_literals(package_root: Path) -> list[tuple[str, int]]:
    """Места пакета, отдающие ответ с кодом валидации, — по ДЕРЕВУ РАЗБОРА.

    ⚠️ ГЕЙТ ЧИТАЕТ ДЕРЕВО РАЗБОРА, А НЕ ТЕКСТ, И ЭТО НЕСУЩЕЕ РЕШЕНИЕ, А НЕ
    СТИЛЕВОЕ ПРЕДПОЧТЕНИЕ. Текстовый поиск считал бы упоминания кода в
    комментариях и строках документации, а комментарии-обоснования в этой кодовой
    базе объёмны и обязательны: гейт краснел бы на правку ДОКУМЕНТАЦИИ и молчал
    бы на переезд кода в переменную. Упрощать этот помощник до поиска подстроки
    поэтому запрещено — он потеряет ровно то свойство, ради которого написан.

    Ищутся ОБА способа завести источник кода:
      * именованный аргумент статуса ответа с ЦЕЛОЧИСЛЕННЫМ литералом;
      * регистрация обработчика исключения ошибок валидации по имени декоратора
        и имени его аргумента.

    Обход РЕКУРСИВНЫЙ (`rglob`, не `glob`): плоский обход не увидел бы модуля в
    подкаталоге, и ревизия проекта уже ловила ровно эту границу
    (tests/test_pages/test_impersonation_gate.py).

    Возвращаются пары «модуль — номер строки», а не число: сообщение об отказе
    обязано называть МЕСТО, иначе тот, кто гейт уронил, останется с числом на
    руках и без способа узнать, где искать.
    """
    sites: list[tuple[str, int]] = []

    for module in sorted(package_root.rglob("*.py")):
        relative = module.relative_to(PROJECT_ROOT).as_posix()
        source = module.read_text(encoding="utf-8")
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            # Модуль, не разобравшийся в дерево, обязан РОНЯТЬ гейт, а не молча
            # выпадать из охвата: неразобранный модуль неотличим от модуля без
            # находок, и охват, тихо потерявший файл, утверждает не то, что
            # обещает.
            raise AssertionError(
                f"{relative}: модуль не разбирается в дерево ({exc}) — охват "
                "гейта потерял бы его молча, а вместе с ним и любой ответ "
                f"{VALIDATION_STATUS_CODE}, который в нём объявлен"
            ) from exc

        for node in ast.walk(tree):
            if isinstance(node, ast.keyword) and node.arg == "status_code":
                value = node.value
                if (
                    isinstance(value, ast.Constant)
                    and type(value.value) is int
                    and value.value == VALIDATION_STATUS_CODE
                ):
                    sites.append((relative, value.lineno))

            if isinstance(node, ast.Call):
                func = node.func
                decorator_name = (
                    func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", None)
                )
                if decorator_name != "exception_handler":
                    continue
                for argument in node.args:
                    exception_name = (
                        argument.attr
                        if isinstance(argument, ast.Attribute)
                        else getattr(argument, "id", None)
                    )
                    if exception_name in VALIDATION_EXCEPTIONS:
                        sites.append((relative, node.lineno))

    return sites


def test_the_swap_rule_and_the_server_response_body_do_not_diverge():
    """Сколько мест приложения отдают код валидации — и что будет, когда первое появится.

    Гейт закрывает не сегодняшнюю ошибку, а расхождение, которое иначе наступит
    МОЛЧА: правило конфигурации подменяет содержимое страницы телом ответа с этим
    кодом, а состав такого тела сегодня выбирает не приложение, а умолчание
    фреймворка.
    """
    sites = _status_code_literals(APP_ROOT)

    listing = "\n".join(f"  {module}:{line}" for module, line in sites) or "  (нет)"
    assert len(sites) == SERVER_SIDE_VALIDATION_RESPONSES, (
        f"мест в app/, отдающих ответ {VALIDATION_STATUS_CODE}, стало "
        f"{len(sites)}, в летописи записано {SERVER_SIDE_VALIDATION_RESPONSES}:\n"
        f"{listing}\n"
        "Правило конфигурации предписывает ПОДМЕНИТЬ содержимое страницы телом "
        "такого ответа. Если тело не фрагмент разметки, пользователь получит в "
        "карточку машинный текст с внутренними именами маршрута и параметра "
        "ВМЕСТО сообщения об ошибке заполнения. Сделайте тело фрагментом либо "
        "примите решение о правиле — и запишите его в летописи над этой "
        "константой вместе с правкой htmx_config.html."
    )


@pytest.mark.asyncio
async def test_validation_rule_carries_both_swap_and_error(
    client: AsyncClient, authed_client: AsyncClient
):
    """Правило валидации несёт ОБА свойства сразу — по ОТРЕНДЕРЕННОМУ документу обоих шеллов.

    Утверждение снимается с ответа, а не с исходника шаблона: сломанное
    экранирование кавычек внутри значения атрибута отбросило бы ВСЕ шесть ключей
    в умолчания при зелёном грепе — htmx о нечитаемой конфигурации не сообщает
    ничем (D-05).

    Своп и признак ошибки читаются рантаймом НЕЗАВИСИМО: подмена выполняется по
    одному свойству, событие ошибки поднимается по другому, и одно не отменяет
    другого. Поэтому оба обязаны стоять вместе — своп ради перерисовки формы с
    эхо-возвратом введённого (FORM-08), признак ошибки ради того, чтобы ответ не
    приезжал в страницу молча.
    """
    shells = (
        ("auth_base.html", (await client.get("/login")).text),
        ("base.html", (await authed_client.get("/dashboard")).text),
    )

    for shell, html in shells:
        rules = _htmx_config_of(html, shell)["responseHandling"]
        by_code = {rule["code"]: rule for rule in rules}

        validation = by_code.get(str(VALIDATION_STATUS_CODE))
        assert validation is not None, (
            f"{shell}: правила {VALIDATION_STATUS_CODE} в конфигурации нет — "
            "ответ об ошибке заполнения формы попадёт под общее правило, и "
            "перерисовка формы с эхо-возвратом введённого станет невозможной"
        )

        assert validation.get("swap") is True, (
            f"{shell}: у правила {VALIDATION_STATUS_CODE} снята подмена "
            f"содержимым ({validation!r}) — форма с ошибкой заполнения не "
            "перерисуется, и кнопка сохранения станет для пользователя мёртвой"
        )

        assert validation.get("error") is True, (
            f"{shell}: у правила {VALIDATION_STATUS_CODE} нет признака ошибки "
            f"({validation!r}) — ответ приедет пользователю в карточку МОЛЧА, "
            "не подняв htmx:responseError, и вместо сообщения об ошибке "
            "заполнения он увидит машинный текст с внутренностями маршрута"
        )

        general = by_code.get("[45]..")
        assert general is not None and general.get("swap") is False, (
            f"{shell}: общее правило [45].. подменяет содержимое "
            f"({general!r}) — тело любого отказа сервера поедет пользователю в "
            "карточку, а правило валидации перестанет отличаться от общего"
        )
