def _converted(sources: dict[str, str]) -> set[str]:
    """Обработчики, уже идущие через слой ответа, — СОБРАНЫ ОБХОДОМ.

    Это множество не объявляется руками намеренно: оно есть ФАКТ исходника, и
    выписанный руками список «переведённых» разошёлся бы с деревом молча — как
    раз в ту сторону, в которую удобно.
    """
    return {
        key for key, handler in _post_handlers(sources).items() if handler.calls_respond
    }


def _unclassified(
    sources: dict[str, str],
    *,
    never: dict[str, str] | None = None,
    not_yet: frozenset[str] | None = None,
) -> set[str]:
    """Обработчики, не попавшие НИ В ОДНО из трёх множеств.

    Это и есть предмет замыкающего утверждения файла: непустой результат
    означает, что обработчик существует, а решения «через слой ответа или нет»
    никто не принимал.

    Перечни приходят параметрами, а не читаются из модуля, ровно затем, чтобы
    контроли могли подать БУДУЩЕЕ состояние (обработчик снят с отставания,
    потому что Фаза 9 его перевела) и увидеть, как гейт на него отвечает.
    """
    never_set = set(NEVER_RESPONDS if never is None else never)
    not_yet_set = set(NOT_YET_CONVERTED if not_yet is None else not_yet)
    converted = _converted(sources)

    return {
        key
        for key in _post_handlers(sources)
        if key not in converted and key not in never_set and key not in not_yet_set
    }


def _backlog(sources: dict[str, str], *, never: dict[str, str] | None = None) -> set[str]:
    """Обработчики, ФАКТИЧЕСКИ ещё не переведённые на слой ответа.

    ⚠️ СОБИРАЕТСЯ ОБХОДОМ, А НЕ ЧИТАЕТСЯ ИЗ КОНСТАНТЫ, И ЭТО НЕСУЩЕЕ РЕШЕНИЕ.
    Сравнение объявленного списка с объявленным числом краснело бы только на
    рассинхронизацию двух строк одного файла; сравнение ФАКТА с объявленным
    числом краснеет на правку ПРИЛОЖЕНИЯ — то есть на то самое событие, ради
    которого счётчик заведён.
    """
    never_set = set(NEVER_RESPONDS if never is None else never)
    converted = _converted(sources)
    return {
        key
        for key in _post_handlers(sources)
        if key not in converted and key not in never_set
    }


