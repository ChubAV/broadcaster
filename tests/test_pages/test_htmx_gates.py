# =============================================================================
# ПЕРЕЧЕНЬ ИЗЪЯТИЙ ПО СМЕЩЁННОМУ КУРСОРУ: обход разметки и два правила
#
# ⚠️ ОБХОД ИЩЕТ ПЕРЕСЕЧЕНИЕ ДВУХ СВОЙСТВ, А НЕ ОДНО ИЗ НИХ. Списков на смещённом
# курсоре в дереве больше двух (расписания, история, история пользователя в
# админке), и объявлять изъятием КАЖДЫЙ значило бы завести перечень, в котором
# настоящее изъятие потерялось бы среди строк, не имеющих к форме ответа
# отношения. Предмет — список, который листается смещённым курсором И СТРОКИ
# КОТОРОГО НЕСУТ ПАНЕЛЬ УДАЛЕНИЯ: только у такого пересечения фрагментное
# удаление вообще возможно, а значит только у него отказ от фрагмента есть
# РЕШЕНИЕ, которое надо объявить.
# =============================================================================

_MACRO_DEFINITION = re.compile(r"{%-?\s*macro\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(")
_MACRO_END = re.compile(r"{%-?\s*endmacro\s*-?%}")
_TEMPLATE_IMPORT = re.compile(
    r"{%-?\s*from\s+\"([^\"]+)\"\s+import\s+([^%}]+?)\s*-?%}"
)
# ⚠️ ГРАНИЦА СЛОВА ОБЯЗАТЕЛЬНА: без неё в счёт попал бы вызов `retry_modal(`,
# который панель не объявляет, а лишь зовёт своё обёрточное имя.
_PANEL_CALL = re.compile(r"\bmodal\s*\(")


def _call_arguments(text: str, start: int) -> str:
    """Аргументы вызова, начинающегося на позиции открывающей скобки.

    Границы считаются БАЛАНСОМ СКОБОК, а не срезом фиксированной длины: у
    панели аргументы многострочные, и срез в N символов терял бы адрес действия
    ровно у тех вызовов, где перед ним стоит длинная подпись.
    """
    depth = 0
    for index in range(start, len(text)):
        char = text[index]
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return text[start : index + 1]
    return text[start:]


def _carries_a_row_removing_panel(text: str) -> bool:
    """Объявляет ли эта разметка панель подтверждения УДАЛЕНИЯ строки."""
    for match in _PANEL_CALL.finditer(text):
        arguments = _call_arguments(text, match.end() - 1)
        if ROW_REMOVING_ACTION_MARK in arguments:
            return True
    return False


def _macro_bodies(text: str) -> dict[str, str]:
    """Тела макросов файла по именам.

    Разбор по телам, а не по файлу целиком, — несущее свойство обхода. Файл
    карточки расписания несёт И подпись счётчика, И панель удаления; страница
    сводного списка расписаний ввозит из него ТОЛЬКО подпись. Обход, считающий
    по файлу, объявил бы её списком с панелью удаления и потребовал бы третьего
    изъятия там, где удалять с экрана нечего.
    """
    bodies: dict[str, str] = {}
    for match in _MACRO_DEFINITION.finditer(text):
        end = _MACRO_END.search(text, match.end())
        bodies[match.group(1)] = text[match.end() : end.start() if end else len(text)]
    return bodies


def _imported_macros(text: str) -> list[tuple[str, tuple[str, ...]]]:
    """Пары «файл разметки → ввезённые из него имена макросов»."""
    imports: list[tuple[str, tuple[str, ...]]] = []
    for match in _TEMPLATE_IMPORT.finditer(text):
        names = tuple(
            part.strip().split(" as ")[0].strip()
            for part in match.group(2).split(",")
            if part.strip()
        )
        imports.append((match.group(1), names))
    return imports


def _lists_on_an_offset_cursor(templates: dict[str, str]) -> set[str]:
    """Файлы разметки, где список листается СМЕЩЁННЫМ курсором И несёт удаление.

    Возвращаются ФАЙЛЫ, а не разделы: улика измерима именно пофайлово, и
    сообщение об отказе обязано называть место, где смещение видно глазами.
    """
    found: set[str] = set()

    for path, text in templates.items():
        portion = [
            line
            for line in text.splitlines()
            if PORTION_REQUEST_MARK in line and OFFSET_CURSOR_MARK in line
        ]
        if not portion:
            continue

        candidates = [text]
        for source, names in _imported_macros(text):
            bodies = _macro_bodies(templates.get(f"{TEMPLATES_DIRECTORY}/{source}", ""))
            candidates.extend(bodies[name] for name in names if name in bodies)

        if any(_carries_a_row_removing_panel(part) for part in candidates):
            found.add(path)

    return found


def _declared_offset_cursor_templates() -> set[str]:
    """Файлы, названные записями перечня изъятий."""
    return {
        template
        for exception in OFFSET_CURSOR_EXCEPTIONS
        for template in exception.templates
    }


