def _header_read_sites(sources: dict[str, str]) -> list[tuple[str, int]]:
    """Места, где имя заголовка признака htmx попадает в исходник приложения.

    Читаются ДВА способа завести второе чтение, и оба обязаны быть видны — закрыв
    один, правка ушла бы вторым:

    1. ЛИТЕРАЛ имени заголовка где угодно в `app/**/*.py`. Разбор по дереву, а
       не по тексту: имя заголовка называется словами в обоснованиях соседних
       модулей, и текстовый поиск краснел бы на правку ДОКУМЕНТАЦИИ.
    2. ССЫЛКА НА КОНСТАНТУ слоя ответа ИЗ ДРУГОГО МОДУЛЯ — включая ввоз её
       именем. Внутри слоя ответа ссылка не считается: там она и есть то самое
       единственное чтение, а считать объявление и его использование за два
       места значило бы требовать, чтобы константа не использовалась нигде.

    Возвращаются пары «модуль — строка», а не число: сообщение об отказе обязано
    называть МЕСТО, иначе тот, кто гейт уронил, останется с числом на руках и без
    способа узнать, где искать.
    """
    sites: list[tuple[str, int]] = []

    for module, text in sources.items():
        tree = _parse(module, text)
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.Constant)
                and isinstance(node.value, str)
                and node.value.lower() == HX_REQUEST_HEADER_NAME.lower()
            ):
                sites.append((module, node.lineno))

            if module == RESPONSE_LAYER_MODULE:
                continue

            if isinstance(node, ast.Name) and node.id == HX_REQUEST_CONSTANT:
                sites.append((module, node.lineno))
            elif isinstance(node, ast.Attribute) and node.attr == HX_REQUEST_CONSTANT:
                sites.append((module, node.lineno))
            elif isinstance(node, ast.ImportFrom):
                for alias in node.names:
                    if alias.name == HX_REQUEST_CONSTANT:
                        sites.append((module, node.lineno))

    return sites


