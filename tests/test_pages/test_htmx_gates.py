# Множество 5: ОБРАБОТЧИКИ, ОТДАЮЩИЕ ФРАГМЕНТ — ВТОРОЙ СЧЁТ ФАЗЫ (D-18)
#
# ⚠️ ЭТО ВТОРОЙ СЧЁТ, А НЕ ТОТ ЖЕ САМЫЙ, И РАЗВЕДЕНИЕ ЗДЕСЬ СМЫСЛОВОЕ, А НЕ
# ОРГАНИЗАЦИОННОЕ. Четыре вещи, которые обязан сказать этот абзац:
#
#   1. ДВА СЧЁТА ОТВЕЧАЮТ НА РАЗНЫЕ ВОПРОСЫ. `NOT_YET_CONVERTED` выше есть
#      УБЫВАЮЩЕЕ число и отвечает на вопрос «СТОИ́Т ЛИ обработчик на слое
#      ответа»: падение означает проделанную работу, рост — регрессию. Перечень
#      ниже есть РАСТУЩЕЕ число и отвечает на другой вопрос — «ОТДАЁТ ЛИ он
#      фрагмент». Обработчик, ушедший на слой ответа веткой ПЕРЕХОДА (204 и
#      заголовок перехода), первый счёт двигает, а второй — нет, и это не
#      расхождение, а ровно то различие, ради которого счётов два.
#
#   2. ОДНО ЧИСЛО ПРОГРЕССА НЕ МОЖЕТ ОТВЕЧАТЬ ЗА ДВА РАЗНЫХ СВОЙСТВА, И ИДИОМА
#      У ПРОЕКТА СВОЯ. Она записана дословно у `MODAL_CONSUMERS`
#      (`tests/test_templates/test_components.py`): «два счёта РАЗНЫХ множеств,
#      приводить их к согласию правкой одного нельзя». Ту же форму приняли две
#      оси обхода подтверждения (`CONFIRMED_DELETE_ROUTES_DECLARED` против
#      `CONFIRMED_DELETE_OUTCOME_CASES_DECLARED`, план 10-03). Свести два счёта
#      в одно число значило бы получить на два разных вопроса один ответ, и
#      неверным он оказался бы ровно на том вопросе, который задали позже.
#
#   3. ПО ЭТОМУ ЧИСЛУ МЕРЯЕТСЯ ПЕРВЫЙ КРИТЕРИЙ ФАЗЫ 11, И ФАЗА 10 ЕГО НЕ
#      ПЕРЕПИСЫВАЕТ. Критерий той фазы говорит о пятнадцати обработчиках класса
#      A и пяти класса B; Фаза 10 даёт ей ИЗМЕРИТЕЛЬНЫЙ ПРИБОР, а не новую цель.
#      Правка чужих критериев успеха до того, как та фаза началась, отвергнута
#      решением D-18: фаза, переписавшая цель следующей, лишает её возможности
#      обнаружить собственное расхождение с планом.
#
#   4. СНЯТИЕ ИЗ ПЕРЕЧНЯ ОТСТАВАНИЯ ТОЛЬКО ФРАГМЕНТНЫХ ОБРАБОТЧИКОВ ОТВЕРГНУТО.
#      Обработчик, стоящий на слое ответа и при этом числящийся непереведённым,
#      есть ровно то расхождение двух множеств, ОТ КОТОРОГО СТОЯТ гейты
#      единственности решения о форме ответа (G-1/G-2). Сохранить его значило бы
#      объявить дефектом то, ради обнаружения чего гейты и написаны, — поэтому
#      согласованность двух счётов утверждается ПРАВИЛОМ (пересечение множеств
#      пусто), а не достигается подгонкой одного перечня под другой.
#
# ⚠️ ПРИЗНАК ПЕРЕДАЧИ ФРАГМЕНТА БЕРЁТСЯ РАЗБОРОМ ДЕРЕВА, А НЕ ПОДСТРОКОЙ.
# Обоснования в этой кодовой базе объёмны, имя аргумента в них называется
