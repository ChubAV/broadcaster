def _fragment_builder_names(function: ast.AST) -> set[str]:
    """Имена вложенных функций, ПОДАННЫХ слою ответа аргументом фрагмента.

    ⚠️ ЭТО НЕ ПОСЛАБЛЕНИЕ РАЗБОРУ, А ГРАНИЦА ЕГО ПРЕДМЕТА, И РАЗНИЦА
    ИЗМЕРЕНА. Сборщик фрагмента возвращает ответ ПО ТРЕБОВАНИЮ слоя: его зовёт
    сам `respond()`, получив его аргументом `fragment=`. Решение о форме ответа
    здесь принимает слой, а не обработчик, — тело фрагмента есть то, ЧЕМ слой
    отвечает, а не второй ответ на тот же вопрос. Замер: без этой границы
    разбор давал ДВЕНАДЦАТЬ мест у ДЕСЯТИ переведённых обработчиков, из них ТРИ
    (`account_groups.py:593`, `account_groups.py:832`, `schedules.py:1228`) —
    сборка фрагмента внутри вложенного `_fragment`, поданного `respond()`.
    Объявить их «выходами в обход слоя» значило бы назвать расхождением ровно
    тот путь, ради которого слой и заведён.

    Узнаётся ИМЕНОВАННЫЙ аргумент фрагмента у вызова слоя ответа, поданный
    ИМЕНЕМ (`fragment=_fragment`). Лямбда и выражение не узнаются, и ошибка
    здесь безопасна ПО НАПРАВЛЕНИЮ: неузнанный сборщик останется в найденном,
    то есть потребует объявления записью, а не проедет молча.
    """
    names: set[str] = set()
    for node in ast.walk(function):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        is_response_call = (isinstance(func, ast.Name) and func.id == RESPONSE_CALL) or (
            isinstance(func, ast.Attribute) and func.attr == RESPONSE_CALL
        )
        if not is_response_call:
            continue
        for keyword in node.keywords:
            if keyword.arg == FRAGMENT_ARGUMENT and isinstance(keyword.value, ast.Name):
                names.add(keyword.value.id)
    return names


def _own_response_builds(function: ast.AST) -> list[tuple[str, int]]:
    """Собственные сборки ответа обработчика — ВИД и СТРОКА, а не «да/нет».

    ⚠️ ФУНКЦИЯ ЗАВЕДЕНА РЯДОМ С `_builds_own_redirect`, А НЕ ВМЕСТО НЕЁ.
    Предмет прежней — РЕДИРЕКТ, и `G-2` в прежней формулировке продолжает его
    стеречь своим разборщиком. Расширить прежнюю функцию значило бы починить
    слепоту ценой потери правила: `G-2` покраснел бы на девяти отказах по
    происхождению, то есть предъявил бы красный вместо измерения.

    ВИД возвращается СТРОКОЙ (`Response(status_code=403)`), а не признаком:
    правило полноты ниже сличает вид объявленный с видом измеренным, и запись,
    у которой сборка сменилась с `403` на `404`, обязана краснеть — иначе
    обоснование записи описывало бы не тот выход, который в дереве.

    Псевдоним импорта не узнаётся — та же названная граница, что у
    `_calls_response_layer` и `_builds_own_redirect`, и та же безопасность по
    направлению: неузнанное имя даёт МЕНЬШЕ найденного, то есть правило числа
    краснеет, а не зеленеет.
    """
    fragments = _fragment_builder_names(function)

    skipped: set[int] = set()
    for node in ast.walk(function):
        if (
            isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and node is not function
            and node.name in fragments
        ):
            for inner in ast.walk(node):
                skipped.add(id(inner))

    found: list[tuple[str, int]] = []
    for node in ast.walk(function):
        if not isinstance(node, ast.Call) or id(node) in skipped:
            continue
        func = node.func
        name = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", None)
        if name not in OWN_RESPONSE_CALLABLES:
            continue

        status: str | None = None
        for keyword in node.keywords:
            if keyword.arg != "status_code":
                continue
            value = keyword.value
            if isinstance(value, ast.Constant):
                status = str(value.value)
            elif isinstance(value, ast.Attribute):
                status = value.attr
            else:
                status = "выражение"
        kind = f"{name}(status_code={status})" if status else f"{name}()"
        found.append((kind, node.lineno))
    return found


def _converted_with_own_response(sources: dict[str, str]) -> dict[str, str]:
    """Переведённые обработчики, несущие СОБСТВЕННУЮ сборку ответа.

    Возвращается отображение «ВХОД → ВИД сборки». Ключ — та же пара «модуль +
    имя обработчика», что у `_post_handlers`: перечень обязан читаться рядом с
    остальными множествами файла и сличаться с ними без перевода.

    ⚠️ ВСЕЛЕННАЯ — ТОЛЬКО ПЕРЕВЕДЁННЫЕ, И ГРАНИЦА НАЗВАНА, А НЕ ПОДРАЗУМЕВАЕТСЯ.
    Обработчик, слоя ответа не знающий, второго решения о форме не несёт: у него
    решение ОДНО, своё, и предмет его — счётчик отставания
    (`NOT_YET_CONVERTED`), а не этот перечень. Собственный отказ у него —
    не расхождение с утверждением слоя, потому что слой о нём ничего не
    утверждает.
    """
    found: dict[str, str] = {}
    for module, text in sources.items():
        tree = _parse(module, text)
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if not any(_declares_post(decorator) for decorator in node.decorator_list):
                continue
            if not _calls_response_layer(node):
                continue
            builds = _own_response_builds(node)
            if not builds:
                continue
            kinds = sorted({kind for kind, _ in builds})
            found[f"{module}::{node.name}"] = ", ".join(kinds)
    return found


