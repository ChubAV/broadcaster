def test_no_converted_handler_builds_its_own_redirect():
    """G-2: у переведённого обработчика НЕ остаётся второго решения о форме ответа.

    Обработчик, ходящий через `respond()` и вдобавок строящий редирект сам,
    несёт ДВА решения об одном вопросе, и какое из них исполнится, зависит от
    ветки, по которой пошло выполнение, — то есть путь деградации снова
    перестаёт быть обязательным.

    ⚠️ СЕГОДНЯ УТВЕРЖДЕНИЕ ИСТИННО НИ НА ЧЁМ, И ЭТО НАЗВАНО. До Фазы 9 множество
    переведённых пусто. Гейтом на пустоту оно при этом не является: предмет
    собирается ТЕМ ЖЕ обходом, который даёт `POST_HANDLERS`, а зубы доказаны
    контролем — он подаёт разборщику ровно тот исходник, который Фаза 9 могла бы
    написать.
    """
    handlers = _post_handlers(_pages_sources())

    both = sorted(
        key
        for key, handler in handlers.items()
        if handler.calls_respond and handler.builds_own_redirect
    )

    assert not both, (
        "обработчик идёт через слой ответа И строит редирект сам:\n  "
        + "\n  ".join(both)
        + "\n\nЭто два решения об одной форме ответа. Уберите собственный "
        "редирект: адрес деградации подаётся в `respond(redirect=...)`, и "
        "именно оттуда он уезжает человеку без JavaScript"
    )


def test_the_gate_imports_no_application_module():
    """Гейт не ввозит НИ ОДНОГО модуля приложения ради построения ожиданий.

    ⚠️ ЭТО ЗАПРЕТ, А НЕ СТИЛЬ. Тест, выводящий ожидание из проверяемого,
    согласился бы с любой правкой. Из того же свойства следует независимость от
    порядка исполнения сюиты и от параллельного прогона: гейт не поднимает
    приложения, не трогает базы и читает только текст файлов.
    """
    tree = ast.parse(Path(__file__).read_text(encoding="utf-8"))

    imported: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.append(node.module)

    from_application = [
        name for name in imported if name == "app" or name.startswith("app.")
    ]

    assert not from_application, (
        f"гейт ввозит модули приложения {from_application} — ожидания могли "
        "быть выведены из проверяемого, и тест согласился бы с любой правкой"
    )


def test_no_post_route_is_declared_in_a_form_the_gate_cannot_see():
    """Ни один маршрут страничного слоя не объявлен формой, НЕВИДИМОЙ разборщику.

    ⚠️ ГЕЙТ, КОТОРЫЙ ЧЕГО-ТО НЕ ВИДИТ, ОБЯЗАН ТРЕБОВАТЬ, ЧТОБЫ ЭТОГО НЕ БЫЛО.
    Объявление ВЫЗОВОМ (`add_api_route`) разборщику не видно: обработчик
    приезжает туда ссылкой, и связать его с объявлением по дереву нечем. Такой
    обработчик не попал бы ни в одно из трёх множеств и не уронил бы замыкающего
    утверждения полноты — то есть решал бы форму ответа мимо слоя ПО УМОЛЧАНИЮ.

    Отказ здесь — не запрет формы навсегда, а требование СНАЧАЛА научить
    разборщик.
    """
    offenders: list[str] = []
    for module, text in _pages_sources().items():
        for node in ast.walk(_parse(module, text)):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr == "add_api_route"
            ):
                offenders.append(f"{module}:{node.lineno}")

    assert not offenders, (
        "маршрут объявлен вызовом `add_api_route`, которого разборщик гейта не "
        f"видит: {sorted(set(offenders))}. Такой обработчик не попадёт ни в "
        "одно из трёх множеств и окажется решающим форму ответа мимо слоя ПО "
        "УМОЛЧАНИЮ. Научите `_post_handlers` этой форме прежде, чем ею "
        "пользоваться"
    )
