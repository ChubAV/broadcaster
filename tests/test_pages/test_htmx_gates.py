def _declares_post(decorator: ast.AST) -> bool:
    """Объявляет ли этот декоратор POST-маршрут.

    Узнаются ОБЕ формы, которыми веб-фреймворк объявляет маршрут декоратором:
    именованный метод (`@любой_роутер.post(...)`) и общая
    (`@любой_роутер.api_route(..., methods=["POST"])`). Вторая формой записи от
    первой не отличается ничем, кроме видимости для наивного разборщика, — то
    есть обработчик, написанный ею, выпал бы из охвата и не уронил бы ни числа,
    ни замыкающего утверждения полноты.

    ⚠️ ИМЯ ОБЪЕКТА РОУТЕРА НЕ ПРОВЕРЯЕТСЯ. Единственный денежный
    POST-обработчик страничного слоя объявлен на `money_router`, и разбор «по
    имени `router`» потерял бы ровно его — то есть слепым пятном гейта
    оказалась бы денежная поверхность.
    """
    if not isinstance(decorator, ast.Call):
        return False
    func = decorator.func
    if not isinstance(func, ast.Attribute):
        return False

    if func.attr == "post":
        return True
    if func.attr != "api_route":
        return False

    for keyword in decorator.keywords:
        if keyword.arg != "methods":
            continue
        if not isinstance(keyword.value, (ast.List, ast.Tuple, ast.Set)):
            # Перечень методов, собранный выражением, разборщику не виден.
            # Считаем объявление POST-овым: пропустить его значило бы вывести
            # обработчика из-под классификации, а лишняя строка в перечне
            # заметна и снимается решением.
            return True
        for element in keyword.value.elts:
            if (
                isinstance(element, ast.Constant)
                and isinstance(element.value, str)
                and element.value.lower() == "post"
            ):
                return True
    return False


def _calls_response_layer(function: ast.AST) -> bool:
    """Идёт ли тело обработчика через главный выход слоя ответа.

    Узнаётся ИМЯ вызова — голое (`respond(...)`) и через модуль
    (`htmx.respond(...)`). Псевдоним импорта не узнаётся, и это названная
    граница (шапка модуля): ошибка здесь безопасна по направлению — обработчик
    окажется в перечне отставания, а не «разрешённым по умолчанию».
    """
    for node in ast.walk(function):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if isinstance(func, ast.Name) and func.id == RESPONSE_CALL:
            return True
        if isinstance(func, ast.Attribute) and func.attr == RESPONSE_CALL:
            return True
    return False


def _builds_own_redirect(function: ast.AST) -> bool:
    """Строит ли обработчик редирект САМ, минуя слой ответа.

    Узнаются оба способа: сборка ответа-редиректа (`RedirectResponse(...)`) и
    возбуждение исключения с кодом перехода — в обеих формах записи статуса, и
    целочисленной, и символьной (`status.HTTP_302_FOUND`). Символьная форма в
    проекте живая, и разбор, знающий только целочисленную, был бы слеп ровно к
    ней.
    """
    for node in ast.walk(function):
        if not isinstance(node, ast.Call):
            continue

        func = node.func
        name = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", None)
        if name == "RedirectResponse":
            return True

        for keyword in node.keywords:
            if keyword.arg != "status_code":
                continue
            value = keyword.value
            if (
                isinstance(value, ast.Constant)
                and type(value.value) is int
                and value.value == 302
            ):
                return True
            if isinstance(value, ast.Attribute) and value.attr.startswith("HTTP_302_"):
                return True
    return False


def _post_handlers(sources: dict[str, str]) -> dict[str, _Handler]:
    """Каждый POST-обработчик поданных исходников — по ДЕРЕВУ РАЗБОРА.

    Ключ записи — пара «модуль + имя функции»: столкновение имён в РАЗНЫХ
    модулях не схлопывает две записи в одну, а столкновение в одном модуле
    роняет счётчик `POST_HANDLERS` (число упадёт), то есть бесшумно потерять
    обработчика гейт не может.
    """
    handlers: dict[str, _Handler] = {}

    for module, text in sources.items():
        tree = _parse(module, text)
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for decorator in node.decorator_list:
                if not _declares_post(decorator):
                    continue
                router = _dotted(decorator.func.value)
                if router is None:
                    continue

                handler = _Handler(
                    module=module,
                    router=router,
                    handler=node.name,
                    calls_respond=_calls_response_layer(node),
                    builds_own_redirect=_builds_own_redirect(node),
                )
                handlers[handler.key] = handler
                break

    return handlers


