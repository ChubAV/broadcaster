@lru_cache(maxsize=None)
def _read_directory(directory: str) -> tuple[tuple[str, str], ...]:
    """Пары «относительный путь → ТЕКСТ исходника» по всему каталогу, РЕКУРСИВНО.

    Возвращается неизменяемый кортеж, а вызывающий получает из него свежий
    словарь: контроли в конце файла подменяют в этом словаре один модуль, и
    подмена не имеет права протечь в следующий тест через кэш.
    """
    root = PROJECT_ROOT / directory
    return tuple(
        (str(path.relative_to(PROJECT_ROOT)), path.read_text(encoding="utf-8"))
        for path in sorted(root.glob("**/*.py"))
    )


def _pages_sources() -> dict[str, str]:
    """Исходники страничного слоя — области, в которой живут POST-обработчики."""
    return dict(_read_directory(PAGES_DIRECTORY))


def _app_sources() -> dict[str, str]:
    """Исходники ВСЕГО приложения — области, в которой считаются чтения и записи."""
    return dict(_read_directory(APP_DIRECTORY))


@lru_cache(maxsize=None)
def _read_templates() -> tuple[tuple[str, str], ...]:
    """Пары «относительный путь → ТЕКСТ разметки» по всему дереву шаблонов.

    Обход РЕКУРСИВНЫЙ по той же причине, по которой рекурсивен обход исходников:
    файл, положенный будущей фазой в новый подкаталог, обязан попасть в охват
    сам, а не ждать, пока кто-то вспомнит про его каталог.
    """
    root = PROJECT_ROOT / TEMPLATES_DIRECTORY
    return tuple(
        (str(path.relative_to(PROJECT_ROOT)), path.read_text(encoding="utf-8"))
        for path in sorted(root.glob("**/*.html"))
    )


