# выросший перечень означает второе решение о форме ответа, принятое без
# записи; молча похудевший — снятый выход при неисправленном утверждении шапки
# слоя ответа либо ослепший разбор.
#
# ЛЕТОПИСЬ ЧИСЛА:
#   0 → 9, Фаза 10, ПЯТАЯ партия, план 10-31, задача 1: перечень заведён
#   ЗАМЕРОМ, и число поставлено ПРОГОНОМ ПОКРАСНЕВШЕГО ПРАВИЛА — заведомо
#   неверное вписано первым, девять ключей прочитаны из текста отказа.
#   ЧЕМ ИЗМЕРЕНО: разбор дерева `app/pages/**/*.py`; вселенная — ПЕРЕВЕДЁННЫЕ
#   POST-обработчики (`_calls_response_layer`), которых замер даёт ДЕСЯТЬ;
#   найденное — вызовы имён из `OWN_RESPONSE_CALLABLES` в теле обработчика ВНЕ
#   вложенного сборщика фрагмента.
#   ⚠️ ДЕВЯТЬ ИЗ ДЕСЯТИ, А НЕ ДЕСЯТЬ: `account_groups.py::account_groups_toggle`
#   переведён и собственного выхода НЕ НЕСЁТ — его единственная сборка ответа
#   живёт во вложенном `_fragment`, поданном слою. Это и есть встроенный
#   антивакуум перечня: будь разбор слеп к границе сборщика фрагмента, тумблер
#   попал бы сюда десятым, а вместе с ним и два фрагмента соседей.
#   ⚠️ ДЕВЯТЬ ИЗ ТРИНАДЦАТИ ПО ВСЕМУ СТРАНИЧНОМУ СЛОЮ, И ЧЕТЫРЕ ОСТАЛЬНЫХ
#   НАЗВАНЫ ЗДЕСЬ, А НЕ ОСТАВЛЕНЫ ЧИТАТЕЛЮ. Ориентир планировщика — тринадцать
#   мест собственного отказа во всём слое — замером ПОДТВЕРЖДЁН дословно:
#   тринадцать вызовов `Response(status_code=403)` в `app/pages/**/*.py`.
#   Четыре из них стоят в обработчиках, слоя ответа НЕ ЗНАЮЩИХ, и потому во
#   вселенную этого перечня не входят: `admin.py::admin_toggle_free_access`,
#   `admin.py::admin_toggle_block`, `auth.py::stop_impersonation`,
#   `billing.py::subscribe_to_plan`. Их предмет — счётчик отставания
#   (`NOT_YET_CONVERTED`), а не расхождение с утверждением слоя: слой о них
#   ничего не утверждает.
OWN_RESPONSE_EXITS_DECLARED = 9


def _own_response_completeness_complaints(
    exits: tuple[_OwnResponseExit, ...],
    sources: dict[str, str] | None = None,
) -> list[str]:
    """Жалобы правила ПОЛНОТЫ — на ПОДАННЫЙ перечень, а не на модульный.

    Перечень приходит параметром ровно затем, чтобы контроль зубов мог подать
    УКОРОЧЕННУЮ копию и увидеть, что правило её заметило. Приём взят у
    соседнего реестра расхождения формы отказа валидации.
    """
    measured = _converted_with_own_response(
        _pages_sources() if sources is None else sources
    )
    declared = {item.entry: item.kind for item in exits}

    complaints: list[str] = []
    for entry in sorted(set(measured) - set(declared)):
        complaints.append(
            f"НАЙДЕН ЗАМЕРОМ, НО НЕ ОБЪЯВЛЕН: {entry} (вид {measured[entry]})"
        )
    for entry in sorted(set(declared) - set(measured)):
        complaints.append(f"ОБЪЯВЛЕН, НО ЗАМЕРОМ НЕ НАЙДЕН: {entry}")
    for entry in sorted(set(declared) & set(measured)):
        if declared[entry] != measured[entry]:
            complaints.append(
                f"ВИД СБОРКИ РАЗОШЁЛСЯ С ЗАМЕРОМ: {entry} объявлен как "
                f"{declared[entry]!r}, а измерен как {measured[entry]!r}"
            )
    return complaints


def _own_response_rationale_complaints(
    exits: tuple[_OwnResponseExit, ...],
) -> list[str]:
    """Жалобы правила ОБОСНОВАНИЙ — на ПОДАННЫЙ перечень.

    Перечень без обоснований есть список того, до чего не дошли руки, и
    отличить его от объявленного выхода нельзя ничем, кроме этих пяти непустых
    полей.
    """
    complaints: list[str] = []

    for item in exits:
        where = item.entry or "(запись без входа)"

        if not item.entry.strip():
            complaints.append(
                "запись собственного выхода не называет ВХОДА — обоснование, "
                "стоящее ни на чём, неотличимо от отсутствующего"
            )
        if not item.kind.strip():
            complaints.append(
                f"выход «{where}» не называет ВИДА собственной сборки: читатель "
                "не найдёт места, которым выход сделан"
            )
        if not item.reason.strip():
            complaints.append(
                f"выход «{where}» объявлен БЕЗ ОБОСНОВАНИЯ — перечень без "
                "обоснований есть список того, до чего не дошли руки"
            )
        if not item.decision_state.strip():
            complaints.append(
                f"выход «{where}» не несёт СОСТОЯНИЯ РЕШЕНИЯ: молчащее "
                "состояние читается как решённое, а решения не было"
            )
        if not item.lifting_condition.strip():
            complaints.append(
                f"выход «{where}» не называет УСЛОВИЯ СНЯТИЯ — через фазу он "
                "станет неотличим от недоделки"
            )
        else:
            if "Фаза 11" not in item.lifting_condition:
                complaints.append(
                    f"выход «{where}» не называет ФАЗЫ РАБОТЫ. Фаза взята ИЗ "
                    "РОАДМАПА (Фаза 11, критерий 1), а не назначена планом; "
                    "условие снятия, потерявшее её имя, оставляет перечень без "
                    "адресата работы"
                )
            if "ВЛАДЕЛЬЦУ" not in item.lifting_condition:
                complaints.append(
                    f"выход «{where}» не называет ВЛАДЕЛЬЦА РЕШЕНИЯ О ФОРМЕ. "
                    "Два адресата здесь РАЗНЫЕ: Фаза 11 снимает выход работой, "
                    "а форму ответа выбирает владелец (D-01 заперт). Условие, "
                    "назвавшее только фазу, читалось бы как назначенное "
                    "решение — ровно то присвоение чужого авторства, которое "
                    "запрещает прецедент окна 51"
                )
        if _OWN_RESPONSE_PRICE.split(":")[0] not in item.reason:
            complaints.append(
                f"обоснование выхода «{where}» не называет ЦЕНЫ ТРЕМЯ "
                "СЛЕДСТВИЯМИ: обоснование без цены превращает объявленный "
                "выход обратно в умолчание"
            )

    return complaints


def _own_response_authorship_complaints(
    exits: tuple[_OwnResponseExit, ...],
) -> list[str]:
    """Жалобы правила АВТОРСТВА — на ПОДАННЫЙ перечень.

    Запись, объявившая себя РЕШЁННОЙ, обязана называть, ЧЕМ решена:
    идентификатором решения владельца по форме `D-NN` либо номером закрытого
    окна реестра. Разбор общий с соседним реестром (`_DECISION_REFERENCE`) —
    вторая копия того же выражения разъехалась бы с первой молча.
    """
    complaints: list[str] = []

    for item in exits:
        state = item.decision_state.strip()
        if not state or state == DECISION_WAITS_FOR_THE_OWNER:
            continue
        if not _DECISION_REFERENCE.search(state):
            complaints.append(
                f"собственный выход «{item.entry}» объявлен РЕШЁННЫМ "
                f"({state!r}), но не называет, ЧЕМ решено"
            )

    return complaints


