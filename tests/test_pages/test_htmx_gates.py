def _parse(module: str, text: str) -> ast.Module:
    """Дерево разбора модуля — либо ГРОМКИЙ отказ.

    Модуль, не разобравшийся в дерево, обязан РОНЯТЬ гейт, а не молча выпадать
    из охвата: неразобранный модуль неотличим от модуля без находок, и охват,
    тихо потерявший файл, утверждает не то, что обещает (форма взята у
    `tests/test_pages/test_htmx_response_contract.py`).
    """
    try:
        return ast.parse(text)
    except SyntaxError as exc:  # pragma: no cover - защита охвата
        raise AssertionError(
            f"{module}: модуль не разбирается в дерево ({exc}) — охват гейта "
            "потерял бы его молча вместе со всеми объявлениями, которые в нём "
            "записаны"
        ) from exc


def _dotted(node: ast.AST) -> str | None:
    """Точечное имя узла (`router`, `pkg.mod.router`) — либо `None`.

    Обращение через модуль узнаётся наравне с голым именем: роутер, названный
    как `pkg.mod.router`, — то же объявление, и невидимый разборщику он оказался
    бы вне охвата по умолчанию.
    """
    parts: list[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if not isinstance(node, ast.Name):
        return None
    parts.append(node.id)
    return ".".join(reversed(parts))


