def _declares_a_route_with_method(decorator: ast.AST, methods: frozenset[str]) -> bool:
    """Объявляет ли декоратор маршрут одного из перечисленных методов.

    Тот же разбор, что у `_declares_a_destructive_route`, но БЕЗ критерия пути:
    здесь считается вселенная целиком, а не её удаляющий срез.
    """
    if not isinstance(decorator, ast.Call):
        return False
    func = decorator.func
    if not isinstance(func, ast.Attribute):
        return False
    if func.attr in methods:
        return True
    if func.attr != "api_route":
        return False
    declared = {
        element.value.lower()
        for keyword in decorator.keywords
        if keyword.arg == "methods"
        and isinstance(keyword.value, (ast.List, ast.Tuple, ast.Set))
        for element in keyword.value.elts
        if isinstance(element, ast.Constant) and isinstance(element.value, str)
    }
    return bool(declared & methods)


def _handlers_with_method(source: str, methods: frozenset[str]) -> dict[str, ast.AST]:
    """Обработчики одного исходника, объявленные маршрутом одного из методов."""
    return {
        node.name: node
        for node in ast.walk(ast.parse(source))
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and any(
            _declares_a_route_with_method(d, methods) for d in node.decorator_list
        )
    }


def _calls_the_origin_guard(handler: ast.AST) -> bool:
    """Зовёт ли обработчик гард происхождения — по ВЫЗОВУ, а не по тексту."""
    return any(
        isinstance(call, ast.Call)
        and isinstance(call.func, ast.Name)
        and call.func.id == ORIGIN_GUARD
        for call in ast.walk(handler)
    )


def page_post_handlers(sources: dict[str, str]) -> set[str]:
    """Ключи «модуль::обработчик» ВСЕХ POST-маршрутов страничного слоя."""
    return {
        f"{module}::{name}"
        for module, source in sources.items()
        for name in _handlers_with_method(source, frozenset({"post"}))
    }


def post_handlers_calling_the_origin_guard(sources: dict[str, str]) -> set[str]:
    """POST-маршруты, которые гард происхождения ЗОВУТ."""
    return {
        f"{module}::{name}"
        for module, source in sources.items()
        for name, handler in _handlers_with_method(
            source, frozenset({"post"})
        ).items()
        if _calls_the_origin_guard(handler)
    }


def handlers_inside_both_gate_universes(sources: dict[str, str]) -> set[str]:
    """Маршруты, лежащие во вселенной ХОТЯ БЫ ОДНОГО гейта полноты.

    Вселенная первого гейта — ВСЕ изменяющие маршруты административного модуля.
    Вселенная второго — POST-маршруты с путём на суффикс подтверждённого
    удаления, ВНЕ админки (изъятие по владению). Объединение и есть то, про что
    слово «полнота» вообще имеет право быть сказано.
    """
    covered: set[str] = set()
    for module, source in sources.items():
        if module == ADMIN_MODULE:
            covered |= {
                f"{module}::{name}"
                for name in _handlers_with_method(source, ADMIN_MUTATING_METHODS)
            }
            continue
        covered |= {
            f"{module}::{name}"
            for name in destructive_route_handlers(module, source)
        }
    return covered


def universe_boundary_complaints(sources: dict[str, str]) -> list[str]:
    """Чем измеренная граница вселенных разошлась с объявленной.

    Жалобы собираются СПИСКОМ, а не роняются первым `assert`, ровно затем, чтобы
    антивакуум был выразим отдельным контролем: правило подаёт сюда ПУСТОЙ набор
    исходников и обязано получить жалобу, а не зелёное молчание.
    """
    if not sources:
        return [
            "АНТИВАКУУМ: на разбор не подано НИ ОДНОГО модуля страничного слоя — "
            "правило границы вселенных зеленело бы пустым множеством, а именно "
            "этим оно и опасно"
        ]

    posts = page_post_handlers(sources)
    if not posts:
        return [
            "АНТИВАКУУМ: в поданных модулях не найдено НИ ОДНОГО POST-маршрута — "
            "разбор декораторов перестал их узнавать, и все три числа ниже "
            "сравнивались бы с пустотой"
        ]

    guarded = post_handlers_calling_the_origin_guard(sources)
    covered = handlers_inside_both_gate_universes(sources)
    tally = (
        f"замерено: POST-обработчиков {len(posts)} (объявлено "
        f"{PAGE_POST_HANDLERS_MEASURED}), зовут гард {len(guarded)} (объявлено "
        f"{ORIGIN_GUARD_CALL_SITES_MEASURED}), внутри вселенных обоих гейтов "
        f"{len(covered)} (объявлено {GATE_UNIVERSE_HANDLERS_MEASURED})"
    )

    complaints: list[str] = []
    if len(posts) != PAGE_POST_HANDLERS_MEASURED:
        complaints.append(
            f"ЧИСЛО POST-ОБРАБОТЧИКОВ РАЗОШЛОСЬ С ДЕРЕВОМ — {tally}. Обработчик "
            f"появился или исчез: {sorted(posts)}"
        )
    if len(guarded) != ORIGIN_GUARD_CALL_SITES_MEASURED:
        complaints.append(
            f"ЧИСЛО МЕСТ ВЫЗОВА ГАРДА РАЗОШЛОСЬ С ДЕРЕВОМ — {tally}. Гард "
            f"повешен или снят, и это решение, а не правка числа: {sorted(guarded)}"
        )
    if len(covered) != GATE_UNIVERSE_HANDLERS_MEASURED:
        complaints.append(
            f"ЧИСЛО МАРШРУТОВ ВНУТРИ ВСЕЛЕННЫХ ОБОИХ ГЕЙТОВ РАЗОШЛОСЬ С ДЕРЕВОМ "
            f"— {tally}. Вселенная гейта расширена или сужена, и запись о границе "
            f"в докстринге гарда стала ложной: {sorted(covered)}"
        )
    if not covered <= guarded:
        complaints.append(
            f"МАРШРУТ ВО ВСЕЛЕННОЙ ГЕЙТА НЕ НЕСЁТ ГАРДА — {tally}: "
            f"{sorted(covered - guarded)}"
        )
    return complaints


def test_the_boundary_of_both_gate_universes_is_declared_by_number():
    """ГРАНИЦА ВСЕЛЕННЫХ НАЗВАНА ЧИСЛОМ, А НЕ СЛОВОМ «ПОЛНОТА» (`WR-05`).

    ⚠️ ЧТО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не расширяет вселенной ни одного гейта, не
    вешает гарда ни на один маршрут и не объявляет двадцать три оставшихся
    маршрута дефектом. Расширение серверного рубежа на них есть решение
    ВЛАДЕЛЬЦА ВЕХИ — какие изменяющие маршруты продукта его несут — и
    фаза-владелец НЕ НАЗНАЧЕНА НАМЕРЕННО: гейт, заведённый на маршруты входа и
    регистрации, которые гарда нести не могут, потребовал бы именованного изъятия
    из решения, которого никто не принимал.

    ЧТО ОНО ДЕЛАЕТ: держит ТРИ числа против дерева, чтобы «полноту держат два
    машинных гейта» нельзя было прочитать как закрытую поверхность. Молча
    выросшее число POST-обработчиков означает маршрут, о гарде на котором никто
    не думал; молча похудевшее число вселенных означает гейт, тихо сузивший
    предмет.
    """
    complaints = universe_boundary_complaints(_pages_sources())

    assert complaints == [], "\n".join(complaints)


def test_control_the_universe_boundary_rule_reddens_on_an_empty_measure():
    """ЧТО ДОКАЗЫВАЕТ: правило выше падает и на ПУСТОМ измеренном множестве.

    ⚠️ БЕЗ АНТИВАКУУМА сломавшийся разбор декораторов зеленил бы правило границы
    НАВСЕГДА: три числа сравнивались бы с пустотой, и запись о границе пережила
    бы своё основание молча.
    """
    on_nothing = universe_boundary_complaints({})
    assert on_nothing, (
        "правило границы вселенных смолчало на ПУСТОМ наборе исходников — оно "
        "зелено по построению"
    )
    assert "АНТИВАКУУМ" in on_nothing[0], (
        f"жалоба на пустом наборе не называет вакуум причиной: {on_nothing}"
    )

    on_sources_without_routes = universe_boundary_complaints({"widgets.py": "x = 1\n"})
    assert on_sources_without_routes, (
        "правило смолчало на исходнике БЕЗ единого POST-маршрута — разбор "
        "декораторов может сломаться, и правило этого не заметит"
    )
    assert "АНТИВАКУУМ" in on_sources_without_routes[0], (
        "жалоба на исходнике без маршрутов не называет вакуум причиной: "
        f"{on_sources_without_routes}"
    )
