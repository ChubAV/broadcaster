# ⚠️ ЭТИ ПРАВИЛА СТОЯТ РЯДОМ С ГРАНИЦЕЙ, ОБЪЯВЛЕННОЙ В ШАПКЕ, А НЕ ПОВЕРХ НЕЁ.
# Шапка говорит: модуль НЕ утверждает, что гард ЗАЩИЩАЕТ, и границу «запрос без
# обоих заголовков пропускается» не пересматривает. Правила ниже её и не
# пересматривают — они проверяют, что предикат ведёт себя ТАК, КАК НАПИСАНО В
# ЕГО СОБСТВЕННОМ ДОКСТРИНГЕ: три ветви, и ни одна из них не пропускает запрос
# ветвью, которая ему не принадлежит. Именно это, а не «защищает», и разошлось
# с записью (`IN-01`, ревизия 2026-09-07).


def _request_with(headers: dict[str, str], *, host: str | None = None) -> Request:
    """Запрос ИЗ ГОЛОГО ASGI-scope: с именем узла и, при `host=None`, без него.

    ⚠️ ИМЯ УЗЛА ЗАПРОСА УБИРАЕТСЯ ЧЕРЕЗ ОТСУТСТВИЕ И ЗАГОЛОВКА `Host`, И ПОЛЯ
    `server`, потому что фреймворк выводит его из ОБОИХ. Клиент тестовой суиты
    так собрать запрос не даёт — он всегда ставит `Host`, — а без этой формы
    случай `IN-01` был бы невыразим, и правило доказывало бы меньше, чем
    утверждает.
    """
    raw = [(name.lower().encode(), value.encode()) for name, value in headers.items()]
    if host is not None:
        raw.append((b"host", host.encode()))
    return Request(
        {
            "type": "http",
            "method": "POST",
            "path": "/accounts/1/delete",
            "query_string": b"",
            "headers": raw,
            "scheme": "http",
            "root_path": "",
            "server": None,
            "client": None,
        }
    )


def test_a_hostless_origin_is_not_the_same_origin_as_a_hostless_request():
    """ДВА ОТСУТСТВИЯ НЕ СКЛАДЫВАЮТСЯ В СОВПАДЕНИЕ ИСТОЧНИКОВ (`IN-01`).

    ЧТО ИМЕННО ЛОВИТСЯ. `urlsplit("null").hostname` есть `None`; заголовок
    `Origin: null` шлют песочница iframe, документ схемы `data:` и часть цепочек
    межсайтовых переходов. Если имя узла отсутствует и у САМОГО запроса, наивное
    сравнение даёт `None == None`, то есть ИСТИНУ, и запрос проезжает ВЕТВЬЮ
    ЗАГОЛОВКА — вместо объявленной ветви БЕЗ ЗАГОЛОВКОВ, у которой основание
    своё и записанное.

    ⚠️ ДОСТИЖИМОСТЬ НАЗВАНА ПРЯМО, И ОНА НУЛЕВАЯ СЕГОДНЯ: за действующим
    обратным прокси проекта имя узла у запроса есть всегда. Правится ТИХОЕ
    РАСШИРЕНИЕ границы, которую модуль описывает точно, а не воспроизведённый
    отказ, — отсюда и severity находки.
    """
    request = _request_with({"origin": "null"}, host=None)

    assert request.url.hostname is None, (
        "форма запроса перестала быть безголовой — правило проверяет НЕ ТОТ "
        f"случай: имя узла запроса {request.url.hostname!r}"
    )

    assert is_same_origin(request) is False, (
        "предикат признал совпадением источников пару ОТСУТСТВИЙ: заголовок "
        "`Origin: null` не несёт имени узла, и запрос его тоже не несёт. Запрос "
        "из песочницы проезжает ВЕТВЬЮ ЗАГОЛОВКА вместо объявленной ветви без "
        "заголовков — то есть граница, которую докстринг описывает точно, тихо "
        "расширена"
    )


