"""Бесплатный доступ администратора — ТРИ ПОВЕРХНОСТИ ПРИМЕНЕНИЯ и две показа.

ПРЕДМЕТ (критерий 5 фазы 05.1, решение D-E). Признак
`subscriptions.has_free_access` объявлен в ОДНОМ месте — в предикате
`access_is_open` — и оттуда достаётся всем, кто спрашивает про доступ:
зависимости страниц (`require_access`), зависимости JSON-входов
(`get_current_user_id_with_access`) и гейту пути отправки (`check_access`).
Ровно поэтому файл проверяет ПОВЕРХНОСТИ, а не предикат: что предикат читает
признак и в каком порядке, утверждает
`tests/test_application/test_subscription_period.py`; здесь — что одно
объявление действительно доехало до каждой из дверей.

⚠️ ВХОД У ВСЕХ ТЕСТОВ — ЧЕЛОВЕК С МЁРТВОЙ ДАТОЙ (фикстура `comped_client`), И
ЭТО УСЛОВИЕ ОСМЫСЛЕННОСТИ. У человека с живым сроком доступ открыт и без
льготы, и весь файл зеленел бы при полностью непрочитанном признаке. На
просроченной строке вердикт «открыт» не может прийти ниоткуда, кроме него.

ЧЕТВЁРТОЕ СОСТОЯНИЕ ПАНЕЛИ И БЕЙДЖ ВИДЖЕТА ПРОВЕРЯЮТСЯ ЗДЕСЬ ЖЕ, а не в
`test_responsive_markup.py`: там предмет — раскладка и примитивы строки, а
здесь — что показ и вердикт говорят об ОДНОМ И ТОМ ЖЕ человеке одно и то же.
Панель, объявляющая «доступ открыт бессрочно» тому, кого дверь не пускает, —
ровно тот класс расхождения, ради которого правило доступа объявлено один раз.
"""
import pytest
from httpx import AsyncClient


@pytest.mark.parametrize(
    "path",
    ["/ads", "/accounts", "/schedules", "/groups", "/history"],
)
@pytest.mark.asyncio
async def test_pages_of_value_open_for_free_access_over_a_dead_date(
    comped_client: AsyncClient, path: str
):
    """Страница создания ценности отвечает 200, а не уводит на оплату.

    Утверждение стоит и по коду, и по ЗАГОЛОВКУ `location`: 302 сам по себе мог
    бы прийти по чужой причине, а `/billing?expired=1` означает ровно одно —
    гейт доступа признал человека просроченным, то есть льгота не прочитана.
    """
    response = await comped_client.get(path, follow_redirects=False)

    assert response.headers.get("location") != "/billing?expired=1", (
        f"{path} увёл человека с выданным бесплатным доступом оплачивать доступ"
    )
    assert response.status_code == 200, (
        f"{path} ответил {response.status_code} при выданном бесплатном доступе"
    )


@pytest.mark.asyncio
async def test_the_json_entry_creates_for_free_access_over_a_dead_date(
    comped_client: AsyncClient,
):
    """JSON-вход создаёт объявление: 201, а не 402 и не 403.

    Вторая поверхность применения. Она отказывает КОДОМ, а не редиректом, и её
    зависимость (`get_current_user_id_with_access`) — отдельная от страничной;
    их общее — единственный предикат. Тест закрывает возможность, при которой
    льгота доехала до страниц и не доехала сюда.
    """
    response = await comped_client.post(
        "/api/ads",
        json={"title": "T", "text": "Body", "images": []},
        follow_redirects=False,
    )

    assert response.status_code == 201, (
        f"/api/ads ответил {response.status_code} при выданном бесплатном "
        "доступе — те же данные недостижимы там, где страничный гейт пускает"
    )


@pytest.mark.asyncio
async def test_the_billing_panel_reads_the_free_access_state(
    comped_client: AsyncClient,
):
    """Панель раздела печатает четвёртое состояние: цену, бейдж, «бессрочно».

    Четыре утверждения, и каждое закрывает своё правило контракта:
      * бейдж `бесплатный доступ` — состояние отличается СЛОВАМИ, а не цветом;
      * `доступ открыт бессрочно` — у льготы даты нет, и панель обязана стоять
        целиком, а не оставлять пустое место;
      * кнопки оплаты НЕТ (P-3): она предлагала бы купить уже имеющееся, а
        оплата сдвинула бы дату, которой при льготе никто не читает;
      * цена ПЕЧАТАЕТСЯ и здесь — цена есть свойство продукта, а не счёт этому
        человеку, и спрятать её значило бы скрыть, во что обойдётся доступ,
        когда льгота кончится.
    """
    html = (await comped_client.get("/billing")).text

    assert "бесплатный доступ" in html, "бейдж четвёртого состояния не напечатан"
    assert "доступ открыт бессрочно" in html, "строка бессрочности не напечатана"
    assert "Оплата не требуется" in html, (
        "место снятой кнопки не занято подписью с причиной — панель без кнопки "
        "и без слов читается как поломка платёжного пути"
    )
    assert 'action="/billing/subscribe"' not in html, (
        "кнопка оплаты нарисована человеку, у которого доступ уже бесплатный"
    )
    assert "₽" in html, (
        "цена не напечатана: она свойство продукта, а не счёт этому человеку"
    )


@pytest.mark.asyncio
async def test_the_sidebar_widget_prints_the_free_access_badge(
    comped_client: AsyncClient,
):
    """Виджет сайдбара печатает бейдж льготы, а не «закрыт».

    Виджет рисуется на всех страничных маршрутах и читает ТОТ ЖЕ словарь шелла,
    из которого берётся вердикт. Ветка льготы проверяется раньше счётных: у
    этого человека `days_left` ОТРИЦАТЕЛЕН, и любая счётная ветка, оказавшись
    выше, напечатала бы ему «закрыт» на каждой из страниц, куда его пускают.
    """
    html = (await comped_client.get("/dashboard")).text

    assert "data-access" in html, "виджет доступа не отрисован вовсе"
    assert "бесплатный" in html, "бейдж бесплатного доступа не напечатан"
    assert ">закрыт<" not in html, (
        "виджет сказал «закрыт» человеку, которого продукт пускает на все "
        "страницы — экран говорит одно, дверь отвечает другое"
    )
